#!/bin/bash
# СТОРОЖ СЕТИ ФЕРМЫ.
#
# ЗАЧЕМ. У телефонов НЕТ своего выхода в интернет: системный http_proxy каждой платы
# указывает на переходник, который слушает на маке по адресу 192.168.34.2. Стоит маку уйти
# из этой сети — перескочить на раздачу с телефона, уснуть, поймать другой Wi-Fi, — и
# одновременно ломается ВСЁ: мосты «не отвечают» (хотя процессы живы и сами прокси ClickIP
# в порядке), у телефонов пропадает интернет целиком, adb видит платы как offline.
#
# 21.08.2026 это стоило половины дня. Владелец сообщил «2 прокси на кз не работают»; не
# работали все три, включая белорусский, и виноваты были не прокси: у мака стоял адрес
# 172.20.10.9 (раздача с телефона), а Wi-Fi не был подключён вовсе. Снаружи это выглядит
# как поломка прокси, и искать её можно долго — потому что искать нечего.
#
# ЧТО ДЕЛАЕТ. Раз в минуту сверяет адрес мака с ожидаемым и, если он не тот, кричит в
# телеграм — один раз на эпизод, а не потоком. Когда адрес возвращается, говорит и об этом:
# «починилось» — такая же новость, как «сломалось».
#
# ЧЕГО НЕ ДЕЛАЕТ. Не лезет в сетевые настройки мака: менять их — решение владельца, и
# сторож, который сам переключает Wi-Fi, однажды переключит его не туда.
#
# ИМЕНА ПЕРЕМЕННЫХ ТОЛЬКО ЛАТИНИЦЕЙ. Первая версия этого файла была написана с русскими
# именами — и bash 3.2 молча их не присвоил: «СЕТЬ=...» это не присваивание, а попытка
# выполнить команду. Скрипт падал на второй же строке проверки. Правило записано давно,
# я его сам нарушил в файле, где сам же о нём и предупредил.
set -u
WANT="${FARM_IP:-192.168.34.2}"
STATE=~/.neironka/set_watch_состояние.txt
LOG=~/.neironka/set_watch.log
INBOX=~/.neironka/tg_входящие.txt

say() {
  echo "$(date '+%H:%M:%S') $1" >> "$LOG"
  printf '%s\t⚠ СЕТЬ\t%s\n' "$(date -u +%Y-%m-%dT%H:%M:%S.000Z)" "$1" >> "$INBOX"
  TOK=$(cat ~/.neironka/tgtok 2>/dev/null | tr -d '\n')
  CHAT=$(cat ~/.neironka/tgchat 2>/dev/null | tr -d '\n')
  if [ -n "$TOK" ] && [ -n "$CHAT" ]; then
    curl -s -o /dev/null --max-time 15 \
      --data-urlencode "chat_id=$CHAT" \
      --data-urlencode "text=$1" \
      "https://api.telegram.org/bot$TOK/sendMessage" || true
  fi
}

while true; do
  NOW=$(ipconfig getifaddr en0 2>/dev/null)
  [ -z "$NOW" ] && NOW="нет адреса"
  PREV=$(cat "$STATE" 2>/dev/null)

  if [ "$NOW" != "$WANT" ]; then
    # Кричим только на СМЕНЕ состояния: постоянный крик читать перестанут, а он и есть
    # единственный способ узнать об этом за минуту, а не за полдня.
    if [ "$PREV" != "bad:$NOW" ]; then
      NET=$(networksetup -getairportnetwork en0 2>/dev/null | sed 's/^.*: //')
      [ -z "$NET" ] && NET="неизвестна"
      say "ФЕРМА ОТРЕЗАНА: у мака адрес $NOW вместо $WANT (сеть: $NET). У телефонов сейчас НЕТ интернета — их прокси смотрит на $WANT. Прокси и мосты тут ни при чём. Вернуть ноут в сеть фермы."
      echo "bad:$NOW" > "$STATE"
    fi
  else
    case "$PREV" in
      bad:*) say "Сеть фермы вернулась: у мака снова $WANT. Телефоны должны ожить сами; если adb видит платы offline — adb kill-server && adb start-server при пустом runner.sessions." ;;
    esac
    echo "ok" > "$STATE"
  fi
  sleep 60
done
