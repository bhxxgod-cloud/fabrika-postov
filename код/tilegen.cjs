'use strict';
// tilegen.cjs — ЗАКАЗ ФОТО-ПЛИТОК ДЛЯ КАРТОЧЕК (15.08).
//
// ЗАЧЕМ. Вердикты владельца: стрижки — «каждая генерится на самой девочке», нос — «фото-варианты
// её носа вместо клипарт-профилей». Вёрстка под плитки уже в cardgen (ф.плитка1..6); этот модуль
// делает вторую половину — ЗАКАЗЫВАЕТ сами плитки у провайдера.
//
// ГЛАВНОЕ ПРАВИЛО — ИМЕНА ИЗ ПЛАНА КАРТОЧКИ. Промпт просит ровно ту стрижку, которую макет
// подпишет под плиткой: список берётся из cardgen.плиткиСтрижки(ключ) — того же розыгрыша по
// ключу поста, что рисует подписи. Формулировка риска от маркетолога: «иначе подпись скажет
// "лесенка", а на фото каре — и мы вернёмся к вранью хук-против-карточки, только внутри карточки».
//
// ФОРМУЛЫ ПРОМПТОВ — ЕГО ЖЕ, ПРОВЕРЕННЫЕ НА 33 ГЕНЕРАЦИЯХ (run6/run10 для стрижек, run6+run11b
// для носа). Знания, оплаченные его тестами:
//   · для стрижек цвет волос ТОТ ЖЕ — меняется форма, не цвет (иначе девочка «перекрашивается»
//     между плитками одной карточки);
//   · для носа — анфас в ТОЙ ЖЕ позе, что база: сравнение «сейчас/вариант» читается только при
//     одинаковом ракурсе; плитка «сейчас» вообще не генерация, а кроп базового фото;
//   · заказы с ОДНИМ референсом: на четырёх бывают таймауты провайдера.
//
// ЭКОНОМИКА, ДВА РЕШЕНИЯ ВЛАДЕЛЬЦА (15.08, «очень дорого получается, согласен?»):
//   1. СЕТКА ОДНИМ ЗАКАЗОМ вместо шести. Просим модель одну картинку 3x2 с шестью стрижками и
//      режем кодом. $0.03 вместо $0.15, впятеро дешевле — и карточка вышла РОВНЕЕ: у всех шести
//      клеток один фон, свет и масштаб головы, чего шесть отдельных генераций не дают никогда.
//      Проверено живым тестом на dark11: одна девочка, шесть стрижек, лицо держится.
//   2. ПЛИТКИ ПРИНАДЛЕЖАТ ДЕВОЧКЕ, А НЕ ПОСТУ. Стрижки её — значит одна сетка на девочку и
//      переиспользование на всех её постах со стрижками. Ключ хранения — имя девочки; повторный
//      вызов для той же девочки не заказывает ничего, отдаёт готовое. 19 девочек = ~$0.60 разово.
//      Владелец расширил идею и на кадры 3/4 постов: переиспользовать, меняя только музыку.
//
// Запуск:
//   node tilegen.cjs --dry стрижки <фото> <ключ>      план и промпты, без денег
//   node tilegen.cjs --go  стрижки <фото> <ключ>      сетка 3x2 одним заказом (~$0.03)
//   node tilegen.cjs --go  нос     <фото> <ключ>      сетка 2x2 одним заказом (~$0.03)
// Плитки кладутся в НЕЙРОНКА/ПЛИТКИ/по-девочке/<девочка>/<вид>/ и готовы для cardgen.собрать(..., {плитки:[...]}).
const fs = require('node:fs');
const path = require('node:path');
const rgen = require(path.join(__dirname, 'rgen.cjs'));
const cg = require(path.join(__dirname, 'cardgen.cjs'));

const DRY = process.argv.includes('--dry');
const GO = process.argv.includes('--go');
const [ВИД, ФОТО, КЛЮЧ] = process.argv.slice(2).filter((a) => !a.startsWith('--'));

// KEEP под плитки: та же девушка, узнаваемость обязательна. «Взрослая девушка 25 лет» — рабочая
// защита от фильтра провайдера (замер маркетолога: без неё режет часть заказов).
const KEEP_ПЛИТКА = 'ОТРЕДАКТИРУЙ ПРИЛОЖЕННОЕ ФОТО: та же взрослая девушка 25 лет. НЕ МЕНЯТЬ и не '
  + '«улучшать»: черты лица, разрез и цвет глаз, овал, тон кожи, родинки. Другая девушка это брак.';
const БЛОК_ПЛИТКА = ' КАДР ДЛЯ ПЛИТКИ КАТАЛОГА: по грудь, лицо к камере, нейтральный светло-серый '
  + 'фон, мягкий ровный свет, лёгкая улыбка, без надписей, букв и логотипов.';

// Варианты носа — РОВНО под подписи макетНос (кнопочный/прямая спинка/мягкая линия/вздёрнутый).
const НОСЫ = [
  ['кнопочный', 'маленький округлый кончик носа'],
  ['прямая спинка', 'ровная тонкая спинка носа'],
  ['мягкая линия', 'плавный мягкий изгиб спинки носа'],
  ['вздёрнутый', 'слегка вздёрнутый кончик носа'],
];

function промпты() {
  if (ВИД === 'стрижки') {
    return cg.плиткиСтрижки(КЛЮЧ).map(({ имя, описание }) => ({
      имя,
      промпт: `${KEEP_ПЛИТКА} ЦВЕТ ВОЛОС ТОТ ЖЕ, что на фото: меняется форма стрижки, не цвет. `
        + `ЗАДАЧА: она со стрижкой «${имя}» (${описание}), волосы уложены естественно.${БЛОК_ПЛИТКА}`,
    }));
  }
  if (ВИД === 'нос') {
    return НОСЫ.map(([имя, описание]) => ({
      имя,
      промпт: `${KEEP_ПЛИТКА} НЕ МЕНЯТЬ также: губы, брови, волосы прядь в прядь, ТА ЖЕ ПОЗА и тот `
        + `же фон, лицо АНФАС как на фото. ЗАДАЧА: измени ТОЛЬКО НОС — ${описание}. `
        + 'Изменение видно при сравнении с фото, но нос живой, без «пластики».' + БЛОК_ПЛИТКА,
    }));
  }
  throw new Error(`не знаю вид «${ВИД}»: умею «стрижки» и «нос»`);
}

(async () => {
  if (!ФОТО || !fs.existsSync(ФОТО) || !КЛЮЧ) {
    console.log('usage: node tilegen.cjs --dry|--go стрижки|нос <фото> <ключ-поста>'); process.exit(1);
  }
  if (!DRY && !GO) { console.log('без --dry или --go ничего не делаю'); process.exit(1); }
  const план = промпты();
  console.log(`${ВИД}: ${план.length} плиток для ключа «${КЛЮЧ}»`);
  if (DRY) {
    for (const [i, p] of план.entries()) console.log(`\n[${i + 1}] ${p.имя}\n    ${p.промпт.slice(0, 160)}…`);
    console.log('\nДенег не потрачено (--dry).');
    return;
  }
  // КЕШ ПО ДЕВОЧКЕ (решение 2). Имя девочки — папка исходника (ОБЛОЖКИ-ДОГЕН/<девочка>/…) либо
  // имя файла. Есть готовые плитки нужного вида — отдаём их, денег не тратим.
  // ИМЯ ДЕВОЧКИ: из папки, если фото лежит в папке девочки (ОБЛОЖКИ-ДОГЕН/<имя>/обложка01.jpg);
  // из имени файла, если фото лежит в ОБЩЕЙ папке (ДОГЕН-РАБОТА/<имя>.jpg). Первая версия
  // смотрела только папку — и пять вызовов маркетолога с базами из ДОГЕН-РАБОТА писали кеш в
  // ПЛИТКИ/по-девочке/ДОГЕН-РАБОТА/, перезаписывая друг друга: осталась одна последняя. Он
  // поймал и назвал строку. Общие папки перечислены явно, чтобы новая общая папка не повторила.
  const ОБЩИЕ_ПАПКИ = new Set(['ДОГЕН-РАБОТА', 'ОБЛОЖКИ-ДОГЕН', 'НОВЫЕ-ДЕВОЧКИ', 'исходники', '.', 'tmp']);
  const папка = path.basename(path.dirname(ФОТО));
  const девочка = ОБЩИЕ_ПАПКИ.has(папка) ? path.basename(ФОТО).replace(/\.[^.]+$/, '') : папка;
  const кеш = require('./места.cjs').вДоме('ПЛИТКИ', 'по-девочке', девочка, ВИД);
  // _сетка.jpg лежит рядом для отладки, но плиткой не считается
  const готовыеРаньше = fs.readdirSync(кеш).filter((f) => f.endsWith('.jpg') && !f.startsWith('_')).sort();
  if (готовыеРаньше.length >= план.length && !process.env.TILE_FORCE) {
    console.log(`у «${девочка}» ${ВИД} уже сгенерены (${готовыеРаньше.length} шт), беру из кеша, $0`);
    console.log(`плитки: ${кеш}`);
    return;
  }

  // СЕТКА ОДНИМ ЗАКАЗОМ (решение 1). Для стрижек — всегда; для носа тоже годится: 2x2.
  const [кол, ряд] = план.length === 6 ? [3, 2] : [2, 2];
  const списокКлеток = план.map((p, i) => `${i + 1}) «${p.имя}»`).join('; ');
  const промптСетки = (ВИД === 'стрижки'
    ? `${KEEP_ПЛИТКА} ЦВЕТ ВОЛОС ТОТ ЖЕ. `
    : `${KEEP_ПЛИТКА} НЕ МЕНЯТЬ также губы, брови, волосы прядь в прядь, лицо АНФАС. `)
    + `СДЕЛАЙ ОДНУ КАРТИНКУ-СЕТКУ ${кол} колонки на ${ряд} ряда, ${план.length} одинаковых клеток, в каждой ОНА ЖЕ по грудь, `
    + 'лицо к камере, нейтральный светло-серый фон, мягкий ровный свет, лёгкая улыбка. '
    + (ВИД === 'стрижки' ? 'В каждой клетке СВОЯ стрижка' : 'В каждой клетке СВОЙ вариант носа, всё остальное лицо одинаковое')
    + `, строго в этом порядке слева направо и сверху вниз: ${списокКлеток}. `
    + 'Клетки без рамок, без подписей, без букв и цифр. Одинаковый масштаб головы во всех клетках.';
  const сетка = path.join(кеш, `_сетка.jpg`);
  await rgen.genToFile(сетка, { model: 'nano-banana-pro', prompt: промптСетки, refFiles: [ФОТО],
    resolution: '2K', aspect: кол === 3 ? '3:2' : '1:1' });
  // РЕЖЕМ ПО ЛИНИЯМ САМОЙ КАРТИНКИ, а не по линейке: разделители модель рисует сама и ставит их
  // не всегда ровно на трети — деление по линейке срезало бы край клетки.
  const код = `
import sys, numpy as np
from PIL import Image
im = Image.open(sys.argv[1]).convert('RGB'); w, h = im.size
g = np.asarray(im.convert('L'), dtype=np.float32)
kol, ryad, out = int(sys.argv[2]), int(sys.argv[3]), sys.argv[4]
def cuts(prof, n):
    L = len(prof); res = [0]
    for k in range(1, n):
        c = int(L * k / n); win = prof[c-40:c+40]; res.append(c - 40 + int(np.argmax(win)))
    return res + [L]
xs = cuts(g.mean(axis=0), kol); ys = cuts(g.mean(axis=1), ryad)
n = 0
for r in range(ryad):
    for c in range(kol):
        n += 1
        im.crop((xs[c]+6, ys[r]+6, xs[c+1]-6, ys[r+1]-6)).save(f'{out}/{sys.argv[5]}_{n:02d}.jpg', quality=92)
print(n)`;
  const { execFileSync } = require('node:child_process');
  const нарезано = execFileSync('python3', ['-c', код, сетка, String(кол), String(ряд), кеш, ВИД], { encoding: 'utf8' }).trim();
  const счёт = rgen.spentSoFar();
  console.log(`сетка ${кол}x${ряд} → ${нарезано} плиток, потрачено $${счёт.usd}`);
  console.log(`плитки: ${кеш}  (кеш по девочке «${девочка}», повторно бесплатно)`);
  console.log(`дальше: cardgen.собрать(шаблон, фото, "${КЛЮЧ}", out, null, { плитки: [...по порядку файлов] })`);
  return;

})().catch((e) => { console.log('упало:', e.message); process.exit(1); });
