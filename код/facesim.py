#!/usr/bin/env python3
"""СХОЖЕСТЬ ЛИЦА МЕЖДУ КАДРАМИ ЧИСЛОМ. Отвечает на один вопрос: на этих двух картинках один и тот
же человек или разные люди.

ЗАЧЕМ ЭТОТ ФАЙЛ ПОЯВИЛСЯ (09.08, самая дорогая поломка фабрики). Начальник поймал глазами пост
нов28: на обложке одна девушка, на кадрах 3 и 4 другая, и различались именно черты лица. Соседний
пост нов29 при том же коде лицо держал. То есть поломка ПЛАВАЮЩАЯ, и глазами её не поймать на
объёме: сто постов в пачке никто не пересмотрит. Мера цвета волос тут не помогает вообще (она
берёт боковые полосы кадра, то есть фон), а «похожа по типажу» это не мера.

ЧЕМ МЕРИМ И ПОЧЕМУ ИМЕННО ТАК.
  • детектор лиц cv2.FaceDetectorYN (yunet.onnx) — тот же, каким отбирали сто аватарок и каким
    работает facevalidate.py. Второй детектор в проекте плодить незачем;
  • сравнение лиц cv2.FaceRecognizerSF (sface.onnx, opencv_zoo, sha256 0ba9fbfa…c34e79).
    Это НЕ детекция, а распознавание: 128-мерный эмбеддинг лица, косинус между эмбеддингами.
    Модель обучена так, что «то же лицо» и «другое лицо» разделяются одним порогом независимо от
    причёски, макияжа, света и цвета волос — а нам ровно это и нужно, потому что цвет волос мы
    меняем НАРОЧНО, и любая мера по пикселям на этом ломается;
  • путь через vision-модель по ключу OpenRouter отвергнут осознанно: он платный, отвечает
    словами («похоже, тот же человек»), не даёт устойчивого числа для порога и не воспроизводим
    на повторном прогоне. Гейт должен считать бесплатно и одинаково.

ПОЧЕМУ МАКСИМУМ ПО ВСЕМ ЛИЦАМ КАДРА, А НЕ ПО КРУПНЕЙШЕМУ. Лицо героини не всегда самое крупное
пятно: на обложке подложка хука даёт ложное «лицо», на эскалаторе метро и в кафе за спиной стоят
прохожие, у арт-шаблонов поверх лица лежит второй слой. Вопрос гейта звучит «есть ли в кадре ТОТ ЖЕ
человек», значит правильный ответ это лучшая пара из всех найденных лиц. Проверено на 34 постах
склада: при выборе только крупнейшего лица мера ложно ругалась на нов14 и фон03, где героиня в
кадре есть, просто не самым большим лицом.

ПОРОГ 0.363 это канонический порог SFace для косинуса, и он же попал в разрыв нашего склада: у 34
постов за сутки числа легли двумя кучками, ниже 0.33 и выше 0.41, между ними пусто. Проверен на
известных примерах: нов28 (начальник сказал «другая девушка») дал 0.084, нов29 («лицо нормально»)
дал 0.514.

Запуск: python3 facesim.py <кадр_A> <кадр_B> [ещё кадры…]
Печатает JSON: {"pairs": {"1-2": 0.51, …}, "faces": [n,…]}. Кадр без лица даёт null, и это НЕ ноль:
ноль читается как «другой человек», а «лица не нашли» это другая ситуация, и решает её вызывающий.
"""
import json
import os
import sys

import cv2
import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
YUNET = os.environ.get('YUNET_MODEL', os.path.join(HERE, 'yunet.onnx'))
SFACE = os.environ.get('SFACE_MODEL', os.path.join(HERE, 'sface.onnx'))

# Порог «то же лицо». Канонический порог SFace, подтверждён на складе (см. шапку).
SAME_FACE = 0.363
# Серая зона: числа рядом с порогом гейт помечает, но по ним приговор выносят глаза.
GREY_LOW, GREY_HIGH = 0.33, 0.42

MIN_AREA = 0.004   # доля кадра: лицо мельче это прохожий на фоне, черты по нему не читаются
MAX_FACES = 4      # больше искать незачем: героиня всегда среди самых крупных лиц

# ПРИВЕДЕНИЕ К ОДНОМУ МАСШТАБУ ПЕРЕД ДЕТЕКТОМ. Это не косметика, а условие правильной работы меры.
# ЧТО БЫЛО. Первая версия считала как есть, и мера начала ложно ругаться на кадры, где начальник
# видит того же человека. Разбор показал причину: качество РАЗМЕТКИ ГЛАЗ у yunet зависит от размера
# картинки. Кадры поста это 1080×1350, сырая генерация фабрики 1856×2304, а обложки начальника
# бывают и 750, и 1280 по длинной стороне. На больших картинках yunet ставил точки глаз мимо, а
# alignCrop по кривым точкам отдаёт SFace ОБРЕЗОК (живой пример: вместо лица один глаз), и косинус
# между лицом и глазом закономерно оказывался ниже порога.
# После приведения длинной стороны к 1400 мера на 15 парах с известным приговором (включая нов28 и
# нов29, которые смотрел начальник) не ошиблась ни разу.
LONG_SIDE = 1400
# «Лицо найдено нормально»: занимает хотя бы 1.5 процента кадра. Меньше — повод попробовать
# запасной масштаб, потому что скорее всего героиню пропустили и нашли прохожего на фоне.
BIG_FACE = 0.015

_det = None
_rec = None


def _models():
    global _det, _rec
    if _det is None:
        for f, what in ((YUNET, 'детектор лиц yunet.onnx'), (SFACE, 'сравнение лиц sface.onnx')):
            if not os.path.exists(f):
                raise SystemExit(json.dumps({'error': f'нет модели: {what} по пути {f}'}, ensure_ascii=False))
        # Порог детекции 0.6: на 0.5 в подложку хука попадали ложные «лица», и мера шумела.
        _det = cv2.FaceDetectorYN_create(YUNET, '', (320, 320), 0.6, 0.3, 200)
        _rec = cv2.FaceRecognizerSF.create(SFACE, '')
    return _det, _rec


def faces(path):
    """Эмбеддинги лиц кадра, крупные сначала. Пустой список значит «лиц не нашли».

    ЗАПАСНЫЕ МАСШТАБЫ ВКЛЮЧАЮТСЯ ТОЛЬКО ПО ДЕЛУ, И ЭТО ПОДОБРАНО ЧИСЛОМ. У yunet узкий рабочий
    диапазон размера лица, и мимо него он ошибается двумя разными способами:
      • лицо МЕЛКОЕ (героиня в полный рост) — не находит вовсе;
      • лицо ОГРОМНОЕ и наклонённое (крупное селфи во весь кадр) — находит только прохожих на фоне,
        а героиню пропускает. Живой случай: спасательный кадр нов25, три найденных «лица» по 25
        пикселей и ни одного настоящего.
    Поэтому: сначала обычный проход; если крупнейшее найденное лицо мелкое (меньше BIG), пробуем
    удвоение и уменьшение и берём проход, который нашёл лицо ЗАМЕТНО крупнее.
    ПОЧЕМУ НЕ ГОНЯТЬ ВСЕ МАСШТАБЫ ВСЕГДА. Проверено на 19 парах с известным приговором: безусловное
    уменьшение кадра портит меру (мелкий размытый кроп теряет приметы, и РАЗНЫЕ люди начинают
    сходиться: нов28 вместо 0.173 давал 0.480, то есть гейт пропускал ровно тот брак, из-за которого
    всё это писалось). С условным запасным ходом расхождений с глазами ноль.
    """
    det, rec = _models()
    img = cv2.imread(path)
    if img is None:
        return []
    # Приведение к одному масштабу: см. LONG_SIDE выше, без него мера ложно ругается.
    h0, w0 = img.shape[:2]
    k0 = LONG_SIDE / max(h0, w0)
    if abs(k0 - 1) > 0.02:
        img = cv2.resize(img, (max(1, int(w0 * k0)), max(1, int(h0 * k0))),
                         interpolation=cv2.INTER_AREA if k0 < 1 else cv2.INTER_CUBIC)
    h, w = img.shape[:2]

    def run(k):
        im = img if k == 1.0 else cv2.resize(
            img, (max(64, int(w * k)), max(64, int(h * k))),
            interpolation=cv2.INTER_AREA if k < 1 else cv2.INTER_CUBIC)
        det.setInputSize((im.shape[1], im.shape[0]))
        _, f = det.detect(im)
        if f is None or len(f) == 0:
            return []
        got = []
        for r in sorted(list(f), key=lambda z: -z[2] * z[3]):
            area = float(r[2] * r[3]) / (k * k) / (w * h)
            if area < MIN_AREA or len(got) >= MAX_FACES:
                continue
            got.append({'area': area, 'e': rec.feature(rec.alignCrop(im, r)).copy()})
        return got

    got = run(1.0)
    if got and got[0]['area'] >= BIG_FACE:
        return got
    for k in (2.0, 0.7):
        alt = run(k)
        if alt and (not got or alt[0]['area'] > got[0]['area'] * 1.5):
            got = alt
        if got and got[0]['area'] >= BIG_FACE:
            break
    return got


def sim(a, b):
    """Схожесть двух наборов лиц: лучшая пара. None если хотя бы в одном кадре лиц нет."""
    if not a or not b:
        return None
    out = -1.0
    for p in a:
        for q in b:
            x, y = p['e'].flatten(), q['e'].flatten()
            out = max(out, float(np.dot(x, y) / (np.linalg.norm(x) * np.linalg.norm(y))))
    return round(out, 3)


def compare(paths):
    fs = [faces(p) for p in paths]
    pairs = {}
    for i in range(len(paths)):
        for j in range(i + 1, len(paths)):
            pairs[f'{i + 1}-{j + 1}'] = sim(fs[i], fs[j])
    return {'pairs': pairs, 'faces': [len(f) for f in fs], 'same_face': SAME_FACE}


if __name__ == '__main__':
    args = sys.argv[1:]
    if len(args) < 2:
        raise SystemExit(json.dumps({'error': 'нужно минимум два файла кадров'}, ensure_ascii=False))
    print(json.dumps(compare(args), ensure_ascii=False))
