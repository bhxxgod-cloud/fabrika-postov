// ЗАЧЕМ. Приказ владельца дословно: «сохрани в коде, чтобы все сохранения были в 3 папки, а не
// по всему рабочему столу». К этому моменту на столе лежало ДВАДЦАТЬ ДВЕ папки и пять zip —
// каждый скрипт заводил себе выходную папку сам, прямо на столе, и через неделю стол превратился
// в свалку, где сам владелец не мог найти, «где все рилсы».
//
// ТРИ МЕСТА, И ТОЛЬКО ОНИ:
//   1. НЕЙРОНКА        — всё рабочее хозяйство: исходники, обложки, авы, логи, архивы, заливы;
//   2. СОКРОВИЩНИЦА    — готовые рилсы (годные плоско + отсев по причинам);
//   3. neironka-poster — код (этот репозиторий). Сюда данные не пишем вообще.
//
// ПРАВИЛО ДЛЯ ЛЮБОГО НОВОГО КОДА: выходную папку НЕ выдумывать, а просить у этого модуля —
// вДоме('МОЯ-ПАПКА') даст путь внутри НЕЙРОНКИ и сам её создаст. Писать на стол напрямую нельзя;
// исключение одно — архивы текущего залива, которые владелец перетаскивает руками в магос
// (вЗалив), они живут на столе до конца залива и потом уезжают в НЕЙРОНКА/ЗАЛИВЫ-АРХИВ.
//
// ПРО СТАРЫЕ ПУТИ. «НЕЙРОНКА ЗАВОД НОВЫЙ» теперь живёт в НЕЙРОНКА/ЗАВОД-НОВЫЙ, на старом месте
// скрытый симлинк — старый код работает, но новый код обязан брать пути отсюда, а не копировать
// строку «НЕЙРОНКА ЗАВОД НОВЫЙ» дальше. Копии этой строки — ровно то, из-за чего переезд папки
// требует симлинков вместо простого mv.
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');

const СТОЛ = path.join(os.homedir(), 'Desktop');
const ДОМ = path.join(СТОЛ, 'НЕЙРОНКА');
const СОКРОВИЩНИЦА = path.join(СТОЛ, 'СОКРОВИЩНИЦА-РИЛСЫ');
const ЗАВОД = path.join(ДОМ, 'ЗАВОД-НОВЫЙ');

/** Папка внутри НЕЙРОНКИ; создаётся при первом обращении. */
function вДоме(...куски) {
  const п = path.join(ДОМ, ...куски);
  fs.mkdirSync(п, { recursive: true });
  return п;
}

/** Годные рилсы (плоско) и отсев с причиной. */
const годные = () => { const п = path.join(СОКРОВИЩНИЦА, 'годные'); fs.mkdirSync(п, { recursive: true }); return п; };
const отсев = (причина) => { const п = path.join(СОКРОВИЩНИЦА, 'отсев', причина || 'разное'); fs.mkdirSync(п, { recursive: true }); return п; };

/**
 * Архив текущего залива — ЕДИНСТВЕННОЕ, что кладём на стол: владелец перетаскивает его руками
 * в магос, и искать его в глубине папок ему неудобно. После залива уносить в НЕЙРОНКА/ЗАЛИВЫ-АРХИВ.
 */
// ВРЕМЕННОЕ (архивы под залив, паки ав, треки на прослушку) — НЕ НА СТОЛ (15.08, владелец:
// «я же просил, чтобы рабочий стол был чистый, сделай папку временные файлы»). Стол = три папки.
const ВРЕМЕННЫЕ = path.join(ДОМ, 'ВРЕМЕННЫЕ');
const вЗалив = (имя) => { fs.mkdirSync(ВРЕМЕННЫЕ, { recursive: true }); return path.join(ВРЕМЕННЫЕ, имя); };
const воВременные = вЗалив;

// НАШ РИЛС УЗНАЁТСЯ ПО ИМЕНИ, ВСЁ ОСТАЛЬНОЕ — ЧУЖОЕ (15.08, инцидент: сокровищница собрала все mp4
// со стола, в том числе ЛИЧНЫЕ видео владельца из СТОЛ-АРХИВ и тестовые ДО/ПОСЛЕ, и 19 таких ушли
// на аккаунты в порциях). Три схемы имён, которые рождает наш конвейер: reel_NN_..., <девочка>-<шаблон>-pN,
// u_NN_reel_... (уникализированные). Файл, не подходящий ни под одну, в годные и в залив не попадает.
const нашРилс = (имя) => /^reel_\d+_/.test(имя) || /-p\d\.mp4$/.test(имя) || /^u_\d+_reel_/.test(имя);
module.exports = { нашРилс, СТОЛ, ДОМ, СОКРОВИЩНИЦА, ЗАВОД, ВРЕМЕННЫЕ, вДоме, годные, отсев, вЗалив, воВременные };
