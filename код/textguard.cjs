'use strict';
// ЕСТЬ ЛИ НА КАДРЕ ЧУЖАЯ НАДПИСЬ, И В КАКОЙ ПОЛОСЕ.
//
// ЗАЧЕМ. 11.08 на живом аккаунте виден брак: наш хук лёг ПОВЕРХ чужой надписи, и текст читается
// кашей («этот ка я себе тут нравлюсь ракций, чем всё ч впервые за год ла за год»). Причина не в
// рендере: хук всегда садится в НИЗ кадра, а исходники мы берём с пинтереста и из поиска, где на
// половине картинок подпись уже нарисована, чаще всего снизу.
//
// ПОЧЕМУ ЗДЕСЬ РАСПОЗНАВАНИЕ ТЕКСТА, А НЕ ПОДСЧЁТ ПЯТЕН. Первый вариант считал плотность мелких
// контрастных пятен с пропорциями букв, и это оказалось негодным: замер на семи кадрах дал 26
// «букв» на фотографии девушки в свитере и 19 на вечернем селфи, то есть вязка и волосы читались
// как подпись, и гейт браковал чистые кадры. Теперь текст читается по-настоящему (easyocr, русский
// и английский, на процессоре), и цифра отвечает ровно на заданный вопрос. Проверено на тех же
// кадрах: на наших обложках с хуком текст найден и прочитан дословно, на свитере ноль строк.
const { spawnSync } = require('node:child_process');
const path = require('node:path');

const PY = `
import sys, json, warnings
warnings.filterwarnings('ignore')
import easyocr, cv2

# Читатель поднимается один раз на весь список файлов: инициализация это несколько секунд, а сам
# разбор кадра меньше секунды, поэтому пачкой звать в разы дешевле, чем по одному.
r = easyocr.Reader(['ru', 'en'], gpu=False, verbose=False)
out = []
for путь in sys.argv[1:]:
    im = cv2.imread(путь, cv2.IMREAD_COLOR)
    if im is None:
        out.append({"файл": путь, "ошибка": "не декодируется"})
        continue
    H = im.shape[0]
    Ш = im.shape[1]
    строки = []
    клочья = []
    for box, текст, увер in r.readtext(путь):
        # ЧТО СЧИТАЕМ НАДПИСЬЮ. Порога уверенности мало: на кадре 008 easyocr с уверенностью выше
        # 0.35 прочитал из текстуры «Ент» и «Нтнои», и гейт зря переставил хук наверх. Поэтому
        # строка должна ВЫГЛЯДЕТЬ СЛОВОМ: не короче 4 знаков, с гласной внутри и с уверенностью от
        # 0.45. Живые подписи это проходят легко (замер: 0.58, 0.63, 0.69, 0.74, 0.78), а буквенный
        # мусор из вязки и блёсток отсекается.
        т = текст.strip()
        if len(т) < 4:
            continue
        if not any(г in т.lower() for г in 'аеёиоуыэюяaeiouy'):
            continue
        ys = [точка[1] for точка in box]
        xs = [точка[0] for точка in box]
        центр = (min(ys) + max(ys)) / 2.0 / float(H)
        # ЛЕВО и ПРАВО в ПИКСЕЛЯХ добавлены 11.08 для гейта рилсов (reelgate.cjs): там надо знать не
        # «есть ли надпись», а «не упирается ли она в край кадра». Живой брак: хук, нарисованный в
        # 4:5, при заливке в 9:16 терял по 160 px с каждой стороны, и в ленту уехало «вший лайкнул
        # через год молчан». Поля меряются только по координатам, поэтому они тут.
        строка = {"текст": т[:60], "увер": round(float(увер), 2),
                  "центр": round(float(центр), 3),
                  "лево": int(min(xs)), "право": int(max(xs)),
                  "верх_px": int(min(ys)), "низ_px": int(max(ys))}
        if увер >= 0.45:
            строки.append(строка)
        elif увер >= 0.18:
            # КЛОЧЬЯ (12.08, дыра с рилсом Дарьи). Чем СИЛЬНЕЕ обрезан текст, тем НИЖЕ уверенность
            # распознавания: срезанную с двух сторон строку «друга не поверила, что это я са» easyocr
            # читает с уверенностью 0.29, и порог 0.45 выбрасывал её целиком. Гейт получал «строк 0»
            # и пропускал самый тяжёлый брак, ловя только лёгкий. Поэтому недоуверенные находки не
            # выбрасываем, а отдаём отдельным списком: для решения «куда сажать хук» они по-прежнему
            # не годятся (мусор из текстур), а для проверки «не упирается ли текст в край кадра»
            # это главная улика, и её дополнительно подтверждает касание края.
            клочья.append(строка)
    # Полосы: верхняя треть и нижняя треть кадра. Середину не считаем: хук туда не садится, а
    # надпись по центру это уже не «мешает хуку», это другой брак (его ловит отдел качества).
    верх = [с for с in строки if с["центр"] <= 0.34]
    низ = [с for с in строки if с["центр"] >= 0.66]
    out.append({"файл": путь, "всего": len(строки), "ширина": int(Ш), "высота": int(H),
                "верх": len(верх), "низ": len(низ),
                "строки": строки[:12], "клочья": клочья[:12]})
print(json.dumps(out, ensure_ascii=False))
`;

/**
 * Прочитать надписи на кадрах.
 * @param {string[]} файлы локальные пути
 */
function замерить(файлы) {
  const r = spawnSync('python3', ['-c', PY, ...файлы],
    { encoding: 'utf8', maxBuffer: 32 * 1024 * 1024, timeout: 15 * 60000 });
  if (r.status !== 0) {
    throw new Error(`чтение надписей не выполнилось: ${String(r.stderr || r.stdout).slice(0, 300)}`);
  }
  try { return JSON.parse(r.stdout); } catch {
    throw new Error(`чтение надписей вернуло не json: ${String(r.stdout).slice(0, 200)}`);
  }
}

/**
 * Куда сажать хук на этом кадре.
 * @returns {{место:'низ'|'верх'|'нет', низ:number, верх:number, строки:object[], почему:string}}
 *   'нет' означает, что обе полосы заняты чужим текстом и кадр под обложку не годится.
 * Замер не вышел (нет python, нет модели) это НЕ повод рушить сборку: возвращаем 'низ', то есть
 * ведём себя ровно как до правки.
 */
function местоХука(файл) {
  let z;
  try { [z] = замерить([файл]); }
  catch (e) { return { место: 'низ', низ: 0, верх: 0, строки: [], почему: `замер не вышел: ${String(e.message).slice(0, 90)}` }; }
  if (!z || z.ошибка) return { место: 'низ', низ: 0, верх: 0, строки: [], почему: `замер не вышел: ${z && z.ошибка}` };
  const общее = { низ: z.низ, верх: z.верх, строки: z.строки || [] };
  if (!z.низ) return { место: 'низ', ...общее, почему: '' };
  if (!z.верх) {
    return { место: 'верх', ...общее,
      почему: `внизу чужая надпись (${z.низ} строк: ${(z.строки[0] || {}).текст || ''}), сажаю хук вверх` };
  }
  return { место: 'нет', ...общее,
    почему: `надписи и внизу (${z.низ}), и вверху (${z.верх}): кадр под обложку не годится` };
}

/**
 * НАША ЛИ ЭТО ОБЛОЖКА. Отвечает на вопрос «не подсунули ли волне её же готовый кадр».
 *
 * ЗАЧЕМ. Живой брак 11.08 на аккаунте Карины: на обложке ДВА наших хука один поверх другого,
 * «этот кадр собрал больше реакций, чем всё что я выкладывала за год» и «я себе тут нравлюсь,
 * впервые за год». Это фразы из НАШЕГО пула, из двух разных постов от 6 и 9 августа. Значит готовая
 * обложка одного поста попала в пул исходников и волна нарисовала на ней второй хук. Переставить
 * надпись наверх тут мало: кадр уже использован, его нельзя брать вообще, иначе нарушается правило
 * «один пост, один аккаунт».
 *
 * КАК СУДИМ. Сравниваем прочитанные строки с пулом хуков по первым четырём словам: распознавание
 * путает буквы, но порядок слов сохраняет, поэтому точное совпадение строки требовать нельзя.
 */
function нашХук(файл) {
  let строки = [];
  try {
    const [z] = замерить([файл]);
    строки = (z && z.строки) || [];
  } catch { return { наш: false, фраза: '', почему: 'замер не вышел' }; }
  if (!строки.length) return { наш: false, фраза: '' };
  const норм = (s) => String(s).toLowerCase().replace(/[^а-яёa-z0-9 ]+/gi, ' ').replace(/\s+/g, ' ').trim();
  const начало = (s) => норм(s).split(' ').slice(0, 4).join(' ');
  let пул = [];
  try {
    const H = require('./hooks.cjs');
    пул = [...Object.values(H.POOLS || {}), ...Object.values(H.POOLS_TT || {})].flat()
      .map((x) => (typeof x === 'string' ? x : (x && (x.text || x.hook)) || '')).filter(Boolean);
  } catch { пул = []; }
  const начала = new Set(пул.map(начало).filter((s) => s.split(' ').length >= 3));
  for (const с of строки) {
    const н = начало(с.текст);
    if (н.split(' ').length >= 3 && начала.has(н)) return { наш: true, фраза: с.текст };
  }
  return { наш: false, фраза: '' };
}

module.exports = { замерить, местоХука, нашХук };

if (require.main === module) {
  const файлы = process.argv.slice(2);
  if (!файлы.length) { console.log('дай пути к кадрам'); process.exit(1); }
  for (const z of замерить(файлы)) {
    if (z.ошибка) { console.log(`${path.basename(z.файл)}: ${z.ошибка}`); continue; }
    const м = z.низ ? (z.верх ? 'нет' : 'верх') : 'низ';
    console.log(`${path.basename(z.файл)}: строк ${z.всего} (верх ${z.верх}, низ ${z.низ}) → место ${м}`
      + (z.строки.length ? ` | ${z.строки.map((с) => с.текст).slice(0, 2).join(' / ')}` : ''));
  }
}
