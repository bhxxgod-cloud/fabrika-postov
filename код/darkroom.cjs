/**
 * Промпт кадра 4 в тёмной или неоновой комнате.
 *
 * Собирает ОБЫЧНЫЙ промпт кадра 4 через pk.lookPrompt (то есть все предохранители личности,
 * типажа, селфи-блока и запрета транспорта остаются на месте) и подменяет в нём один блок фона.
 *
 * @param {object} o
 * @param {object} o.variant запись из DARK или NEON
 * @param {string} o.template ключ шаблона (карточный, например img-beauty-guide)
 * @param {string} [o.srcHair] цвет волос исходника, как в onepost
 * @param {number} [o.hairIdx] индекс целевого цвета волос
 * @param {number} [o.hairLenIdx] индекс длины волос
 * @param {string} [o.poseSeed] семя разведения позы (отпечаток исходника)
 * @returns {string} готовый промпт
 */
function darkPrompt({ variant, template = 'img-beauty-guide', srcHair = 'auto', hairIdx = 0,
  hairLenIdx = 0, poseSeed = '', selfie = false, phone = false, mirror = false } = {}) {
  if (!variant || !variant.place) throw new Error('darkroom: не передан вариант из пула DARK или NEON');
  const bg = BGS[variant.bg];
  if (!bg) throw new Error(`darkroom: у варианта «${variant.slug}» неизвестный блок фона «${variant.bg}»`);
  const базовый = pk.lookPrompt({ template, step: 4, srcHair, hairIdx, hairLenIdx,
    place: variant.place, light: variant.light, bgMode: 'quiet', poseSeed });
  if (!базовый.includes(pk.QUIET_BG)) {
    // Молчаливая неудача тут это оплаченный заказ со старым ровным светом, то есть выброшенные
    // деньги и потерянный смысл всей затеи. Поэтому падаем.
    throw new Error('darkroom: в промпте кадра 4 не нашёлся блок QUIET_BG, promptkit изменился. '
      + 'Проверь BG_MODES.quiet и подмену в darkPrompt, тихо отдавать промпт со старым светом нельзя');
  }
  // ВТОРОЙ КРУГ ВСЕГДА ИДЁТ С ПЛОХОЙ КАМЕРОЙ: приговор «слишком хорошее качество» относится ко всем
  // новым кадрам, а не к отдельным вариантам, поэтому строка приклеена к самим блокам фона второго
  // круга, а не выставлена наружу отдельной ручкой (лишняя ручка это лишний способ забыть её нажать).
  const bg2 = (variant.bg === 'corner' || variant.bg === 'black' || variant.bg === 'etalon')
    ? `${bg} ${FRONTCAM}` : bg;
  let готовый = базовый.replace(pk.QUIET_BG, bg2);
  // ГЕОМЕТРИЯ СЪЁМКИ. Строку ставим СРАЗУ ЗА БЛОКОМ ФОНА, то есть уже после всех слов про место и
  // свет и до блока качества: она про точку съёмки, а не про человека, и рядом с фоном ей место.
  if (selfie || phone || mirror) готовый = готовый.replace(bg2, `${bg2} ${SELFIE_HARD}`);
  if (phone || mirror) {
    for (const { было, стало } of СПОРНЫЕ) {
      if (!готовый.includes(было)) {
        throw new Error(`darkroom: в промпте не нашёлся кусок «${было.slice(0, 40)}…», promptkit `
          + 'изменился. Телефон в кадре без снятия этого запрета не заказываем: два спорящих '
          + 'требования модель решает в свою пользу, то есть деньги уйдут на кадр без телефона');
      }
      готовый = готовый.replace(было, стало);
    }
    // У двух вариантов свет идёт от экрана, и там СВОИМИ СЛОВАМИ сказано, что телефон в кадр не
    // попадает (иначе он спорил бы с общим запретом). В режиме телефона эта оговорка обязана уйти,
    // иначе промпт спорит сам с собой в двух соседних фразах. Замена мягкая: оговорка есть не у всех
    // вариантов, и её отсутствие это не поломка promptkit, а просто другой вариант.
    готовый = готовый.replace(', САМ ТЕЛЕФОН В КАДР НЕ ПОПАДАЕТ', '')
      .replace(' САМ ТЕЛЕФОН В КАДР НЕ ПОПАДАЕТ:', '');
    готовый = готовый.replace(SELFIE_HARD, `${SELFIE_HARD} ${mirror ? MIRROR_LINE : PHONE_LINE}`);
  }
  return готовый;
}

