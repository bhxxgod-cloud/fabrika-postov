// СТОРОЖ СТАТИЧНОГО ХРОМА (11.08, разбор /tmp/wave7.log). Сделан по образцу viewsguard.cjs.
//
// ЗАЧЕМ. Волна постов вся сидит на служебном headless-Chrome с портом CDP 9666: заливка референса,
// заказ на фабрике, опрос рендера, вёрстка кадров. Когда этот браузер портится, волна не встаёт, а
// продолжает жечь исходники: замер /tmp/wave7.log — 153 попытки, 71 готов, 82 «брака», и 66 из этих
// 82 это просто «статичный Chrome не поднялся на порту 9666». Ни один из 66 не был браком качества,
// и ни один не потратил денег.
//
// ГЛАВНЫЙ УРОК ЗАМЕРА: curl /json/version НЕ ЯВЛЯЕТСЯ ПРОВЕРКОЙ ЖИВОСТИ.
// В момент разбора порт отвечал 200 за 0.0003 с, а playwright не мог подключиться вообще:
//   connectOverCDP таймаут 4 с → провал за 5 с (вебсокет соединился, дальше тишина)
//   connectOverCDP таймаут 90 с → OK за 28.8 с, страниц 26
//   после уборки вкладок → не подключился и за 110 с
//   свежий браузер → OK за 178 мс
// То есть HTTP-ручки браузера обслуживаются отдельно и живут даже у полумёртвого Chrome. Поэтому
// сторож стучит ДВАЖДЫ: сначала дешёвым HTTP (есть ли порт), потом настоящим подключением CDP —
// именно им работает волна, и только он говорит правду.
//
// ЧТО СТОРОЖ ДЕЛАЕТ И ЧЕГО НЕ ДЕЛАЕТ.
//   • Три неудачных отстука подряд → поднимает служебный Chrome тем же способом, что adminbrowser.cjs
//     (общий код, не копия: поднятьЕслиНужно там же под файловым локом, так что сторож и волна не
//     поднимут два браузера).
//   • Если порт есть, а подключение мертво, гасит РОВНО НАШ процесс: по pid, у которого в командной
//     строке и --user-data-dir=~/.neironka-admin-profile, и --remote-debugging-port=9666. Проверка по
//     обоим признакам, и только потом kill по этому pid.
//   • НИКАКОГО pkill по Chrome и НИКАКОГО pkill по Orbita. В окнах Chrome у начальника личные
//     профили, в Orbita живёт ферма аккаунтов; один такой pkill стоит рабочего дня. Правило старше
//     этой задачи и здесь не обсуждается.
//   • Попутно прибирает сиротские вкладки (у них своя грация и своё правило «последнюю не закрывать»,
//     см. adminbrowser.cjs): они и есть причина, по которой подключение из миллисекунд превращается
//     в десятки секунд.
//
// Запуск: nohup node chromeguard.cjs >> /tmp/chromeguard.log 2>&1 &
'use strict';
const fs = require('fs');
const { execSync } = require('child_process');
const admin = require('./adminbrowser.cjs');

// Путь лога через окружение нужен ровно для одного: проверить сам сторож на отдельном порту и
// отдельном профиле, не пачкая рабочий лог и не трогая рабочий браузер.
const ЛОГ = process.env.CHROMEGUARD_LOG || '/tmp/chromeguard.log';
const ПОРОГ_ПРОВАЛОВ = Number(process.env.CHROMEGUARD_FAILS || 3);
const ПАУЗА_МС = Number(process.env.CHROMEGUARD_EVERY_MS || 60000);
// Сколько ждём настоящего подключения на отстуке. Здесь нужен КОРОТКИЙ порог, а не рабочие 90 с:
// сторож проверяет здоровье, а не работает. Живой браузер отвечает за сотни миллисекунд, и 25 с это
// уже «болеет» — как раз тот случай, когда волна ещё не падает, но каждый пост теряет полминуты.
const ПРОБА_МС = Number(process.env.CHROMEGUARD_PROBE_MS || 25000);

// ПИШЕМ В ЛОГ ОДИН РАЗ. Запускают сторожа через «nohup … >> /tmp/chromeguard.log», то есть stdout уже
// и есть этот файл: с console.log каждая строка ложилась в лог дважды и читать его было противно.
// В терминале (tty) наоборот печатаем, чтобы при запуске руками было видно, что происходит.
const пиши = (s) => {
  const строка = `[${new Date().toISOString()}] ${s}`;
  if (process.stdout.isTTY) console.log(строка);
  try { fs.appendFileSync(ЛОГ, строка + '\n'); } catch {}
};

/** Настоящая проба: подключаемся так же, как это делает волна. Возвращает {ok, мс, страниц, почему}. */
async function проба() {
  const t0 = Date.now();
  if (!(await admin.портОтвечает(5000))) return { ok: false, мс: Date.now() - t0, почему: 'порт не отвечает' };
  let browser = null;
  try {
    const { chromium } = require('playwright-core');
    browser = await chromium.connectOverCDP(admin.CDP, { timeout: ПРОБА_МС });
    const ctx = browser.contexts()[0];
    const страниц = ctx ? ctx.pages().length : 0;
    return { ok: true, мс: Date.now() - t0, страниц };
  } catch (e) {
    return { ok: false, мс: Date.now() - t0, почему: `CDP: ${String(e.message).split('\n')[0].slice(0, 90)}` };
  } finally {
    // Отцепляемся, НЕ ЗАКРЫВАЯ браузер: browser.close() для CDP-соединения гасит общее окно, а это
    // ровно то, что запрещено (окно статично и живёт для всех скриптов).
    if (browser && typeof browser.disconnect === 'function') await browser.disconnect().catch(() => {});
  }
}

// Метка нашего профиля в командной строке: имя папки профиля, каким его знает adminbrowser.
// Через env берём то же значение, что и он, иначе сторож на тестовом профиле искал бы рабочий.
const ПРОФИЛЬ_МЕТКА = require('node:path').basename(process.env.ADMIN_PROFILE || '.neironka-admin-profile');

/**
 * ЭТО САМ БРАУЗЕР, А НЕ ЕГО ХЕЛПЕР. Проверка обязательна и найдена на живом замере: хелперы Chrome
 * (renderer, gpu-process, utility) НАСЛЕДУЮТ всю командную строку родителя, то есть и
 * --user-data-dir=…/.neironka-admin-profile, и --remote-debugging-port=9666. Без этой проверки поиск
 * «нашего» процесса возвращал шесть pid вместо одного, и сторож послал бы SIGTERM рендереру. Главный
 * процесс отличается двумя вещами: у него нет --type= и он не лежит в папке Helpers.
 */
function главныйПроцесс(s) {
  if (s.includes('--type=')) return false;
  if (s.includes('/Helpers/')) return false;
  return /\/Contents\/MacOS\/(Google Chrome|Chromium) /.test(s);
}

/**
 * pid НАШЕГО служебного Chrome. Ищем по трём признакам одновременно (профиль, порт, главный процесс),
 * поэтому ни чужой Chrome, ни хелпер под эту проверку не попадают физически. Возвращает null, если
 * такого процесса нет.
 */
function нашPid() {
  try {
    const строки = execSync('ps ax -o pid=,command=', { encoding: 'utf8', maxBuffer: 8 << 20 }).split('\n');
    for (const s of строки) {
      if (!s.includes(ПРОФИЛЬ_МЕТКА)) continue;
      if (!s.includes(`--remote-debugging-port=${admin.PORT}`)) continue;
      if (!главныйПроцесс(s)) continue;
      const pid = Number(s.trim().split(/\s+/)[0]);
      if (pid > 0) return pid;
    }
  } catch (e) { пиши(`не смог перечислить процессы: ${e.message}`); }
  return null;
}

// ОСТЫВАНИЕ МЕЖДУ ПЕРЕЗАПУСКАМИ. Если браузер не оживает, толку от перезапуска раз в минуту нет, а
// вреда много: волна каждый раз теряет вкладку на полуслове. Проверено на себе: с заведомо
// невыполнимой пробой сторож дёргал Chrome каждые 8 секунд. Поэтому чаще, чем раз в 5 минут, не лезем
// и честно пишем в лог, что ждём.
const ОСТЫВАНИЕ_МС = Number(process.env.CHROMEGUARD_COOLDOWN_MS || 5 * 60000);
let последнийПодъём = 0;

async function поднять(почему) {
  const прошло = Date.now() - последнийПодъём;
  if (последнийПодъём && прошло < ОСТЫВАНИЕ_МС) {
    пиши(`НЕ поднимаю (${почему}): прошлый подъём был ${Math.round(прошло / 1000)} с назад, `
      + `остывание ${Math.round(ОСТЫВАНИЕ_МС / 1000)} с. Если так повторяется, дело не в подъёме: смотреть надо руками`);
    return;
  }
  последнийПодъём = Date.now();
  пиши(`ПОДНИМАЮ служебный Chrome: ${почему}`);
  const pid = нашPid();
  if (pid) {
    // Порт есть, а подключиться нельзя: браузер испорчен, и другого способа, кроме перезапуска, нет.
    // Гасим ТОЛЬКО этот pid и ТОЛЬКО убедившись в обоих признаках (это уже сделано в нашPid).
    пиши(`  наш служебный Chrome это pid ${pid} (профиль ${ПРОФИЛЬ_МЕТКА}, порт ${admin.PORT}, главный процесс, `
      + 'не хелпер) — гашу РОВНО ЭТОТ pid, чужое не трогаю');
    try { process.kill(pid, 'SIGTERM'); } catch (e) { пиши(`  kill не удался: ${e.message}`); }
    for (let i = 0; i < 15; i++) {
      await new Promise((r) => setTimeout(r, 1000));
      let жив = true; try { process.kill(pid, 0); } catch { жив = false; }
      if (!жив) break;
    }
  } else {
    пиши('  своего процесса Chrome не нашёл: просто поднимаю новый');
  }
  const итог = await admin.поднятьЕслиНужно();
  пиши(`  подъём: ${итог}`);
  const п = await проба();
  пиши(п.ok ? `  ✅ подключение живое за ${п.мс} мс, страниц ${п.страниц}`
    : `  ⚠ после подъёма подключиться так и не вышло (${п.почему})`);
}

let провалов = 0;
пиши(`сторож встал: отстук раз в ${Math.round(ПАУЗА_МС / 1000)} с, порог ${ПОРОГ_ПРОВАЛОВ} провала подряд, `
  + `проба подключения ${Math.round(ПРОБА_МС / 1000)} с, порт ${admin.PORT}`);

let занят = false;
async function отстук() {
  if (занят) return;   // подъём длиннее минуты: второй отстук в это время только мешает
  занят = true;
  try {
    const п = await проба();
    if (п.ok) {
      провалов = 0;
      const убрано = await admin.прибратьСиротские().catch(() => ({ closed: 0, total: 0 }));
      пиши(`отстук: живой, подключение ${п.мс} мс, страниц ${п.страниц}`
        + (убрано.closed ? `, прибрал сиротских вкладок ${убрано.closed} из ${убрано.total}` : ''));
      return;
    }
    провалов++;
    пиши(`отстук: ПРОВАЛ ${провалов} из ${ПОРОГ_ПРОВАЛОВ} за ${п.мс} мс — ${п.почему}`);
    if (провалов >= ПОРОГ_ПРОВАЛОВ) {
      await поднять(`${провалов} провала отстука подряд`);
      провалов = 0;
    }
  } catch (e) { пиши(`отстук сорвался сам: ${e.message}`); }
  finally { занят = false; }
}

отстук();
setInterval(отстук, ПАУЗА_МС);
