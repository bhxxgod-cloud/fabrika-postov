#!/bin/bash
# АВТОНОМНОСТЬ УБОРЩИКА АККОВ — круг раз в час, 24/7.
#
# ПОЧЕМУ ЦИКЛ, А НЕ КРОН. Проверено 06.08: крон на этом маке НЕ МОЖЕТ читать ~/Desktop. И
# /usr/sbin/cron, и launchd-агент получают EPERM на readdir внутри папки проекта (macOS TCC: у
# планировщика нет Full Disk Access). Ровно поэтому давно стоявшая крон-запись со stats.cjs не
# сработала ни разу — в /tmp/stats.log лежит только «EPERM: process.cwd failed». Цикл запускается
# из обычной сессии, права у него есть. Когда начальник выдаст крону Full Disk Access
# (Системные настройки → Конфиденциальность → Полный доступ к диску → /usr/sbin/cron),
# этот цикл можно будет заменить крон-записью.
#
# СИНГЛТОН СДЕЛАН НАРОЧНО НЕ ЧЕРЕЗ pgrep. В runners3.sh сторож написан как
#   pgrep -f "RUNNER_ID=$N node localrunner.cjs"
# и не срабатывает НИКОГДА: присваивание переменной окружения выполняет шелл, в argv процесса его
# нет, шаблон не совпадает — и раннеры плодятся. Здесь замок это КАТАЛОГ: mkdir атомарен, гонки
# двух запусков в одну секунду не существует. Владельца проверяем двумя независимыми способами:
# kill -0 (процесс жив) и `ps -o command=` (это действительно наш цикл, а не переиспользованный pid).
#
# Запуск:  nohup ./accjanitorloop.sh >/dev/null 2>&1 &      (лог /tmp/accjanitor.log)
# Стоп:    kill "$(cat /tmp/accjanitorloop.lock/pid)"
# Режим:   JANITOR_MODE=dry ./accjanitorloop.sh   — круги без починки (только отчёты)
set -u
DIR="/Users/qq/Desktop/neironka-poster"
LOG="${JANITOR_LOG:-/tmp/accjanitor.log}"
LOCKDIR="/tmp/accjanitorloop.lock"
EVERY="${JANITOR_EVERY:-3600}"        # круг раз в час: внешние чеки дешёвые, вход в акки редкий
MODE="${JANITOR_MODE:-fix}"           # fix = чинит безопасное; dry = только смотрит

cd "$DIR" || exit 1

if ! mkdir "$LOCKDIR" 2>/dev/null; then
  OLD="$(cat "$LOCKDIR/pid" 2>/dev/null || echo '')"
  if [ -n "$OLD" ] && kill -0 "$OLD" 2>/dev/null && ps -o command= -p "$OLD" 2>/dev/null | grep -q accjanitorloop; then
    echo "$(date '+%F %T') цикл уборщика уже работает (pid $OLD) — выхожу" >> "$LOG"
    exit 0
  fi
  # Владельца нет (упал или pid переиспользован) — замок снимаем сами, иначе один аварийный
  # выход выключил бы автономность навсегда.
  rm -rf "$LOCKDIR" && mkdir "$LOCKDIR" || exit 1
fi
echo $$ > "$LOCKDIR/pid"
# Замок снимаем на ЛЮБОМ выходе, включая Ctrl-C и kill: висящий замок это тихо выключенная уборка.
# Заодно гасим ТЕКУЩЕГО ребёнка (круг или sleep) — иначе цикл не останавливается, см. ниже.
CHILD=""
cleanup() { [ -n "$CHILD" ] && kill "$CHILD" 2>/dev/null; rm -rf "$LOCKDIR"; }
trap 'cleanup; exit 0' INT TERM
trap 'cleanup' EXIT

# ПОЧЕМУ ЧЕРЕЗ `& wait`, А НЕ ПРОСТО КОМАНДОЙ. Пока bash ждёт обычную команду переднего плана, он
# ОТКЛАДЫВАЕТ обработчик сигнала до её конца: цикл со `sleep 3600` на обычный `kill` не реагирует
# целый час, и «остановил уборщика» на деле означает «он ещё работает». Проверено на приёмке 06.08
# дважды: сперва на часовом сне, потом на FIRST_SLEEP — `kill` пришлось добивать до -9.
# С фоновым запуском и `wait` обработчик срабатывает сразу, поэтому ТАК ПУСКАЕТСЯ ВСЁ, включая
# первый сон: команда, которую нельзя прервать, не должна существовать в этом файле вовсе.
run() { "$@" & CHILD=$!; wait "$CHILD" 2>/dev/null; CHILD=""; }

# FIRST_SLEEP — не гнать круг в первую же секунду после старта: если прогон только что был руками,
# внешние запросы и платная сверка лиц повторились бы впустую.
[ -n "${FIRST_SLEEP:-}" ] && run sleep "$FIRST_SLEEP"

ARGS=""
[ "$MODE" = "fix" ] && ARGS="--fix"

while true; do
  # Лог не должен расти вечно: 24 круга в сутки по ~15 КБ отчёта. Свежий хвост сохраняем.
  if [ -f "$LOG" ] && [ "$(wc -c < "$LOG")" -gt 5000000 ]; then
    tail -n 2000 "$LOG" > "$LOG.tmp" && mv "$LOG.tmp" "$LOG"
  fi
  echo "=== $(date '+%F %T') круг уборщика ($MODE) ===" >> "$LOG"
  # Круг сам держит свой замок (/tmp/accjanitor.lock) и сам решает, пора ли платная сверка лиц
  # (accheck раз в 6 часов) — здесь ничего дополнительно троттлить не надо.
  run node accjanitor.cjs $ARGS >> "$LOG" 2>&1
  echo "=== $(date '+%F %T') круг закончен, следующий через ${EVERY}с ===" >> "$LOG"
  run sleep "$EVERY"
done
