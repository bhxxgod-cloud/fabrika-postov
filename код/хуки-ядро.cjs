'use strict';
// ЯДРО ПОДБОРА ХУКОВ без базы и без консоли: одна логика на CLI (хук.cjs) и на панель (API).
// Раньше логика жила внутри CLI, и кнопка в панели неизбежно получила бы свою копию правил.
const fs = require('fs');
const path = require('path');
const { регистр: РЕГИСТР } = require('./регистр.cjs');

const ПУЛ = JSON.parse(fs.readFileSync(path.join(__dirname, 'хуки-владельца-пул.json'), 'utf8'));
const ШАБЛОНЫ = Object.keys(ПУЛ).filter((k) => !k.startsWith('_'));
const ВСЕ = [];
for (const t of ШАБЛОНЫ) for (const рег of ['крик', 'пов']) for (const h of ПУЛ[t][рег] || []) ВСЕ.push({ ...h, шаблон: t });
const ПО_ID = new Map(ВСЕ.map((h) => [h.id, h]));

// РЕГИСТР ЗАВИСИТ ОТ РОЛИ (правка главного чата, 25.08). На кадре и в подписи надпись всегда
// дневниковая: крик с восклицаниями читается там как реклама и убивает доверие. В заголовке
// ютуба наоборот, дневник не цепляет, работает обвинение.
const РЕГИСТР_РОЛИ = { подпись: 'пов', кадр: 'пов', заголовок: 'крик', превью: 'крик' };
function регистрДляРоли(роль, площадка) {
  if (площадка === 'youtube') return РЕГИСТР_РОЛИ[роль] || 'крик';
  return роль === 'заголовок' ? 'крик' : 'пов';
}

function шаблонИзКлюча(ключ) {
  const s = String(ключ || '').toLowerCase();
  return ШАБЛОНЫ.slice().sort((a, b) => b.length - a.length).find((t) => s.includes(t)) || null;
}

const СТОП = new Set(['это','что','тебя','твой','твоя','твоё','твои','себя','мне','моя','мой','моё','как','так','его','она','они','уже','всё','все','вот','ещё','был','была','было','если','после','из-за','не','на','и','а','в','с','по','за','до','от','ты','я','бы','же','мои','нет','там','этот','эта','эту','тот']);
// Числа отдельным токеном: «10/10» распадается на два коротких «10», и фильтр длины их выбрасывал.
// Из-за этого под подпись «Ты не на 10/10» на превью лезло «Что мешает быть на 10/10».
function ЯДРО(t) {
  const out = new Set();
  for (const w of String(t).toLowerCase().replace(/ё/g, 'е').replace(/[^а-яa-z0-9\s\/-]/gi, ' ').split(/\s+/).filter(Boolean)) {
    if (/\d/.test(w)) { out.add('ЧИСЛО:' + w.replace(/[^0-9\/]/g, '')); continue; }
    if (w.length > 3 && !СТОП.has(w)) out.add(w.slice(0, 6));
  }
  return out;
}
const ПЕРЕСЕК = (a, b) => { for (const w of a) if (b.has(w)) return true; return false; };

// Совместимые: тот же шаблон, тот же регистр, без пересечения значимых слов с уже занятыми.
// Короткие вперёд: на превью нужно то, что читается за полсекунды.
function совместимые(шаблон, занятыеТексты, регХочу) {
  const рег = регХочу || (занятыеТексты.length ? РЕГИСТР(занятыеТексты[0]) : null);
  const ядра = занятыеТексты.map(ЯДРО);
  return ВСЕ.filter((h) => h.шаблон === шаблон)
    .filter((h) => !занятыеТексты.includes(h.т))
    .filter((h) => (рег ? РЕГИСТР(h.т) === рег : true))
    .filter((h) => !ядра.some((я) => ПЕРЕСЕК(ЯДРО(h.т), я)))
    .sort((a, b) => a.т.length - b.т.length);
}

// Выбор с учётом истории: реже использованные вперёд, иначе один хук уйдёт во все посты подряд.
function выбрать({ шаблон, занятыеВсюду = [], занятыеПлощадки = [], роль = 'подпись', площадка = 'tiktok', частота = new Map() }) {
  const хочу = занятыеПлощадки.length ? null : регистрДляРоли(роль, площадка);
  let канд = совместимые(шаблон, занятыеВсюду, хочу);
  if (!канд.length && хочу) канд = совместимые(шаблон, занятыеВсюду, null);   // регистр кончился — берём что есть
  if (!канд.length) return null;
  канд.sort((a, b) => (частота.get(a.id) || 0) - (частота.get(b.id) || 0) || a.т.length - b.т.length);
  const выбран = канд[0];
  const запас = канд.slice(1).filter((h) => РЕГИСТР(h.т) === РЕГИСТР(выбран.т)).slice(0, 3);
  return { выбран, запас };
}

module.exports = { ПУЛ, ШАБЛОНЫ, ВСЕ, ПО_ID, РЕГИСТР, регистрДляРоли, шаблонИзКлюча, совместимые, выбрать, ЯДРО };
