const lanePath = (n) => (n === 0 ? LOCK : `${LOCK}.${n}`);
let myLane = null;
async function takeLock(waitMs = 40 * 60000) {
  const until = Date.now() + waitMs;
  for (;;) {
    for (let n = 0; n < LANES; n++) {
      const p = lanePath(n);
      // PID пишем С ПЕРЕВОДОМ СТРОКИ (13.08): без него cat по нескольким замкам слипал номера в
      // кашу вида «1247512281…», проверка «держит ли процесс замок» молчала, и сегодня за это
      // дважды убили РАБОТАВШИЕ сборки, приняв их за ждущих в очереди.
      try { fs.writeFileSync(p, `${process.pid}\n`, { flag: 'wx' }); myLane = p; return; }
      catch {
        // ГОНКА ЖДУЩИХ (13.08): между «занято» и чтением файла сосед мог снести протухший лок,
        // и readFileSync падал ENOENT, роняя всю сборку на шаге взятия лока. Файла нет — полоса
        // свободна, пробуем её же ещё раз.
        let содержимое = null;
        try { содержимое = fs.readFileSync(p, 'utf8'); } catch { n--; continue; }
        const pid = Number(содержимое.trim() || 0);
        // pid ноль или мусор это НЕ живой держатель: kill(0, 0) сигналит всей своей группе
        // процессов и всегда «жив», из-за чего пустой файл замка держал полосу все 45 минут
        // протухания (13.08).
        let alive = false; try { if (pid > 0) { process.kill(pid, 0); alive = true; } } catch {}
        let stale = false; try { stale = Date.now() - fs.statSync(p).mtimeMs > 45 * 60000; } catch {}
        // Полосу освобождаем, только если держатель мёртв или лок совсем старый: иначе это чужая
        // живая сборка, и лезть в неё нельзя.
        if (!alive || stale) { try { fs.unlinkSync(p); } catch {} n--; }
      }
    }
    if (Date.now() > until) throw new Error('конвейер занят, попробуй через пару минут');
    console.log(`  ⏳ жду освобождения конвейера (полос ${LANES})…`);
    await sleep(15000);
  }
}
