function ключ(файл) {
  return require('node:crypto').createHash('sha1')
    .update(ВЕРСИЯ_ПРОМПТА).update(fs.readFileSync(файл)).digest('hex');
}

async function спросить(файл) {
  const KEY = process.env.OPENROUTER_API_KEY;
  if (!KEY) return { ok: false, причина: 'нет OPENROUTER_API_KEY' };
  const к = ключ(файл);
  const кэш = кэшЧитать();
  if (кэш[к]) return { ok: true, оценки: кэш[к], изКэша: true };
  const буф = fs.readFileSync(файл);
  const тип = path.extname(файл).toLowerCase() === '.png' ? 'png' : 'jpeg';
  const r = await fetch('https://openrouter.ai/api/v1/chat/completions', {
    method: 'POST',
    headers: { Authorization: `Bearer ${KEY}`, 'Content-Type': 'application/json' },
    body: JSON.stringify({
      model: MODEL, max_tokens: 300, temperature: 0,
      messages: [{ role: 'system', content: SYSTEM }, { role: 'user', content: [
        { type: 'text', text: 'Годится ли этот кадр на аватарку?' },
        { type: 'image_url', image_url: { url: `data:image/${тип};base64,${буф.toString('base64')}` } }] }],
    }),
    signal: AbortSignal.timeout(90000),
  }).catch((e) => ({ ok: false, _err: e.message }));
  if (!r || !r.ok) return { ok: false, причина: `модель не ответила${r && r.status ? ` (HTTP ${r.status})` : ''}` };
  const j = await r.json().catch(() => null);
  const t = j?.choices?.[0]?.message?.content || '';
  let о = null;
  try { о = JSON.parse((t.match(/\{[\s\S]*\}/) || ['null'])[0]); } catch { о = null; }
  if (!о) return { ok: false, причина: 'модель вернула не JSON' };
  кэшПисать(к, о);
  return { ok: true, оценки: о };
}

