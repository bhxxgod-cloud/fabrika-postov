/**
 * Проверить один файл на пригодность в аватарку.
 * @param {object} г запись геометрии из геометрия()
 * @param {object|null} рез запись резкости из cover_qa.резкость (может быть null)
 * @param {object|null} мод оценки модели (может быть null)
 * @returns {{годится:boolean, причины:string[], метка:string}}
 *   метка — короткое слово для имени файла в «браке», чтобы приговор читался с диска.
 */
function приговор(г, рез, мод) {
  const причины = [];
  const метки = [];
  if (г.ошибка) return { годится: false, причины: [г.ошибка], метка: 'нечитается' };

  if (г.квадрат > ДОПУСК_КВАДРАТА) {
    причины.push(`кадр не квадратный: ${г.ш}x${г.в} (расхождение ${(г.квадрат * 100).toFixed(0)}%) — `
      + 'инстаграм дорежет его по ЦЕНТРУ, а центр портрета это грудь, а не лицо');
    метки.push('не-квадрат');
  }
  if (!г.лицо_найдено) {
    причины.push('лица на кадре НЕ НАЙДЕНО: либо оно закрыто, либо кадр снят набок, либо лица там нет');
    метки.push('лица-нет');
  } else {
    if (г.доля_круга < ПОРОГ_ЛИЦО_КРУГ) {
      причины.push(`лицо мелкое: ${(г.доля_круга * 100).toFixed(0)}% диаметра круга `
        + `(<${(ПОРОГ_ЛИЦО_КРУГ * 100).toFixed(0)}%) — в ленте это ${Math.round(г.доля_круга * 32)} px`);
      метки.push('лицо-мелкое');
    }
    if (г.лицо_в_круге < ПОРОГ_ЛИЦО_В_КРУГЕ) {
      причины.push(`круг режет лицо: внутри окружности осталось ${(г.лицо_в_круге * 100).toFixed(0)}% `
        + `рамки лица (<${(ПОРОГ_ЛИЦО_В_КРУГЕ * 100).toFixed(0)}%), лицо ушло от центра на `
        + `${г.смещение.toFixed(2)} радиуса`);
      метки.push('круг-режет-лицо');
    }
    if (г.вторых_лиц > 0) {
      причины.push(`в кадре ещё ${г.вторых_лиц} заметное лицо — на аве читается как «их двое»`);
      метки.push('два-человека');
    }
  }
  // Мыло берём из cover_qa: ось от пропорций кадра не зависит, порог там выведен на 151 исходнике.
  if (рез && рез.метрики) {
    const м = рез.метрики;
    const мутный = м.кадр != null && м.кадр < CQA.ПОРОГ_КАДР;
    const мутноеЛицо = м.лицо != null && м.лицо < CQA.ПОРОГ_ЛИЦО;
    const спасли = м.глаза != null && м.глаза >= CQA.СПАС_ГЛАЗА;
    if (мутный && мутноеЛицо && !спасли) {
      причины.push(`мыло: кадр ${м.кадр} (<${CQA.ПОРОГ_КАДР}), лицо ${м.лицо} (<${CQA.ПОРОГ_ЛИЦО})`);
      метки.push('мыло');
    }
  }
  if (мод) {
    if (мод.plan === 'общий') { причины.push('общий план: на аве в 32 px героиня превратится в пятно'); метки.push('общий-план'); }
    if (Number.isFinite(мод.tilt_deg) && мод.tilt_deg >= ПОРОГ_НАКЛОН) {
      причины.push(`кадр снят набок: голова повёрнута на ${мод.tilt_deg}° (>=${ПОРОГ_НАКЛОН}°)`); метки.push('набок');
    }
    if (мод.ui_overlay) { причины.push('в кадре интерфейс Instagram или TikTok — это переснятый скриншот чужого поста'); метки.push('скриншот'); }
    if (Number.isFinite(мод.foreign_text_pct) && мод.foreign_text_pct >= ПОРОГ_ЧУЖОЙ_ТЕКСТ) {
      причины.push(`чужие надписи занимают ${мод.foreign_text_pct}% кадра (>=${ПОРОГ_ЧУЖОЙ_ТЕКСТ}%)`); метки.push('чужой-текст');
    }
    if (Number.isFinite(мод.second_person) && мод.second_person >= ПОРОГ_ВТОРОЙ) {
      причины.push(`второй человек заметен на ${мод.second_person}/10 — кадр читается как «их двое»`); метки.push('два-человека');
    }
    if (мод.explicit) { причины.push('откровенность'); метки.push('откровенно'); }
    if (Number.isFinite(мод.face_visible_pct) && мод.face_visible_pct < ПОРОГ_ВИДНО_ЛИЦО) {
      причины.push(`лицо закрыто: видно ${мод.face_visible_pct}% (порог ${ПОРОГ_ВИДНО_ЛИЦО}%)`); метки.push('лицо-закрыто');
    }
    // ПРОФИЛЬ отдельной осью: на круглой аве в 32 px профиль без второго глаза читается как затылок.
    // Ловится только так — доля видимого лица у профиля высокая, лицо ведь ничем не закрыто.
    if (мод.profile) { причины.push('строгий профиль: второго глаза не видно, на мелкой круглой аве это читается как затылок'); метки.push('профиль'); }
    if (мод.noisy) { причины.push('грубое зерно или следы апскейла: на мелкой аве это читается как грязь'); метки.push('шум'); }
    if (Number.isFinite(мод.sharp) && мод.sharp < ПОРОГ_РЕЗКОСТЬ) { причины.push(`модель видит мыло ${мод.sharp}/10 (порог ${ПОРОГ_РЕЗКОСТЬ})`); метки.push('мыло'); }
    if (Number.isFinite(мод.attractive) && мод.attractive < ПОРОГ_КРАСОТА) { причины.push(`слабая привлекательность ${мод.attractive}/10 (порог ${ПОРОГ_КРАСОТА})`); метки.push('слабая'); }
  }
  return {
    годится: причины.length === 0,
    причины,
    метка: метки.length ? [...new Set(метки)].join('+') : 'ок',
  };
}

/**
 * Проверить пачку файлов.
 * @param {string[]} файлы
 * @param {{безМодели?:boolean, поток?:number}} opts
 * @returns {Promise<object[]>} {файл, годится, причины, метка, гео, мод, непроверено}
 */
async function проверитьПачку(файлы, opts = {}) {
  const гео = геометрия(файлы);
  // Резкость считает cover_qa: та же питон-обвязка, тот же yunet, порог выведен на 151 исходнике.
  let рез = [];
  try { рез = CQA.резкость(файлы); } catch { рез = []; }
  const поРез = new Map(рез.map((r) => [r.ист, r]));

  const итог = new Array(файлы.length);
  const поток = Math.max(1, Number(opts.поток || process.env.AVA_QA_CONC || 5));
  let i = 0;
  const рабочий = async () => {
    for (;;) {
      const n = i++;
      if (n >= файлы.length) return;
      const ф = файлы[n];
      const г = гео[n] || { файл: ф, ошибка: 'нет замера' };
      let мод = null;
      let непроверено = false;
      if (!opts.безМодели && !г.ошибка) {
        const о = await спросить(ф).catch((e) => ({ ok: false, причина: String(e.message).slice(0, 80) }));
        if (о.ok) мод = о.оценки; else непроверено = true;
      }
      итог[n] = { файл: ф, ...приговор(г, поРез.get(ф) || null, мод), гео: г, мод, непроверено };
      if (opts.шаг) opts.шаг(итог[n], n + 1, файлы.length);
    }
  };
  await Promise.all(Array.from({ length: Math.min(поток, файлы.length) }, рабочий));
  return итог;
}

/**
 * Разложить приговор по диску: плохие уезжают в <папка>/брак, причина уходит в имя файла.
 * Файлы НЕ УДАЛЯЮТСЯ: приговор должен быть обратим движением мыши.
 * @param {object[]} итог результат проверитьПачку
 * @param {string} папка куда класть подпапку «брак»
 * @returns {number} сколько переложено
 */
function разложить(итог, папка) {
  const БРАК = path.join(папка, 'брак');
  let n = 0;
  for (const r of итог) {
    if (r.годится || r.непроверено) continue;
    fs.mkdirSync(БРАК, { recursive: true });
    const имя = path.basename(r.файл);
    const ext = path.extname(имя);
    const цель = path.join(БРАК, `${имя.slice(0, имя.length - ext.length)}__${r.метка}${ext}`);
    try { fs.renameSync(r.файл, цель); n++; } catch (e) { console.log(`  не переложил ${имя}: ${e.message}`); }
  }
  return n;
}

function собрать(входы) {
  const файлы = [];
  for (const в of входы) {
    let st = null;
    try { st = fs.statSync(в); } catch { continue; }
    if (st.isDirectory()) {
      for (const f of fs.readdirSync(в).sort()) {
        if (/\.(jpe?g|png|webp)$/i.test(f)) файлы.push(path.join(в, f));
      }
    } else файлы.push(в);
  }
  return файлы;
}

