/**
 * Геометрия круга для набора файлов.
 * @param {string[]} файлы локальные пути
 * @returns {object[]} по записи на файл
 */
function геометрия(файлы) {
  if (!файлы.length) return [];
  const r = spawnSync('python3', ['-c', PY, YUNET, ...файлы],
    { encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 });
  if (r.status !== 0) {
    return файлы.map((ф) => ({ файл: ф, ошибка: `питон упал: ${String(r.stderr || '').slice(0, 120)}` }));
  }
  try { return JSON.parse(r.stdout); }
  catch { return файлы.map((ф) => ({ файл: ф, ошибка: 'питон вернул не JSON' })); }
}

