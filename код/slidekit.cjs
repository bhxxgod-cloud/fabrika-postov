//
// Три правила, которые нарушались:
//   1. ВСЕ кадры строго 4:5 (1080×1350). Раньше мои рендеры были 4:5, а картинки от генератора
//      приходили 1:1 (2048×2048) и уезжали в карусель как есть — лента показывала разнобой.
//   2. Хук НЕ ЛОЖИТСЯ НА ЛИЦО: текст живёт в своей верхней зоне с затемнением, а не поверх лица.
//   3. Призыв на финальном кадре объясняет, ГДЕ искать: главная строка — про поиск в яндексе,
//      потому что «neironka.pro» без объяснения зритель не находит (замечание начальника).
'use strict';
const fs = require('node:fs');
const { execFileSync } = require('node:child_process');
const FF = require('ffmpeg-static');
const W = 1080, H = 1350;

// Любую картинку приводим к 4:5: масштабируем по большей стороне и режем по центру.
function to45(src, out) {
  execFileSync(FF, ['-y', '-i', src,
    '-vf', `scale=${W}:${H}:force_original_aspect_ratio=increase,crop=${W}:${H}`,
    '-q:v', '2', out], { stdio: 'ignore' });
  return out;
}

// ИНФОГРАФИКИ вписываем ЦЕЛИКОМ (letterbox на белом): фабрика отдаёт их выше 4:5, и центр-кроп
// срезал заголовок и низ (Дарья #46, 06.08). Кропать инфографику нельзя, там текст по краям.
// УМНОЕ ПРИВЕДЕНИЕ К 4:5 (09.08, начальник прислал рилс: «не влазит главное фото, оно обрезанное»).
// Проблема: to45 приводит кадр обрезкой, и это правильно для ФОТО, но убийственно для КАРТОЧЕК с
// инфографикой: у карточки «оценка внешности» срезало заголовок сверху и рекомендации снизу.
// Решение: смотрим на пропорции источника. Если он ВЫШЕ, чем 4:5 (то есть карточка), вписываем
// целиком с фоном под цвет самой карточки. Если ниже или примерно 4:5 — обрезаем как раньше.
// Порог 0.83 (4:5 = 0.8) даёт запас на округления размеров фабрики.
// БЕЛЫХ ПОЛЕЙ ПО БОКАМ БОЛЬШЕ НЕТ (09.08, приказ начальника: «2 и 3 фото белые края по бокам,
// нельзя так»). Раньше кадр выше 4:5 вписывался целиком, и по бокам оставались белые полосы: в
// ленте это читается как склеенный на телефоне пост. Теперь такой кадр РЕЖЕТСЯ, но не по центру,
// а с привязкой к ВЕРХУ: у карточки сверху заголовок, его терять нельзя, а снизу мелкая сноска,
// её потеря не страшна. Берём 15 процентов лишней высоты сверху и остальное снизу.
function to45smart(src, out, opts = {}) {
  let w = 0, h = 0;
  try {
    const r = require('node:child_process').spawnSync(FF, ['-hide_banner', '-i', src], { encoding: 'utf8' });
    const m = String(r.stderr || '').match(/,\s(\d{2,5})x(\d{2,5})[\s,]/);
    if (m) { w = +m[1]; h = +m[2]; }
  } catch {}
  const ratio = w && h ? w / h : 0.8;
  if (ratio && ratio < 0.83) {
    // КАРТОЧКА-ПРОСТЫНЯ (сильно выше 4:5): резать нельзя, там текст по всей высоте, обрезка съедает
    // заголовок (нов01, 09.08). Вписываем ЦЕЛИКОМ, а поля по бокам заливаем цветом САМОЙ карточки,
    // а не белым: край инфографики кремовый, поле сливается с ним и не читается как склейка на
    // телефоне. Так и текст цел, и «белых полей» нет.
    if (ratio < 0.72) {
      const bg = edgeColor(src);
      execFileSync(FF, ['-y', '-i', src, '-vf',
        `scale=${W}:${H}:force_original_aspect_ratio=decrease,pad=${W}:${H}:(ow-iw)/2:(oh-ih)/2:color=${bg}`,
        '-q:v', '2', out], { stdio: 'ignore' });
      return out;
    }
    // Кадр лишь ЧУТЬ выше 4:5 (фото с лицом, образ): НИКАКОГО вертикального сжатия (09.08, начальник:
    // «растянутое лицо, ужас»). Сжатие было незаметно на карточке, но на лице давало искажение.
    // Фото приводим ОБРЕЗКОЙ: масштаб по большей стороне и центр-кроп, лицо не тянется, полей нет.
    //
    // КАРТОЧКУ РЕЖЕМ ОТ ВЕРХА, А НЕ ПО ЦЕНТРУ (09.08). Замысел «берём 15 процентов лишней высоты
    // сверху, остальное снизу» был описан в комментарии выше ещё 09.08, но в коде его не было:
    // ветка молча звала центр-кроп. Карточка фабрики приходит 1080×1440, центр-кроп срезает по 45
    // пикселей сверху и снизу, и первым уходит ЗАГОЛОВОК («ТВОЙ ЛУЧШИЙ ОБРАЗ — BEAUTY GUIDE»,
    // живой пример пост 8dc64e15). Снизу у карточки мелкая строка образов, её потеря не заметна.
    // КАРТОЧКУ БОЛЬШЕ НЕ РЕЖЕМ ВООБЩЕ (11.08). Обрезка от верха оставляла заголовок, но съедала низ,
    // и отдел качества по складу дал по этому ровно один диагноз: 21 брак из 22 это «низ карточки
    // обрезан», уходит блок рекомендаций. Спор «что важнее, заголовок или низ» решается тем, что
    // резать не надо ни то ни другое: карточка приходит 1080x1440, вписанная в 1080x1350 она даёт
    // по 34 пикселя поля с боков, залитых цветом собственного края, то есть поля не читаются как
    // склейка (это уже проверено на карточках-простынях выше). Текст цел весь.
    if (opts.topBias) {
      const bg = edgeColor(src);
      execFileSync(FF, ['-y', '-i', src, '-vf',
        `scale=${W}:${H}:force_original_aspect_ratio=decrease,pad=${W}:${H}:(ow-iw)/2:(oh-ih)/2:color=${bg}`,
        '-q:v', '2', out], { stdio: 'ignore' });
      return out;
    }
    return to45(src, out);
  }
  return to45(src, out);
}

// Приведение к 4:5 с привязкой к ВЕРХУ: из лишней высоты забираем сверху 15 процентов, снизу
// остальное. Нужно карточкам с инфографикой, у которых заголовок стоит первой строкой.
function to45top(src, out) {
  execFileSync(FF, ['-y', '-i', src,
    '-vf', `scale=${W}:-2,crop=${W}:${H}:0:(ih-${H})*0.15`,
    '-q:v', '2', out], { stdio: 'ignore' });
  return out;
}

// ТЁМНЫЙ ТОН ПОДЛОЖКИ ПЛАШКИ БЕРЁМ С ПЕРВОГО КАДРА ПОСТА (09.08, приказ начальника: «мне не
// нравится фон чёрный на подписи на 4 фото, сделай лучше фон тёмный как на 1 снимке того же
// поста»). Чистый чёрный читается как наклейка поверх чужой картинки, а тон с обложки делает
// плашку частью поста.
// ЧИТАЕМОСТЬ ВАЖНЕЕ КРАСОТЫ: если кадр светлый, взятый тон притемняем, а не заменяем чёрным.
// Иначе на светлой обложке (окно, белая стена) подложка стала бы белой, и белый текст исчез.
function darkTone(src) {
  try {
    const r = require('node:child_process').spawnSync(FF,
      ['-hide_banner', '-i', src, '-vf', 'crop=iw:ih*0.34:0:ih*0.66,scale=1:1', '-frames:v', '1',
        '-f', 'rawvideo', '-pix_fmt', 'rgb24', 'pipe:1'], { maxBuffer: 1 << 20 });
    const b = r.stdout;
    if (b && b.length >= 3) {
      let [cr, cg, cb] = [b[0], b[1], b[2]];
      // Целевая яркость подложки около 30 из 255: тон обложки сохраняем, светлоту приводим.
      const lum = 0.299 * cr + 0.587 * cg + 0.114 * cb;
      const k = lum > 1 ? Math.min(1, 34 / lum) : 1;
      cr = Math.round(cr * k); cg = Math.round(cg * k); cb = Math.round(cb * k);
      return { rgb: [cr, cg, cb], css: `rgb(${cr},${cg},${cb})` };
    }
  } catch {}
  return { rgb: [10, 10, 12], css: 'rgb(10,10,12)' };   // запасной почти чёрный
}

// Цвет края картинки: усредняем левую полосу в один пиксель и читаем его RGB. Нужен, чтобы поля у
// карточки-простыни были под цвет бумаги инфографики, а не белые.
function edgeColor(src) {
  try {
    const r = require('node:child_process').spawnSync(FF,
      ['-hide_banner', '-i', src, '-vf', 'crop=6:ih:0:0,scale=1:1', '-f', 'rawvideo', '-pix_fmt', 'rgb24', 'pipe:1'],
      { maxBuffer: 1 << 20 });
    const b = r.stdout;
    if (b && b.length >= 3) {
      const hex = (n) => n.toString(16).padStart(2, '0');
      return '0x' + hex(b[0]) + hex(b[1]) + hex(b[2]);
    }
  } catch {}
  return '0xEFEBE3';   // запасной кремовый под бумагу инфографики
}

