/**
 * Отступной ход: сборка без фактов поста.
 *
 * СНАЧАЛА ВСЁ РАВНО ПРОБУЕМ captions (12.08). Модуль подписи по построению работает без фактов:
 * его главное правило «блок собирается из факта, а нет факта — нет блока», и на пустой meta он
 * честно отдаёт первую строку, путь и вопрос, зато по НОВОЙ схеме и через все проверки. Пулы ниже
 * остаются последним рубежом на случай, если и это упало: раньше они подхватывались всегда, когда
 * вызывающий не передал meta, и в ленту уезжал текст с денежным оффером и пятью императивами,
 * потому что мимо captions они шли мимо и всех проверок.
 */
function собратьИзПулов(template, opts) {
  const TPLC = require('./templates.cjs');
  try {
    const CAP = require('./captions.cjs');
    const pkey0 = textPoolKey(template);
    const platform = (opts && opts.platform) || 'tiktok';
    return CAP.buildCaption({
      template,
      hook: (opts && opts.hook) || '',
      meta: {},
      seed: (opts && (opts.seed || opts.postId)) || `${template}|${Date.now()}`,
      marker: TPLC.frame4Marker(platform),
      tags: pickTags(TAG_POOLS[pkey0] || TAG_POOLS['*']),
      platform,
      mode: opts && opts.mode,
      cta: opts && opts.cta,
      style: opts && opts.style,
      noTags: opts && opts.noTags,
    });
  } catch (e) {
    console.log(`  ⚠ подпись без фактов не собралась (${String(e.message).slice(0, 90)}), беру пул`);
  }
  const hearts = TPLC.isHearts(template);
  const titles = hearts ? HEARTS_TITLES : POST_TITLES;
  const hookText = String((opts && opts.hook) || '').toLowerCase().replace(/[^а-яёa-z ]/gi, ' ').trim();
  const hookWords = new Set(hookText.split(/\s+/).filter((w) => w.length > 4));
  const differs = (t) => {
    const w = String(t).toLowerCase().replace(/[^а-яёa-z ]/gi, ' ').split(/\s+/).filter((x) => x.length > 4);
    if (!hookWords.size || !w.length) return true;
    const same = w.filter((x) => hookWords.has(x)).length;
    return same / w.length < 0.4;   // больше 40% общих слов = тот же текст, берём другой
  };
  const okTitles = titles.filter(differs);
  const title = (okTitles.length ? okTitles : titles)[Math.floor(Math.random() * (okTitles.length || titles.length))];
  const howto = HOWTO_POOL[Math.floor(Math.random() * HOWTO_POOL.length)];
  // Теги и хвост берём по СМЫСЛУ шаблона, а не по признаку «сердечки или всё остальное».
  const pkey = textPoolKey(template);
  // ПЯТЬ ТЕГОВ НА ПОСТ (13.08, прямой приказ начальника: «стало 2 хештега вместо 5 — исправь»).
  // Прошлое ужатие до 2-3 по замерам Metricool отменено приказом: приказ свежее замера.
  const tags = pickTags(TAG_POOLS[pkey] || TAG_POOLS['*'], 5);
  const tails = CAPTION_TAILS.concat(CAPTION_TAILS_BY_KEY[pkey] || []);
  const tail = tails[Math.floor(Math.random() * tails.length)];
  // ═══ ПОДСТАНОВКА СЛОВА-МАРКЕРА ══════════════════════════════════════════════════════════════
  // ЖИВОЙ БАГ (09.08, найден на постах фон01…фон05). В пулах POST_CAPTIONS и HOWTO_POOL стоит
  // «нейронка про ${marker}», но строки пулов взяты в ОДИНАРНЫЕ кавычки, то есть это обычный
  // текст, а не шаблонная строка. Подставлять его было некому, и в подпись поста уезжала
  // ДОСЛОВНАЯ заглушка: «наберите «нейронка про ${marker}» в яндексе». Читатель видит код вместо
  // запроса, то есть путь к нам ломается ровно в том месте, ради которого подпись и написана.
  // Лечим подстановкой здесь и проверкой ниже, а не переписыванием пулов на бэктики: в пулах
  // текст правят вручную, и одиночная кавычка там надёжнее.
  //
  // КАКОЕ СЛОВО. Подпись у поста одна, а слов-маркеров два: «шаблоны» для фотопоста в тикток и
  // «промпты» для рилса в инстаграм (templates.FRAME4_CTA). По умолчанию берём тикток: подпись
  // едет вместе с четырьмя кадрами. Вызывающий, который готовит текст под рилс, передаёт
  // platform:'reels' и получает своё слово.
  const marker = TPLC.frame4Marker((opts && opts.platform) || 'tiktok');
  // НАЗВАНИЕ ТРЕНДА подставляется из ОДНОГО места на весь проект (captions.трендСловами), ровно как
  // слово-маркер: заголовок обязан назвать тренд теми словами, какими его зовёт аудитория, а держать
  // второй список названий в этом файле значит завести второй источник правды.
  let trend = 'этот тренд на своё фото';
  try { trend = require('./captions.cjs').трендСловами(require('./captions.cjs').collectFacts({ template })); } catch {}
  // БЛОК ТЕЛА (POST_CAPTIONS/HEARTS_CAPTIONS) ИЗ СКЛЕЙКИ УБРАН 14.08. Он стоял между заголовком и
  // инструкцией и состоял из общих фраз про себя («заняло меньше времени, чем я выбирала фотку»),
  // то есть отодвигал инструкцию — единственное, ради чего описание открывают. Начальник забраковал
  // это дословно: «сами описания очень слабы, они не про настоящий тикток, а про нашу выдумку».
  // В живых подписях ниши (radar_posts) такого блока нет ни у кого: сразу после первой строки идут
  // шаги. Сами пулы оставлены на месте, но из сборки не читаются: если решим вернуть блок, он
  // вернётся правкой одной строки, а не восстановлением удалённых текстов.
  const text = `${title}\n\n${howto}\n\n${tail}\n\n${tags}`
    .replace(/\$\{marker\}/g, marker).replace(/\$\{trend\}/g, trend);
  // НЕЗАКРЫТАЯ ЗАГЛУШКА ЭТО ОШИБКА, А НЕ КОСМЕТИКА: пусть падает здесь, а не печатается в ленте.
  // Ровно та же дисциплина, что у audit() в promptkit: заглушку нельзя пускать дальше молча.
  const left = text.match(/\$\{[^}\n]{1,40}\}/);
  if (left) throw new Error(`slidekit: в подписи осталась заглушка «${left[0]}», её некому подставить`);
  // СЛЕШ В ПОДПИСИ ЗАПРЕЩЁН (11.08, приказ начальника: «почему тут слеши, запрети их в описаниях
  // вообще»). Повод был ложный: слеш он увидел в КАТАЛОГЕ хуков, где я сам поставил его как
  // пометку переноса строки, а в самой фразе стоит \n и слеша нет. Но запрет всё равно правильный
  // и стоит дёшево, потому что настоящий путь для такой утечки уже был: в подпись однажды уехала
  // дословная заглушка «${marker}» из пула, и мы поймали это только глазами на живых постах.
  // Слеш в тексте подписи это почти всегда след служебной разметки, а не речь девочки, поэтому
  // рубим здесь, а не ищем потом в ленте. Ссылки не задеваем: их в подписи нет по правилу
  // «ссылка живёт в сторис, а не в био и не в подписи».
  const слеш = /[\\/]/.exec(text);
  if (слеш) throw new Error('slidekit: в подписи есть слеш, это след разметки, а не речь: '
    + `«${text.slice(Math.max(0, слеш.index - 25), слеш.index + 25).replace(/\n/g, ' ')}»`);
  return text;
}

