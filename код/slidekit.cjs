// То есть копий геометрии было не пять, а больше, и одна из них жила в другой системе координат.
//
// ЛЕЧИМ ПРИЧИНУ, А НЕ ЧИСЛО. Пока каждая копия хранит СВОЙ отступ в СВОИХ координатах (4:5 у
// карусели, 9:16 у рилса), они обязаны разъезжаться: правка одной физически не может дойти до
// другой. Поэтому источник правды теперь ОДИН и выражен так, как о нём думает владелец и как его
// проверяет гейт — ДОЛЕЙ ВЫСОТЫ ГОТОВОГО РИЛСА. Каждый рисовальщик пересчитывает долю в свои
// пиксели сам.
//
// 0.82 — выбор владельца по трём отрисованным вариантам (см. разбор ниже). Порог гейта 0.85.
const HOOK_LOW = Number(process.env.HOOK_LOW || 0.82);

/**
 * Низ блока хука в пикселях для холста 4:5 (1080x1350).
 * Кадр 4:5 заливается в 9:16 с растяжением 1920/1350 = 1.4222, поэтому долю переводим обратно и
 * добавляем внутреннее поле блока 26px.
 */
const низДляКарусели = (доля) => Math.round(1350 - ((доля * 1920) / (1920 / 1350) + 26));

const HOOK_BOTTOM = Number(process.env.HOOK_BOTTOM || низДляКарусели(HOOK_LOW));
const HOOK_PAD = Number(process.env.HOOK_PAD || 200);

// ДВЕ СТРОКИ, А НЕ СКОЛЬКО ПОЛУЧИТСЯ. Раньше строку отдавали браузеру как есть и он переносил её
// сам, а после сужения полосы до 680px это дало две беды.
//   1. СИРОТА В ПОСЛЕДНЕЙ СТРОКЕ. Живой снимок теста 14.08: «коллеги спросили не / влюбилась ли я
//      после этого / фото 🤭» — третья строка из одного слова, вид дешёвый.
//   2. БЛОК ПОЛЗЁТ НА ЛИЦО. Низ блока прибит к 1013 (ниже нельзя, там интерфейс), поэтому каждая
//      лишняя строка растит блок ВВЕРХ на 57px. Замер по десяти исходникам (sharpmeter, рамка лица
//      yunet): подбородок ниже 62.7 процента высоты у шести из десяти, то есть третья строка
//      заезжает на лицо, а это брак «ТЕКСТ НА ЛИЦЕ» на гейте карусели (validatepost.cjs, правило
//      text_placement_ok). Держим две строки и отдаём 57px обратно лицу.
// Кегль уменьшаем только когда иначе не влезает: 42px наш стандарт, ниже 28px читаемости нет.
// Средняя ширина знака этого шрифта ~0.6em (замерено по живым обложкам).
function подогнатьХук(текст, pad = HOOK_PAD) {
  const полоса = W - 2 * pad;
  let строки = String(текст).trim().split('\n').map((s) => s.trim()).filter(Boolean);
  const влезает = (s, fs) => s.length * fs * 0.6 <= полоса;
  // Ручного переноса нет, а строка длинная: делим по словам на две части, ближе к равным.
  if (строки.length === 1 && !влезает(строки[0], 42)) {
    const слова = строки[0].split(/\s+/);
    let лучший = 1, разрыв = Infinity;
    for (let i = 1; i < слова.length; i++) {
      const а = слова.slice(0, i).join(' ').length, б = слова.slice(i).join(' ').length;
      const d = Math.abs(а - б);
      if (d < разрыв) { разрыв = d; лучший = i; }
    }
    строки = [слова.slice(0, лучший).join(' '), слова.slice(лучший).join(' ')];
  }
  const длинная = Math.max(...строки.map((s) => s.length));
  let кегль = 42;
  if (!влезает(''.padEnd(длинная), кегль)) кегль = Math.max(28, Math.floor(полоса / (длинная * 0.6)));
  return { строки, кегль };
}

// Разметка блока хука. Отдельно от рендера, потому что magosreels собирает свой html вокруг уже
// подготовленного кадра и ему нужен именно кусок стилей, а не готовая картинка.
// место === 'верх' — низ исходника занят чужой надписью (вердикт textguard.cjs, живой брак 11.08 на
// аккаунте Карины: наш хук лёг поверх подписи пинтерестного кадра). top:120px это 6 процентов
// высоты, до зоны интерфейса оттуда далеко, поэтому верхний вариант в пересчёте не нуждается.
function хукБлок(текст, opts = {}) {
  const pad = opts.pad ?? HOOK_PAD;
  const bottom = opts.bottom ?? HOOK_BOTTOM;
  const вверх = opts.место === 'верх';
  const { строки, кегль } = подогнатьХук(текст, pad);
  const css = `.t{position:absolute;left:0;right:0;${вверх ? 'top:120px' : `bottom:${bottom}px`};`
    + `padding:26px ${pad}px;text-align:center;`
    + `color:rgba(255,255,255,.97);font-size:${кегль}px;font-weight:500;line-height:1.36;`
    + `text-shadow:0 2px 6px rgba(0,0,0,.85),0 6px 22px rgba(0,0,0,.55);`
    // ПОДЛОЖКА .45, А НЕ .34 (11.08). Осмотр десяти хуков на трёх обложках: на светлом низе кадра
    // (гравий, снег, стол) при .34 буквы читаются на грани. На тёмных кадрах .45 ничего не портит,
    // подложка всё равно уходит в прозрачность к краям.
    + `background:linear-gradient(to bottom,rgba(0,0,0,0),rgba(0,0,0,.45) 22%,rgba(0,0,0,.45) 78%,rgba(0,0,0,0))}`
    + `.t div{margin:2px 0}`;
  const html = `<div class="t">${строки.map((l) => `<div>${l}</div>`).join('')}</div>`;
  return { css, html, строки, кегль };
}

// Готовый кадр: фото + хук снизу. Этим пользуются onepost, pickup, rehook_covers и makepost.
async function хукНизом(src, out, текст, opts = {}) {
  const { b64, mime } = b64of(src);
  const блок = хукБлок(текст, opts);
  const html = `<!doctype html><meta charset="utf-8"><style>*{margin:0;padding:0}
    body{width:${W}px;height:${H}px;position:relative;overflow:hidden;background:#000;
      font-family:-apple-system,'Helvetica Neue',Arial,sans-serif;-webkit-font-smoothing:antialiased}
    img{width:${W}px;height:${H}px;object-fit:cover;display:block}
    ${блок.css}</style>
    <img src="data:${mime};base64,${b64}">${блок.html}`;
  return render(html, out);
}

