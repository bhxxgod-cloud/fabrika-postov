// в поисковом запросе мы и различаем, с какой площадки пришёл человек. Слово НЕ пишем здесь руками,
// его отдаёт контракт (templates.frame4Marker), иначе через месяц оно опять разъедется по файлам.
// По умолчанию tiktok: так себя ведёт весь старый код, который зовёт ctaSlide без площадки.
async function ctaSlide(src, out, style) {
  const { b64, mime } = b64of(src);
  const o = (style && typeof style === 'object') ? style : { style };
  const platform = o.platform || 'tiktok';
  const marker = require('./templates.cjs').frame4Marker(platform);
  const key = (o.style && CTA_STYLES[o.style]) ? o.style : pickCta(o.seed);
  const st = CTA_STYLES[key];
  // Тон подложки: с ПЕРВОГО кадра поста, если его передали, иначе с самого финала (лучше, чем чёрный).
  const tone = darkTone(o.cover && fs.existsSync(o.cover) ? o.cover : src);
  const block = typeof st.block === 'function' ? st.block(marker) : st.block;
  const css = typeof st.css === 'function' ? st.css(tone.rgb) : st.css;
  const html = `<!doctype html><meta charset="utf-8"><style>
    *{margin:0;padding:0;box-sizing:border-box}
    body{width:${W}px;height:${H}px;position:relative;overflow:hidden;background:#000;
      font-family:-apple-system,'Helvetica Neue',Arial,sans-serif;-webkit-font-smoothing:antialiased}
    img{width:${W}px;height:${H}px;object-fit:cover;display:block}
    ${css}
  </style><img src="data:${mime};base64,${b64}">${block}`;
  await render(html, out);
  return { out, style: key, platform, marker, tone: tone.css };
}

