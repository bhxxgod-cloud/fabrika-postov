// ВЫБОР ПЛАШКИ БЕЗ ПОВТОРА ПОДРЯД (06.08, претензия начальника «одна и та же плашка призыва»).
// Пять стилей были, но выбирались чистым random(): при 5 вариантах два поста подряд получают
// одинаковую плашку с вероятностью 20%, а три подряд — заметно часто, и лента читалась как одна
// реклама. Теперь помним последний индекс в rotors.json и гарантированно с него сходим.
const ROTORS = require('node:path').join(__dirname, 'rotors.json');
function rotorRead() { try { return JSON.parse(fs.readFileSync(ROTORS, 'utf8')) || {}; } catch { return {}; } }
function rotorWrite(patch) {
  try { fs.writeFileSync(ROTORS, JSON.stringify({ ...rotorRead(), ...patch })); } catch {}
}
function pickCta(seed) {
  const N = CTA_KEYS.length;
  const last = Number(rotorRead().cta);
  let i = seed != null ? seedNum(seed) % N
                       : ((Number.isInteger(last) ? last : -1) + 1 + Math.floor(Math.random() * (N - 1))) % N;
  if (i === last) i = (i + 1) % N;
  rotorWrite({ cta: i });
  return CTA_KEYS[i];
}

// Финальный слайд. Третий аргумент: ключ стиля строкой ИЛИ {style, seed, platform} — seed даёт
// детерминированный стиль на пост (пересборка того же поста даст тот же кадр).
//
// СЛОВО-МАРКЕР НА ФИНАЛЕ ЗАВИСИТ ОТ ПЛОЩАДКИ (09.08, приказ начальника). Фотопост уезжает в тикток
