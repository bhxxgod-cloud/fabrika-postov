function freshLockDate(n) {
  const d = new Date(Date.now() - (n % 3) * 86400000);
  const s = d.toLocaleDateString('ru-RU', { weekday: 'long', day: 'numeric', month: 'long' });
  return s.charAt(0).toUpperCase() + s.slice(1);
}
