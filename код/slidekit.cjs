// 31,7% меньше просмотров, а в тиктоке наоборот +5% при 1-2 тегах. Отсюда 3 для инстаграма и рилса,
// 2 для тиктока. Само число подписи режет captions по площадке (captions.подрезатьТеги), здесь
// параметр нужен вызывающим, которые берут теги напрямую.
function pickTags(pool, сколько = 5) {
  let n = 0;
  try { n = Number(JSON.parse(fs.readFileSync(ROTOR, 'utf8')).n) || 0; } catch {}
  try { fs.writeFileSync(ROTOR, JSON.stringify({ n: n + 1 })); } catch {}
  const L = pool.length;
  return [0, 1, 4, 8, 12].slice(0, Math.max(0, сколько)).map((d) => pool[(n + d) % L]).join(' ');
}
