// FACTORY_HOOKS, теперь единственный пул лежит в hooks.cjs, а здесь остался только вызов.
// Валидный хук для фабрики: свой текст, если проходит по длине, иначе случайный из пула шаблона.
// opts.avoid (09.08): не отдавать этот же текст второй раз. Нужно там, где на одном посте берутся
// ДВА хука из одного пула (обложка у нас, hookText в заказе фабрики): без avoid оба выпадали
// одинаковыми, и на кадрах поста стояла одна и та же фраза дважды.
function factoryHook(template, own, opts) {
  // ПУЛ ХУКОВ ПЕРЕЕХАЛ В hooks.cjs (11.08, приказ: «нам нужно прикольные байтовые надписи писать
  // на 1 фото, они у нас слабые очень»). ПОЧЕМУ БЫЛИ СЛАБЫЕ, по факту, а не по вкусу: здесь лежал
  // пул из 3-6 фраз на шаблон, то есть начальник видел не неудачные варианты, а ВЕСЬ пул. Выбор шёл
  // чистым random без памяти, поэтому на пачке из пяти постов один текст выпадал дважды. И корень:
  // фразы ОПИСЫВАЛИ содержимое («разобрали брови, губы, оттенок»), тем закрывая любопытство, а хук
  // обязан открывать вопрос, ответ на который лежит на кадре 2.
  // Новый пул 83 фразы, отобран из 256 сырых с проверкой длины, запретных слов и наличия вопроса.
  // ЗАНЯТЫЕ ФРАЗЫ ПРОБРАСЫВАЕМ ДАЛЬШЕ (11.08): их считает зовущий по базе (свои по аккаунту плюс
  // последние по ферме), а выбор из свободных делает hooks.pick. Без этого проброса замер давал
  // 18 разных хуков на 40 постов, с ним 29 из 40, то есть пул выбирается до конца, а не по кругу.
  return require('./hooks.cjs').pick(template, {
    own, avoid: (opts && opts.avoid) || null, seed: (opts && opts.seed) || null,
    avoidSet: (opts && opts.avoidSet) || [], family: opts && opts.family, look: opts && opts.look,
  });
}

// ПОДПИСЬ ПОСТА: отдельный текст, НЕ дубль хука с кадра (правка начальника 06.08: «текст
// заголовка и на фото одинаковый, нет хештегов»). Опирается на брендовый финальный кадр.
// ХЕШТЕГИ (06.08, по данным разведки TikTok и Instagram):
//   • обе платформы читают МАКСИМУМ 5 тегов (IG с декабря 2025, TikTok с августа 2025),
//     остальное срезается, а простыня тегов у Meta официально в списке понижаемого;
//   • теги про ИИ (#нейросеть #ии #ai) тянут пост в техно-аудиторию и в пул ИИ-приколов,
//     а не к женской 18-30, поэтому их НЕТ в пулах: метим тему РЕЗУЛЬТАТА, не инструмента;
//   • брендовый тег на всю сетку не ставим: это готовый граф связей наших аккаунтов;
//   • наборы обязаны отличаться между постами и аккаунтами, иначе сетку склеивают как спам.
// Поэтому держим ПУЛ на тему и берём из него 5 тегов со сдвигом по счётчику: соседние посты
// никогда не получают одинаковую пятёрку.
// ПУЛЫ РАЗВЕДЕНЫ ПО СМЫСЛУ (09.08). Было два пула, hearts и beauty, и «beauty» уезжал на всё
// подряд: на чб сквозь пальцы, на дудл и на гелик уходили теги про цветотип и макияж, то есть
