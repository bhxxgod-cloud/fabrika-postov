// Рендер ВО ВКЛАДКЕ статичного хрома (06.08, начальник: «постоянно открываются ненужные
// хромы»): раньше каждая плашка поднимала свой headless Chrome и в доке мигала вторая иконка.
// Теперь Chrome ровно один, рендер открывает и закрывает только вкладку.
async function render(html, out) {
  const { openAdmin, снятьСвою } = require('./adminbrowser.cjs');
  const { page, done } = await openAdmin();
  try {
    await page.setViewportSize({ width: W, height: H });
    // ТАЙМАУТ 120 СЕКУНД, А НЕ 30 ПО УМОЛЧАНИЮ (14.08). Хром у фермы ОДИН на всех, и ночью в него
    // одновременно ходят восемь сборок постов и три резки рилсов. Кадр приезжает сюда строкой
    // base64 на 1-2 МБ, её надо разобрать и отрисовать — под такой очередью 30 секунд кончались, и
    // приведение к 9:16 падало 32 раза из 293. Ронять готовую работу из-за очереди нельзя: сторожа
    // выше по стеку всё равно поймают настоящий висяк (у onepost это 40 минут, у резки 15).
    const png = out.replace(/\.jpe?g$/i, '.png');
    // Через общую защиту: метка страницы сверяется до и после съёмки, иначе при
    // занятой вкладке снимок молча уходит с чужой страницы.
    await снятьСвою(page, html, png, { ждатьМс: 400 });
    execFileSync(FF, ['-y', '-i', png, '-q:v', '2', out], { stdio: 'ignore' });
    fs.unlinkSync(png);
  } finally { await done(); }
  return out;
}

