// ПЕРЕНОС ХУКА ПО СМЫСЛУ (правило ветки «Ревизия хуков» 15.08): до 3 строк, перенос после
// запятой/скобки/двоеточия, а не по ширине; строка-сирота из одного слова = брак; длинные фразы
// живут (владелец утвердил 90-знаковую), но кегль не ниже ~34px — hookSlideTT рисует 52px на
// строку, поэтому длинные режем на 3 строки, а не даём браузеру переносить в 4-5.
function переносХука(t) {
  t = String(t || '').replace(/\s+/g, ' ').trim();
  if (t.length <= 34) return t;
  const слова = t.split(' ');
  const целевых = t.length <= 52 ? 2 : 3;
  const цель = Math.ceil(t.length / целевых);
  // точки разрыва: после знаков препинания — приоритет, иначе по словам
  const строки = []; let тек = '';
  for (let i = 0; i < слова.length; i++) {
    const w = слова[i]; const проба = тек ? тек + ' ' + w : w;
    const знак = /[,:)(;]$/.test(w);
    const остал = слова.length - i - 1;
    if (строки.length < целевых - 1 && проба.length >= цель * 0.8 && (знак || проба.length >= цель) && остал >= 2) {
      строки.push(проба); тек = '';
    } else тек = проба;
  }
  if (тек) строки.push(тек);
  // сирота: последняя строка из одного слова — приклеиваем к предыдущей
  if (строки.length > 1 && !строки[строки.length - 1].includes(' ')) {
    const last = строки.pop(); строки[строки.length - 1] += ' ' + last;
  }
  // ширина: hookSlideTT рисует 52px, в 1080-PAD влезает ~30 знаков; длиннее — браузер ломает в 4-ю строку
  const итог = [];
  for (const л of строки) {
    if (л.length <= 34 || итог.length + строки.length >= 3) { итог.push(л); continue; }
    const ws = л.split(' '); let a = '', b = '';
    for (const w of ws) { if ((a + ' ' + w).trim().length <= 34 && !b) a = (a + ' ' + w).trim(); else b = (b + ' ' + w).trim(); }
    if (b && !b.includes(' ') && a.includes(' ')) { const aw = a.split(' '); b = aw.pop() + ' ' + b; a = aw.join(' '); }
    итог.push(a); if (b) итог.push(b);
  }
  return итог.slice(0, 3).join('\n');
}


