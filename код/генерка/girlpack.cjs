// комнату, и владелец дважды получал поясной план вместо лица: «лицо не близко, а далеко всё
// равно», «давай тренд с носом сделаем, чтобы он был ближе». Этим темам комната даётся одной
// строкой — как источник света и фона, без единого требования её показать.
const КРУПНЫЙ_ПЛАН = new Set(['img-nose-verdict', 'img-glow-plan', 'img-lip-guide', 'img-brow-map']);
const сценаКрупно = () => 'В ДРУГОМ МЕСТЕ И ПОЗЖЕ: она в комнате со ВТОРОГО ПРИЛОЖЕННОГО ФОТО, '
  + 'но комната здесь только фон и источник света — она размыта и занимает мало места, '
  + 'кадр про лицо. ' + ДОМАШНЯЯ_ОДЕЖДА;

async function образыДляОбложки(имя, обложка, tpl) {
  const [p3, opis] = ШАБЛОНЫ[tpl] || []; if (!p3) return null;
  const ключ = path.basename(обложка).replace(/\.[^.]+$/, '');
  const d = path.join(ВЫХ, имя, tpl, ключ); fs.mkdirSync(d, { recursive: true });
  const артСтарый = !opis && АРТ2[tpl];                       // аниме/пиксар: кадр2 арт, кадр3/4 — другие ракурсы
  const артНовый = tpl in (typeof АРТ_ШАБЛОНЫ !== 'undefined' ? АРТ_ШАБЛОНЫ : {}) && tpl !== 'img-beauty-guide'; // 13 арт-тем: кадр2 арт, кадр3 поза2, кадр4 портрет
  const карт = !артСтарый && !артНовый;
  const k1 = path.join(d, карт ? 'кадр3.png' : 'кадр2.png');
  const сцена = СЦЕНА_СВОЯ.has(tpl) ? ''
    : КРУПНЫЙ_ПЛАН.has(tpl) ? сценаКрупно()
    : сцена2Для(обложка);
  // Квартиру прикладываем только домашнему миру: у Дубая и Бали своя локация, и снимок русской
  // комнаты там всё поломает.
  const мир = мирОбложки(обложка);
  // МОСКВА ИДЁТ ПО ТОМУ ЖЕ ПУЛУ, ЧТО И «ДОМ» (29.08). Как только covergen начал писать город в имя
  // файла, московские заглавные перестали считаться домашними и ушли на текстовое описание — при
  // том что утверждённые владельцем восемнадцать квартир это и есть Москва. Питер тоже: снимков
  // под него нет, а обычная квартира с ремонтом ничем не выдаёт город.
  // Бали остаётся на описании: там вилла, и русская комната сломала бы кадр.
  const домашний = мир === 'дом' || мир === 'москва' || мир === 'питер' || мир === 'неон';
  const комната = СЦЕНА_СВОЯ.has(tpl) ? null
    : (домашний || мир === 'дубай') ? квартираДля(ключ, мир) : null;
  // СЕЛФИ ДОБАВЛЯЕМ ЗДЕСЬ, А НЕ В КАЖДОМ ШАБЛОНЕ (29.08). Требование лежало в константе МИКРОПОЗА,
  // но она вписана только в часть строк: из 37 карточных тем её не было у двадцати с лишним, в том
  // числе у стрижки, носа, сияния и «лучшего размера». У Ани из трёх первых постов селфи вышло
  // ровно на одном — на том единственном, где МИКРОПОЗА стояла. Дописывать её в каждую строку
  // значит завтра забыть в новой; поэтому подмешиваем в одном месте, через которое проходят все.
  // БЕЗ ЛИЦА — БЕЗ СЕЛФИ-БЛОКА (30.08). Подмешивание работает по правилу «нет слова СЕЛФИ —
  // допиши требования к селфи», и тема про машину под него попадала: там лица нет вовсе, а блок
  // требует «лицо по центру, взгляд в объектив». Два прямо противоположных приказа в одном
  // промпте — и модель вернула бы обратно то самое селфи, от которого владелец и уходил.
  const БЕЗ_ЛИЦА = new Set(['img-car-match', 'img-lux-bag']);
  const p3селфи = (БЕЗ_ЛИЦА.has(tpl) || p3.includes('СЕЛФИ'))
    ? p3 : (p3 + СЕЛФИ_БАЗА + СЕЛФИ_БЕЗ_РУКИ);
  await gen(k1, сРукойПоКлючу(p3селфи, ключ) + сцена, [обложка, комната]);
  const переписка = (process.env.SBORKA || 'сб1') === 'сб2';
  if (артСтарый) {
    await gen(path.join(d, 'кадр3.png'), АРТ2[tpl], k1);
    if (!переписка) await gen(path.join(d, 'кадр4.png'), АРТ3[tpl], k1);
  } else if (артНовый) {
    await gen(path.join(d, 'кадр3.png'), opis, k1);
    if (!переписка) await gen(path.join(d, 'кадр4.png'), opis + ' Крупный портрет по плечи.', k1);
  } else if (!переписка) {
    // Та же комната, что на кадре 3: правило владельца — кадры 3 и 4 это одна съёмка в одном месте.
    await gen(path.join(d, 'кадр4.png'), POSE2(opis) + сцена, [k1, комната]);
  }
  // Сборка ждёт файл кадр4 и падает без него: в режиме переписки кладём копию третьего,
  // он всё равно не попадает ни в ролик, ни в пакет — только в зеркало панели фермы.
  if (переписка) {
    const к4 = path.join(d, 'кадр4.png');
    const к3 = path.join(d, карт ? 'кадр3.png' : 'кадр2.png');
    if (!fs.existsSync(к4) && fs.existsSync(к3)) fs.copyFileSync(к3, к4);
  }
  return d;
}
