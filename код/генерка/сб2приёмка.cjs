// сб2приёмка.cjs — ПРИЁМКА ПОСТОВ ВТОРОГО СПОСОБА ПЕРЕД ОТПРАВКОЙ (29.08).
//
// ЗАЧЕМ. Приёмки не было вовсе: посты уезжали в группу сразу после сборки, и брак владелец ловил
// глазами. Ровно так ушли ролики, где кадр 3 оказался кропом обложки («3Й КАДР УНИК, НУ КАК ЫТ
// ПРОЕБАЛСЯ»), и десяток роликов с одним и тем же ответом бывшего. Оба случая ловятся числом за
// секунды, но только если это число кто-то считает.
//
// ЧТО ПРОВЕРЯЕМ, И ПОЧЕМУ ИМЕННО ЭТО:
//   1) ДЛИНА И ЗВУК. Пост без звуковой дорожки или короче девяти секунд — это оборванная сборка.
//      Такое случается, когда генерация кадра упала, а сборщик доехал до конца на том, что было.
//   2) КАДР 3 ≠ КАДР 1. Смысл всей схемы в том, что зритель видит ПЕРЕМЕНУ. Если кадр результата
//      это та же фотография, поста нет — есть слайд с надписью.
//   3) КАДР 4 НЕ ПОВТОРЯЕТСЯ МЕЖДУ ПОСТАМИ. Скрин переписки — единственная развязка ролика.
//      Один и тот же ответ бывшего в десяти роликах подряд читается как штамповка.
//   4) КАДР 1 НЕ ПОВТОРЯЕТСЯ МЕЖДУ ПОСТАМИ. Заглавная — это то, по чему пост открывают.
//
// ЧЕМ СЧИТАЕМ. Отпечаток 8×8 в оттенках серого, среднее расхождение по 64 точкам. Порог 8 из 255
// подобран по факту: два кадра одной генерации с чуть иной позой дают 15-40, а кроп той же
// фотографии — 2-6. Тонкой настройки тут не нужно, разрыв между «то же самое» и «другое» большой.
//
// ЗАПУСК:
//   node сб2приёмка.cjs <папка> [маска]     проверить и напечатать приговор
//   node сб2приёмка.cjs <папка> [маска] --в-тг   годные сразу уходят в Traffic
'use strict';

const fs = require('node:fs');
const path = require('node:path');
const { execFileSync, spawnSync } = require('node:child_process');

const РЕПО = '/Users/qq/Desktop/neironka-poster';
// ffprobe берём системный: рядом с ffmpeg-static его нет, и замер длительности молча возвращал
// ноль — сборка «на 0 секунд» выглядела исправной (29.08).
const FFPROBE = ['/opt/homebrew/bin/ffprobe', '/usr/local/bin/ffprobe']
  .find((p) => fs.existsSync(p)) || 'ffprobe';
const FFMPEG = path.join(РЕПО, 'node_modules/ffmpeg-static/ffmpeg');

const ПОРОГ = Number(process.env.СБ2_ПОРОГ || 8);
const МИН_СЕК = Number(process.env.СБ2_МИН_СЕК || 9);

const папка = process.argv[2];
const маска = (process.argv[3] && !process.argv[3].startsWith('--')) ? process.argv[3] : 'сб2-';
const ВТГ = process.argv.includes('--в-тг');
if (!папка) { console.log('нужна папка с постами'); process.exit(2); }

// ПОСТЕР НА КАДРЕ 2 ПРОВЕРЯЕМ ТЕКСТОМ (30.08). Четыре поста уехали в группу набором фотографий:
// на кадре 2 у них не было ни одного знака — постер не заказался, а приёмка этого не видела.
// Замер на реальных файлах: настоящий постер даёт 128-844 знака (35 из 35 постов), отсутствие
// постера — ровно 0. Порог 60 знаков лежит посередине с запасом больше чем вдвое.
// Считаем локально через macOS Vision, платных обращений нет.
const TEXTBOX = require('node:os').homedir() + '/.neironka/bin/textbox';
function знаковНаКадре(файл) {
  if (!fs.existsSync(файл) || !fs.existsSync(TEXTBOX)) return null;
  const r = spawnSync(TEXTBOX, [файл], { encoding: 'utf8', timeout: 30000 });
  if (r.status !== 0) return null;
  return String(r.stdout || '').replace(/\s+/g, '').length;
}

// БРАК ТГ-СКРИНА (30.08). Один пост уехал с полностью английским интерфейсом. Признаки замерены
// на 22 заведомо бракованных и 228 заведомо годных скринах: 22 из 22 пойманы, ложных ноль.
// Время в формате AM/PM — сильнейший признак: в русском телеграме часы всегда 24-часовые.
// «общени» без первых букв не случайно: значок скрепки съедает начало слова «Сообщение», и
// строгая проверка на полное слово выбрасывала треть хороших скринов.
const АНГЛИЦИЗМЫ = /\b(last seen|today|message|back|recently|online|yesterday)\b/i;
function скринБракован(файл) {
  if (!fs.existsSync(файл) || !fs.existsSync(TEXTBOX)) return null;
  const r = spawnSync(TEXTBOX, [файл], { encoding: 'utf8', timeout: 30000 });
  if (r.status !== 0) return null;
  const текст = String(r.stdout || '');
  const беды = [];
  if (АНГЛИЦИЗМЫ.test(текст)) беды.push('английский интерфейс');
  if (/\d{1,2}:\d{2}\s*(AM|PM)/i.test(текст)) беды.push('время в формате AM/PM');
  if (!/был\W{0,3}а\W{0,3}\s*(недавно|давно)/i.test(текст) && !/в сети/i.test(текст)) {
    беды.push('нет русского статуса «был(а) недавно»');
  }
  if (!/общени/i.test(текст)) беды.push('нет поля «Сообщение»');
  return беды;
}

/** Отпечаток кадра: 64 числа яркости. Файла нет — null, это отдельный случай, а не «чёрный кадр». */
function отпечаток(файл) {
  if (!fs.existsSync(файл)) return null;
  const r = spawnSync(FFMPEG, ['-v', 'error', '-i', файл, '-vf', 'scale=8:8,format=gray',
    '-f', 'rawvideo', '-'], { maxBuffer: 1 << 20, timeout: 30000 });
  const b = r.stdout;
  return (b && b.length >= 64) ? Array.from(b.slice(0, 64)) : null;
}
const расхождение = (a, b) => (!a || !b) ? Infinity
  : a.reduce((s, x, i) => s + Math.abs(x - b[i]), 0) / a.length;

function длительность(файл) {
  try {
    const s = execFileSync(FFPROBE, ['-v', 'error', '-show_entries', 'format=duration',
      '-of', 'default=nw=1:nk=1', файл], { encoding: 'utf8' }).trim();
    return Number(s) || 0;
  } catch { return 0; }
}
function естьЗвук(файл) {
  try {
    return execFileSync(FFPROBE, ['-v', 'error', '-select_streams', 'a', '-show_entries',
      'stream=codec_name', '-of', 'default=nw=1:nk=1', файл], { encoding: 'utf8' }).trim().length > 0;
  } catch { return false; }
}

const посты = fs.readdirSync(папка)
  .filter((f) => f.endsWith('.mp4') && f.startsWith(маска)).sort();
if (!посты.length) { console.log(`в ${папка} нет постов по маске «${маска}»`); process.exit(0); }

const КАДРЫ = path.join(папка, '_кадры');
const годные = [], брак = [];
const виденные = { 1: [], 4: [] };

for (const файл of посты) {
  const полный = path.join(папка, файл);
  const имя = файл.replace(/\.mp4$/, '');
  const беды = [];

  const сек = длительность(полный);
  if (сек < МИН_СЕК) беды.push(`длина ${сек.toFixed(1)}с (ждём от ${МИН_СЕК})`);
  if (!естьЗвук(полный)) беды.push('нет звуковой дорожки');

  const д = path.join(КАДРЫ, имя);
  const о = {};
  for (const н of [1, 3, 4]) о[н] = отпечаток(path.join(д, `frame${н}.jpg`));

  // НЕТ КАДРОВ — ЭТО БРАК, А НЕ «ПРОВЕРЯТЬ НЕЧЕГО» (30.08). Раньше отсутствие кадра снимало ВСЕ
  // проверки разом: `if (!о[н]) continue`, и пост без единого кадра получал галочку. Два поста
  // Ани прошли приёмку именно так.
  if (!о[1] && !о[3] && !о[4]) беды.push('кадров нет — проверить нечем');

  // У АРТ-ТЕМ КАДР 2 БЕЗ ТЕКСТА — ЭТО НОРМА (31.08). Там второй красивый кадр вместо макета, и
  // требовать с него надписи значит браковать исправные посты. Список тем берём из имени файла.
  const АРТ_ТЕМЫ = /(rain-look|bw-editorial|golden-portrait|retro-90s|double-exposure|doodle|popart|winx|gta|fantasy|plush-toy|anime|pixar)/;
  if (!АРТ_ТЕМЫ.test(имя)) {
    const постер = знаковНаКадре(path.join(д, 'frame2.jpg'));
    if (постер !== null && постер < 60) {
      беды.push(`на кадре 2 нет постера (${постер} знаков, ждём от 60)`);
    }
  }
  const скрин = скринБракован(path.join(д, 'frame4-тг.jpg'));
  if (скрин && скрин.length) беды.push('скрин переписки: ' + скрин.join(', '));

  if (о[1] && о[3] && расхождение(о[1], о[3]) < 10) {
    беды.push(`кадр 3 повторяет кадр 1 (${расхождение(о[1], о[3]).toFixed(1)})`);
  }
  for (const н of [1, 4]) {
    if (!о[н]) continue;
    const близкий = виденные[н].find((в) => расхождение(в.о, о[н]) < ПОРОГ);
    if (близкий) беды.push(`кадр ${н} повторяет пост ${близкий.имя}`);
  }

  if (беды.length) { брак.push({ имя, беды }); } else {
    годные.push(полный);
    for (const н of [1, 4]) if (о[н]) виденные[н].push({ имя, о: о[н] });
  }
  console.log(`${беды.length ? '✗' : '✓'} ${имя}${беды.length ? ' — ' + беды.join('; ') : ''}`);
}

console.log(`\nгодных ${годные.length} из ${посты.length}, брака ${брак.length}`);

// ЖУРНАЛ ОТПРАВЛЕННЫХ (29.08). Первый же прогон с «--в-тг» послал владельцу десять повторов:
// приёмка не помнила, что эти посты уже уходили поштучно, и отправила все годные разом. Журнал
// лежит рядом с постами, а не в /tmp: временную папку система чистит, и память об отправках
// исчезала бы вместе с ней ровно тогда, когда она нужна.
const ЖУРНАЛ = path.join(папка, '_отправлено.json');
const ужеСлали = (() => {
  try { return new Set(JSON.parse(fs.readFileSync(ЖУРНАЛ, 'utf8'))); } catch { return new Set(); }
})();
const кОтправке = годные.filter((ф) => !ужеСлали.has(path.basename(ф)));
if (годные.length !== кОтправке.length) {
  console.log(`уже отправляли раньше: ${годные.length - кОтправке.length}, их пропускаем`);
}

if (ВТГ && кОтправке.length) {
  const дом = require('node:os').homedir() + '/.neironka/';
  const чит = (f) => { try { return fs.readFileSync(дом + f, 'utf8').trim(); } catch { return ''; } };
  const env = { ...process.env, TELEGRAM_BOT_TOKEN: чит('tgtok_контент'), TELEGRAM_CHAT_ID: чит('tgchat_контент') };
  // ПО ОДНОМУ, С ИМЕНЕМ И ОПИСАНИЕМ (31.08, владелец: «ты кидаешь посты без нейминга, нужен
  // нейминг и описание, и я буду проверять»). Альбомом по восемь ролики летели без подписей:
  // в группе видно только видео, и понять, какой это тренд и что за текст к нему пойдёт, нельзя.
  // Теперь у каждого ролика в подписи его имя (сборка-модель-тренд-вид-проход) и готовый текст
  // для тиктока из файла <имя>.tt.txt, который лежит рядом.
  for (let i = 0; i < кОтправке.length; i += 1) {
    const пачка = кОтправке.slice(i, i + 1);
    const имяП = path.basename(пачка[0], '.mp4');
    let описание = '';
    try { описание = fs.readFileSync(path.join(папка, имяП + '.tt.txt'), 'utf8').trim(); } catch {}
    const подпись = имяП + (описание ? '\n\n' + описание : '');
    const r = spawnSync('node', [path.join(РЕПО, 'tgsend.cjs'), ...пачка, '--note', подпись],
      { env, encoding: 'utf8' });
    const строка = (r.stdout || r.stderr || '').trim().split('\n').slice(-1)[0];
    console.log(строка);
    // В журнал пишем ТОЛЬКО то, что телеграм принял: пометить до ответа значит потерять пост
    // навсегда при первой же ошибке сети.
    if (r.status === 0 && /отправлено/.test(строка)) {
      пачка.forEach((ф) => ужеСлали.add(path.basename(ф)));
      fs.writeFileSync(ЖУРНАЛ, JSON.stringify([...ужеСлали], null, 1));
    }
  }
} else if (ВТГ) {
  console.log('нового к отправке нет');
}
