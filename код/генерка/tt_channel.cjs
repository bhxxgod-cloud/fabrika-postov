// ТТ-ЗАГОЛОВКИ ГОЛОСОМ КАНАЛА-СТИЛИСТА (утверждено владельцем 21.08) + строка «ссылка в био».
// Мост до штатного коммита в hooks2/captions. Хук на кадре — от девочки, заголовок — от канала.
const ЗАГОЛОВКИ = {
  'img-face-report': ['ЕЁ САМООЦЕНКА ПОСЛЕ ЭТОГО >>', 'ОЦЕНИЛИ ЕЁ ВНЕШНОСТЬ ЧЕСТНО, ОНА ТАКОГО НЕ ЖДАЛА'],
  'img-nose-verdict': { хвалит: ['ПОСЛЕ ЭТОГО ГАЙДА ДЕВОЧКИ НАЧИНАЮТ ЛЮБИТЬ СВОЙ НОС'], примеряет: ['ОНА ПРИМЕРИЛА НОВЫЙ НОС ЗА МИНУТУ, ВЕРДИКТ В КОНЦЕ'] },
  'img-brow-map': ['ТРЕНД СДЕЛАЛ ПРИГОВОР СТАРЫМ БРОВЯМ 😢'],
  'img-haircut-match': ['ДЕВОЧКИ, ОТГОВОРИТЕ ЕЁ ОТ НОВОГО ОБРАЗА 😂😂'],
  'img-makeup-colortype': ['ЕЁ ЦВЕТА ОКАЗАЛИСЬ НЕ ТЕ, ЧТО В КОСМЕТИЧКЕ'],
  'img-beauty-guide': ['ОНА ПОПРОБОВАЛА ГАЙД И В НЕЁ ВЛЮБИЛСЯ КРАШ 😍😍'],
  'img-boyfriend-match': ['ПОДБИРАЕМ ПАРНЯ ПО ТИПАЖУ 🤫 РЕЗУЛЬТАТ В КОНЦЕ'],
  '*арт': ['ТЫ НЕ ПОВЕРИШЬ, ЧТО ЭТО ОДНА И ТА ЖЕ ДЕВОЧКА'],
};
const БИО = ['ссылка на шаблон в био', 'ссылка на промпт в био', 'ссылка на гайд в био'];
const h = (s) => { let x = 2166136261; for (const c of String(s)) x = Math.imul(x ^ c.charCodeAt(0), 16777619) >>> 0; return x >>> 0; };
// tt: готовый текст из hooks2.caption('tiktok'); заменяем первую строку и добавляем био-строку перед тегами.
/**
 * Подпись для тиктока.
 *
 * ВИДЕО И ФОТО ПОДПИСЫВАЮТСЯ ПО-РАЗНОМУ (30.08, правило владельца). У фото-поста тикток
 * показывает отдельный заголовок, у ВИДЕО его нет вовсе — там одно описание под роликом.
 * Раньше заголовок стоял первой строкой заглавными буквами и у роликов просто пропадал: пост
 * начинался с середины мысли. Поэтому для видео заголовок вплетается в текст как первая фраза,
 * а не висит отдельной строкой, и всё описание идёт слитно, с хештегами в самом низу.
 *
 * @param {string} tpl шаблон тренда
 * @param {string} ttТекст заготовка описания (первая строка — место под заголовок)
 * @param {object} [o] seed для выбора варианта, ветка, и вид: 'видео' (по умолчанию) либо 'фото'
 */
function каналТТ(tpl, ttТекст, { seed = '', ветка = null, вид = 'видео', сб2Описание = '' } = {}) {
  let з = ЗАГОЛОВКИ[tpl] || ЗАГОЛОВКИ['*арт'];
  if (!Array.isArray(з)) з = з[ветка || 'хвалит'] || Object.values(з)[0];
  const заголовок = з[h(seed) % з.length];
  const строки = String(ttТекст).split('\n');
  const био = БИО[h(seed + 'b') % БИО.length];

  // УНИВЕРСАЛЬНОЕ ОПИСАНИЕ, БЕЗ РАМКИ (30.08, решение владельца: «мы не разберём, на какой акк
  // что постить — они вразнобой; давай универсальное описание, типа повторить можно ниже и просто
  // что делать»).
  //
  // ПОЧЕМУ НЕ ОТ ПЕРВОГО ЛИЦА И НЕ «РАЗБОР ПОДПИСЧИЦЫ». Один и тот же ролик уходит и на аккаунты
  // вида «Приговор стилиста» (там ведущая разбирает других), и на «Новая я» (там личный глоу-ап).
  // Личное «мне написал бывший» на экспертном аккаунте звучит хвастовством, а «разбираю
  // подписчицу» на личном — чужой ролью. Описание, которое не говорит НИ про себя, НИ про
  // подписчицу, подходит обоим: оно про то, что показано в ролике, и как это повторить.
  // Историю рассказывает сам ролик — хук на кадре и переписка в конце; описание её не дублирует.
  if (сб2Описание) {
    // СТРОЕНИЕ ОПИСАНИЯ ЗАДАНО ВЛАДЕЛЬЦЕМ (30.08): строка-реакция с сердечками, потом что делать,
    // потом ровно ПЯТЬ хештегов. Реакция короткая и без «я»: она про результат в ролике, а не
    // про автора, поэтому одинаково ложится и на экспертные аккаунты, и на личные.
    const РЕАКЦИИ = [
      'получилось супер 🥰', 'ну красивый же результат?) 💗', 'мне очень нравится 🩷',
      'это просто топ 😍', 'вышло лучше, чем ждала 💖', 'ну очень красиво получилось 🥹💗',
      'до сих пор пересматриваю 🫶', 'вот это результат 😻',
    ];
    const реакция = РЕАКЦИИ[h(seed + 'r') % РЕАКЦИИ.length];
    const шаги = 'повторить можно так: в яндексе набираем «нейронка про шаблоны» → '
      + 'загружаем одно селфи → выбираем этот разбор. готово за минуту, бесплатно';
    // Ровно пять тегов: тикток показывает первые несколько, а длинный хвост читается как спам.
    // Берём теги темы, добиваем общими и режем до пяти.
    const свои = String(ttТекст).split('\n').filter((с) => /^#/.test(с.trim()))
      .join(' ').trim().split(/\s+/).filter(Boolean);
    const общие = ['#нейросеть', '#глоуап', '#тренд', '#рек', '#fyp'];
    const пять = [];
    for (const т of [...свои, ...общие]) {
      const k = т.toLowerCase();
      if (!пять.some((x) => x.toLowerCase() === k)) пять.push(т);
      if (пять.length === 5) break;
    }
    return безМед([реакция, шаги, био, пять.join(' ')].filter(Boolean).join('\n\n'));
  }

  if (вид === 'видео') {
    // Заголовок с капса переводим в обычную речь: строчными он читается как продолжение мысли,
    // а капсом посреди описания — как кричащая вставка.
    const первая = заголовок.charAt(0) + заголовок.slice(1).toLowerCase();
    // Первая строка заготовки была местом под заголовок — её отбрасываем и склеиваем остальное
    // в один абзац, разделяя шаги точкой с запятой: в ленте перенос строки съедается свёрткой.
    const тело = строки.slice(1).filter((с) => с.trim() && !/^#/.test(с.trim()));
    const теги = строки.filter((с) => /^#/.test(с.trim())).join(' ').trim();
    // Куски склеиваем ЧЕРЕЗ ЗНАКИ, а не пробелом: без них выходит «любить свой нос оказалось, у
    // меня своя история» — две фразы срастаются в одну и текст перестаёт читаться.
    // Нумерованные шаги теряют цифры (в сплошном абзаце «1.» выглядит опечаткой) и разделяются
    // стрелками: так последовательность видна без переносов, которые лента всё равно свернёт.
    const шаги = [], проза = [];
    for (const с of тело) {
      const т = с.trim();
      (/^\d+[.)]\s/.test(т) ? шаги : проза).push(т.replace(/^\d+[.)]\s*/, ''));
    }
    const тчк = (т) => (/[.!?…:]$/.test(т) ? т : т + '.');
    const части = [тчк(первая), ...проза.map(тчк)];
    if (шаги.length) части.push(шаги.join(' → '));
    const абзац = части.join(' ').replace(/\s+/g, ' ').trim();
    return безМед([абзац, био, теги].filter(Boolean).join('\n\n'));
  }

  строки[0] = заголовок;
  let текст = безМед(строки.join('\n'));
  const и = текст.lastIndexOf('\n\n#');
  return и > 0 ? текст.slice(0, и) + '\n' + био + текст.slice(и) : текст + '\n' + био;
}
// без мед-лексики нигде (тт И инста) + дедуп тегов: замена #ринопластика→#формалица
// сталкивается с уже стоящим #формалица и даёт дубль в строке тегов (баг 21.08, нос у n02)
function безМед(т) {
  т = String(т).replace(/#ринопластика/gi, '#формалица').replace(/хирург\w*/gi, 'мастер');
  return т.split('\n').map((с) => {
    if (!/^#/.test(с.trim())) return с;
    const seen = new Set();
    return с.split(/\s+/).filter((t) => { const k = t.toLowerCase(); if (seen.has(k)) return false; seen.add(k); return true; }).join(' ');
  }).join('\n');
}
module.exports = { каналТТ, ЗАГОЛОВКИ, безМед };
