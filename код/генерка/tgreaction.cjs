/**
 * Собрать кадр 4 «реакция в телеграме».
 * @param {string} фото не используется (оставлен для совместимости вызова)
 * @param {string} out куда записать jpg 1080x1920
 * @param {string} ключ id поста: от него детерминированно выбираются диалог, время и батарея
 * @param {string} [тип] бывший|парень|подруга|мама|коллега
 */
async function собрать(фото, out, ключ, тип) {
  const типы = Object.keys(АРХЕТИПЫ);
  const хэш = [...String(ключ)].reduce((a, c) => (a * 31 + c.charCodeAt(0)) >>> 0, 7);
  const т = тип && АРХЕТИПЫ[тип] ? тип : типы[хэш % типы.length];
  const а = АРХЕТИПЫ[т];
  const имя = а.имена[(хэш >>> 3) % а.имена.length];
  const реплика = а.реплики[(хэш >>> 9) % а.реплики.length];
  const час = 20 + ((хэш >>> 5) % 3);
  const мин = (хэш >>> 7) % 60;
  const батарея = 28 + ((хэш >>> 11) % 60);
  const непрочит = 1 + ((хэш >>> 13) % 8);
  const диалог = { имя, реплики: [{ он: реплика }] };
  const прелюдия = ПРЕЛЮДИИ[(хэш >>> 15) % ПРЕЛЮДИИ.length];
  const сырой = out.replace(/(\.\w+)$/, '.экран$1');
  await renderHtml(html(диалог, час, мин, батарея, непрочит, прелюдия), сырой, W, H);
  const { execFileSync } = require('node:child_process');
  const FF = require(path.join(__dirname, '..', 'node_modules', 'ffmpeg-static'));
  execFileSync(FF, ['-y', '-loglevel', 'error', '-i', сырой,
    '-vf', `scale=-2:${КАДР_H},pad=${КАДР_W}:${КАДР_H}:(ow-iw)/2:0:color=0x0d0d12`,
    '-q:v', '2', out]);
  try { fs.unlinkSync(сырой); } catch {}
  return { архетип: т, имя, реплика };
}

