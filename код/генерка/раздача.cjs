// раздача.cjs — НАЗНАЧЕНИЕ СВЕЖЕЙ ЗАГЛАВНОЙ КАЖДОМУ ПОСТУ (29.08).
//
// ЗАЧЕМ. Приказ владельца: «давай 1 кадр новый закажем, все след посты чтобы были уникальными».
// Заглавная — это то, по чему пост открывают; если она повторяется, лента читается как штамповка,
// даже когда тренды внутри разные.
//
// ПОЧЕМУ ОТДЕЛЬНЫМ ШАГОМ, А НЕ ВНУТРИ СБОРКИ. Сборщик умеет брать свободную обложку сам, но при
// параллельном запуске три потока стартуют одновременно, читают один и тот же реестр и разбирают
// одну и ту же заглавную — так очки-22 ушла в пять постов подряд. Раздача выполняется ОДИН раз до
// старта потоков, каждому посту достаётся своя, и только после этого запускается сборка.
//
// РЕЕСТР ОБЩИЙ СО СБОРЩИКОМ (реестр.json рядом с постами девочки): всё, что уже уходило в работу,
// сюда больше не попадёт. Именно это и делает «следующие посты» уникальными, а не только текущую
// пачку.
//
// ЗАПУСК: node раздача.cjs <девочка> <шаблон,шаблон,...>
// Печатает строки «шаблон|обложка.jpg» — по одной на пост, готовые к скармливанию в цикл.
'use strict';

const fs = require('node:fs');
const path = require('node:path');

const H = process.env.HOME + '/Desktop/НЕЙРОНКА';
const ОБЛ = H + '/ОБЛОЖКИ-ДОГЕН';
const ВЫХ = process.env.OUT_DIR || (H + '/ГЕНЕРАЦИЯ-2.0');

const ИМЯ = process.argv[2];
const ШАБЛОНЫ = String(process.argv[3] || '').split(',').filter(Boolean);
if (!ИМЯ || !ШАБЛОНЫ.length) {
  console.error('нужно: node раздача.cjs <девочка> <шаблон,шаблон,...>');
  process.exit(2);
}

const папка = path.join(ОБЛ, ИМЯ);
// Та же выборка, что у сборщика: всё, кроме служебных сеток, листов и явного брака.
const всеОбл = fs.readdirSync(папка)
  .filter((f) => /\.(jpe?g|png)$/i.test(f) && !/^[_.]/.test(f) && !/_сетка|_лист|брак/i.test(f))
  .sort();

const реестр = path.join(ВЫХ, ИМЯ, 'реестр.json');
const занятые = fs.existsSync(реестр)
  ? JSON.parse(fs.readFileSync(реестр, 'utf8'))
  : { обложки: [], хуки: [] };

const свободные = всеОбл.filter((f) => !занятые.обложки.includes(f));
// Свежие (те, что covergen положил последними) идут первыми: у них ещё ни одного поста.
свободные.sort((a, b) =>
  fs.statSync(path.join(папка, b)).mtimeMs - fs.statSync(path.join(папка, a)).mtimeMs);

// ВЫДАЁМ СТОЛЬКО, СКОЛЬКО ЕСТЬ (29.08). Раньше нехватка хотя бы одной заглавной роняла раздачу
// целиком, и вызывающий получал пустоту вместо четырнадцати готовых назначений: пятнадцать постов
// не собирались из-за одной недостающей обложки. Теперь отдаём доступное, а про остаток сообщаем —
// вызывающий вернётся за добавкой, когда covergen доложит.
const сколько = Math.min(свободные.length, ШАБЛОНЫ.length);
if (!сколько) {
  console.error(`НЕТ СВОБОДНЫХ ЗАГЛАВНЫХ у «${ИМЯ}». `
    + `Догенерируй: node covergen.cjs --go <исходник ${ИМЯ}> ${ШАБЛОНЫ.length}`);
  process.exit(3);
}
if (сколько < ШАБЛОНЫ.length) {
  console.error(`заглавных хватает на ${сколько} из ${ШАБЛОНЫ.length}: остальные подождут covergen`);
}

const выдано = [];
ШАБЛОНЫ.slice(0, сколько).forEach((tpl, i) => {
  const обл = свободные[i];
  выдано.push(обл);
  console.log(`${tpl}|${обл}`);
});

// Пишем в реестр СРАЗУ: если сборка часть постов не осилит, повторный запуск возьмёт следующие
// заглавные, а не те же самые. Потерять пару обложек дешевле, чем выпустить два поста с одной.
fs.mkdirSync(path.dirname(реестр), { recursive: true });
занятые.обложки.push(...выдано);
fs.writeFileSync(реестр, JSON.stringify(занятые, null, 1));
console.error(`выдано ${выдано.length}, свободных осталось ${свободные.length - выдано.length}`);
