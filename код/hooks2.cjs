/**
 * ОТСЕВ ВЛАДЕЛЬЦА. Живёт файлом рядом, а не правкой пулов в коде, по двум причинам.
 *
 * Первая: хук в пуле лежит ПАРОЙ с продолжением подписи, и выкусывание строк из
 * кода рано или поздно разведёт пару с её половиной. Фильтр по тексту хука
 * оставляет пару целой.
 *
 * Вторая: отсев это решение про содержание, а не про код. Владелец пересматривает
 * его пачками, и такое решение должно быть обратимым одним файлом, а не
 * восстановлением по git.
 *
 * Пустой или отсутствующий файл значит «не отсеиваем ничего», то есть поведение
 * ровно как до отсева.
 */
const ВЫЧЕРКНУТО = (() => {
  try {
    const сырое = JSON.parse(require('fs').readFileSync(
      require('path').join(__dirname, 'вычеркнутые-хуки.json'), 'utf8'));
    const карта = {};
    for (const [шаблон, список] of Object.entries(сырое)) {
      карта[шаблон] = new Set((список || []).map((т) => String(т).replace(/\s+/g, ' ').trim()));
    }
    return карта;
  } catch { return {}; }
})();

const вычеркнут = (template, хук) => {
  const набор = ВЫЧЕРКНУТО[String(template || '').trim()];
  return !!набор && набор.has(String(хук).replace(/\s+/g, ' ').trim());
};

/** Полный пул шаблона: свои хуки + общие блоки своей группы. Подписчичьи строки отдельно. */
function пулы(template) {
  const r = запись(template);
  if (!r) return null;
  const свои = r.хуки.filter(([h]) => !вычеркнут(template, h));
  const общие = r.группа === 'разбор' ? УНИВЕРСАЛ_КАРТОЧКИ
    : r.группа === 'перерисовка' ? НЕЙРОНКА_УМЕЕТ
      : r.группа === 'снимок' ? [...НЕЙРОНКА_УМЕЕТ, ...РИЛ_ТРЕНД]
        : r.группа === 'флекс' ? РИЛ_ТРЕНД : [];
  const все = [...свои, ...общие];
  const проПодп = (t) => /подписчиц/i.test(t);
  const подписчица = все.filter(([h]) => проПодп(h)).concat(r.группа === 'разбор' ? ПОДПИСЧИЦА_КАРТОЧКИ : []);
  const обычные = все.filter(([h]) => !проПодп(h));
  return { r, обычные, подписчица };
}

/**
 * Каждый ли 4-й пост про подписчицу. Считаем СЧЁТЧИКОМ внутри девочки (opts.seq, порядковый номер
 * поста у персоны), потому что хеш на пачке из 8 постов давал 4 из 8 (маркетолог, живая сборка).
 * Хеш id остаётся фолбэком, когда seq не передан.
 */
function проПодписчицу(o) {
  const каждый = Number(process.env.SUB_EVERY || 4);
  if (!каждый || каждый < 2) return false;
  if (o && o.seq != null && o.seq !== '') return (Number(o.seq) % каждый) === каждый - 1;
  if (o && o.id) return seedNum(String(o.id)) % каждый === 0;
  return false;
}

/**
 * Выбор пары для поста. Возвращает {hook, продолжение, r} или null для незнакомого шаблона.
 * avoidSet: занятые хуки (плоско), обходим; seed/id: детерминированный выбор.
 */
function pickPair(template, opts) {
  const o = opts || {};
  const p = пулы(template);
  if (!p) return null;
  const { r } = p;
  const флоск = (s) => String(s || '').replace(/\s+/g, ' ').trim();
  const занято = new Set((o.avoidSet || []).map(флоск).filter(Boolean));
  const хочетПодп = (r.группа === 'разбор' || r.группа === 'перерисовка') && p.подписчица.length && проПодписчицу(o);
  let пул = хочетПодп ? p.подписчица : p.обычные;
  const свободные = пул.filter(([h]) => !занято.has(флоск(h)) && h !== o.avoid);
  if (свободные.length) пул = свободные;
  const seed = String(o.seed || o.id || `${template}|${o.seq || 0}`);
  let [hook, продолжение] = пул[хеш(seed, пул.length)];
  if (/\{город\}/.test(hook)) hook = hook.replace('{город}', ГОРОДА_GTA[хеш(seed + '#city', ГОРОДА_GTA.length)]);
  return { hook, продолжение, r, подписчица: !!хочетПодп };
}
/** Пара по уже выбранному хуку (для подписи под известной обложкой). null, если хук чужой. */
function pairFor(template, hook) {
  const p = пулы(template); if (!p) return null;
  const флоск = (s) => String(s || '').replace(/\s+/g, ' ').trim().toLowerCase();
  const h = флоск(hook);
  const все = [...p.обычные, ...p.подписчица];
  let row = все.find(([x]) => флоск(x) === h);
  if (!row && /\{город\}/.test(все.map((x) => x[0]).join(' '))) row = все.find(([x]) => /\{город\}/.test(x) && флоск(x.replace('{город}', '')).slice(0, 12) === h.slice(0, 12));
  if (!row) return null;
  return { hook: String(hook), продолжение: row[1], r: p.r, подписчица: /подписчиц/i.test(row[0]) };
}
/** Одна строка хука (совместимо с hooks.pick). */
function pick(template, opts) { const p = pickPair(template, opts); return p ? p.hook : null; }

/** Пять тегов: 3 тематических + 2 общих, порядок по хешу поста. */
function tags(template, platform, seed) {
  const r = запись(template); if (!r) return '';
  const pl = плоскоПлощадка(platform);
  const общие = (pl === 'instagram' && r.группа !== 'разбор' ? ОБЩИЕ_ТЕГИ.instagramArt : ОБЩИЕ_ТЕГИ[pl]).slice();
  const s = String(seed || template);
  const a = общие.splice(хеш(s + '#t1', общие.length), 1)[0];
  const b = общие.splice(хеш(s + '#t2', общие.length), 1)[0];
  const все = [...r.теги, a, b];
  // Ротируем порядок, чтобы хвосты у одной девочки не совпадали.
  const k = хеш(s + '#rot', все.length);
  return [...все.slice(k), ...все.slice(0, k)].join(' ');
}

/**
 * Подпись под площадку. Инстаграм: продолжение + «где и как» + теги. ТикТок: заголовок капсом +
 * продолжение + шаги 1-2-3 + теги. Слово-маркер («промпты»/«шаблоны») подставляется по площадке.
 */
function caption(template, pair, platform, opts) {
  const o = opts || {};
  const r = pair && pair.r ? pair.r : запись(template);
  if (!r) return null;
  const pl = плоскоПлощадка(platform);
  const слово = o.marker || ЭФФЕКТ_СЛОВО[pl];
  const seed = String(o.seed || o.id || pair.hook);
  const продолжение = String(pair.продолжение || '').trim();
  const хвост = продолжение.endsWith(':') ? '' : ' где сделала:';
  const где = pl === 'instagram'
    ? `${продолжение}${хвост} в яндексе «нейронка про ${слово}», одно селфи, дальше «${r.эффект}», готово за минуту`
    : `${продолжение}${хвост}\n1. в яндексе набираем «нейронка про ${слово}»\n2. грузим одно селфи\n3. открываем «${r.эффект}», готово за минуту`;
  const заголовки = pair.подписчица ? ПОДПИСЧИЦА_ЗАГОЛОВКИ : r.заголовки;
  const шапка = pl === 'tiktok' ? заголовки[хеш(seed + '#title', заголовки.length)] + '\n' : '';
  const текст = `${шапка}${где}\n\n${tags(template, pl, seed)}`;
  return текст;
}

/** Всё разом для сборщика: хук + две подписи (тг-пост это 4 фото + видео + 2 описания). */
function build(template, opts) {
  const pair = pickPair(template, opts);
  if (!pair) return null;
  return {
    hook: pair.hook, подписчица: pair.подписчица,
    instagram: caption(template, pair, 'instagram', opts),
    tiktok: caption(template, pair, 'tiktok', opts),
  };
}

