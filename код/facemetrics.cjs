// ЗАЧЕМ (претензия владельца 14.08: «карточки трендов не совсем реальные — они рандомно нарисованы»).
// Он прав, и это было записано в самом cardgen.cjs открытым текстом: числа брались из
// псевдослучайного потока по id поста, а оправдание звучало как «это честно ровно настолько же,
// насколько „оценка" у партнёра: там числа тоже рисует модель, а не измерение». Оправдание плохое.
// Псевдослучайность даёт устойчивость (одно фото — одна карточка) и разнообразие между постами, но
// НЕ СВЯЗЬ С ЛИЦОМ: у двух разных девушек «симметрия» отличалась потому, что отличался id поста.
// Зритель этого не докажет, но и ценности в такой карточке нет — она украшение, а не разбор.
//
// ЧТО ЗДЕСЬ МОЖНО ИЗМЕРИТЬ ЧЕСТНО. Детектор yunet отдаёт рамку лица и ПЯТЬ ТОЧЕК: правый глаз,
// левый глаз, кончик носа, правый и левый углы рта. Из них считаются настоящие величины:
//
//   СИММЕТРИЯ   насколько глаза и углы рта равноудалены от вертикальной оси лица;
//   ПРОПОРЦИИ   отношение ширины лица к высоте против канона 0.75;
//   ГЛАЗА       межзрачковое расстояние к ширине лица (канон около 0.46);
//   ГУБЫ        ширина рта к межзрачковому расстоянию (канон около 1.0);
//   НОС         стоит ли нос по вертикали между линией глаз и линией рта в каноническом месте;
//   ОВАЛ ЛИЦА   форма выводится из отношения сторон рамки, а не выбирается из списка;
//   ГАРМОНИЯ    среднее по измеренным — то есть тоже измерение, а не отдельная выдумка.
//
// ЧЕГО ИЗМЕРИТЬ НЕЛЬЗЯ, И ЭТО НАДО ЗНАТЬ. Точек для БРОВЕЙ у yunet нет вообще, а КОЖА по одному
// кадру меряется только косвенно (текстура через sharpmeter, и это свойство СЪЁМКИ, а не кожи:
// мягкий свет и сглаживание камеры дадут ту же цифру, что и уход). Эти две строки остаются на
// прежнем детерминированном потоке, и врать про них «измерено» нельзя.
//
// ПРО ЧЕСТНОСТЬ ШКАЛЫ. Само превращение пропорции в «балл красоты» условно: канонические отношения
// это традиция портретной живописи, а не закон природы. Но величина ПОД баллом теперь настоящая и
// принадлежит именно этому лицу — разные девушки получают разные числа по разным причинам, а не
// потому, что у постов разные id. Диапазон держим прежний (7.6-9.6): карточка остаётся приятной,
// иначе смысл поста ломается, а разброс внутри диапазона теперь заслуженный.
//
// Запуск для проверки: node facemetrics.cjs <фото> [<фото>…]
const fs = require('node:fs');
const path = require('node:path');
const { spawnSync } = require('node:child_process');

const YUNET = process.env.YUNET || path.join(__dirname, 'yunet.onnx');

// Пять точек приходят в хвосте строки детектора: x,y,w,h, затем 5 пар координат, затем уверенность.
const PY = `
import sys, json, cv2
img = cv2.imread(sys.argv[1])
if img is None:
    print(json.dumps({'error': 'кадр не читается'})); sys.exit()
h, w = img.shape[:2]
d = cv2.FaceDetectorYN_create(sys.argv[2], '', (w, h), 0.5, 0.3, 200)
d.setInputSize((w, h))
_, f = d.detect(img)
if f is None or not len(f):
    print(json.dumps({'w': w, 'h': h, 'face': None})); sys.exit()
r = max(f, key=lambda t: t[2] * t[3])
print(json.dumps({
    'w': w, 'h': h,
    'face': {'x': float(r[0]), 'y': float(r[1]), 'w': float(r[2]), 'h': float(r[3])},
    'точки': {
        'глаз_п': [float(r[4]), float(r[5])],
        'глаз_л': [float(r[6]), float(r[7])],
        'нос':    [float(r[8]), float(r[9])],
        'рот_п':  [float(r[10]), float(r[11])],
        'рот_л':  [float(r[12]), float(r[13])],
    },
    'увер': float(r[-1]),
}))
`;

// Vision-фоллбэк (25.08): cv2 в системе нет, питон-yunet пуст. Бинарь ~/.neironka/bin/facebox
// (swift+Vision) отдаёт {w,h,face,точки} в том же формате. Используем, когда питон не дал точек.
function точкиVision(src) {
  try {
    const FB = require('os').homedir() + '/.neironka/bin/facebox';
    if (!fs.existsSync(FB)) return null;
    const r = spawnSync(FB, [src], { encoding: 'utf8', maxBuffer: 1 << 22 });
    const line = String(r.stdout || '').trim().split('\n').filter((s) => s.startsWith('{')).pop();
    if (!line) return null;
    const j = JSON.parse(line);
    return j && j.face && j.точки ? j : null;
  } catch { return null; }
}
function сырыеТочки(src) {
  if (!fs.existsSync(src)) return null;
  if (fs.existsSync(YUNET)) {
    try {
      const r = spawnSync('python3', ['-c', PY, src, YUNET], { encoding: 'utf8', maxBuffer: 1 << 22 });
      const line = String(r.stdout || '').trim().split('\n').filter((s) => s.startsWith('{')).pop();
      if (line) { const j = JSON.parse(line); if (j && j.face) return j; }
    } catch { /* питон/cv2 недоступен — идём в Vision */ }
  }
  return точкиVision(src);
}

// Отклонение переводим в балл: ноль отклонения даёт верх диапазона, отклонение в «допуск» — низ.
// Мягкая кривая (корень) вместо прямой: у настоящих лиц мелкие отклонения есть всегда, и линейная
// шкала сажала бы всех в середину, где карточка перестаёт различать людей.
const балл = (откл, допуск, низ, верх) => {
  const t = Math.min(1, Math.max(0, Math.abs(откл) / допуск));
  return +(верх - (верх - низ) * Math.sqrt(t)).toFixed(1);
};

/**
 * Замер лица по фотографии.
 * Возвращает null, если лица нет или детектор недоступен: тогда карточка обязана откатиться на
 * прежний детерминированный поток, а не рисовать нули.
 */
function замерить(src) {
  const j = сырыеТочки(src);
  if (!j) return null;
  const { face: f, точки: т } = j;
  const [пгx, пгy] = т.глаз_п, [лгx, лгy] = т.глаз_л;
  const [нx, нy] = т.нос, [прx, прy] = т.рот_п, [лрx, лрy] = т.рот_л;

  const межглаз = Math.hypot(лгx - пгx, лгy - пгy);
  if (!(межглаз > 4)) return null;                       // лицо слишком мелкое, замер бессмыслен
  const ось = (пгx + лгx) / 2;                           // вертикальная ось по центру глаз
  const ширРта = Math.hypot(лрx - прx, лрy - прy);
  const линияГлаз = (пгy + лгy) / 2;
  const линияРта = (прy + лрy) / 2;

  // СИММЕТРИЯ: насколько глаза и углы рта равноудалены от оси, в долях межглазного расстояния.
  const переклГлаз = Math.abs((ось - пгx) - (лгx - ось)) / межглаз;
  const переклРта = Math.abs((ось - прx) - (лрx - ось)) / межглаз;
  const переклНоса = Math.abs(нx - ось) / межглаз;
  const симметрия = балл((переклГлаз + переклРта + переклНоса) / 3, 0.28, 7.9, 9.5);

  // ПРОПОРЦИИ: ширина рамки к высоте против канона 0.75.
  const пропорция = f.w / f.h;
  const пропорции = балл(пропорция - 0.75, 0.22, 8.0, 9.3);

  // ГЛАЗА: межглазное к ширине лица, канон около 0.46.
  const глазаОтн = межглаз / f.w;
  const глаза = балл(глазаОтн - 0.46, 0.14, 8.2, 9.5);

  // ГУБЫ: ширина рта к межглазному, канон около 1.0.
  const губыОтн = ширРта / межглаз;
  const губы = балл(губыОтн - 1.0, 0.35, 8.1, 9.4);

  // НОС: по вертикали кончик носа канонически стоит примерно на 2/3 пути от глаз ко рту.
  const пролёт = линияРта - линияГлаз;
  const носОтн = пролёт > 1 ? (нy - линияГлаз) / пролёт : 0.66;
  const нос = балл(носОтн - 0.66, 0.3, 8.0, 9.3);

  // ОВАЛ ЛИЦА: форма выводится из отношения сторон, а не выбирается из списка наугад.
  const форма = пропорция > 0.86 ? 'КРУГЛОЕ'
    : пропорция > 0.80 ? 'КВАДРАТНОЕ'
      : пропорция > 0.72 ? 'ОВАЛЬНОЕ'
        : пропорция > 0.66 ? 'ВЫТЯНУТОЕ' : 'СЕРДЦЕ';
  const овал = балл(пропорция - 0.75, 0.26, 8.2, 9.2);

  // РОВНОСТЬ РТА: насколько углы рта стоят на одной высоте, в долях его ширины. Это единственная
  // величина про губы, которую пять точек дают прямо — ширину контура или объём по ним не измерить,
  // и выдавать оценку объёма за замер нельзя.
  const ровностьРта = балл(ширРта > 1 ? (прy - лрy) / ширРта : 0, 0.16, 7.4, 9.3);

  // КОНЧИК НОСА: его отклонение от оси лица. Спинку, крылья и профиль по пяти точкам не измерить
  // вообще — для них нужен профиль или плотная сетка точек, и у карточки носа они остаются на
  // прежнем потоке.
  const кончикНоса = балл(переклНоса, 0.22, 8.0, 9.5);

  const измерено = { симметрия, пропорции, глаза, губы, нос, овал };
  const гармония = +(Object.values(измерено).reduce((a, b) => a + b, 0) / 6).toFixed(1);

  return {
    ...измерено,
    гармония,
    ровностьРта,
    кончикНоса,
    форма,
    // Сырые величины отдаём наружу: по ним видно, что балл получен из замера, и их можно
    // перепроверить руками, не залезая внутрь формул.
    сырое: {
      пропорция: +пропорция.toFixed(3),
      межглаз_к_ширине: +глазаОтн.toFixed(3),
      рот_к_межглазу: +губыОтн.toFixed(3),
      нос_по_вертикали: +носОтн.toFixed(3),
      перекос: +((переклГлаз + переклРта + переклНоса) / 3).toFixed(3),
      увер: +(j.увер || 0).toFixed(2),
    },
  };
}

// сырыеТочки НАРУЖУ (15.08): кропы карточки в cardgen угадывали, где губы и нос, фиксированными
// долями рамки лица — а тут лежат НАСТОЯЩИЕ координаты рта и носа от того же детектора. Разбор
// и замер в cardgen.кропы.
module.exports = { замерить, сырыеТочки };

if (require.main === module) {
  const файлы = process.argv.slice(2);
  if (!файлы.length) { console.log('usage: node facemetrics.cjs <фото> [<фото>…]'); process.exit(1); }
  for (const f of файлы) {
    const з = замерить(f);
    if (!з) { console.log(`✗ ${path.basename(f)}: лица нет или детектор недоступен`); continue; }
    console.log(`${path.basename(f)}  ${з.форма}`);
    console.log(`   симметрия ${з.симметрия}  пропорции ${з.пропорции}  глаза ${з.глаза}`
      + `  губы ${з.губы}  нос ${з.нос}  овал ${з.овал}  → гармония ${з.гармония}`);
    console.log(`   сырое: ${JSON.stringify(з.сырое)}`);
  }
}
