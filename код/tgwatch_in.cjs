'use strict';
// ЧТЕНИЕ ВХОДЯЩИХ ИЗ ГРУППЫ ВЛАДЕЛЬЦА.
//
// ЗАЧЕМ (14.08, прямая претензия: «ты не увидел моих сообщений в тг»). Отправку в группу мы
// настроили и пользовались ей весь день, а чтение — нет. Владелец писал с 14:12, спрашивал «ты
// видишь мои сообщения?», и два часа я отвечал в одну сторону, не зная, что меня о чём-то просят.
// Односторонний канал хуже отсутствия канала: он создаёт у обеих сторон ощущение связи, которой нет.
//
// ЧТО ДЕЛАЕТ. Раз в минуту спрашивает у телеграма новые сообщения и складывает их в файл
// ~/.neironka/tg_входящие.txt — по строке на сообщение, с временем и автором. Дальше их читает
// дежурный (человек или сессия) и отвечает. Ничего не отправляет и ни на что не реагирует сам:
// решать, что делать с просьбой владельца, — не работа сторожа.
//
// ПРО СМЕЩЕНИЕ (offset). Телеграм отдаёт обновления по одному разу: подтверждённые больше не
// придут. Поэтому смещение хранится на диске, а не в памяти — перезапуск сторожа не должен
// приводить ни к потере сообщений, ни к их повтору.
//
// ВАЖНОЕ ОГРАНИЧЕНИЕ. Метод getUpdates нельзя звать из двух мест сразу: телеграм отдаёт обновление
// тому, кто попросил первым, и второй его уже не увидит. Поэтому сторож ровно один — при запуске он
// проверяет, не работает ли уже такой же.
//
// Запуск: node tgwatch_in.cjs [пауза_сек=60]
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { execFileSync } = require('node:child_process');

const ПАУЗА = (Number(process.argv[2]) || 60) * 1000;
const ПАПКА = path.join(os.homedir(), '.neironka');
const ФАЙЛ = path.join(ПАПКА, 'tg_входящие.txt');
const СМЕЩЕНИЕ = path.join(ПАПКА, 'tg_offset.txt');
const МЕДИА = path.join(ПАПКА, 'tg_медиа');

const читать = (f, по) => { try { return fs.readFileSync(f, 'utf8').trim(); } catch { return по; } };
// КЛЮЧИ ИЗ ~/.neironka, А НЕ ИЗ /tmp (15.08, владелец: «мне важно, чтобы этот чат всегда имел к тебе
// доступ»). /tmp чистится при перезагрузке: сторож стартовал бы без токена, keepalive поднимал бы его
// каждую минуту, и мост молчал бы неотличимо от «владелец не писал». /tmp оставлен запасным.
const TOKEN = (process.env.TELEGRAM_BOT_TOKEN || читать(path.join(ПАПКА, 'tgtok'), '') || читать('/tmp/.tgtok', '')).trim();
const CHAT = (process.env.TELEGRAM_CHAT_ID || читать(path.join(ПАПКА, 'tgchat'), '') || читать('/tmp/.tgchat', '') || читать('/tmp/tg_chat.txt', '')).trim();
const ПУЛЬС = path.join(ПАПКА, 'tg_мост_пульс.txt');   // время последнего УСПЕШНОГО опроса, по нему keepalive ловит зависание
if (!TOKEN) { console.log('нет токена: ~/.neironka/tgtok пуст'); process.exit(1); }
// ОТКАЗ ТЕЛЕГРАМА — В ФАЙЛ ВХОДЯЩИХ, чтобы главный чат увидел его тем же каналом, что и сообщения
// владельца. Особенно 409 Conflict: кто-то ещё дёргает getUpdates этим токеном (15.08 это делала
// ветка Магоса) и ворует обновления; молча это не лечится, надо гнать второго опрашивающего.
let последнийОтказ = '';
function tревога_(j) {
  const d = String(j.description || '');
  if (/Conflict/i.test(d)) тревога('409 Conflict: кто-то ещё опрашивает getUpdates этим токеном и ворует сообщения владельца. Найти и убить второго опрашивающего (ветки Магос/Маркетолог не должны трогать бота claudex057_bot).');
  else if (/Unauthorized/i.test(d)) тревога('401 Unauthorized: токен бота отозван или сменён. Мост мёртв, нужен новый токен от владельца в ~/.neironka/tgtok.');
  else тревога(`телеграм отказал: ${d}`);
}
function тревога(текст) {
  if (текст === последнийОтказ) return; последнийОтказ = текст;
  fs.appendFileSync(ФАЙЛ, `${new Date().toISOString()}\t⚠ МОСТ\t${текст}\n`);
}

// ОДИН СТОРОЖ, А НЕ ДВА (см. разбор про getUpdates выше).
try {
  const свои = execFileSync('pgrep', ['-f', 'tgwatch_in\\.cjs'], { encoding: 'utf8' })
    .split('\n').map((s) => s.trim()).filter(Boolean).filter((p) => Number(p) !== process.pid);
  if (свои.length) { console.log(`сторож входящих уже работает (pid ${свои[0]}), второй не нужен`); process.exit(0); }
} catch { /* pgrep никого не нашёл — это норма */ }

const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
fs.mkdirSync(ПАПКА, { recursive: true });
fs.mkdirSync(МЕДИА, { recursive: true });

async function заход() {
  const offset = Number(читать(СМЕЩЕНИЕ, '0')) || 0;
  const url = `https://api.telegram.org/bot${TOKEN}/getUpdates?timeout=30&limit=50`
    + (offset ? `&offset=${offset}` : '');
  const r = await fetch(url, { signal: AbortSignal.timeout(45000) });
  const j = await r.json();
  if (!j.ok) {
    console.log('телеграм отказал:', j.description);
    tревога_(j);
    return;
  }
  fs.writeFileSync(ПУЛЬС, String(Date.now()));
  последнийОтказ = '';
  const обновления = j.result || [];
  if (!обновления.length) return;

  let последнее = offset;
  const строки = [];
  for (const u of обновления) {
    последнее = Math.max(последнее, u.update_id + 1);
    const m = u.message || u.channel_post;
    if (!m) continue;
    // Своё эхо пропускаем: сообщения от бота нам самим ничего не сообщают.
    if (m.from && m.from.is_bot) continue;
    const кто = (m.from && (m.from.first_name || m.from.username)) || 'владелец';
    const когда = new Date(m.date * 1000).toISOString();
    // КАРТИНКИ И ВИДЕО СКАЧИВАЕМ, А НЕ ПОМЕЧАЕМ (15.08, живой случай). Владелец прислал скриншот
    // залитой истории с подписью «история )». Сторож записал строку «[фото]» и пошёл дальше, а
    // ТЕЛЕГРАМ УДАЛЯЕТ ПОДТВЕРЖДЁННОЕ ОБНОВЛЕНИЕ: file_id пропал вместе с ним, и картинку стало
    // не достать ничем — пришлось просить прислать заново. Пометка «[фото]» хуже, чем ничего:
    // она сообщает, что что-то было, и одновременно уничтожает возможность это посмотреть.
    let скачано = '';
    const файлИд = (m.photo && m.photo[m.photo.length - 1] && m.photo[m.photo.length - 1].file_id)
      || (m.video && m.video.file_id) || (m.document && m.document.file_id)
      || (m.animation && m.animation.file_id) || (m.voice && m.voice.file_id);
    if (файлИд) {
      try {
        const инфо = await (await fetch(`https://api.telegram.org/bot${TOKEN}/getFile?file_id=${файлИд}`,
          { signal: AbortSignal.timeout(30000) })).json();
        if (инфо.ok && инфо.result && инфо.result.file_path) {
          const расш = path.extname(инфо.result.file_path) || '.bin';
          const имяФ = `${new Date(m.date * 1000).toISOString().replace(/[:.]/g, '-')}_${m.message_id}${расш}`;
          // ВХОДЯЩЕЕ КЛАДЁМ ПО ДНЯМ И ОТДЕЛЬНО ОТ ВСЕГО, ЧТО МЫ ЛЬЁМ.
          //
          // Владелец 21.08: «надо чтобы посты оттуда не мешались с теми, что мы будем лить».
          // Раньше всё падало одной кучей в tg_медиа, и отличить присланное от готового к
          // публикации можно было только по дате в имени — то есть глазами и на память.
          // Цена ошибки известна: сегодня чужие кадры в папке телефона едва не уехали в
          // карусель на живом аккаунте.
          //
          // Разделение простое и физическое: день = папка. Рядом лежит метка-предупреждение,
          // чтобы никакой сценарий и никакой человек не принял это за очередь на заливку.
          const день = new Date(m.date * 1000).toISOString().slice(0, 10);
          const папкаДня = path.join(МЕДИА, день);
          try {
            fs.mkdirSync(папкаДня, { recursive: true });
            const метка = path.join(папкаДня, 'ЭТО-ВХОДЯЩЕЕ-НЕ-ПУБЛИКОВАТЬ.txt');
            if (!fs.existsSync(метка)) {
              fs.writeFileSync(метка,
                'Здесь лежит то, что ПРИСЛАЛИ НАМ в телеграм.\n' +
                'Это НЕ очередь на публикацию и НЕ комплекты постов.\n' +
                'Готовое к заливке живёт только в ~/Desktop/НЕЙРОНКА/ПОСТЫ-ФЕРМА/<аккаунт>/.\n' +
                'Брать отсюда файлы для постинга нельзя — так на аккаунт уходит чужой кадр.\n', 'utf8');
            }
          } catch { /* не смогли создать папку дня — упадём в общую, лишь бы не потерять файл */ }
          const куда = fs.existsSync(папкаДня) ? path.join(папкаДня, имяФ) : path.join(МЕДИА, имяФ);
          const бин = Buffer.from(await (await fetch(
            `https://api.telegram.org/file/bot${TOKEN}/${инфо.result.file_path}`,
            { signal: AbortSignal.timeout(120000) })).arrayBuffer());
          fs.writeFileSync(куда, бин);
          скачано = ` [файл: ${куда}]`;
        }
      } catch (e) { скачано = ` [файл не скачался: ${String(e.message).slice(0, 50)}]`; }
    }
    const текст = (m.text || m.caption
      || (m.video ? '[видео]' : m.photo ? '[фото]' : m.document ? '[файл]' : '[без текста]')) + скачано;
    // ЧУЖОЙ ЧАТ БОЛЬШЕ НЕ ВЫБРАСЫВАЕМ, А ПОМЕЧАЕМ (14.08, вечер: «в тг ты не видишь мои
    // сообщения»). Было: сообщение не из CHAT молча пропускалось, и смещение всё равно
    // двигалось — то есть письмо владельца исчезало навсегда, а в файле не оставалось даже
    // следа, что оно приходило. За 6 часов работы сторож записал ноль строк, и понять почему
    // было нечем. Отдельно опасен переезд группы в супергруппу: у неё ДРУГОЙ id, и весь чат
    // разом становится «чужим». Молчание — худший исход: лучше лишняя строка с пометкой,
    // чем потерянная просьба.
    const свой = !CHAT || String(m.chat && m.chat.id) === String(CHAT);
    const метка = свой ? '' : `\t[чат ${m.chat && m.chat.id} «${(m.chat && (m.chat.title || m.chat.username)) || '?'}»]`;
    строки.push(`${когда}\t${кто}\t${String(текст).replace(/\s+/g, ' ')}${метка}`);
  }
  // СНАЧАЛА СТРОКИ, ПОТОМ СМЕЩЕНИЕ (аудит 15.08). Было наоборот: смещение писалось первым, и
  // падение между двумя записями теряло сообщения владельца НАВСЕГДА — телеграм апдейт уже
  // подтвердил и второй раз не отдаст. Теперь при падении между записями строка продублируется
  // при перезапуске: дубль в файле лучше потерянного письма.
  if (строки.length) {
    fs.appendFileSync(ФАЙЛ, строки.join('\n') + '\n');
    for (const s of строки) console.log('  ✉ ' + s);
  }
  fs.writeFileSync(СМЕЩЕНИЕ, String(последнее));
}

(async () => {
  console.log(`сторож входящих пошёл: чат ${CHAT || '(любой)'}, заход раз в ${ПАУЗА / 1000} с`);
  console.log(`входящие складываю в ${ФАЙЛ}`);
  for (;;) {
    await заход().catch((e) => console.log('заход упал:', String(e.message).slice(0, 80)));
    await sleep(ПАУЗА);
  }
})();
