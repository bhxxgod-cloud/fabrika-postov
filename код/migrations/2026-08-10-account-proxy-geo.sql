-- СВЯЗКА «АККАУНТ → ПРОКСИ → ГЕО» (10.08).
--
-- ПРИКАЗ: «прокси нужно начать тречить, где больше валида, какие меньше падают по статистике и с
-- каких больше просмотров, например какое гео».
--
-- ПОЧЕМУ НУЖНЫ НОВЫЕ ПОЛЯ, А НЕ СТАРЫЕ. В accounts уже есть три вещи про прокси, и ни одна не
-- отвечает на вопрос начальника:
--   ig_proxy        строка с ПАРОЛЁМ, живёт только у акков с профилем GoLogin (на 10.08 таких 3 из
--                   238), у 150 акков магоса пустая. Группировать по ней нельзя и печатать нельзя.
--   egress_country  страна ФАКТИЧЕСКОГО выхода, но её ставит только замер egress через GoLogin;
--                   у магос-акков профиля нет, значит замера нет и поле пустое (211 из 238 пустых).
--   proxy (jsonb)   заполнено у 2 акков, наследие.
-- Поэтому добавляем узкие поля-факты, которые можно писать ЛЮБЫМ способом (пролив магосом, файл от
-- бота, назначение из пула) и по которым можно группировать статистику просмотров.
--
-- ПАРОЛЬ НЕ ХРАНИМ: только хост, порт и гео. Этого хватает и для группировки по гео, и чтобы найти
-- конкретную sticky-сессию (у click-ip порт = отдельный IP), а секрет остаётся в ig_proxy/пуле.
ALTER TABLE accounts ADD COLUMN IF NOT EXISTS proxy_host text;      -- хост провайдера (74.81.81.81, proxy.click-ip.com …), без логина и пароля
ALTER TABLE accounts ADD COLUMN IF NOT EXISTS proxy_port text;      -- порт = sticky-сессия = отдельный IP; NULL если известна только пачка
ALTER TABLE accounts ADD COLUMN IF NOT EXISTS proxy_geo  text;      -- KZ | GE | RU | GB | '?' (неизвестно). Врать нельзя: не разобрали → '?'
ALTER TABLE accounts ADD COLUMN IF NOT EXISTS proxy_geo_src text;   -- откуда узнали: ig_proxy | proxy_pool | health_note | файл | вручную
ALTER TABLE accounts ADD COLUMN IF NOT EXISTS proxy_bound_at timestamptz; -- когда связку записали (снимок правды на дату)

-- Индекс под группировку отчёта по гео.
CREATE INDEX IF NOT EXISTS idx_accounts_proxy_geo ON accounts(proxy_geo);

-- ГЕО ОПРЕДЕЛЯЕТСЯ ПО СТРОКЕ ПРОКСИ, А НЕ ПО НАЗВАНИЮ ФАЙЛА, ИЗ КОТОРОГО ЕЁ ВЗЯЛИ.
-- Провайдеры кладут страну в логин сессии:
--   click-ip: c99804db…__cr.kz;sessttl.120   → KZ,   …__cr.ge → GE (грузинские),  …__cr.ru → RU
--   sous:     8185…-cc-KZ-s-u1940570381…     → KZ
-- proxy_pool.country доверия не заслуживает: у живого кз-пула там стоит '?', то есть по нему
-- 100 кз-прокси числятся «неизвестно». Фолбэк только на РЕАЛЬНЫЙ замер egress_country.
