      // был один, это работало. Но с REEL_RESUME пачку перезапускают: реестр не даёт резать один
      // пост дважды, а вот ИМЯ файла у нового рилса той же персоны совпадает со старым — и новый
      // молча затирает старый в той же папке. Замер: в логах 60 успешных нарезок, в папке 23 файла.
      // То есть терялось больше половины работы, и по логам это выглядело как успех.
      // Id поста делает имя уникальным навсегда: один пост = один файл, сколько раз ни перезапускай.
      const short8 = String(p.id).slice(0, 8);
      const out = path.join(OUT, `reel_${String(i + 1).padStart(2, '0')}${СУФ}_${p.persona}_${short8}.mp4`);
      // Трек выбирается сборщиком по идентификатору поста, значит у каждого рилса свой звук.
      // ТРЕК ПО КРУГУ (09.08, начальник заметил повтор внутри пятёрки): раздаём треки по индексу
      // поста, а не по хэшу, тогда в пачке из N рилсов звучит N разных треков, пока их хватает.
      // ТОЛЬКО ПРОВЕРЕННЫЕ ТРЕКИ (09.08, приказ начальника: «делай рилсы с верифнутыми отрывками»).
      // Проверенный это тот, рядом с которым лежит файл .points с секундами, которые он отобрал на слух.
      const audioDir = path.join(__dirname, 'audio');
      const all = fs.readdirSync(audioDir).filter((f) => /\.(mp3|m4a|aac|wav)$/i.test(f)).sort();
      const verified = all.filter((f) => fs.existsSync(path.join(audioDir, f + '.points')));
      const pool = (process.env.ANY_TRACK === '1' || !verified.length) ? all : verified;
      // ТРЕК ВЫБИРАЕМ ПО ID ПОСТА, А НЕ ПО НОМЕРУ В ЦИКЛЕ (правка 09.08, разбор инцидента).
      // Что было: `pool[i % pool.length]`, а pipeline.sh запускает этот скрипт ПО ОДНОЙ персоне,
      // поэтому i всегда 0, и все рилсы получали один и тот же первый трек. Проверено вручную:
      // у 50 файлов в reels50 и у 31 в magos_reels md5 декодированной дорожки совпадал побитово.
      // Инстаграм сопоставляет аудио отпечатком и собирает такие рилсы на одну страницу трека,
      // то есть это была идеальная склейка нашей фермы, которую не отменяет уникализация картинки.
      // Теперь номер трека берётся из хэша id поста: он стабилен для поста и разный между постами
      // независимо от того, одним прогоном идёт пачка или по одному.
      const seed = require('node:crypto').createHash('sha1').update(String(p.id)).digest()[0]
        + require('node:crypto').createHash('sha1').update(String(p.id)).digest()[1] * 256;
      // РАЗДАЧА ПАЧКИ ГЛАВНЕЕ ХЭША (10.08, см. разбор выше): если для пачки посчитана пара
      // «трек плюс секунда», берём её, и тогда двух одинаковых отпечатков в пачке не бывает.
      // Хэш id остаётся запасным путём — на случай, когда ни у одного трека нет отобранных секунд.
      const seg = assign.get(i);
      const track = seg ? path.join(__dirname, 'audio', seg.track)
        : (pool.length ? path.join(__dirname, 'audio', pool[seed % pool.length]) : '');
      // ═══ ВСЕ КАДРЫ РОЖДАЮТСЯ В 9:16 (12.08) ═══════════════════════════════════════════════
      // ПОЧЕМУ ЭТО ЗДЕСЬ, А НЕ В ЭТАЛОНЕ. Стандарт «все 4 кадра 9:16, полей нет» принят 11.08 и
      // РЕАЛИЗОВАН в ttkit (to916 c fill) и в эталонной сборке reeltest916.cjs. Но боевой путь
      // magosreels → reelbuild не звал ttkit НИ РАЗУ: он получал кадры 4:5 и сам решал, залить или
      // вписать. Кадры 1 и 3 заливались во весь экран, а карточка и финал вписывались с размытыми
      // полосами, то есть на экране они ВИДИМО МЕНЬШЕ соседних. Начальник ловил это пять раз, и
      // каждый раз чинили либо эталон, либо env-флаги REEL_CARDS/REEL_FIT_LAST, а прод оставался
      // прежним. Поэтому приведение к 9:16 переезжает СЮДА, в единственный боевой путь.
      // Отключение: REEL_916=0 (вернуться к старому поведению reelbuild).
      // ДВЕ ОШИБКИ ПЕРВОЙ ВЕРСИИ ЭТОЙ ПРАВКИ, ОБЕ ПОЙМАНЫ ГЛАЗАМИ НА ГОТОВЫХ КАДРАХ:
      //   · «кадр 2 это всегда карточка» неверно. У сердечек и арта на втором кадре ФОТО (frame2:
      //     'art' в templates.cjs), и вписывание в рамку делало его вдвое мельче соседей, то есть
      //     ровно тот брак, который чинили. Тип кадра берём у шаблона, а не по номеру;
      //   · кадр 4 нельзя заливать: на нём УЖЕ вожжена плашка от края до края, и заливка срезала
      //     ей текст («а себе тут», «a.pro» вместо neironka.pro). Текстовые кадры по стандарту
      //     рисуются ЗАНОВО поверх чистого исходника (frame4_raw), а не режутся.
      let кадры916 = frames;
      // ОТРАБОТАЛО ЛИ ПРИВЕДЕНИЕ НА САМОМ ДЕЛЕ (14.08). Ниже сборщику передаётся флаг «кадры уже
      // 9:16, не подгоняй», и он был привязан к ПЕРЕМЕННОЙ ОКРУЖЕНИЯ REEL_916, а не к результату.
      // Разница вылезла на живой ферме: восемь сборок и три резки делят один хром, и приведение
      // падало по таймауту page.setContent — 32 раза из 293. В обработчике кадры откатывались на
      // 4:5, но флаг всё равно уходил, то есть сборщику давали 4:5 и запрещали их вписывать. Такой
      // рилс выходит с обрезанными боками. Теперь флаг ставится только когда приведение реально
      // прошло; при откате сборщик вписывает кадры сам, как делал до появления 9:16-ветки.
      let привелиК916 = false;
      if (process.env.REEL_916 !== '0') {
        try {
          const TT = require('./ttkit.cjs');
          const конф = TPL.get(p.tpl || '');
          const картаНаВтором = конф && конф.frame2 === 'card';
          кадры916 = [];
          for (const [j, f] of frames.entries()) {
            const o = f.replace(/\.jpg$/, '_916.jpg');
            if (j === 0 && чистыйЛокально && p.hook_text) {
              // Кадр 1: чистое фото на весь экран, хук нанесён заново поверх 9:16.
              await TT.hookSlideTT(чистыйЛокально, o, String(p.hook_text).replace(/\\n/g, '\n'), { fill: true });
            } else if (j === 1 && картаНаВтором) {
              // КАРТОЧКУ НЕ ОТДАЛЯЕМ (12.08, приказ начальника: «на рилсе его не нужно отдалять,
              // пусть это будет статичный кадр на таких шаблонах»).
              // Своя карточка рисуется сразу 1080x1920, то есть УЖЕ 9:16. Гнать её через cardTo916
              // значит вписать 9:16 в 9:16 с запасом под чистую зону: картинка сядет в рамку и
              // визуально уедет вдаль, а по бокам встанут полосы. Поэтому: если пропорции уже
              // близки к 9:16, кадр берём КАК ЕСТЬ, один в один. Вписывание оставлено только для
              // старых карточек фабрики 4:5 и 1080x1440, где текст идёт от края до края и резать
              // его нельзя. Зум на карточку не идёт в любом случае: она числится текстовым кадром.
              // ОРИГИНАЛ КАРТОЧКИ 1920 ПЕРВЫМ (13.08, приказ: «постер не двигается и он 9:16 на
              // весь экран»). В карусели карточка лежит кропом 4:5, и рилс из неё выходил с
              // тёмными полями. Если onepost сохранил оригинал (meta.card916), берём его как есть.
              let карта916 = null;
              if (p.card916) {
                try { карта916 = await скачатьЧистый(p.card916, `.card916_${short}.jpg`); } catch {}
              }
              // НЕТ ОРИГИНАЛА 1920 — РИСУЕМ КАРТОЧКУ ЗАНОВО, А НЕ ВПИСЫВАЕМ КРОП (14.08, владелец
              // прислал два рилса подряд: «почему 2 фото гайда не на весь экран», «ты должен
              // заполнять весь экран»).
              //
              // ЧТО БЫЛО. meta.card916 сохранён только у 95 постов из 484: остальные собраны до
              // того, как onepost научился класть оригинал. Без него сюда приходил кроп 4:5, и
              // cardTo916 честно вписывал его в 9:16 — с размытыми полями сверху и снизу. На экране
              // карточка занимала меньше половины высоты, соседние кадры при этом шли во весь экран.
              //
              // ПОЧЕМУ ПЕРЕРИСОВКА, А НЕ РАСТЯЖЕНИЕ. Растянуть кроп нельзя: карточка это ДОКУМЕНТ,
              // текст в ней идёт от края до края, и любое растяжение или обрезка съедает строки —
              // ровно тот брак, из-за которого 11.08 забраковали 21 пост из 22. А нарисовать её
              // заново стоит НОЛЬ: cardgen это наш собственный рендер вёрстки, без генераций и без
              // денег, и он детерминирован по id поста — выйдет та же карточка, только сразу 1920.
              //
              // Не вышло нарисовать (нет исходника, упал хром) — откатываемся на прежнее поведение:
              // лучше карточка с полями, чем рилс без карточки.
              let сделали = false;
              if (карта916) { fs.copyFileSync(карта916, o); сделали = true; }
              if (!сделали && чистыйЛокально && p.tpl) {
                try {
                  await require('./cardgen.cjs').собрать(p.tpl, чистыйЛокально, String(p.id), o);
                  сделали = fs.existsSync(o) && fs.statSync(o).size > 20000;
                  if (сделали) console.log(`  · ${p.persona}: карточка перерисована в 9:16 (оригинала 1920 в базе нет)`);
                } catch (e) { console.log(`  ⚠ ${p.persona}: карточку заново не нарисовать (${String(e.message).slice(0, 40)})`); }
              }
              if (!сделали) {
                const рз = TT.probeSize(f) || { w: 1080, h: 1350 };
                const уже916 = Math.abs((рз.w / рз.h) - (9 / 16)) < 0.02;
                if (уже916) fs.copyFileSync(f, o);
                else TT.cardTo916(f, o, { bg: f });
              }
            } else if (j === frames.length - 1 && чистыйФинал) {
              // Финал: чистое фото на весь экран, плашка нанесена заново, высота под рилс.
              await TT.ctaSlideTT(чистыйФинал, o, { platform: 'reels', cover: frames[0], fill: true });
            } else {
              TT.to916(f, o, { fill: true });
            }
            кадры916.push(o);
          }
          привелиК916 = true;
        } catch (e) {
          console.log(`  ⚠ ${p.persona}: приведение к 9:16 не отработало (${String(e.message).slice(0, 50)}),`
            + ' кадры вписывает сборщик');
          кадры916 = frames;
          привелиК916 = false;
        }
      }
      // Когда кадры УЖЕ приведены к 9:16, reelbuild не должен ни заливать, ни вписывать заново:
      // любая его подгонка здесь только испортит готовый холст. Условие именно на привелиК916, а
      // не на переменную окружения — разбор ловушки выше, у объявления флага.
      // REEL_CARDS='-1' даёт ЗАВЕДОМО пустое множество карточек: пустая строка тут не годится,
      // потому что в reelbuild стоит `process.env.REEL_CARDS || '1'` и пустая строка вернула бы
      // дефолтную единицу, то есть карточку снова стали бы вписывать поверх готового 9:16.
      // ═══ КАДР 4 СО ЗВУКОМ (сборка сб1) ═══════════════════════════════════════════════════════
      //
      // Что добавляется на финальный кадр и почему именно здесь:
      //   • печатающаяся строка поиска Яндекса (yabar.py) вместо статичной плашки;
      //   • клики клавиатуры ПО ОДНОМУ НА БУКВУ, синхронно с набором;
      //   • озвучка в конце, под которую музыка САДИТСЯ сама (сайдчейн в reelbuild).
      //
      // Здесь, а не в reelbuild, потому что строка рисуется поверх КАРТИНКИ и превращает кадр в
      // видео. Сборщик про это знать не обязан: ему всё равно, картинка на входе или mp4, ветка
      // по расширению у него уже есть.
      //
      // ВСЁ ПОД ФЛАГАМИ И ПО УМОЛЧАНИЮ ВЫКЛЮЧЕНО. Без REEL_YABAR ролик собирается ровно как
      // собирался, ни один существующий пост не меняется. Это осознанно: сборка сб1 пока
      // проверяется на одном посту глазами, и раскатывать её на весь поток рано.
      let кадрыДляСборки = кадры916;
      let звукКадра = '';
      if (process.env.REEL_YABAR === '1' && кадры916.length >= 4) {
        const финал = кадры916[кадры916.length - 1];
        const видео = финал.replace(/\.(jpe?g|png)$/i, '_ya.mp4');
        try {
          execFileSync('python3', [path.join(__dirname, 'yabar.py'), финал, видео], {
            cwd: __dirname, stdio: 'ignore', timeout: 300000,
            env: { ...process.env,
              YABAR_SECONDS: process.env.YABAR_SECONDS || '5',
              YABAR_Y: process.env.YABAR_Y || '0.74',
              YABAR_DIM_FROM: process.env.YABAR_DIM_FROM || '0.58' },
          });
          if (fs.existsSync(видео)) {
            кадрыДляСборки = [...кадры916.slice(0, -1), видео];
            const клики = видео.replace(/\.mp4$/, '-клики.wav');
            if (fs.existsSync(клики)) звукКадра = клики;
            console.log('  ⌨ строка Яндекса на финальном кадре' + (звукКадра ? ' + клики' : ''));
          }
        } catch (e) {
          // Падение строки НЕ роняет пост: собираем как раньше, без неё. Ролик без анимации
          // лучше, чем отсутствующий ролик.
          console.log(`  ⚠ строка Яндекса не нарисовалась (${String(e.message).slice(0, 60)}), собираю без неё`);
        }
      }

      execFileSync('node', [path.join(__dirname, 'reelbuild.cjs'), out, ...кадрыДляСборки],
        { cwd: __dirname, stdio: 'ignore', env: { ...process.env, REEL_SEED: p.id,
          ...(привелиК916 ? { REEL_CARDS: '-1', REEL_FIT_LAST: '0' } : {}),
          ...(track ? { REEL_TRACK: track } : {}), ...(seg ? { REEL_AT: String(seg.at) } : {}),
          ...(звукКадра ? { REEL_SFX: звукКадра, REEL_SFX_DB: process.env.REEL_SFX_DB || '-5' } : {}) } });
