// ПОДГОТОВКА ZIP-ПУЛА РИЛСОВ ДЛЯ magos (08.08).
//
// ЗАЧЕМ. У магоса нет уникализатора видео: он умеет только ZIP-пул, из которого КАЖДОМУ акку
// достаётся СВОЙ файл и больше никому. Значит уникальность делаем мы: берём разные посты со
// склада, каждый собираем в отдельный рилс своим сборщиком (свой трек по хэшу поста, своя
// безопасная зона), и складываем в архив. Один акк = один рилс = ноль пересечений по кадру и по
// отпечатку звука, то есть железное правило «один пост = один акк» соблюдается автоматически.
//
// Ничего не публикуем и не тратим: только скачиваем уже оплаченные кадры и режем локально.
// Запуск: node magosreels.cjs [сколько]
//
// ═══ ОДИН ФАЙЛ ВМЕСТО ТРЁХ (13.08) ═══════════════════════════════════════════════════════════════
// БЫЛО. Рядом лежали три неотслеживаемые копии по 38 КБ: magosreels.cjs (боевой),
// magosreels_all.cjs (массовая резка) и magosreels_mine.cjs (второй воркер). Различались они
// СОТНЯМИ БАЙТ: две строки в запросе, одна дописка в реестр, имена двух файлов состояния. При этом
// любая правка сборки (звук, гейт, хук, карточка) требовала ручного переноса в три места, и
// «поправил сборку рилсов» на деле означало «поправил одну треть». Это та же болезнь, из-за которой
// пул хуков съехался в hooks.cjs, только с файлом в тридцать восемь килобайт.
//
// СТАЛО. Различия сведены к переменным окружения, копии удалены. Соответствие один в один:
//   magosreels.cjs        → без переменных (поведение боевого не изменилось)
//   magosreels_all.cjs    → REEL_DISTINCT=0 REEL_RESUME=1 REEL_ALLOW=1
//   magosreels_mine.cjs   → REEL_DISTINCT=0 REEL_RESUME=1 REEL_ALLOW=1 REEL_SLOT=mine
//
// ПЕРЕМЕННЫЕ РЕЖИМА:
//   REEL_DISTINCT  1 (умолч) один пост на персону, защита раздачи: в ZIP-пул не попадут два рилса
//                  с одним лицом. 0 режет ВСЕ годные посты — это нужно на этапе резки, где терять
//                  посты нельзя, а раздача по аккам идёт отдельным шагом.
//   REEL_RESUME    0 (умолч). 1 включает реестр собранных: id дописывается после гейта, и упавший
//                  или перезапущенный прогон продолжает с места, ничего не режа дважды.
//   REEL_SLOT      '' (умолч). Имя слота даёт СВОЮ пару реестров и своё имя архива.
//
//                  ВНИМАНИЕ, ЗДЕСЬ БЫЛО НАПИСАНО НЕВЕРНОЕ (исправлено 14.08 по факту). Стояло:
//                  «два воркера с разными слотами не режут один пост». Это правда ТОЛЬКО когда у
//                  слотов разные белые списки (REEL_ALLOW=1). Без списка оба берут из ОБЩЕГО
//                  склада, а реестр у каждого свой — то есть про работу друг друга они не знают.
//                  Замер на живой пачке: слоты n2 и n3 пересеклись на 77 постах, 53 поста нарезаны
//                  дважды, в архив на залив попали 92 дубля. Для ZIP-пула это прямой брак: смысл
//                  пула в том, что каждому аккаунту достаётся СВОЙ файл, а по одинаковым кадрам
//                  Instagram как раз и сшивает аккаунты в сеть.
//
//                  КАК ПРАВИЛЬНО ГНАТЬ НЕСКОЛЬКО ПАЧЕК ПО ОБЩЕМУ СКЛАДУ: дать им ОДИН И ТОТ ЖЕ
//                  слот. Тогда реестр общий и один пост дважды не режется. Имена файлов при этом
//                  не сталкиваются, потому что с 14.08 в имени стоит id поста.
//                  Разные слоты нужны там, где склады РАЗНЫЕ: свой белый список у каждого.
//   REEL_ALLOW     0 (умолч) берём весь годный склад. 1 включает белый список слота: режем только
//                  перечисленные в нём id. Умолчание именно «выкл»: иначе забытый от прошлой пачки
//                  файл незаметно сужает боевой прогон до нескольких постов.
//   REEL_MAX_PROC  2 (умолч). Больше двух сборок разом ffmpeg не тянет (замер: 16 полос роняли
//                  машину). Сторож ниже не даёт запустить третью.
//   REEL_STATE_DIR где лежат реестры. Умолчание ~/.neironka/reels, НЕ /tmp: состояние пачки на 380
//                  постов не должно исчезать от уборки временных файлов.
//   REEL_DATE_DIR  1 (умолч) складывать прогон в подпапку своего дня (РИЛСЫ-ВСЕ/2026-08-13).
//                  0 возвращает свалку в один каталог, где вчерашнее от сегодняшнего по имени
//                  не отличить. Архив в обоих случаях уходит уровнем выше.
//
// ТРИ ЛОВУШКИ, ПОЙМАННЫЕ ПРИ СХЛОПЫВАНИИ (в копиях они были живыми):
//   1. ПУСТОЙ БЕЛЫЙ СПИСОК ОЗНАЧАЛ «НИ ОДНОГО ПОСТА». Условие id = ANY($5) при пустом массиве не
//      пропускает ничего, поэтому забытый или подчищенный /tmp/reels_allow.txt давал «постов: 0»
//      молча, и это выглядело как поломка склада. Теперь пустой список означает «без ограничения».
//   2. ДВА ВОРКЕРА ЗАТИРАЛИ ОДИН АРХИВ. Имя magos-reels.zip не зависело от слота, а пишется он в
//      общий каталог: кто заканчивал вторым, тот и оставался. Теперь имя несёт слот.
//   3. КАТАЛОГ ВЫХОДА ПО УМОЛЧАНИЮ вёл в скретчпад давно закрытой сессии. Живёт до первой уборки
//      /tmp, потом сборка молча складывает рилсы в никуда. Умолчание переведено на стабильный путь.
