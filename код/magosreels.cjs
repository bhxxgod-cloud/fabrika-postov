// КАТАЛОГ ВЫХОДА. Прежнее умолчание вело в скретчпад закрытой сессии (см. ловушку 3 в шапке).
// Теперь стабильный путь рядом с остальными материалами; OUT_DIR по-прежнему главнее.
// УМОЛЧАНИЕ ВЕДЁТ В «ЗАВОД НОВЫЙ» (14.08, претензия владельца: «где хранятся рилсы? почему я не
