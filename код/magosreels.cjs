const ДЕНЬ = new Date().toLocaleDateString('sv-SE'); // sv-SE даёт ровно ГГГГ-ММ-ДД
const OUT = process.env.REEL_DATE_DIR === '0' ? БАЗА_ВЫХОДА : path.join(БАЗА_ВЫХОДА, ДЕНЬ);

// ═══ РЕЖИМ СБОРКИ ═══════════════════════════════════════════════════════════════════════════════
const DISTINCT = process.env.REEL_DISTINCT === undefined ? true : process.env.REEL_DISTINCT !== '0';
const RESUME = process.env.REEL_RESUME === '1';
const SLOT = (process.env.REEL_SLOT || '').trim();
// Суффикс слота: пустой слот сохраняет ИСТОРИЧЕСКИЕ имена файлов, чтобы уже накопленное состояние
// (reels_done.txt на 22 записи) осталось на месте, а не начиналось с нуля.
const СУФ = SLOT ? `_${SLOT}` : '';
const STATE = process.env.REEL_STATE_DIR
  || path.join(require('node:os').homedir(), '.neironka', 'reels');
const ФАЙЛ_ГОТОВЫХ = path.join(STATE, `reels_done${СУФ}.txt`);
const ФАЙЛ_СПИСКА = path.join(STATE, `reels_allow${СУФ}.txt`);

// ПЕРЕЕЗД СОСТОЯНИЯ ИЗ /tmp (13.08). Реестры жили в /tmp, то есть пачка на 380 постов держалась на
// каталоге, который система вправе подчистить в любой момент.
fs.mkdirSync(STATE, { recursive: true });
const прочитать = (f) => { try { return fs.readFileSync(f, 'utf8').split('\n').map((s) => s.trim()).filter(Boolean); } catch { return []; } };
const СТАРЫЙ_ГОТОВЫЕ = `/tmp/reels_done${СУФ}.txt`;
const СТАРЫЙ_СПИСОК = `/tmp/reels_allow${СУФ}.txt`;

// РЕЕСТР СОБРАННЫХ СЛИВАЕТСЯ КАЖДЫЙ ЗАПУСК, А НЕ КОПИРУЕТСЯ ОДНАЖДЫ, И ЭТО НЕ ПЕДАНТИЗМ. На момент
// правки старая копия magosreels_all ещё РЕЗАЛА и дописывала в /tmp свои id. Разовое копирование
// сняло бы снимок, всё дописанное после него осталось бы только в /tmp, и эти посты уехали бы на
// пересборку по второму разу. Реестр монотонный (собранного не убывает), поэтому объединение
// безопасно всегда. Слитое сразу возвращаем на новое место: тогда уборка /tmp ничего не уносит.
const ГОТОВЫЕ = RESUME
  ? [...new Set([...прочитать(ФАЙЛ_ГОТОВЫХ), ...прочитать(СТАРЫЙ_ГОТОВЫЕ)])]
  : [];
if (RESUME && ГОТОВЫЕ.length > прочитать(ФАЙЛ_ГОТОВЫХ).length) {
  try {
    fs.writeFileSync(ФАЙЛ_ГОТОВЫХ, ГОТОВЫЕ.join('\n') + '\n');
    console.log(`  ↪ реестр собранных слит из ${СТАРЫЙ_ГОТОВЫЕ}: всего ${ГОТОВЫЕ.length}`);
  } catch {}
}

// БЕЛЫЙ СПИСОК СЛИВАТЬ НЕЛЬЗЯ: его ведут руками, и объединение воскресило бы id, которые из пачки
// намеренно вычеркнули. Поэтому новый файл главнее, а старый берётся только пока нового нет.
// ПУСТОЙ СПИСОК = БЕЗ ОГРАНИЧЕНИЯ, а не «ни одного поста» (ловушка 1 в шапке): в запросе это
// выражено как «$5 IS NULL ИЛИ id в списке», поэтому пустоту отдаём именно как null.
// БЕЛЫЙ СПИСОК ВКЛЮЧАЕТСЯ ЯВНО, И ЭТО ПОЙМАНО ЖИВЫМ ПРОГОНОМ. Первая редакция читала файл всегда,
// раз он есть. Боевой запуск тут же подобрал оставшийся от массовой резки /tmp/reels_allow.txt на
// 8 id и выдал «постов: 0» — то есть схлопывание молча изменило поведение боевого пути, который
// про списки никогда не знал. Умолчание «берём всё» единственно верное: список это инструмент
// пачки, а не свойство склада.
let СПИСОК = [];
if (process.env.REEL_ALLOW === '1') {
  if (fs.existsSync(ФАЙЛ_СПИСКА)) СПИСОК = прочитать(ФАЙЛ_СПИСКА);
  else {
    СПИСОК = прочитать(СТАРЫЙ_СПИСОК);
    if (СПИСОК.length) {
      try {
        fs.copyFileSync(СТАРЫЙ_СПИСОК, ФАЙЛ_СПИСКА);
        console.log(`  ↪ белый список перенесён: ${СТАРЫЙ_СПИСОК} → ${ФАЙЛ_СПИСКА} (${СПИСОК.length} id)`);
      } catch {}
    }
  }
}

// СТОРОЖ ПАРАЛЛЕЛИ (13.08). ffmpeg грузит процессор всерьёз: замер дня — два воркера идут ровно,
