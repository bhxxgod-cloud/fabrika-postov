  // порождает sh, у которого шаблон попадает в СОБСТВЕННУЮ командную строку, и pgrep считает этот sh
  // живой сборкой. На проверке сторож так насчитал три сборки при нуле запущенных и отказал бы
  // на ровном месте. Без шелла шаблон нигде, кроме самого pgrep, не появляется, а себя pgrep не ищет.
  const все = require('node:child_process')
    // Шаблон с хвостом ловит и старые копии (magosreels_all, magosreels_mine): пока они где-то
    // остались запущенными, они точно так же делят ffmpeg, и сторож обязан их видеть.
    .execFileSync('pgrep', ['-f', 'magosreels[^ ]*\\.cjs'], { encoding: 'utf8' })
    .split('\n').map((s) => Number(s.trim())).filter((p) => p && p !== process.pid);
