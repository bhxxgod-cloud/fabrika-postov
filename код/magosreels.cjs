// ПЕРЕРИСОВКА ХУКА ПОД 9:16 (11.08, брак пойман начальником: «вший лайкнул через год молча»).
// Обложки старого склада несут хук, впечатанный со старыми полями 90px. В карусели 4:5 это влезало,
// а рилс заливает кадр в 9:16 и показывает только центральные 70.3 процента ширины (полоса 759px из
// 1080, поля по 160px срезаются). Длинные хуки резались по бокам.
// Чиним ЛОКАЛЬНО, не трогая базу: если у поста есть ЧИСТЫЙ исходник (source_cover_url) и текст хука,
// рисуем кадр 1 заново поверх чистого фото, тогда хук гарантированно внутри видимой полосы. Если
// чистого исходника нет, оставляем готовую обложку как есть (риск обрезки только на длинных хуках
// старых постов без исходника).
//
// ПОЛЯ 200px, А НЕ 170 (14.08). Здесь стояло 170, и это была ошибка расчёта: 170px формально влезали
// в видимую полосу 759px, но всего на 9.7px, а после растяжения в 9:16 это 13.8px от края готового
// рилса при требовании гейта 40px. Строка во всю ширину блока вставала на грань брака «ТЕКСТ
// УПИРАЕТСЯ В КРАЙ»: замер показал рилс с хуком на полях 170px, забракованный с «стоит от 22 px
// слева и 23 px справа». Край текста в рилсе считается как
// x' = x*1.4222 - 228; для x' = 40 нужно x = 188, берём 200 с запасом 16px на тень и скругление букв.
// Разбор чисел и оговорка про то, чего эти поля НЕ чинят (обложки со старым впечатанным хуком) — в
// slidekit.cjs рядом с константой.
// Число обязано совпадать с HOOK_PAD в slidekit.cjs (там разбор полный, туда же 14.08 сведена вся
// вёрстка блока): один и тот же хук рисуется на сборке поста и заново на резке, и если поля
// разойдутся, перерисовка сдвинет текст относительно уже проверенного гейтом кадра. Переменная
// здесь оставлена ради замеров на живых пачках — умолчание менять только вместе со slidekit.
const HOOK_PAD = Number(process.env.REEL_HOOK_PAD || 200);
// НИЗ БЛОКА ХУКА (12.08, обмер собранных рилсов). Прежний bottom:96px в 4:5 после заливки в 9:16
// сажал текст на 84-91% высоты холста, то есть целиком ПОД интерфейс рилса (он начинается с ~75%).
// Считаем от заливки: кадр 1350 растягивается до 1920 (х1.4222), низ блока должен лечь не глубже
// 75% от 1920 = 1440, значит в координатах 4:5 это 1440/1.4222 = 1013, то есть bottom = 337.
// УМОЛЧАНИЕ БЕРЁМ У slidekit, А НЕ ЦИФРОЙ (14.08). Число здесь уже дважды отставало от общего: и
// когда низ поправили только тут, и когда его пересмотрели только там. Резка перерисовывает хук
// поверх кадра, который сборка уже нарисовала, — разъезд означает, что текст сдвинется относительно
// проверенного гейтом положения. Переменная оставлена ради замеров на живых пачках.
const HOOK_BOTTOM = Number(process.env.REEL_HOOK_BOTTOM || slidekit.HOOK_BOTTOM);
// АВТОПОДГОН ТЕКСТА (12.08, приказ «текст может не влазить, нужно чтобы точно помещался»).
// Видимая полоса 9:16 это центральные 759px, с полями HOOK_PAD текст живёт в 1080-2*200 = 680px.
// Сама подгонка и вёрстка блока теперь общие (slidekit, сведено 14.08) — здесь остаётся только
// подстановка своих чисел, потому что резке нужны переменные окружения для замеров на живых пачках.
async function перерисоватьХук(чистыйUrl, текст, out, tag) {
  const сырой = out.replace(/\.jpg$/, '_raw.jpg');
  // Чистый исходник бывает ССЫЛКОЙ (source_cover_url) и ЛОКАЛЬНЫМ ПУТЁМ (meta.source_cover, его
  // пишет rehook_covers). Раньше локальный путь не понимался, и 64 поста со склада шли мимо
  // перерисовки прямо на риск обрезки.
  if (/^\//.test(String(чистыйUrl)) && fs.existsSync(чистыйUrl)) fs.copyFileSync(чистыйUrl, сырой);
  else await fetchToFile(чистыйUrl, сырой, { what: 'чистый исходник', ms: 60000, min: 5000 });
  const плоский = slidekit.to45(сырой, out.replace(/\.jpg$/, '_45.jpg'));
  const b64 = fs.readFileSync(плоский).toString('base64');
  // Вид хука берём у slidekit — тот же самый блок, что рисует onepost на сборке поста. Свой html
  // здесь остаётся потому, что кадр уже приведён к 4:5 и лежит в памяти строкой base64, а не файлом.
  const блок = slidekit.хукБлок(текст, { pad: HOOK_PAD, bottom: HOOK_BOTTOM });
  const html = `<!doctype html><meta charset="utf-8"><style>*{margin:0;padding:0}
    body{width:1080px;height:1350px;position:relative;overflow:hidden;background:#000;
      font-family:-apple-system,'Helvetica Neue',Arial,sans-serif;-webkit-font-smoothing:antialiased}
    img{width:1080px;height:1350px;object-fit:cover;display:block}
    ${блок.css}</style>
    <img src="data:image/jpeg;base64,${b64}">${блок.html}`;
  await slidekit.renderHtml(html, out, 1080, 1350);
  try { fs.unlinkSync(сырой); fs.unlinkSync(плоский); } catch {}
  return out;
}

