async function main() {
  const a = process.argv.slice(2);
  const флаг = (n, d) => { const i = a.indexOf(`--${n}`); return i >= 0 ? a[i + 1] : d; };
  const есть = (n) => a.includes(`--${n}`);

  const реф = флаг('ref', '');
  const тег = флаг('tag', 'девочка');
  const сколько = Number(флаг('n', 1));
  const откуда = Number(флаг('from', 0));   // с какой локации начать
  const out = флаг('out', path.join(require('node:os').homedir(), 'Desktop/НЕЙРОНКА/ЛОКАЦИИ', тег));
  const модель = флаг('model', 'nano-banana-pro');
  const res = флаг('res', '1K');

  if (!реф || !fs.existsSync(реф)) {
    console.log('нужен --ref <файл.jpg>. Пример:');
    console.log('  node facelocs.cjs --ref ~/Downloads/фото.jpg --tag катя --n 10');
    console.log(`\nлокаций в пуле: ${ЛОКАЦИИ.length}`);
    process.exit(1);
  }
  fs.mkdirSync(out, { recursive: true });

  if (есть('dry')) {
    for (let i = 0; i < сколько; i++) {
      const л = ЛОКАЦИИ[(откуда + i) % ЛОКАЦИИ.length];
      console.log(`\n[${л.тег}]\n${промпт({ локация: л.текст, поза: ПОЗЫ[i % ПОЗЫ.length] })}`);
    }
    console.log('\n(сухой прогон, денег ноль)');
    return;
  }

  let ок = 0;
  for (let i = 0; i < сколько; i++) {
    const л = ЛОКАЦИИ[(откуда + i) % ЛОКАЦИИ.length];
    const поза = ПОЗЫ[i % ПОЗЫ.length];
    const файл = path.join(out, `${тег}-${String(i + 1).padStart(2, '0')}-${л.тег}.jpg`);
    try {
      process.stdout.write(`[${i + 1}/${сколько}] ${л.тег} … `);
      await rgen.genToFile(файл, {
        prompt: промпт({ локация: л.текст, поза }),
        refFiles: [реф],
        model: модель,
        aspect: '9:16',
        resolution: res,
      });
      ок++;
      console.log('ок');
    } catch (e) {
      console.log(`ОШИБКА: ${e.message.slice(0, 90)}`);
    }
  }
  console.log(`\nготово ${ок} из ${сколько}, папка: ${out}`);
}

if (require.main === module) main().catch((e) => { console.error('ОШИБКА:', e.message); process.exit(1); });
module.exports = { ЛОКАЦИИ, ПОЗЫ, промпт };
