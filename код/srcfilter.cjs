// ПРИЁМКА НОВЫХ ИСХОДНИКОВ. Один вход для всех источников сбора: дал список скачанных файлов,
// получил ответ, какие из них легли в src_good, какие в src_bad и почему.
//
// ЗАЧЕМ ОТДЕЛЬНЫМ МОДУЛЕМ (11.08, задача «набрать 700 исходников»). Собирать фотографии мы будем из
// разных мест: яндекс-картинки, публичные профили инстаграма, паблики. Каждому источнику нужен один
// и тот же разбор на входе, и если этот разбор жить будет внутри каждого сборщика, пороги разъедутся
// в первый же день, а вместе с ними разъедется и качество обложек. Здесь разбор один.
//
// ЧТО ЗДЕСЬ НЕ ДЕЛАЕТСЯ. Свои пороги не выдумываются НИ ОДНОГО. Всё числовое решение принимает
// cover_qa.резкость (он же зовёт sharpmeter), а тут только раскладка по папкам и защита от дублей.
// cover_qa.cjs и sharpmeter.cjs модуль только ЧИТАЕТ и вызывает.
//
// ТРИ ВОРОТ ПО ПОРЯДКУ, И ПОРЯДОК ВАЖЕН, ПОТОМУ ЧТО КАЖДЫЕ СЛЕДУЮЩИЕ ДОРОЖЕ ПРЕДЫДУЩИХ:
//   1. ЦЕЛОСТНОСТЬ И РАЗМЕР. Битый и крохотный файл отсеивается сравнением байтов, это даром.
//      Отдельно сюда попадает мусор источника: заглушки «нет картинки», иконки, спрайты.
//   2. ДУБЛЬ ПО ВОСПРИЯТИЙНОМУ ХЭШУ. Считается по рецепту uniqcheck.cjs: кадр в серое 8 на 8,
//      каждый пиксель против среднего, 64 бита, расстояние Хэмминга до 5 бит это тот же кадр.
//      Дубль ловим ДО замера резкости, потому что замер зовёт питон с детектором лица, а это самая
//      дорогая часть прогона, и платить ею за уже лежащую у нас фотографию незачем.
//      Сравниваем против ВСЕХ трёх куч (годные, брак, непригодные) плюс против уже принятых в этом
//      же прогоне: одна и та же картинка приходит из яндекса по двум разным запросам постоянно.
//   3. ЧИСЛОВОЙ ГЕЙТ ОБЛОЖКИ. cover_qa.резкость: мыло по трём осям, размер лица 14% высоты
//      обложки, срез лица кропом 4:5. Плюс своё отдельное решение «лица не нашли»: файл без лица
//      референсом быть не может по определению, и это не порог, а факт.
//
// МОДЕЛЬНАЯ ЧАСТЬ ЗДЕСЬ НЕ ЗОВЁТСЯ СОВСЕМ, И ЭТО СОЗНАТЕЛЬНО (11.08). У ключа openrouter кончился
// баланс, ручка отвечает 402, а «проверка не состоялась» это не «плохо» (тот же урок записан в
// cover_qa.cjs у функции непроверено). Принимать сотни файлов, ожидая ответа, которого не будет,
// значит либо ронять прогон, либо тихо считать весь набор браком. Поэтому на входе работает только
// числовая часть, а файл получает пометку «модель не смотрела»: когда баланс пополнят, эту кучу
// можно будет прогнать вторым эшелоном отдельно, ничего не пересобирая.
//
// НИЧЕГО НЕ УДАЛЯЕМ: брак переезжает в src_bad, а не исчезает. Правило старше этой задачи.
const fs = require('node:fs');
const path = require('node:path');
const { execFileSync } = require('node:child_process');
const FF = require('ffmpeg-static');
const { резкость } = require('./cover_qa.cjs');

const ДОМ = __dirname;
// КУДА КЛАСТЬ ГОДНЫЕ, ПЕРЕОПРЕДЕЛЯЕТСЯ (11.08). Кучу годных иногда разбирают глазами, и разбор идёт
// ПАПКОЙ: пока человек или агент смотрит src_pending, сыпать в ту же папку свежий сбор нельзя, он
// собьёт счёт и подсунет на осмотр непросмотренное как просмотренное. Поэтому целевая папка это
// параметр прогона (SRC_GOOD_DIR), а не константа.
const ГОДНЫЕ = path.join(ДОМ, process.env.SRC_GOOD_DIR || 'src_good');
const БРАК = path.join(ДОМ, 'src_bad');
const НЕПРИГОДНЫЕ = path.join(ДОМ, 'src_unfit');
// ПАПКИ ДЛЯ СРАВНЕНИЯ НА ДУБЛЬ. Дубль обложки это брак поста, а лежать уже взятая фотография может
// в любой из наших куч, включая те, что сейчас у кого-то на осмотре. Сравнивать надо со ВСЕМИ,
// иначе мы вторично возьмём кадр, который уже ушёл в пост.
const ПАПКИ_ИНДЕКСА = [...new Set([ГОДНЫЕ, БРАК, НЕПРИГОДНЫЕ,
  ...(process.env.SRC_INDEX_EXTRA || 'src_good,src_pending,src_pending2').split(',')
    .map((s) => s.trim()).filter(Boolean).map((s) => path.join(ДОМ, s))])];
const ЖУРНАЛ = path.join(ДОМ, 'src_intake.jsonl');
const КЭШ_ХЭШЕЙ = path.join(ДОМ, '.src_phash.json');

// МИНИМУМ ПО БАЙТАМ И ПИКСЕЛЯМ. Это не про качество, а про мусор источника: превью 236 на 236 из
// выдачи, иконка, заглушка. Резкость и лицо на таком мерить бессмысленно, детектор просто не найдёт
// лицо и файл уйдёт в брак с невнятной причиной. Числа взяты по факту: самый маленький наш годный
// исходник это 1080 по короткой стороне, но чтобы не выбросить годное с запасом, порог ниже.
const МИН_БАЙТ = 25 * 1024;
const МИН_СТОРОНА = 500;

const ПОРОГ_ДУБЛЯ = 5;   // расстояние Хэмминга, рецепт и обоснование в uniqcheck.cjs

// ── ВОСПРИЯТИЙНЫЙ ХЭШ ─────────────────────────────────────────────────────────────────────────
// Считаем ровно тем же путём, что uniqcheck.cjs: тот же ffmpeg, та же сетка 8 на 8, то же среднее.
// Своей второй реализации быть не должно, иначе два наших проверщика однажды разойдутся в ответе
// про один и тот же файл, и разбираться в этом будет некому.
function ахэш(файл) {
  const raw = execFileSync(FF, ['-v', 'error', '-i', файл, '-vf', 'scale=8:8,format=gray',
    '-frames:v', '1', '-f', 'rawvideo', '-'], { maxBuffer: 1 << 20 });
  const пиксели = [...raw.slice(0, 64)];
  if (пиксели.length < 64) throw new Error('кадр не декодировался');
  const среднее = пиксели.reduce((a, b) => a + b, 0) / 64;
  let биты = 0n;
  пиксели.forEach((p, i) => { if (p > среднее) биты |= (1n << BigInt(i)); });
  return биты;
}
const хэмминг = (a, b) => { let x = a ^ b, n = 0; while (x) { n += Number(x & 1n); x >>= 1n; } return n; };

// ── ИНДЕКС УЖЕ ЛЕЖАЩИХ ────────────────────────────────────────────────────────────────────────
/**
 * Хэши всех файлов в наших кучах.
 *
 * КЭШ ОБЯЗАТЕЛЕН, И ВОТ ПОЧЕМУ. Хэш считает ffmpeg отдельным процессом на файл. На двух сотнях
 * файлов это ещё терпимо, а конвейеру нужно 500 исходников в сутки, то есть куча будет расти до
 * тысяч, и пересчёт всей кучи перед каждой пачкой станет главной тратой времени в прогоне.
 * Ключ кэша это имя плюс размер плюс mtime: пересжатый или подменённый файл ключ меняет, поэтому
 * устаревшего хэша в кэше остаться не может.
 */
function индекс({ тихо = false } = {}) {
  let кэш = {};
  try { кэш = JSON.parse(fs.readFileSync(КЭШ_ХЭШЕЙ, 'utf8')); } catch { /* кэша ещё нет */ }
  const свежий = {};
  const записи = [];
  let посчитано = 0, битых = 0;
  for (const папка of ПАПКИ_ИНДЕКСА) {
    let имена = [];
    try { имена = fs.readdirSync(папка); } catch { continue; }
    for (const имя of имена) {
      if (!/\.(jpe?g|png|webp)$/i.test(имя)) continue;
      const п = path.join(папка, имя);
      let ст; try { ст = fs.statSync(п); } catch { continue; }
      const ключ = `${path.basename(папка)}/${имя}|${ст.size}|${Math.round(ст.mtimeMs)}`;
      let hex = кэш[ключ];
      if (!hex) {
        try { hex = ахэш(п).toString(16); посчитано++; } catch { битых++; continue; }
      }
      свежий[ключ] = hex;
      записи.push({ файл: имя, папка: path.basename(папка), хэш: BigInt(`0x${hex}`) });
    }
  }
  try { fs.writeFileSync(КЭШ_ХЭШЕЙ, JSON.stringify(свежий)); } catch { /* кэш это удобство, не факт */ }
  if (!тихо) console.log(`индекс хэшей: ${записи.length} файлов (досчитано ${посчитано}, не декодировалось ${битых})`);
  return записи;
}

/** Первый найденный дубль среди записей индекса, либо null. */
function дубль(хэш, записи, порог = ПОРОГ_ДУБЛЯ) {
  for (const з of записи) if (хэмминг(хэш, з.хэш) <= порог) return з;
  return null;
}

// ── ИМЕНА ─────────────────────────────────────────────────────────────────────────────────────
// Держим сложившийся вид имени: номер, запрос, отпечаток. Номер это порядок появления в куче, по
// нему в разборах ссылаются на файл («074 дало схожесть 0.36»), и ломать его нельзя.
function следующийНомер() {
  let макс = 0;
  for (const папка of ПАПКИ_ИНДЕКСА) {
    let имена = []; try { имена = fs.readdirSync(папка); } catch { continue; }
    for (const имя of имена) {
      const m = /^(\d{3,4})_/.exec(имя);
      if (m) макс = Math.max(макс, Number(m[1]));
    }
  }
  // СМЕЩЕНИЕ НУМЕРАЦИИ (SRC_NUM_OFFSET). Самая дорогая часть приёмки это замер: он поднимает питон с
  // детектором лица и идёт примерно 240 файлов в минуту, тогда как скачивание даёт больше тысячи.
  // То есть на объёме в тысячи файлов узкое место уже не сеть, а гейт, и гонять его надо в несколько
  // процессов. Мешает этому ровно одно: номер берётся как «максимум в кучах плюс один», два процесса
  // возьмут ОДИН И ТОТ ЖЕ номер, и второй затрёт файл первого. Смещение разводит их диапазоны, и
  // молчаливой потери файла не будет.
  return макс + 1 + Number(process.env.SRC_NUM_OFFSET || 0);
}
/** Короткая латинская метка причины отказа для имени файла. */
function краткая(причина) {
  const с = String(причина || '');
  if (/лица не найдено/i.test(с)) return 'noface';
  if (/набок|наклон/i.test(с)) return 'roll';
  if (/мелк/i.test(с)) return 'smallface';
  if (/срез/i.test(с)) return 'cropcut';
  if (/мыл|резкост/i.test(с)) return 'blur';
  if (/замер/i.test(с)) return 'nometric';
  return 'bad';
}
const ярлык = (s) => String(s || 'без_запроса').trim().toLowerCase()
  .replace(/[^a-zа-яё0-9]+/gi, '_').replace(/^_+|_+$/g, '').slice(0, 40) || 'без_запроса';

// ── ЦЕЛОСТНОСТЬ ───────────────────────────────────────────────────────────────────────────────
// Тот же маркер конца картинки, что в sharpmeter.добыть: оборванный jpeg декодер дорисует ровным
// цветом, и мы замерим резкость этой заливки, а не фотографии.
function целый(буф) {
  if (буф.length < МИН_БАЙТ) return `мелкий файл ${Math.round(буф.length / 1024)} кб (<${МИН_БАЙТ / 1024})`;
  const jpg = буф[0] === 0xFF && буф[1] === 0xD8;
  const png = буф[0] === 0x89 && буф[1] === 0x50;
  const webp = буф.slice(0, 4).toString('latin1') === 'RIFF' && буф.slice(8, 12).toString('latin1') === 'WEBP';
  if (jpg) return буф[буф.length - 2] === 0xFF && буф[буф.length - 1] === 0xD9 ? null : 'jpeg оборван';
  if (png) return буф.subarray(буф.length - 12).includes(Buffer.from('IEND')) ? null : 'png оборван';
  if (webp) return null;
  return 'не картинка';
}

/**
 * Принять пачку скачанных файлов.
 *
 * @param {{путь:string, запрос?:string, ссылка?:string, источник?:string}[]} кандидаты
 * @param {object} [o]
 * @param {object[]} [o.индекс] готовый индекс хэшей, чтобы не пересчитывать на каждой пачке
 * @param {boolean} [o.тихо] не печатать построчно
 * @returns {{годные:object[], брак:object[], непригодные:object[], дубли:object[], битые:object[]}}
 */
function принять(кандидаты, o = {}) {
  const записи = o.индекс || индекс({ тихо: o.тихо });
  const итог = { годные: [], брак: [], непригодные: [], дубли: [], битые: [] };
  const говорить = (s) => { if (!o.тихо) console.log(s); };

  // ВОРОТА 1 и 2 идут файл за файлом, потому что оба дешёвые и оба умеют выкинуть кандидата до
  // дорогого замера. Всё, что их прошло, уходит в замер ОДНОЙ пачкой: sharpmeter поднимает питон
  // с onnx-детектором, и один вызов на сто файлов кончается в разы быстрее ста вызовов.
  const кПроверке = [];
  for (const к of кандидаты) {
    let буф; try { буф = fs.readFileSync(к.путь); } catch (e) { итог.битые.push({ ...к, причина: `не читается: ${e.message}` }); continue; }
    const беда = целый(буф);
    if (беда) { итог.битые.push({ ...к, причина: беда }); continue; }
    let хэш; try { хэш = ахэш(к.путь); } catch (e) { итог.битые.push({ ...к, причина: `не декодируется: ${e.message}` }); continue; }
    const д = дубль(хэш, записи);
    if (д) { итог.дубли.push({ ...к, причина: `дубль ${д.папка}/${д.файл}` }); continue; }
    // Кандидата сразу кладём в индекс: две одинаковые картинки внутри одной пачки это норма.
    записи.push({ файл: path.basename(к.путь), папка: 'пачка', хэш });
    кПроверке.push({ ...к, хэш });
  }
  говорить(`ворота 1-2: битых ${итог.битые.length}, дублей ${итог.дубли.length}, к замеру ${кПроверке.length}`);
  if (!кПроверке.length) return итог;

  // ВОРОТА 3: числовой гейт обложки. Пачками по 40, чтобы один упавший питон не унёс весь прогон.
  const замеры = [];
  for (let i = 0; i < кПроверке.length; i += 40) {
    const часть = кПроверке.slice(i, i + 40);
    try { замеры.push(...резкость(часть.map((к) => к.путь))); }
    catch (e) {
      говорить(`  ⚠ замер части ${i}-${i + часть.length} упал (${String(e.message).slice(0, 90)}), беру по одному`);
      for (const к of часть) {
        try { замеры.push(...резкость([к.путь])); }
        catch (e2) { замеры.push({ ист: к.путь, ошибка: String(e2.message).slice(0, 120) }); }
      }
    }
  }
  const по = new Map(замеры.map((з) => [з.ист, з]));

  let номер = следующийНомер();
  for (const к of кПроверке) {
    const з = по.get(к.путь) || { ошибка: 'замер потерял файл' };
    let куда = ГОДНЫЕ, вид = 'годные', причина = null;
    if (з.ошибка) { куда = БРАК; вид = 'брак'; причина = `замер не вышел: ${з.ошибка}`; }
    else if (!з.лицо_найдено) {
      // НЕ ПОРОГ, А ФАКТ. Исходник это референс лица: по нему модель сохраняет личность на кадрах
      // 3 и 4. Нет лица, нечего сохранять, и никакая резкость этого не исправит.
      куда = БРАК; вид = 'брак'; причина = 'лица не найдено (yunet): референсом быть не может';
    } else if (з.непригоден) {
      // Мелкое или срезанное лицо: снимок бывает безупречным, а референсом не служит. Разделение
      // куч не наше изобретение, оно уже описано в srcbad.cjs у константы НЕПРИГОДНЫЕ.
      куда = НЕПРИГОДНЫЕ; вид = 'непригодные'; причина = з.причина;
    } else if (з.брак) { куда = БРАК; вид = 'брак'; причина = з.причина; }

    // ПРИЧИНА ОТКАЗА В ИМЕНИ ФАЙЛА. Журнал ведётся, но кучи брака разбирают глазами и ПАПКОЙ, а в
    // папке видно только имя: без метки непонятно, лежит тут мелкое лицо или лежащий набок кадр,
    // и приходится лезть в журнал за каждым файлом. Метка короткая и латиницей, чтобы имя не пухло.
    const метка = вид === 'годные' ? '' : `_${краткая(причина)}`;
    const рас = path.extname(к.путь).toLowerCase() || '.jpg';
    const основа = `${String(номер++).padStart(3, '0')}_${ярлык(к.запрос)}${метка}_${з.ошибка ? 'nohash' : к.хэш.toString(16).padStart(16, '0')}`;
    fs.mkdirSync(куда, { recursive: true });
    // ЗАЩИТА ОТ ЗАНЯТОГО ИМЕНИ, И ЭТО ОПЛАЧЕННЫЙ УРОК (11.08). Приёмку гоняли тремя процессами сразу
    // ради темпа, номера разводили смещением, и всё равно 300 принятых файлов из 4471 исчезли:
    // renameSync в существующий путь МОЛЧА затирает цель, и совпавшее имя означает потерянную
    // фотографию, которую журнал при этом честно записал как принятую. Проверка «занято, беру
    // следующее» стоит один stat и делает потерю невозможной, сколько бы процессов ни работало.
    let имя = основа + рас;
    for (let к2 = 1; fs.existsSync(path.join(куда, имя)); к2++) имя = `${основа}-${process.pid}${к2 > 1 ? `-${к2}` : ''}${рас}`;
    const цель = path.join(куда, имя);
    try { fs.renameSync(к.путь, цель); }
    catch { try { fs.copyFileSync(к.путь, цель); fs.unlinkSync(к.путь); } catch (e) { итог.битые.push({ ...к, причина: `не переложился: ${e.message}` }); continue; } }

    const запись = {
      файл: имя, вид, причина, источник: к.источник || null, запрос: к.запрос || null,
      ссылка: к.ссылка || null, размер: з.ш && з.в ? `${з.ш}x${з.в}` : null,
      метрики: з.метрики || null, гео: з.гео || null,
      // Отметка про модель обязательна: без неё через неделю никто не отличит «модель сказала ок»
      // от «модель не спрашивали, потому что кончился баланс».
      модель: 'не проверено (openrouter 402)',
      когда: new Date().toISOString(),
    };
    try { fs.appendFileSync(ЖУРНАЛ, `${JSON.stringify(запись)}\n`); } catch { /* журнал не должен ронять приёмку */ }
    итог[вид].push(запись);
    говорить(`  ${вид === 'годные' ? '✅' : вид === 'непригодные' ? '△' : '⛔'} ${имя}${причина ? ` — ${причина}` : ''}`);
  }
  return итог;
}

