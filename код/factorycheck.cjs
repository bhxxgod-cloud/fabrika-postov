// ЗАЧЕМ. 11.08 волна на 160 постов молотила час и не дала ни одного поста: на каждый заказ провайдер
// партнёра отвечал 403 «User is locked. Reason: Exhausted balance». Внутри одного поста это видно
// только через 10-25 минут ожидания рендера, а волна из четырёх полос успела сжечь час времени и
// разложить 15 заказов в отказ. Такое надо ловить ДО старта: одним чтением очереди фабрики.
//
// НИЧЕГО НЕ ЗАКАЗЫВАЕМ. Проверка бесплатная: читаем список последних заказов и смотрим, чем они
// кончились. Заказать пробный кадр было бы честнее, но это деньги, а ответ и так виден по истории.
const { openAdmin } = require('./adminbrowser.cjs');

/** Признаки, по которым отказ означает «дальше бессмысленно, это не наша сторона». */
const БЕЗНАДЁЖНО = [
  /Exhausted balance/i,     // у партнёра кончились деньги на генерации
  /User is locked/i,
  /insufficient|balance/i,
];

/**
 * Прочитать состояние очереди фабрики.
 * @returns {Promise<{по: object, свежих: number, отказов: number, безнадёжных: number, причина: string}>}
 */
async function состояние(сколько = 12) {
  const { page, done } = await openAdmin();
  try {
    const r = await page.evaluate(async (n) => {
      const x = await fetch('/api/admin/promo/posts').then((z) => z.json());
      const все = x.posts || [];
      const по = {};
      for (const z of все) по[z.status] = (по[z.status] || 0) + 1;
      // СМОТРИМ ТОЛЬКО НА СВЕЖИЕ ЗАКАЗЫ ПО ВРЕМЕНИ (11.08, вторая редакция).
      // Первая редакция брала последние N заказов независимо от возраста, и это дало ложный стоп:
      // партнёр пополнил баланс, а проверка всё ещё видела отказы часовой давности и не пускала волну.
      // Отказ имеет смысл, только если он СВЕЖИЙ: старая история ничего не говорит о текущем балансе.
      const порог = Date.now() - 30 * 60000;
      const свежие = все.slice(0, n)
        .map((z) => ({
          st: z.status,
          t: Date.parse(z.createdAt || z.created_at || z.updatedAt || 0) || 0,
          err: String(z.error || z.errorMessage || z.failureReason || (z.meta && z.meta.error) || ''),
        }))
        .filter((z) => !z.t || z.t >= порог);
      return { по, свежие };
    }, сколько);
    const отказы = r.свежие.filter((z) => z.st === 'failed' || z.st === 'error');
    const безнадёжные = отказы.filter((z) => БЕЗНАДЁЖНО.some((re) => re.test(z.err)));
    return {
      по: r.по,
      свежих: r.свежие.length,
      отказов: отказы.length,
      безнадёжных: безнадёжные.length,
      причина: (безнадёжные[0] || отказы[0] || {}).err ? (безнадёжные[0] || отказы[0]).err.slice(0, 220) : '',
    };
  } finally {
    await done().catch(() => {});
  }
}

/**
 * Можно ли пускать волну. Отказываем, когда среди свежих заказов ЕСТЬ безнадёжный отказ: один такой
 * это уже приговор всей волне, потому что причина общая для всех заказов, а не для конкретного кадра.
 */
async function можноПускать() {
  const с = await состояние();
  if (с.безнадёжных > 0) {
    return { можно: false, почему: `фабрика отказывает по причине не с нашей стороны: ${с.причина}`, с };
  }
  // Все свежие заказы в отказе, но текста нет: тоже не пускаем, но говорим об этом иначе.
  if (с.свежих >= 5 && с.отказов === с.свежих) {
    return { можно: false, почему: `все ${с.свежих} последних заказов фабрики в отказе`, с };
  }
  return { можно: true, почему: '', с };
}

module.exports = { состояние, можноПускать };

if (require.main === module) {
  (async () => {
    const r = await можноПускать();
    console.log(`статусы фабрики: ${JSON.stringify(r.с.по)}`);
    console.log(`свежих ${r.с.свежих}, отказов ${r.с.отказов}, из них безнадёжных ${r.с.безнадёжных}`);
    if (r.можно) console.log('ВЕРДИКТ: волну пускать можно');
    else console.log(`ВЕРДИКТ: ВОЛНУ НЕ ПУСКАТЬ, ${r.почему}`);
    process.exit(r.можно ? 0 : 2);
  })().catch((e) => { console.error('ОШИБКА:', e.message); process.exit(1); });
}
