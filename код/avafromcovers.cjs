'use strict';
// ПУЛ АВАТАРОК ИЗ ДОГЕНЕРЕННЫХ ОБЛОЖЕК. Приказ владельца 15.08: «наши 1 фотки для поста могут
// быть авами!!!»
//
// ОТКУДА БЕРЁМ. ~/Desktop/ОБЛОЖКИ-ДОГЕН/<девочка>/обложка*.jpg — это работа covergen.cjs:
// сгенерированные снимки ОДНОЙ И ТОЙ ЖЕ девушки в разных местах, 9:16, лицо крупное. На 15.08 их
// 226 в пятнадцати папках, и они растут. Каждый уже прошёл приёмку covergen: лицо сверено с
// оригиналом через facesim, картинка сверена с уже принятыми через dHash.
//
// ═══ ГЛАВНОЕ: КРОПИТЬ НАДО ПО ЛИЦУ, А НЕ ПО ЦЕНТРУ. ЭТО ЗАМЕР, А НЕ ВКУС ══════════════════════
// Аватарку показывают КРУГОМ, вписанным в квадрат. Кадр 9:16 в квадрат не влезает, его придётся
// резать, и весь вопрос в том, откуда брать квадрат.
// Замер по всем 226 обложкам (yunet, доля площади рамки лица, попавшей в круг):
//   · ЦЕНТРАЛЬНЫЙ квадрат режет лицо у 91 обложки из 226, это 40%. Худший случай — 73% рамки,
//     то есть у героини срезано больше четверти лица, обычно макушка;
//   · квадрат ПО ЛИЦУ: медиана 100%, десятый процентиль 100%, режет только у единиц.
// Почему так: центр кадра 9:16 приходится на грудь. Лицо на этих обложках стоит в верхней трети —
// центр рамки лица лежит на 0.41 высоты по медиане, макушка на 0.26. Центральный квадрат
// (от 0.28 до 0.72 высоты) начинается НИЖЕ макушки, поэтому и срезает её.
// Проверено глазами на пяти кадрах, включая худшие: на 072-нов38/обложка16 центральный квадрат
// оставляет в круге джинсовую куртку и обрезанную макушку, а квадрат по лицу — портрет целиком.
//
// ═══ ВТОРОЕ ГЛАВНОЕ: ОДНА АВА = ОДИН АККАУНТ ══════════════════════════════════════════════════
// Две одинаковые аватарки на разных акках это то, по чему их связывают. Ровно эта беда уже была с
// обложками рилсов: 90 рилсов из 209 сделаны на ВОСЬМИ фотографиях (замер 14.08, из-за него и
// появился covergen). Повторять её на аватарках нельзя.
// Сверяем перцептивным dHash 16x16 (256 бит) счётом coverguard.cjs, порог тот же 48 бит — и внутри
// новой пачки, и ПРОТИВ УЖЕ СОБРАННОГО ПУЛА, чтобы новая ава не совпала со старой.
//
// ═══ И ТРЕТЬЕ, ЧЕГО dHASH НЕ ЛОВИТ, А ЖИВОЙ ЧЕЛОВЕК ЛОВИТ СРАЗУ ═══════════════════════════════
// Все обложки одной папки это ОДНА ДЕВУШКА. dHash разведёт их легко: это разные снимки, разные
// места, расхождение сотни бит. Но зритель увидит одно лицо. Поэтому папка на выходе это НЕ пул
// «на любой аккаунт», а пул НА ОДНУ ПЕРСОНУ: раздавать эти авы можно только тем аккаунтам, которые
// уже ведут эту же девушку (у avapack.cjs то же правило и та же причина: «чужое лицо не совпадёт
// с постами акка»). Сколько аккаунтов ведёт одну персону — вопрос к владельцу, инструмент за него
// не решает и папки не смешивает.
//
// НИЧЕГО НЕ ЗАЛИВАЕТ И НЕ ПОСТИТ: собирает папку и zip, дальше руками.
//
// ЗАПУСК:
//   node avafromcovers.cjs                          собрать всё, с проверкой моделью
//   node avafromcovers.cjs --только-числа           без модели и без денег
//   node avafromcovers.cjs --девочка блонд-авто     одну персону
//   node avafromcovers.cjs --zip                    ещё и упаковать в zip для залива

const fs = require('node:fs');
const path = require('node:path');
const { execFileSync } = require('node:child_process');
const FF = require('ffmpeg-static');
const CG = require('./coverguard.cjs');
const AQ = require('./avaqa.cjs');

const ВХОД = process.env.AVA_COVERS_IN || path.join(process.env.HOME, 'Desktop', 'ОБЛОЖКИ-ДОГЕН');
const ВЫХОД = process.env.AVA_COVERS_OUT || path.join(process.env.HOME, 'Desktop', 'АВЫ-15-08', 'из-обложек');
// Пул, против которого сверяемся на повтор. Нет папки — сверять не с чем, это не ошибка.
const ПУЛ = process.env.AVA_POOL || path.join(process.env.HOME, 'Desktop', 'АВЫ-15-08', 'пул');
const ПОРОГ_БИТ = Number(process.env.COVER_THRESH || 48);
// ПОТОЛОК СТОРОНЫ, А НЕ ЦЕЛЬ. Обложки лежат в 572x1024, квадрат из них выходит 572x572. Тянуть его
// до 1080 незачем: инстаграм показывает аву в 320 px, а апскейл детали не рождает, только вес и
// следы интерполяции, за которые avaqa же и забракует кадр по «шуму». Уменьшаем, если больше.
const ПОТОЛОК = Number(process.env.AVA_SIDE_MAX || 1080);

/**
 * Квадрат по лицу из кадра 9:16.
 * @param {string} ист исходная обложка
 * @param {string} out куда писать квадрат
 * @param {object} г запись avaqa.геометрия по этому файлу (нужны ш, в, рамка)
 * @returns {{сторона:number, сверху:number, поЛицу:boolean}}
 */
function квадратПоЛицу(ист, out, г) {
  const W = г.ш;
  const H = г.в;
  const сторона = Math.min(W, H);
  let сверху = Math.round((H - сторона) / 2);       // запасной вариант: центр, если лица нет
  let поЛицу = false;
  if (г.рамка) {
    // 0.55 высоты рамки, а не 0.5: глаза стоят выше середины лица, и центр по рамке уводит круг
    // на лоб. Тот же коэффициент стоит в avapack.cjs, он там подобран на живых кадрах.
    const fy = г.рамка.y + г.рамка.h * 0.55;
    сверху = Math.round(Math.min(Math.max(0, fy - сторона / 2), Math.max(0, H - сторона)));
    поЛицу = true;
  }
  const слева = Math.round(Math.max(0, (W - сторона) / 2));
  const цель = Math.min(ПОТОЛОК, сторона);
  fs.mkdirSync(path.dirname(out), { recursive: true });
  execFileSync(FF, ['-nostdin', '-y', '-loglevel', 'error', '-i', ист,
    '-vf', `crop=${сторона}:${сторона}:${слева}:${сверху},scale=${цель}:${цель}`, '-q:v', '2', out]);
  return { сторона, сверху, поЛицу };
}

function папки() {
  if (!fs.existsSync(ВХОД)) return [];
  return fs.readdirSync(ВХОД)
    .filter((d) => !d.startsWith('.') && fs.statSync(path.join(ВХОД, d)).isDirectory())
    .sort();
}

/** Обложки девочки. Подпапка «брак» не берётся: covergen уже её отбраковал. */
function обложки(девочка) {
  const p = path.join(ВХОД, девочка);
  return fs.readdirSync(p).filter((f) => /^обложка.*\.(jpe?g|png)$/i.test(f)).sort()
    .map((f) => path.join(p, f));
}

/** Хэши уже собранного пула — чтобы новая ава не совпала со старой. */
function хэшиПула() {
  const из = [];
  if (!fs.existsSync(ПУЛ)) return из;
  for (const f of fs.readdirSync(ПУЛ)) {
    if (!/\.(jpe?g|png)$/i.test(f)) continue;
    try { из.push({ имя: f, хэш: CG.hashImage(path.join(ПУЛ, f)) }); } catch { /* битый файл пропускаем */ }
  }
  return из;
}

async function собрать(opts = {}) {
  const девочки = opts.девочка ? [opts.девочка] : папки();
  if (!девочки.length) { console.log(`нет папок в ${ВХОД}`); return; }
  const пул = хэшиПула();
  console.log(`девочек: ${девочки.length}, в пуле для сверки: ${пул.length} ав, порог повтора ${ПОРОГ_БИТ} бит из 256`);

  const свод = { всего: 0, взято: 0, брак: 0, повтор: 0, безЛица: 0 };
  const принятые = [...пул];      // сюда копятся хэши всего, что уже взяли: и пул, и новые

  for (const д of девочки) {
    const исходники = обложки(д);
    if (!исходники.length) continue;
    свод.всего += исходники.length;
    const вых = path.join(ВЫХОД, д);
    fs.mkdirSync(вых, { recursive: true });

    // Один прогон детектора на всю папку: вызов yunet стоит секунды, по файлу — это часы на пачке.
    const гео = new Map(AQ.геометрия(исходники).map((г) => [г.файл, г]));

    // 1. КРОП. Режем всё, потом судим: судить надо ровно тот кадр, который поедет в аву.
    const кроп = [];
    for (const ист of исходники) {
      const г = гео.get(ист);
      if (!г || г.ошибка) { свод.брак++; continue; }
      if (!г.лицо_найдено) {
        // Лицо не нашли — кропить по лицу не по чему. Такой кадр в аву не берём молча: он поедет
        // в «брак» на общих основаниях, и причина будет видна в имени.
        свод.безЛица++;
      }
      const имя = `ava_${д}_${path.basename(ист).replace(/^обложка/, '').replace(/\.(jpe?g|png)$/i, '')}.jpg`
        .replace(/_+/g, '_');
      const out = path.join(вых, имя);
      try { квадратПоЛицу(ист, out, г); кроп.push({ ист, out }); }
      catch (e) { console.log(`  ${path.basename(ист)}: кроп не вышел — ${e.message.slice(0, 60)}`); свод.брак++; }
    }
    if (!кроп.length) continue;

    // 2. ОТДЕЛ КАЧЕСТВА по тем же правилам, что и старый пул.
    const итог = await AQ.проверитьПачку(кроп.map((k) => k.out), { безМодели: opts.безМодели });
    const плохие = итог.filter((r) => !r.годится && !r.непроверено);
    AQ.разложить(итог, вых);
    свод.брак += плохие.length;

    // 3. ДЕДУП. Только по тому, что пережило отдел качества.
    const живые = итог.filter((r) => r.годится || r.непроверено).map((r) => r.файл).filter((f) => fs.existsSync(f));
    const ПОВТОРЫ = path.join(вых, 'повторы');
    let взято = 0;
    for (const ф of живые) {
      let хэш = null;
      try { хэш = CG.hashImage(ф); } catch { хэш = null; }
      if (!хэш) { взято++; continue; }              // не посчитался хэш — не повод выбрасывать кадр
      let ближайшее = { имя: null, бит: 9999 };
      for (const п of принятые) {
        const d = CG.hamming(хэш, п.хэш);
        if (d < ближайшее.бит) ближайшее = { имя: п.имя, бит: d };
      }
      if (ближайшее.бит <= ПОРОГ_БИТ) {
        fs.mkdirSync(ПОВТОРЫ, { recursive: true });
        const цель = path.join(ПОВТОРЫ, path.basename(ф).replace(/\.jpg$/i, `__повтор-${ближайшее.бит}бит-с-${ближайшее.имя}`));
        try { fs.renameSync(ф, цель); } catch { /* уже нет */ }
        свод.повтор++;
        continue;
      }
      принятые.push({ имя: path.basename(ф), хэш });
      взято++;
    }
    свод.взято += взято;
    console.log(`  ${д}: обложек ${исходники.length} → ав ${взято}`
      + `${плохие.length ? `, брак ${плохие.length}` : ''}`);
  }

  console.log(`\nитог: обложек ${свод.всего}, аватарок ${свод.взято}, `
    + `брак ${свод.брак}, повторов ${свод.повтор}`
    + `${свод.безЛица ? `, без найденного лица ${свод.безЛица}` : ''}`);
  console.log(`готово: ${ВЫХОД}`);
  console.log('ВНИМАНИЕ: одна папка = одна девушка. Авы из папки можно ставить только аккаунтам,');
  console.log('которые уже ведут эту же персону, иначе лицо на аве не совпадёт с лицом в постах.');
  return свод;
}

/** Zip для залива. Именно zip: магос принимает пул одним архивом. Ничего не публикует. */
function упаковать() {
  const zip = path.join(path.dirname(ВЫХОД), 'АВАТАРКИ-ИЗ-ОБЛОЖЕК.zip');
  try { fs.unlinkSync(zip); } catch { /* не было */ }
  // -x исключает служебные подпапки: брак и повторы в залив ехать не должны.
  execFileSync('zip', ['-q', '-r', zip, path.basename(ВЫХОД),
    '-x', '*/брак/*', '*/повторы/*', '*.DS_Store'], { cwd: path.dirname(ВЫХОД) });
  const мб = (fs.statSync(zip).size / 1048576).toFixed(1);
  console.log(`zip: ${zip} (${мб} МБ)`);
  return zip;
}

if (require.main === module) {
  (async () => {
    const арг = process.argv.slice(2);
    const безМодели = арг.includes('--только-числа');
    const делатьZip = арг.includes('--zip');
    const i = арг.indexOf('--девочка');
    const девочка = i >= 0 ? арг[i + 1] : null;
    await собрать({ безМодели, девочка });
    if (делатьZip) упаковать();
  })().catch((e) => { console.error(`ИТОГ: ✗ ${e.message}`); process.exit(1); });
}

module.exports = { квадратПоЛицу, собрать, упаковать, папки, обложки, хэшиПула, ПОРОГ_БИТ };
