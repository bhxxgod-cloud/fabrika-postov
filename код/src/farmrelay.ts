// farmrelay.ts — МОСТ К ФЕРМЕ ТЕЛЕФОНОВ ЧЕРЕЗ ОБЛАКО.
//
// ЗАЧЕМ. Вкладка «TikTok ферма» ходила из браузера ПРЯМО на http://127.0.0.1:7420.
// Замысел был разумный: панель отдаётся из облака, ферма живёт на маке, а браузер
// открыт на том же маке и физически может дотянуться до обоих. На практике так
// нельзя, и упирается это не в наш код.
//
// Страница открыта по https, а идёт на http и в частную сеть. Каждый браузер
// закрывает это по-своему, и ни одну из дверей нельзя открыть со стороны сервера:
//
//   • Chrome требует отдельного разрешения на переход из публичной сети в частную
//     (Private Network Access) и может дополнительно спросить человека;
//   • SAFARI не делает исключения для localhost вовсе и не понимает этого
//     заголовка. Владелец видит ровно «Load failed» — это его формулировка
//     заблокированного запроса, у Chrome она другая.
//
// То есть направление «браузер → localhost» неисправимо для части браузеров.
// Разворачиваем направление: ФЕРМА САМА СТУЧИТСЯ В ОБЛАКО и держит канал, а
// браузер разговаривает только со своим же доменом по https. Тогда ни смешанного
// содержимого, ни частной сети не возникает в принципе, и работает это в любом
// браузере, включая телефон владельца вдали от дома.
//
// КАК УСТРОЕНО. Длинный опрос, без веб-сокетов: библиотеки в проекте нет, а
// заводить зависимость ради одного канала дороже, чем обойтись обычным HTTP.
//
//   1. браузер зовёт /api/farm/call?path=/api/boards на СВОЁМ домене;
//   2. вызов кладётся в очередь и ждёт ответа;
//   3. ферма висит на /api/farm/pull и забирает вызов, как только он появился;
//   4. ферма исполняет его у себя и кладёт ответ в /api/farm/push;
//   5. ожидающий вызов просыпается и отдаёт ответ браузеру.
//
// ЧЕСТНОСТЬ СОСТОЯНИЯ. Если ферма не приходила за вызовами дольше порога, мы
// отвечаем «ферма офлайн» СРАЗУ, а не морозим браузер на таймаут. Разница важна:
// «мак выключен» и «запрос потерялся» это разные беды, и лечатся они разным.

import type { Express, Request, Response, RequestHandler } from 'express';

/** Ожидающий вызов: браузер уже ждёт, ферма ещё не ответила. */
type Вызов = {
  id: string;
  method: string;
  path: string;
  body: string | null;
  /** Кому отдать ответ, когда он придёт. */
  ответить: (r: Ответ) => void;
  создан: number;
};

type Ответ = {
  status: number;
  headers?: Record<string, string>;
  /** Тело в base64: через канал ходят и картинки экранов, не только json. */
  base64: string;
};

// Живём в памяти процесса: канал существует ровно столько, сколько существует
// сам процесс панели, и переживать перезапуск ему незачем. Ферма приходит снова
// через секунду после любого разрыва.
const ОЖИДАЮТ = new Map<string, Вызов>();
/** Вызовы, которые ферма ещё не забрала. */
const ОЧЕРЕДЬ: Вызов[] = [];
/** Ферма, висящая на длинном опросе прямо сейчас (ждёт работы). */
let ждётРаботы: ((v: Вызов[]) => void) | null = null;
let последнийВизитФермы = 0;

/** Сколько ждём ответа фермы, прежде чем признать вызов потерянным. */
const ПОТОЛОК_ВЫЗОВА_МС = 25_000;
/** Сколько держим опрос фермы открытым, если работы нет. */
const ДЛИНА_ОПРОСА_МС = 20_000;
/** Через сколько молчания считаем ферму офлайн. */
const ОФЛАЙН_ПОСЛЕ_МС = 45_000;
/** Потолок тела: экран платы это png на сотни килобайт, но не мегабайты. */
const ПОТОЛОК_ТЕЛА = 8 * 1024 * 1024;

let счётчик = 0;
const новыйId = () => `в${Date.now().toString(36)}-${(++счётчик).toString(36)}`;

export const фермаНаСвязи = (): boolean => Date.now() - последнийВизитФермы < ОФЛАЙН_ПОСЛЕ_МС;

/** Отдать ферме накопившееся, если она сейчас слушает. */
function разбудитьФерму(): void {
  if (!ждётРаботы || !ОЧЕРЕДЬ.length) return;
  const кому = ждётРаботы;
  ждётРаботы = null;
  кому(ОЧЕРЕДЬ.splice(0, ОЧЕРЕДЬ.length));
}

export function registerFarmRelay(app: Express, requireAuth: RequestHandler): void {
  const токен = process.env.API_TOKEN || process.env.DASHBOARD_PASSWORD || '';
  const своя = (req: Request): boolean => {
    const h = String(req.headers.authorization || '');
    return Boolean(токен) && h === `Bearer ${токен}`;
  };

  /**
   * СТОРОНА ФЕРМЫ: забрать работу.
   *
   * Держим соединение открытым до двадцати секунд. Это не «медленно», а ровно
   * наоборот: вызов уходит к ферме в ту же миллисекунду, когда появился, без
   * ожидания следующего опроса. Пустой ответ по истечении срока — это норма, а
   * не сбой, и ферма просто приходит снова.
   */
  app.get('/api/farm/pull', async (req: Request, res: Response) => {
    if (!своя(req)) return res.status(401).json({ error: 'нужен Bearer API_TOKEN' });
    последнийВизитФермы = Date.now();

    if (ОЧЕРЕДЬ.length) {
      return res.json({ вызовы: ОЧЕРЕДЬ.splice(0, ОЧЕРЕДЬ.length) .map(({ id, method, path, body }) => ({ id, method, path, body })) });
    }

    let закрыт = false;
    const таймер = setTimeout(() => {
      if (закрыт) return;
      закрыт = true;
      if (ждётРаботы === выдать) ждётРаботы = null;
      res.json({ вызовы: [] });
    }, ДЛИНА_ОПРОСА_МС);

    const выдать = (v: Вызов[]) => {
      if (закрыт) return;
      закрыт = true;
      clearTimeout(таймер);
      res.json({ вызовы: v.map(({ id, method, path, body }) => ({ id, method, path, body })) });
    };
    // Второй ожидающий вытесняет первого: ферма одна, и два одновременных
    // опроса значат, что предыдущий уже мёртв (перезапуск, разрыв сети).
    if (ждётРаботы) { try { ждётРаботы([]); } catch { /* уже отвечено */ } }
    ждётРаботы = выдать;

    req.on('close', () => {
      if (закрыт) return;
      закрыт = true;
      clearTimeout(таймер);
      if (ждётРаботы === выдать) ждётРаботы = null;
    });
  });

  /** СТОРОНА ФЕРМЫ: положить ответ на конкретный вызов. */
  app.post('/api/farm/push', (req: Request, res: Response) => {
    if (!своя(req)) return res.status(401).json({ error: 'нужен Bearer API_TOKEN' });
    последнийВизитФермы = Date.now();
    const { id, status, headers, base64 } = (req.body || {}) as Partial<Ответ> & { id?: string };
    if (!id) return res.status(400).json({ error: 'нет id вызова' });
    const вызов = ОЖИДАЮТ.get(String(id));
    // Вызова уже нет — это НЕ ошибка фермы: браузер мог уйти со страницы или
    // истёк потолок ожидания. Отвечаем спокойно, чтобы ферма не считала это сбоем.
    if (!вызов) return res.json({ принято: false, причина: 'вызов уже не ждут' });
    ОЖИДАЮТ.delete(String(id));
    вызов.ответить({
      status: Number(status) || 502,
      headers: (headers as Record<string, string>) || {},
      base64: String(base64 || ''),
    });
    res.json({ принято: true });
  });

  /** СТОРОНА ФЕРМЫ: сказать, что жива, даже когда работы нет. */
  app.post('/api/farm/beat', (req: Request, res: Response) => {
    if (!своя(req)) return res.status(401).json({ error: 'нужен Bearer API_TOKEN' });
    последнийВизитФермы = Date.now();
    res.json({ ok: true });
  });

  /** СТОРОНА БРАУЗЕРА: жива ли ферма. Дёшево и без ожидания. */
  app.get('/api/farm/status', requireAuth, (_req: Request, res: Response) => {
    res.json({
      наСвязи: фермаНаСвязи(),
      последнийВизит: последнийВизитФермы ? new Date(последнийВизитФермы).toISOString() : null,
      молчитСек: последнийВизитФермы ? Math.round((Date.now() - последнийВизитФермы) / 1000) : null,
      вОчереди: ОЧЕРЕДЬ.length,
      ждут: ОЖИДАЮТ.size,
    });
  });

  /**
   * СТОРОНА БРАУЗЕРА: вызвать ручку фермы как свою.
   *
   * Путь приходит параметром, а не куском адреса: так он не путается с
   * маршрутами самой панели и его легко проверить целиком. Разрешаем только
   * пути, начинающиеся с /api/ — мост существует для управления фермой, а не
   * для доступа к файлам на маке.
   */
  const вызватьФерму = async (req: Request, res: Response): Promise<void> => {
    const путь = String(req.query.path || '');
    if (!путь.startsWith('/api/')) {
      res.status(400).json({ error: 'путь должен начинаться с /api/' });
      return;
    }
    if (!фермаНаСвязи()) {
      // Отвечаем СРАЗУ. Морозить браузер на двадцать пять секунд, когда мы уже
      // знаем, что мака нет в сети, значит превращать понятную беду в непонятную.
      res.status(503).json({
        error: 'ферма офлайн',
        подробно: последнийВизитФермы
          ? `пульт телефонов молчит ${Math.round((Date.now() - последнийВизитФермы) / 1000)} с`
          : 'пульт телефонов ни разу не выходил на связь с момента запуска панели',
      });
      return;
    }

    const тело = req.method === 'GET' || req.method === 'HEAD'
      ? null
      : JSON.stringify(req.body ?? {});

    const вызов: Вызов = {
      id: новыйId(),
      method: req.method,
      path: путь,
      body: тело,
      создан: Date.now(),
      ответить: () => {},
    };

    const ответ = await new Promise<Ответ | null>((resolve) => {
      вызов.ответить = resolve;
      ОЖИДАЮТ.set(вызов.id, вызов);
      ОЧЕРЕДЬ.push(вызов);
      разбудитьФерму();
      setTimeout(() => {
        if (!ОЖИДАЮТ.has(вызов.id)) return;
        ОЖИДАЮТ.delete(вызов.id);
        resolve(null);
      }, ПОТОЛОК_ВЫЗОВА_МС);
    });

    if (!ответ) {
      res.status(504).json({ error: 'ферма не ответила вовремя', путь });
      return;
    }

    const буфер = Buffer.from(ответ.base64, 'base64');
    if (буфер.length > ПОТОЛОК_ТЕЛА) {
      res.status(502).json({ error: 'ответ фермы слишком велик' });
      return;
    }
    // Тип содержимого несём с той стороны как есть: через мост ходят и json, и
    // png с экранами плат, и подменять его здесь значит ломать картинки.
    const тип = ответ.headers?.['content-type'] || 'application/json; charset=utf-8';
    res.status(ответ.status).setHeader('Content-Type', тип).send(буфер);
  };

  app.get('/api/farm/call', requireAuth, вызватьФерму);
  app.post('/api/farm/call', requireAuth, вызватьФерму);
  app.delete('/api/farm/call', requireAuth, вызватьФерму);
}
