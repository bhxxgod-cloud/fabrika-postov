// Локальный генератор подписей для TikTok — без LLM. Короткая фраза из набора
// + 3–5 случайных хэштегов нейросетей. У каждого поста свой набор (по сиду),
// чтобы подписи не повторялись пачкой.

const PHRASES = [
  'Собрал нейросети, которые реально экономят время',
  'Одна подписка — и весь ИИ под рукой',
  'Тестирую нейронки для контента — вот что выжило',
  'Как я делаю контент за пару минут через нейросети',
  'Нейросети, которыми пользуюсь каждый день',
  'Это заменило мне половину рабочих задач',
  'Показываю, что умеют нейросети в 2026',
  'Топ нейронок для работы и учёбы',
  'Сделал за 5 минут то, на что уходил час',
  'ИИ-инструменты, о которых мало кто знает',
  'Мой стек нейросетей для соцсетей',
  'Пробую нейросети так, чтобы экономить время',
  'Нейросеть сделала это лучше меня',
  'Автоматизирую рутину нейросетями',
  'Как выжать максимум из нейросетей',
];

const HASHTAGS = [
  '#нейросети', '#нейросеть', '#нейронка', '#ии', '#ai', '#chatgpt', '#midjourney',
  '#искусственныйинтеллект', '#нейросетидляработы', '#контент', '#автоматизация',
  '#промпт', '#нейросетидляденег', '#технологии', '#продуктивность', '#нейроарт',
  '#заработоквинтернете', '#лайфхак', '#генерация', '#будущее',
];

function rng(seed: number) {
  let s = seed >>> 0;
  return () => {
    s = (s + 0x6d2b79f5) | 0;
    let t = Math.imul(s ^ (s >>> 15), 1 | s);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

function pick<T>(arr: T[], r: () => number): T {
  return arr[Math.floor(r() * arr.length)];
}

// Собрать подпись: 1 фраза + 3–5 случайных уникальных хэштегов.
export function tiktokCaption(seed: number): string {
  const r = rng(seed | 0);
  const phrase = pick(PHRASES, r);
  const count = 3 + Math.floor(r() * 3); // 3–5
  const tags: string[] = [];
  const pool = [...HASHTAGS];
  while (tags.length < count && pool.length) {
    const idx = Math.floor(r() * pool.length);
    tags.push(pool.splice(idx, 1)[0]);
  }
  return `${phrase} ${tags.join(' ')}`;
}
