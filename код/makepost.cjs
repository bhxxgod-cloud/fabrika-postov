// Заказ шаблона на фабрике по НАШЕМУ домашнему фото. Возвращает URL кадра-инфографики.
async function factoryGuide(page, homeFile, template) {
  const b64 = fs.readFileSync(homeFile).toString('base64');
  const refUrl = await page.evaluate(async ({ b64 }) => {
    const bin = Uint8Array.from(atob(b64), (c) => c.charCodeAt(0));
    const fd = new FormData();
    fd.append('file', new File([bin], 'home.jpg', { type: 'image/jpeg' }));
    const r = await fetch('/api/admin/promo/upload', { method: 'POST', body: fd });
    const j = await r.json().catch(() => ({}));
    if (!r.ok || !j.url) throw new Error('загрузка домашнего кадра не прошла');
    return j.url;
  }, { b64 });
  // Фабрика требует hookText 20–140 знаков, PATCH текстов больше не отдаёт — шлём запасной
  // хук из пула, иначе заказ гайда падает в HTTP 400 (ночь 06.08).
  const id = await page.evaluate(async ({ refUrl, template, fallbackHook }) => {
    const t = await (await fetch('/api/admin/promo/posts', {
      method: 'PATCH', headers: { 'content-type': 'application/json' },
      body: JSON.stringify({ templateId: template }),
    })).json().catch(() => ({}));
    let hookText = String(t.hookText || t.hook || '').trim();
    if (hookText.length < 20 || hookText.length > 140) hookText = fallbackHook;
    const r = await fetch('/api/admin/promo/posts', {
      method: 'POST', headers: { 'content-type': 'application/json' },
      body: JSON.stringify({ customPhotoUrl: refUrl, templateId: template,
        hookText, captionText: t.captionText || t.caption || '' }),
    });
    const j = await r.json().catch(() => ({}));
    return r.ok ? (j.id || j.postId || (j.post && j.post.id) || null)
                : { err: `HTTP ${r.status}: ${JSON.stringify(j).slice(0, 120)}` };
  }, { refUrl, template, fallbackHook: factoryHook(template) });
  if (!id || id.err) throw new Error(`фабрика не приняла заказ гайда — ${id && id.err ? id.err : 'ответ без id'}`);
  for (let i = 0; i < 90; i++) {
    await sleep(6000);
    const p = await page.evaluate(async (id) => {
      const r = await fetch('/api/admin/promo/posts');
      if (!r.ok) return null;
      const x = ((await r.json()).posts || []).find((z) => z.id === id);
      return x ? { st: x.status, urls: x.imageUrls || [] } : null;
    }, id);
    if (p && p.st === 'done' && p.urls.length >= 2) return p.urls[1];   // кадр 2 = инфографика
    if (p && p.st === 'error') throw new Error('гайд не отрендерился');
  }
  throw new Error('таймаут гайда');
}

