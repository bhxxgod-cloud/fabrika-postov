function heartsPresetPair(seed) {
  const N = HEARTS_PRESETS.length;
  if (process.env.HEARTS_PRESET) {
    const forced = HEARTS_PRESETS.findIndex((x) => x.id === process.env.HEARTS_PRESET);
    if (forced < 0) throw new Error(`нет пресета ${process.env.HEARTS_PRESET}; есть: ${HEARTS_PRESETS.map((x) => x.id).join(', ')}`);
    return [HEARTS_PRESETS[forced], HEARTS_PRESETS[(forced + 3) % N]];
  }
  const n = seedNum(seed);
  const last = Number(rotorRead().hearts);
  let a = n % N;
  if (a === last) a = (a + 1) % N;
  const b = (a + 1 + ((n >>> 8) % (N - 1))) % N;
  rotorWrite({ hearts: a });
  return [HEARTS_PRESETS[a], HEARTS_PRESETS[b]];
}
