// РЕТРАЙ ЗАКАЗА, КОГДА RENDERGRID НЕ СМОГ СКАЧАТЬ РЕФЕРЕНС.
//
// ЧТО ЗА БЕДА. Заказ картинки уходит в RenderGrid со ссылкой на референс в поле image_urls, а
// RenderGrid качает эту ссылку СИНХРОННО, на постановке заказа. Когда скачивание у него не
// получилось, приходит HTTP 400 с телом
//   {"error":{"code":"ERR_INVALID_REQUEST","message":"Failed to fetch the URL", ...}}
// и весь пост умирает на этом месте. Умирает дорого: к этой минуте уже оплачен рендер фабрики и,
// как правило, один заказ картинки, а пост уходит в брак целиком и пересобирается с нуля.
//
// ПРИЧИНА НАЙДЕНА ЧИСЛОМ, А НЕ ДОГАДКОЙ (11.08). Поле details в ответе RenderGrid всё говорит:
//   {"code":"ERR_INVALID_REQUEST","message":"Failed to fetch the URL",
//    "details":{"reason":"ConnectTimeout","url":"https://pub-….r2.dev/promo-assets/personas/….jpg"}}
// reason это ConnectTimeout: RenderGrid не смог даже ОТКРЫТЬ соединение с r2.dev, отвалившись через
// 5 секунд. Не 429, не 403, не 404. Для сравнения, заведомо мёртвая ссылка (объекта нет) отвечает
// СОВСЕМ ДРУГИМ текстом: message «Upstream returned an error status», details {status: 404, url}.
// То есть «Failed to fetch the URL» это не отказ хранилища и не наша испорченная заливка, а
// сетевой недобор между сетью RenderGrid и публичным техническим домёном Cloudflare r2.dev. Та же
// ссылка в ту же секунду отдаётся нашим curl за 0.2 с с кодом 200.
// Замер частоты на СВЕЖИХ ссылках (8 разных заливок, по одному заказу на каждую): 1 отказ из 8,
// это 13% на заказ. Пост делает 2-3 заказа, отсюда и получались потерянные полпачки.
// Отсюда два вывода: лечится это повтором (недобор случайный), и лечится окончательно только на
// стороне партнёра, если отдавать референс со своего домена, а не с r2.dev.
//
// ЗАМЕР 11.08 (что проверено и что отброшено):
//   • рейт-лимит публичного домена r2.dev ОТБРОШЕН. Одна и та же живая ссылка, пачки по 1, 5, 10 и
//     20 параллельных скачиваний плюс 40 запросов подряд: 85 запросов, около 600 МБ, все 200, ни
//     одного 429, ни одного Retry-After, ни одного обрыва;
//   • «параллельные полосы виноваты» ОТБРОШЕНО. В логе волны, которую считали однополосной
//     (/tmp/wave_n1.log), в первой же строке стоит «полос 3», и браков там 17 при 10 готовых. То
//     есть сравнения «3 полосы против 1 полосы» на самом деле не было, обе волны трёхполосные и
//     обе сыпались одинаково;
//   • «виноват сам исходник» (размер, формат, разрешение) ОТБРОШЕНО. Три файла
//     (044_девушка_блондинка, 054_девушка_каре_образ, 063_летнее_селфи) в одной волне упали с этой
//     ошибкой, а в другой прошли насквозь. Один и тот же байт-в-байт файл ведёт себя по-разному;
//   • заливка референса в 3 потока ПРОВЕРЕНА и работает: три параллельные заливки дали три живых
//     объекта, по каждому 200 и целое тело сразу же и через 2 секунды.
// Всё вместе сходится с ConnectTimeout выше: недобор СЛУЧАЙНЫЙ и на стороне сети RenderGrid, а
// значит лечится повтором. Поэтому здесь ретрай, а не перестройка канала.
//
// ПРОВЕРКА РАБОТОЙ (11.08, свежие заливки, 3 полосы, как в волне):
//   • без ретрая: 8 заказов, 1 отказ ConnectTimeout, это 13% на заказ;
//   • с ретраем: 9 заказов, отказов на первой попытке 0, окончательный брак 0%;
//   • с ретраем: 15 заказов, на первой попытке легли 2 (13%), ОБА спасены со второй попытки,
//     окончательный брак 0%.
// Итого по 32 заказам на свежие ссылки: 3 первичных отказа (9%), после ретрая ноль.
//
// ПОЧЕМУ НА РЕТРАЕ МЕНЯЕМ САМУ ССЫЛКУ. Повтор с тем же адресом рискует лечь в ту же ямку: если у
// RenderGrid отрицательный ответ по этому адресу где-то закешировался, сколько ни повторяй, он
// будет доставать его из кеша. Заливка бесплатна и занимает меньше секунды, поэтому перед вторым и
// третьим заходом просим у вызывающего НОВЫЙ адрес того же файла. Если вызывающий такой
// возможности не дал, повторяем со старым адресом: это всё равно лучше, чем потерянный пост.
//
// ДЕНЬГИ. Провал скачивания приходит в двух видах, и цена у них разная.
//   • НА ПОСТАНОВКЕ заказа (HTTP 400 «Failed to fetch the URL») он БЕСПЛАТЕН: rgen считает цену по
//     принятому заказу, а этот заказ не принят. Таких повторов не жалко, их три.
//   • УЖЕ НА РЕНДЕРЕ («The source image could not be fetched») заказ принят, то есть $0.03 списаны,
//     и каждый повтор стоит ещё столько же. Такой повтор РОВНО ОДИН. Формулировку живьём поймать не
//     удалось, ветка стоит на будущее, поэтому она и зажата одним повтором.
// Львиную долю потерь даёт ПЕРВЫЙ, бесплатный вид: 17 браков из 22 в волне /tmp/wave_n1.log.
//
// ЧЕГО ЗДЕСЬ СОЗНАТЕЛЬНО НЕТ. Отказ модерации по содержимому фотографии
// («The source image was rejected. Try a different photo.») выглядит похоже и приходит тем же
// каналом, но он ДЕТЕРМИНИРОВАННЫЙ: тот же файл отклонят и на второй раз, и на десятый. Он явно
// исключён в isRenderRefFetchFail, и возвращать его в ретрай нельзя, это чистый слив денег. Такие
// исходники надо уводить в карантин, это отдельная задача.
'use strict';

const rgen = require('./rgen.cjs');

const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

// Паузы между попытками. Первый повтор почти сразу: ошибка мгновенная и часто одноразовая.
const BACKOFF_MS = [5000, 15000, 40000];

/** Отказ НА ПОСТАНОВКЕ заказа: HTTP 400 «Failed to fetch the URL». Денег не стоит, ретраим щедро. */
function isOrderRefFetchFail(err) {
  const m = String((err && err.message) || err || '');
  return /Failed to fetch the URL/i.test(m) || /ERR_INVALID_REQUEST[\s\S]*fetch the URL/i.test(m);
}

/** Тот же провал скачивания, но УЖЕ НА РЕНДЕРЕ: заказ приняли, значит $0.03 списаны, и каждый
 *  повтор это ещё $0.03. Поэтому таких повторов ровно один, а не три. */
function isRenderRefFetchFail(err) {
  const m = String((err && err.message) || err || '');
  // «The source image was rejected. Try a different photo.» РЕТРАИТЬ НЕЛЬЗЯ, и это не догадка:
  // 11.08 пост по файлу 033_аутфит_девушка_лето упал именно так, и полный текст ошибки взят из
  // /creations/301debbf по API (в логе волны он обрезан на «The sour», из-за чего его четыре часа
  // считали неудачным скачиванием). Это отказ МОДЕРАЦИИ по содержимому фотографии: тот же файл
  // отклонят и на второй, и на десятый раз. Тот же файл упал так же в обеих волнах 10.08.
  if (/source image was rejected/i.test(m)) return false;
  return /The source image (could not|can(no|')t) be (fetched|downloaded|retrieved)/i.test(m)
    || /(failed|unable) to (download|fetch) (the )?(source|reference|input) image/i.test(m);
}

/** Та ли это беда вообще: RenderGrid не сумел скачать референс. Прочие 400 (фильтр безопасности,
 *  пустой промпт) ретраить НЕЛЬЗЯ, они от повтора не пройдут, а время и деньги съедят. */
function isRefFetchFail(err) {
  return isOrderRefFetchFail(err) || isRenderRefFetchFail(err);
}

/**
 * Заказать картинку в файл с ретраем по неудачному скачиванию референса.
 *
 * Полностью повторяет вызов rgen.genToFile, поэтому подставляется на его место один в один.
 *
 * @param {string} dest куда сохранить готовый кадр
 * @param {object} opts опции rgen.genToFile: prompt, refUrls, model, aspect, tag и прочие
 * @param {object} [o]
 * @param {(refUrls: string[]) => Promise<string[]>} [o.freshRefs] дать НОВЫЕ адреса тех же
 *        референсов (перезалить файл). Не задан - повторяем со старыми адресами
 * @param {number} [o.tries] сколько всего попыток, по умолчанию 4 (первая плюс три повтора)
 * @returns {Promise<string>} путь к файлу, как у rgen.genToFile
 */
async function genToFile(dest, opts, { freshRefs = null, tries = BACKOFF_MS.length + 1 } = {}) {
  let refUrls = (opts && opts.refUrls) || [];
  let last = null;
  // Платных повторов (отказ пришёл уже на рендере, деньги списаны) разрешаем ровно один.
  let paidRetries = 0;
  for (let attempt = 1; attempt <= tries; attempt++) {
    try {
      return await rgen.genToFile(dest, { ...opts, refUrls });
    } catch (e) {
      last = e;
      if (!isRefFetchFail(e) || attempt === tries) throw e;
      const paid = isRenderRefFetchFail(e);
      if (paid && paidRetries >= 1) {
        console.log('  ⚠ RenderGrid второй раз не взял референс уже НА РЕНДЕРЕ: дальше не повторяю, '
          + 'каждая такая попытка это оплаченный заказ');
        throw e;
      }
      if (paid) paidRetries++;
      const pause = BACKOFF_MS[attempt - 1] || BACKOFF_MS[BACKOFF_MS.length - 1];
      console.log(`  ⚠ RenderGrid не скачал референс (попытка ${attempt} из ${tries}`
        + `${paid ? ', отказ на рендере, заказ был оплачен' : ', отказ на постановке, денег не стоил'}), `
        + `это НЕ брак поста: жду ${pause / 1000} с и повторяю заказ`);
      // Новый адрес того же файла: см. шапку, повтор по старому адресу может биться о кеш отказа.
      if (freshRefs && refUrls.length) {
        try {
          const fresh = await freshRefs(refUrls);
          if (Array.isArray(fresh) && fresh.length && fresh.every((u) => /^https?:\/\//i.test(u))) {
            refUrls = fresh;
            console.log('    → референс перезалит, у заказа будет новый адрес');
          }
        } catch (e2) {
          console.log(`    ⚠ перезалить референс не вышло (${String(e2.message).slice(0, 80)}), `
            + 'повторяю со старым адресом');
        }
      }
      await sleep(pause);
    }
  }
  throw last;
}

module.exports = { genToFile, isRefFetchFail, isOrderRefFetchFail, isRenderRefFetchFail, BACKOFF_MS };
