// схожесть 0.223, 0.152, 0.132 при пороге 0.363, чужая внешность, чужая причёска, чужая
// одежда, чужой фон, то есть ровно результат чистого text-to-image. Четвёртый кадр той же
// персоны с тем же промптом, но с исходником, залитым через POST /uploads, дал 0.775 и
// глазами ту же девушку в той же майке на том же фоне, только в новой позе. Ссылка при этом
// живая: анонимный curl отдаёт HTTP 200 и image/jpeg. Значит дело не в файле и не в промпте,
// а в канале image_urls: провайдер его молча не тянет, а заказ всё равно считается принятым и
// оплаченным. ПОЭТОМУ ЗДЕСЬ ПО УМОЛЧАНИЮ ЗАЛИВКА: исходник качается к нам и уходит file_id.
// Флаг --url возвращает старое поведение, он оставлен только для перепроверки канала.
//
// ПОЧЕМУ ФОН ПРОСИМ ТОТ ЖЕ. Чем меньше мы просим поменять, тем меньше модель «переосмысляет»
// человека. Смена позы плюс смена локации плюс смена одежды разом это ровно тот заказ, на
// котором фабрика получала схожесть лица 0.08 вместо порога 0.363. Меняем ОДНО: позу и ракурс.
//
// ЧЕГО ТУТ НЕТ И ПОЧЕМУ. Поля strength (доля правки) в этом API не существует по факту: оно
// принимается, проверяется по диапазону и ни на что не влияет (проверено заказом 11.08).
// Доля изменения задаётся ТОЛЬКО словами промпта, поэтому вся сила здесь в тексте.
//
// ПРОВЕРКА РЕЗУЛЬТАТА ЧИСЛОМ. После скачивания сразу считается схожесть лица с исходником
// через facesim.py (эмбеддинги SFace, порог 0.363). Кадр ниже порога это ДРУГОЙ человек, и
// его нельзя пускать в пул, каким бы красивым он ни был.
//
// ЗАПУСК:
//   node facegen.cjs --n 3                       три персоны из базы, по одному кадру
//   node facegen.cjs --persona нов450             конкретная персона
//   node facegen.cjs --ref ./face.jpg --tag аня   свой локальный файл референсом
// Флаги: --out <папка>, --model nano-banana-pro|nano-banana-2, --res 1K|2K|4K, --pose <текст>,
//        --dry (собрать промпт и ничего не заказывать, денег ноль),
//        --url (слать референс ссылкой вместо заливки: НЕ РАБОТАЕТ, см. замер выше).
//
// ═══ ПОКОЛЕНИЯ: ГЛАВНАЯ ГРАБЛЯ ЭТОГО ФАЙЛА (13.08, разбор жалобы «стал здоровый нос») ═══
// Кадр отсюда становится ОБЛОЖКОЙ поста, и по нему же потом заказывают следующий пакет кадров.
// Если референсом взять не живое селфи, а предыдущую генерацию, дрейф лица складывается, и
// проверка ниже его НЕ ЛОВИТ: она сверяет кадр с ближайшим родителем, а не с живым человеком.
// Замер по персоне «розовая-полумесяц» (пакет МОДЕЛИ-НОВЫЕ-13-08 заказан с РОЗОВАЯ/pink1_новый.jpg):
//   живое селфи ↔ поколение 1 = 0.200 (уже чужой человек), поколение 1 ↔ поколение 2 = 0.751 («ок»),
//   живое селфи ↔ кадр 1 живого поста = 0.318 при пороге 0.363. Итог: 14 постов из 15 с чужим лицом.
// ПОЭТОМУ: если у персоны записан эталон (faceref.cjs), референсом берётся ОН, а не то, что
// передали; и результат сверяется С ЭТАЛОНОМ. Референс-генерацию без эталона берём только по
// явному FACE_CHAIN_OK=1: это осознанный шаг, а не случайность.
