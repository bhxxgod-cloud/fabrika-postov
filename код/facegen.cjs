//
// КАК РЕФЕРЕНС ДОХОДИТ ДО МОДЕЛИ (грабли, стоившие проекту двух недель, см. шапку rgen.cjs).
// Поля `images` в API НЕТ, оно молча выбрасывается, и кадр выходит с другим человеком при
// коде ответа 202. Остаются два пути: image_urls со ссылкой и image_file_ids после заливки
// в POST /uploads.
//
// ССЫЛКОЙ НЕ РАБОТАЕТ, ЗАЛИВКОЙ РАБОТАЕТ (замер 11.08, 4 заказа, $0.10). Три кадра, где
