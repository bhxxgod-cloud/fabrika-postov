// СВОЙ ПУЛ ИСХОДНИКОВ: НОВЫЙ КАДР С ТЕМ ЖЕ ЛИЦОМ ПО РЕФЕРЕНСУ.
//
// ЗАЧЕМ. Исходники красивых девушек мы до сих пор ИСКАЛИ на стороне: чужие фото из подборок,
// по одной штуке на пост. Пул конечен, повторы палятся, а лицо в посте держится только пока
// есть исходник. Здесь исходник берётся из НАШЕЙ базы (posts.meta->>'source_cover_url', это
// чистое фото без надписей, из которого делалась обложка) и по нему заказывается НОВЫЙ кадр
