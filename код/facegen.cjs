// ═══ БАЗА ════════════════════════════════════════════════════════════════════════════════════
async function изБазы({ persona, limit }) {
  const { Client } = require('pg');
  const c = new Client({
    connectionString: fs.readFileSync('/tmp/dburl.txt', 'utf8').trim(),
    ssl: { rejectUnauthorized: false },
  });
  await c.connect();
  try {
    const где = persona ? "AND meta->>'persona' = $1" : '';
    const r = await c.query(
      `SELECT DISTINCT ON (meta->>'persona') meta->>'persona' persona,
              meta->>'source_cover_url' src, created_at
         FROM posts
        WHERE meta->>'source_cover_url' IS NOT NULL ${где}
        ORDER BY meta->>'persona', created_at DESC`,
      persona ? [persona] : [],
    );
    // Свежие первыми: у поздних персон исходники отобраны придирчивее.
    r.rows.sort((a, b) => new Date(b.created_at) - new Date(a.created_at));
    return r.rows.slice(0, limit || r.rows.length);
  } finally { await c.end(); }
}

// ═══ МЕРА СХОЖЕСТИ ═══════════════════════════════════════════════════════════════════════════
// Возвращает косинус SFace между лицом исходника и лицом нового кадра, либо null если лица не
// нашлось. null это НЕ ноль: «лица не нашли» и «другой человек» разные беды.
function схожесть(a, b) {
  const r = spawnSync('python3', [path.join(HERE, 'facesim.py'), a, b], { encoding: 'utf8' });
  const line = String(r.stdout || '').trim().split('\n').filter((s) => s.startsWith('{')).pop();
  if (!line) return { v: null, why: String(r.stderr || 'facesim молчит').slice(-200) };
  const j = JSON.parse(line);
  const v = j.pairs && j.pairs['1-2'];
  return { v: (v === null || v === undefined) ? null : Number(v), порог: j.same_face || 0.363 };
}

function скачать(url, dest) {
  const r = spawnSync('curl', ['-sS', '--fail', '--max-time', '90', '-o', dest, url], { encoding: 'utf8' });
  if (r.status !== 0) throw new Error(`не скачался исходник ${url}: ${String(r.stderr || '').slice(0, 200)}`);
  return dest;
}

// ═══ ОДИН КАДР ═══════════════════════════════════════════════════════════════════════════════
/**
 * @param {object} o
 * @param {string} o.tag имя персоны, оно же имя файла
 * @param {string} [o.url] публичная ссылка на исходник (уйдёт в image_urls)
 * @param {string} [o.file] локальный файл исходника (уйдёт заливкой в image_file_ids)
 * @returns {Promise<{ok:boolean, src:string, out:string, sim:number|null}>}
 */
async function кадр({ tag, url, file, out = OUT_DEFAULT, model = 'nano-banana-pro',
  resolution = '1K', поза, dry = false, persona = null }) {
  if (!url && !file) throw new Error(`${tag}: нет ни ссылки, ни файла исходника`);
  fs.mkdirSync(out, { recursive: true });
  const src = path.join(out, `${tag}_исходник.jpg`);

  // ЭТАЛОН БЬЁТ ПЕРЕДАННЫЙ РЕФЕРЕНС. Имя персоны берём из явного persona, иначе из tag: в пакетах
  // tag это «розовая_25», то есть персона плюс номер кадра, поэтому номер отрезаем.
  const кто = persona || String(tag).replace(/_\d+р?$/, '');
  const э = faceref.эталон(кто);
  if (э && !э.пропал) {
    if (э.подменён) throw new Error(`${tag}: файл эталона подменён (sha не сходится): ${э.файл}`);
    fs.copyFileSync(э.файл, src);
    console.log(`  референс взят из эталона персоны «${кто}»: ${path.basename(э.файл)}`);
    url = null; file = э.файл;
  } else if (url) { if (!fs.existsSync(src)) скачать(url, src); } else { fs.copyFileSync(file, src); }

  // БЕЗ ЭТАЛОНА НЕ ДАЁМ РИСОВАТЬ ПО ГЕНЕРАЦИИ. Метка .ген.json пишется рядом с каждым нашим
  // кадром (ниже), поэтому своё поколение мы узнаём точно; для файлов, оставшихся с прошлых
  // прогонов, работает второе правило — имя вида «..._новый.jpg».
  if (!э || э.пропал) {
    const ref = file || src;
    const это_генерация = fs.existsSync(`${ref}.ген.json`) || /_новый\.(jpe?g|png)$/i.test(path.basename(ref));
    if (это_генерация && process.env.FACE_CHAIN_OK !== '1') {
      throw new Error(`${tag}: референс это НАША ЖЕ ГЕНЕРАЦИЯ (${path.basename(ref)}), а эталон персоны «${кто}» не записан. `
        + 'Так копится дрейф лица: замер 13.08 — два шага увели персону с 0.200 до 0.318 при пороге 0.363. '
        + `Запиши живое селфи: node faceref.cjs --set "${кто}" <файл>. Осознанный обход: FACE_CHAIN_OK=1`);
    }
  }

  // Поза по хэшу имени, чтобы у разных персон получались разные кадры, а повтор для той же
  // персоны был воспроизводим.
  const idx = [...tag].reduce((a, ch) => (a * 31 + ch.codePointAt(0)) % 9973, 7) % ПОЗЫ.length;
  const p = промпт({ поза: поза || ПОЗЫ[idx] });
  if (dry) { console.log(`\n[${tag}] промпт (${p.length} знаков):\n${p}\n`); return { ok: null, src, out: null, sim: null }; }

  const dest = path.join(out, `${tag}_новый.jpg`);
  console.log(`\n[${tag}] заказываю кадр, референс ${url ? 'ссылкой' : 'заливкой файла'}`);
  // ПОВТОР ПРИ 503 ОТ ПРОВАЙДЕРА. Он ловится регулярно и денег НЕ стоит: заказ не принят,
  // списания нет. Без повтора персона просто выпадает из пачки на ровном месте.
  for (let попытка = 1; ; попытка++) {
    try {
      await rgen.genToFile(dest, {
        prompt: p, model, aspect: process.env.FACE_ASPECT || '9:16', resolution, tag,
        ...(url ? { refUrls: [url] } : { refFiles: [src] }),
      });
      break;
    } catch (e) {
      if (попытка >= 4 || !/HTTP 503|provider_unavailable/.test(e.message)) throw e;
      console.log(`  провайдер занят (503), повтор ${попытка} через 20 с, денег не потрачено`);
      await new Promise((r) => setTimeout(r, 20000));
    }
  }

  const s = схожесть(src, dest);
  const порог = s.порог || 0.363;
  const вердикт = s.v === null ? 'лица не нашли, смотреть глазами'
    : s.v >= порог ? 'ТО ЖЕ ЛИЦО' : 'ДРУГОЙ ЧЕЛОВЕК, в пул нельзя';
  console.log(`  схожесть лица ${s.v === null ? 'null' : s.v.toFixed(3)} при пороге ${порог}`
    + `${э && !э.пропал ? ' (с ЭТАЛОНОМ персоны)' : ''}: ${вердикт}`);

  // МЕТКА ПОКОЛЕНИЯ РЯДОМ С КАДРОМ. Через неделю по файлу «розовая_25_новый.jpg» уже не сказать,
  // с чего он нарисован, а от этого зависит, можно ли брать его референсом (см. блок про поколения
  // в шапке). Метка отвечает на это без базы и без догадок.
  try {
    fs.writeFileSync(`${dest}.ген.json`, JSON.stringify({
      персона: кто, из: path.resolve(э && !э.пропал ? э.файл : (file || src)),
      эталон: !!(э && !э.пропал), схожесть: s.v, порог, модель: model,
      когда: new Date().toISOString().slice(0, 19).replace('T', ' '),
    }, null, 1));
  } catch { /* метка это удобство, из-за неё кадр терять нельзя */ }

  // БРАК УЕЗЖАЕТ ИЗ ПУЛА, А НЕ ЛЕЖИТ В НЁМ (13.08). Раньше вердикт «ДРУГОЙ ЧЕЛОВЕК» только
  // печатался в консоль, а файл оставался в папке пакета рядом с годными — и сборщик постов брал
  // его как обычную обложку. В пакете 13.08 так лежало 5 таких кадров (бмв-очки 0.226/0.300/0.347/
  // 0.348, загорелая 0.166); в посты они не успели попасть только по везению. Ничего не удаляем:
  // кадр уезжает в подпапку БРАК с причиной рядом.
  if (s.v !== null && s.v < порог) {
    try {
      const брак = path.join(out, 'БРАК');
      fs.mkdirSync(брак, { recursive: true });
      const куда = path.join(брак, path.basename(dest));
      fs.renameSync(dest, куда);
      if (fs.existsSync(`${dest}.ген.json`)) fs.renameSync(`${dest}.ген.json`, `${куда}.ген.json`);
      fs.appendFileSync(path.join(брак, 'причины.txt'),
        `${new Date().toISOString().slice(0, 19)} ${path.basename(dest)} схожесть ${s.v} при пороге ${порог}, эталон ${э && !э.пропал ? э.файл : 'не записан'}\n`);
      console.log(`  → кадр уведён в ${path.basename(брак)}/${path.basename(dest)}, в пул он не попадёт`);
      return { ok: false, src, out: куда, sim: s.v, порог, брак: true };
    } catch (e) { console.log(`  ⚠ кадр забракован, но увести его не вышло (${e.message}), НЕ БЕРИ его в посты`); }
  }
  return { ok: s.v !== null && s.v >= порог, src, out: dest, sim: s.v, порог };
}

// ═══ ЗАПУСК ══════════════════════════════════════════════════════════════════════════════════
async function main() {
  const a = process.argv.slice(2);
  const флаг = (n, d) => { const i = a.indexOf(`--${n}`); return i >= 0 ? a[i + 1] : d; };
  const есть = (n) => a.includes(`--${n}`);
  const out = флаг('out', OUT_DEFAULT);
  const model = флаг('model', 'nano-banana-pro');
  const resolution = флаг('res', '1K');
  const dry = есть('dry');
  const поза = флаг('pose', null);

  let задачи = [];
  const ref = флаг('ref', null);
  if (ref) {
    задачи = [{ tag: флаг('tag', path.basename(ref).replace(/\.\w+$/, '')), file: ref }];
  } else {
    const persona = флаг('persona', null);
    const n = Number(флаг('n', persona ? 1 : 3));
    const строки = await изБазы({ persona, limit: n });
    if (!строки.length) throw new Error('в базе не нашлось исходников (meta->>source_cover_url)');
    задачи = строки.map((r) => ({ tag: r.persona, url: r.src }));
  }
  // ЗАЛИВКА ПО УМОЛЧАНИЮ, ССЫЛКА ТОЛЬКО ПО ЯВНОМУ --url (см. замер в шапке файла).
  if (!есть('url')) {
    for (const з of задачи) {
      if (!з.url) continue;
      const f = path.join(out, `${з.tag}_исходник.jpg`);
      fs.mkdirSync(out, { recursive: true });
      if (!fs.existsSync(f)) скачать(з.url, f);
      з.file = f; delete з.url;
    }
  }

  const итог = [];
  for (const з of задачи) {
    try { итог.push(await кадр({ ...з, out, model, resolution, поза, dry })); } catch (e) {
      console.error(`  ✗ ${з.tag}: ${e.message}`);
      итог.push({ tag: з.tag, ok: false, err: e.message });
    }
  }
  console.log('\n═══ ИТОГ ═══');
  for (const [i, r] of итог.entries()) {
    console.log(`${задачи[i].tag}: ${r.err ? `ошибка ${r.err}` : r.ok === null ? 'сухой прогон'
      : `${r.ok ? 'лицо сохранено' : 'лицо потеряно'} (${r.sim === null ? 'null' : r.sim.toFixed(3)})`}`);
  }
  // Деньги считаем сами: rgen.spentSoFar округляет до центов, а кадр в 1K стоит $0.025, то есть
  // округление съедает половину цены и в отчёт уходит враньё.
  const д = rgen.spentSoFar();
  const цена = (rgen.PRICE_RES[model] || {})[String(resolution).toUpperCase()] || 0;
  console.log(`заказов ${д.orders}, потрачено $${(д.orders * цена).toFixed(3)}`);
}

if (require.main === module) main().catch((e) => { console.error('ПАДЕНИЕ:', e.message); process.exit(1); });
module.exports = { кадр, промпт, изБазы, схожесть, ПОЗЫ };
