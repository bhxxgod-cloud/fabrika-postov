'use strict';
// РАСКЛАДКА РАСПИСАНИЯ ПОД ЗАЗОР (26.08.2026). Готовит возврат приостановленных каналов.
//
// ЗАЧЕМ. Раздача часов по кругу на десяти каналах даёт минимальный разрыв в одну минуту: десять
// «независимых» каналов публикуют почти одновременно, а это ровно та подпись сети, за которую нас
// накрыло 26.08. Подбирать вручную бессмысленно, тут нужна раскладка.
//
// ПОЧЕМУ МИНУТА ТЕПЕРЬ ПОЛЕ, А НЕ ХЕШ. Пока каналов было пять, минуту хватало брать хешем от
// имени. На десяти хеш выдал почти одинаковые минуты (05, 05, 08, 12, 13, 38, 39, 46, 49), и
// развести публикации стало нельзя в принципе: свобода в часах шагом 60 минут этого не вытянет.
// Поэтому раскладываем ОБЕ координаты: и час, и минуту.
//
// КАК. Идеальная сетка: 1440 минут делим на число публикаций. Каналы получают часы равномерным
// шагом 24/НА_КАНАЛ (пять роликов = раз в ~5 часов, а не пять подряд), точка старта у каждого
// своя. Минута канала подбирается так, чтобы его публикации легли ближе всего к своим точкам
// сетки. Затем проход улучшения до устойчивости.
//
// Запуск: node разложить-часы.cjs [постов_на_канал] [--записать] [--только-живые]
const { Client } = require('pg');
const DBURL = require('./dburl.cjs')();
const НА_КАНАЛ = Number(process.argv[2] || 5);
const ТОЛЬКО_ЖИВЫЕ = process.argv.includes('--только-живые');

(async () => {
  const c = new Client({ connectionString: DBURL, ssl: { rejectUnauthorized: false } });
  await c.connect();
  const { rows: каналы } = await c.query(
    `SELECT slug, title FROM yt_channels WHERE platform='youtube' AND title IS NOT NULL ${ТОЛЬКО_ЖИВЫЕ ? 'AND enabled' : ''} ORDER BY id`);
  await c.end();

  const N = каналы.length * НА_КАНАЛ;
  const шаг = 1440 / N;
  const шагЧасов = 24 / НА_КАНАЛ;
  const план = {};              // slug -> {часы, минута}
  const точки = [];

  const общийМинимум = (пп) => {
    const t = пп.map((p) => p.t).sort((a, b) => a - b);
    let m = Infinity;
    for (let i = 1; i < t.length; i++) m = Math.min(m, t[i] - t[i - 1]);
    return Math.min(m, (1440 - t[t.length - 1]) + t[0]);
  };
  // вариант канала: старт часов + минута
  // МИНУТЫ КАНАЛОВ ОБЯЗАНЫ РАЗЛИЧАТЬСЯ. Оптимизатор, которому важен только зазор, находит
  // РЕГУЛЯРНУЮ решётку: четыре канала на :03, четыре на :33. Зазор при этом идеальный, а
  // подпись новая и не лучше прежней, живые каналы не публикуют одной минутой. Поэтому минута
  // соседа занята: держим не меньше трёх минут разницы между минутами разных каналов.
  function лучшийВариант(ch, чужие) {
    const занятыеМинуты = [...new Set(чужие.map((p) => p.м))];
    let луч = null;
    for (let старт = 0; старт < 24; старт++) {
      const часы = Array.from({ length: НА_КАНАЛ }, (_, k) => Math.round(старт + k * шагЧасов) % 24);
      if (new Set(часы).size !== часы.length) continue;
      for (let м = 3; м < 58; м += 1) {
        if (занятыеМинуты.some((z) => Math.abs(z - м) < 3)) continue;
        const свои = часы.map((h) => ({ slug: ch.slug, канал: ch.title, h, м, t: h * 60 + м }));
        const мини = чужие.length ? общийМинимум([...чужие, ...свои]) : общийМинимум(свои);
        // ПОКРЫТИЕ СУТОК ВТОРОЙ МЕТРИКОЙ. Оптимизатор, которому важен только зазор, сажает каналы
        // на одни и те же наборы часов: на пяти каналах вышло всего три набора, девять пустых
        // часов и структура «три часа подряд, потом пауза». Зазор при этом безупречный. Поэтому
        // при равном зазоре предпочитаем вариант, занимающий ещё не занятые часы.
        const занятыеЧасы = new Set(чужие.map((p) => p.h));
        const новых = часы.filter((h) => !занятыеЧасы.has(h)).length;
        if (!луч || мини > луч.мини || (мини === луч.мини && новых > луч.новых)) луч = { мини, часы, м, свои, новых };
      }
    }
    return луч;
  }

  for (const ch of каналы) {
    const луч = лучшийВариант(ch, точки);
    план[ch.slug] = { часы: луч.часы.slice().sort((a, b) => a - b), минута: луч.м };
    точки.push(...луч.свои);
  }
  // проход улучшения до устойчивости: первым каналам досталось свободно, последним тесно
  for (let круг = 0; круг < 8; круг++) {
    let менялось = false;
    for (const ch of каналы) {
      const чужие = точки.filter((p) => p.slug !== ch.slug);
      const было = общийМинимум(точки);
      const луч = лучшийВариант(ch, чужие);
      if (луч && луч.мини > было) {
        план[ch.slug] = { часы: луч.часы.slice().sort((a, b) => a - b), минута: луч.м };
        точки.length = 0; точки.push(...чужие, ...луч.свои);
        менялось = true;
      }
    }
    if (!менялось) break;
  }

  точки.sort((a, b) => a.t - b.t);
  const разрывы = точки.slice(1).map((p, i) => p.t - точки[i].t);
  const кольцо = (1440 - точки[точки.length - 1].t) + точки[0].t;
  console.log('каналов: ' + каналы.length + ' по ' + НА_КАНАЛ + ' в сутки = ' + точки.length + ' публикаций (идеальный шаг ' + шаг.toFixed(1) + ' мин)');
  console.log('минимальный разрыв: ' + Math.min(...разрывы, кольцо) + ' мин, средний: ' + Math.round(разрывы.reduce((a, b) => a + b, 0) / разрывы.length) + ' мин');
  console.log('пар ближе 15 минут: ' + (разрывы.filter((d) => d < 15).length + (кольцо < 15 ? 1 : 0)) + '\n');
  for (const ch of каналы) {
    const p = план[ch.slug];
    console.log('  ' + ch.title.slice(0, 30).padEnd(32) + 'минута :' + String(p.минута).padStart(2, '0') + '  часы ' + p.часы.join(','));
  }
  if (process.argv.includes('--записать')) {
    const c2 = new Client({ connectionString: DBURL, ssl: { rejectUnauthorized: false } });
    await c2.connect();
    for (const ch of каналы) await c2.query('UPDATE yt_channels SET post_hours=$2, post_minute=$3, updated_at=now() WHERE slug=$1',
      [ch.slug, план[ch.slug].часы.join(','), план[ch.slug].минута]);
    await c2.end();
    console.log('\nзаписано в базу');
  } else console.log('\nприменить: node разложить-часы.cjs ' + НА_КАНАЛ + ' --записать');
})().catch((e) => { console.error('ERR', e.message); process.exit(1); });
