// branchwatch.cjs — СТОРОЖ СОСЕДНИХ ВЕТОК ЧАТА (14.08).
//
// ЗАЧЕМ. Приказ владельца: «поставь туда сторожа, проверяй что он делает, и когда он что-то
// запилит — чтобы мы сразу подхватили». Ветки (маркетолог, магос) работают параллельно с главным
// чатом, и их выводы доходили до нас только когда владелец сам про них вспоминал. Между «ветка
// придумала» и «главный чат узнал» проходили часы, а за эти часы главный чат успевал собрать
// пачку по старым правилам — ровно то, что сейчас и случилось: посты пришлось останавливать,
// потому что маркетолог не доработал.
//
// ЧТО ДЕЛАЕТ. Смотрит на файл переписки ветки. Каждый её ОТВЕТ (текстовый блок assistant) — это
// готовая мысль, и как только появляется новый, сторож шлёт его в группу владельца с пометкой,
// от какой ветки. Ничего не решает и ни на что не отвечает: разбирать выводы ветки — работа
// главного чата, а не сторожа.
//
// ПОЧЕМУ ЧИТАЕМ ФАЙЛ, А НЕ СПРАШИВАЕМ ВЕТКУ. Спросить можно только тогда, когда сам вспомнил —
// то есть ровно та беда, которую чиним. Файл переписки пишется веткой сам, без нашего участия,
// и по нему видно появление ответа в ту же минуту.
//
// ЧЕГО СТОРОЖ НЕ ВИДИТ, И ЭТО ВАЖНО ЗНАТЬ (14.08, разбор через час после запуска). Ветка умеет
// написать ГЛАВНОМУ ЧАТУ НАПРЯМУЮ, минуя свою переписку. Так пришёл весь список маркетолога — а
// сторож его не увидел и владельцу ничего не ушло. Тот справедливо решил, что маркетолог молчит,
// хотя маркетолог ответил, и ответ лежал у главного чата. Вывод: сторож закрывает только один из
// двух путей. Прямое сообщение обязан пересылать владельцу САМ главный чат, сразу как получил, —
// это не то, что можно доделать потом, потому что «потом» и означает, что владелец не в курсе.
//
// СЧЁТЧИК ПРОЧИТАННОГО НА ДИСКЕ. Перезапуск сторожа не должен приводить ни к потере ответов, ни
// к их повтору в группе — та же причина, по которой смещение хранится на диске у сторожа
// телеграма (tgwatch_in.cjs).
//
// Запуск: node branchwatch.cjs [пауза_сек=60]
'use strict';
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');

const ПАУЗА = (Number(process.argv[2]) || 60) * 1000;
const ПАПКА = path.join(os.homedir(), '.neironka');
const СЧЁТ = path.join(ПАПКА, 'branchwatch_прочитано.json');
const КОРЕНЬ = path.join(os.homedir(), '.claude', 'projects');

// За кем следим: имя ветки → кусок пути её рабочей копии.
//
// СПИСОК УСТАРЕВАЕТ САМ, И ЭТО УЖЕ СТОИЛО НАМ ВЕЧЕРА. 21.08 владелец спросил, почему
// главный чат по ферме встал, а я не заметил. Ответ был некрасивый: сторож следил за тремя
// СТАРЫМИ ветками и про ферму с ютубом не знал вовсе. Ветки переезжают в новые рабочие копии,
// а список остаётся прежним — и сторож честно сторожит пустоту.
//
// Правило: завёл новую рабочую ветку — впиши её СЮДА, иначе её молчание никто не увидит.
const ВЕТКИ = {
  'Ферма': 'loving-dhawan-5db7e9',
  'Генерка': 'affectionate-chaplygin-0b6ffc',
  'Магос': 'nostalgic-wescoff-606ff5',
  'Ютуб': 'untitled-folder',
};

// МОЛЧАНИЕ — ТОЖЕ СОБЫТИЕ.
//
// Сторож умел пересылать только то, что ветка СКАЗАЛА. А встают они молча: процесс жив,
// последняя строка в переписке час назад, и снаружи это неотличимо от «работает и думает».
// Владелец увидел остановку раньше меня — потому что смотрел на экран, а я на журнал.
//
// Теперь считаем и тишину: ветка молчит дольше порога — один раз кричим в телеграм и ждём,
// пока она заговорит. Повторно не долбим: молчащая ветка это повод посмотреть, а не поток тревог.
const ТИШИНА_МС = 25 * 60 * 1000;
const кричали = new Set();

const читать = (f, по) => { try { return fs.readFileSync(f, 'utf8'); } catch { return по; } };
const TOKEN = (process.env.TELEGRAM_BOT_TOKEN || читать(path.join(os.homedir(), '.neironka', 'tgtok'), '') || читать('/tmp/.tgtok', '')).trim();
const CHAT = (process.env.TELEGRAM_CHAT_ID || читать(path.join(os.homedir(), '.neironka', 'tgchat'), '') || читать('/tmp/.tgchat', '')).trim();
if (!TOKEN || !CHAT) { console.log('нет токена или чата'); process.exit(1); }

// ОДИН СТОРОЖ, А НЕ ДВА (15.08). Перезапуск через nohup дважды поднял два процесса, и каждый
// писал в ленту свою копию каждого ответа — счётчик прочитанного у них общий, но между чтением и
// записью оба успевают увидеть одно и то же. Дубли в ленте читаются как «ветка повторяется».
// Та же защита стоит у сторожа телеграма, и по той же причине.
try {
  const свои = require('node:child_process').execFileSync('pgrep', ['-f', 'branchwatch\\.cjs'], { encoding: 'utf8' })
    .split('\n').map((s) => s.trim()).filter(Boolean).filter((p) => Number(p) !== process.pid);
  if (свои.length) { console.log(`сторож веток уже работает (pid ${свои[0]})`); process.exit(0); }
} catch { /* никого нет — это норма */ }

fs.mkdirSync(ПАПКА, { recursive: true });
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

// Файл переписки ветки: самый свежий .jsonl в её каталоге проекта.
function файлВетки(кусок) {
  let лучший = null;
  for (const d of fs.readdirSync(КОРЕНЬ)) {
    if (!d.includes(кусок)) continue;
    const пд = path.join(КОРЕНЬ, d);
    for (const f of fs.readdirSync(пд)) {
      if (!f.endsWith('.jsonl')) continue;
      const п = path.join(пд, f);
      const t = fs.statSync(п).mtimeMs;
      if (!лучший || t > лучший.t) лучший = { п, t };
    }
  }
  return лучший && лучший.п;
}

// Ответы ветки по порядку. Берём ТОЛЬКО текстовые блоки: вызовы инструментов это её кухня,
// владельцу нужен вывод, а не каждый шаг.
function ответы(файл) {
  const из = [];
  for (const s of читать(файл, '').split('\n')) {
    if (!s.trim()) continue;
    let j; try { j = JSON.parse(s); } catch { continue; }
    if (j.type !== 'assistant') continue;
    const c = j.message && j.message.content;
    if (!Array.isArray(c)) continue;
    for (const b of c) {
      if (b && b.type === 'text' && String(b.text || '').trim()) из.push(String(b.text).trim());
    }
  }
  return из;
}

// ПИШЕМ В ФАЙЛ, А НЕ В ТЕЛЕГРАМ (15.08, прямое требование владельца: «не давай апдейты по чату
// маркетолога — пиши в память себе, но мне не спамь»).
//
// Сторож заводился, чтобы Я не пропускал ветки, и это он делает. Но пересылал он их владельцу — а
// ветки переписываются десятками сообщений в час, и поток их рассуждений хоронил то немногое, где
// нужен он сам. Теперь итоги копятся здесь, а владельцу пишет главный чат и только когда есть
// решение или готовый результат.
const ЛЕНТА = path.join(ПАПКА, 'ветки_лента.txt');
async function послать(текст) {
  fs.appendFileSync(ЛЕНТА, `\n${'─'.repeat(70)}\n${new Date().toISOString().slice(11, 19)}  ${текст}\n`);
  return true;
}

async function заход() {
  let прочитано = {};
  try { прочитано = JSON.parse(читать(СЧЁТ, '{}')); } catch { прочитано = {}; }
  for (const [имя, кусок] of Object.entries(ВЕТКИ)) {
    const файл = файлВетки(кусок);
    if (!файл) continue;
    const все = ответы(файл);
    const было = Number(прочитано[имя] || 0);
    // ПЕРВЫЙ ЗАПУСК НЕ ВЫВАЛИВАЕТ ВСЮ ИСТОРИЮ: она уже прочитана владельцем, и сотня старых
    // сообщений в группе похоронит то новое, ради чего сторож и ставился.
    if (!(имя in прочитано)) { прочитано[имя] = все.length; continue; }
    for (const текст of все.slice(было)) {
      await послать(`🔔 ВЕТКА «${имя}»:\n\n${текст}`);
      console.log(`  → ${имя}: ${текст.slice(0, 70).replace(/\s+/g, ' ')}…`);
      await sleep(1200);
    }
    прочитано[имя] = все.length;

    // ТИШИНА. Смотрим, когда ветка в последний раз что-то СКАЗАЛА, а не когда файл трогали:
    // файл шевелится и от вызовов инструментов, то есть «ветка думает» и «ветка встала»
    // по времени файла неразличимы. Берём время последней строки ассистента.
    try {
      const мс = Date.now() - fs.statSync(файл).mtimeMs;
      if (мс > ТИШИНА_МС) {
        if (!кричали.has(имя)) {
          кричали.add(имя);
          const мин = Math.round(мс / 60000);
          await послать(`🔕 ВЕТКА «${имя}» МОЛЧИТ ${мин} мин.\n\n`
            + 'Это не обязательно поломка — но и не обязательно работа. Проверь, не встала ли она '
            + 'на вопросе, на подтверждении или на упавшем шаге. Молча встающая ветка снаружи '
            + 'неотличима от думающей, поэтому сторож говорит об этом один раз и больше не долбит.');
          console.log(`  🔕 ${имя} молчит ${мин} мин`);
          await sleep(1200);
        }
      } else {
        кричали.delete(имя);
      }
    } catch { /* нет файла — тишину не считаем */ }
  }
  fs.writeFileSync(СЧЁТ, JSON.stringify(прочитано, null, 1));
}

(async () => {
  console.log(`сторож веток пошёл: ${Object.keys(ВЕТКИ).join(', ')}, заход раз в ${ПАУЗА / 1000} с`);
  for (;;) {
    await заход().catch((e) => console.log('заход упал:', String(e.message).slice(0, 90)));
    await sleep(ПАУЗА);
  }
})();
