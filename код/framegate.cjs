//   3. ВЕРТИКАЛЬНОЕ СЖАТИЕ. Прямо измерить растянутость лица нельзя, зато можно измерить то, из
//      чего она получалась: отношение сторон ИСХОДНИКА к 4:5. Если исходник ушёл в кадр не обрезкой,
//      а подгонкой по высоте, лицо тянется. Поэтому кадр обязан быть либо обрезкой, либо вписыванием
