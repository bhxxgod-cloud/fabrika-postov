//   4. КАДР 4 НЕ КРОП КАДРА 3. Перцептивный отпечаток: у кропа того же изображения отпечаток близкий,
//      у отдельной генерации далёкий. Плюс требуем от сборщика метку «финал догенерирован»: одно
//      число может обмануть, два независимых признака сразу — уже нет.
//   5. ТЕЛЕФОН. Мокап локскрина рисуем МЫ САМИ (slidekit.lockMock), поэтому телефон в кадре это не
//      случайность, а вызов функции. Гейт проверяет согласие сборщика с контрактом: если шаблону
//      телефон не разрешён (templates.phoneOk), а сборщик сообщает про мокап, это брак сборки.
//   6. ЦВЕТ ВОЛОС. Для карточных шаблонов образ обязан заметно менять цвет волос относительно
//      обложки. Мерим средний цвет двух боковых зон верхней половины кадра (там волосы) и требуем
//      расстояния в цвете. Число грубое, поэтому порог низкий: гейт ловит «цвет вообще не тронули»,
//      а тонкую разницу по-прежнему смотрят глаза на контактном листе.
//   7. ТЕКСТЫ. Хук и подпись обязаны быть разными (правило начальника), хештеги обязательны, мамы
//      в хуке нет (аудитория подростки), ИИ-теги в подписи запрещены.
//
// Тип шаблона тут НЕ определяется регэкспами: спрашиваем templates.cjs, он единый источник правды.
'use strict';
const fs = require('node:fs');
const { spawnSync } = require('node:child_process');
const FF = require('ffmpeg-static');
const TPL = require('./templates.cjs');

const W = 1080, H = 1350;

/** Размер кадра. Читаем у ffmpeg, а не доверяем имени файла. */
function size(file) {
  const r = spawnSync(FF, ['-hide_banner', '-i', file], { encoding: 'utf8' });
  const m = String(r.stderr || '').match(/,\s(\d{2,5})x(\d{2,5})[\s,]/);
  return m ? { w: +m[1], h: +m[2] } : { w: 0, h: 0 };
}

/** Средний цвет зоны кадра (crop в синтаксисе ffmpeg). Возвращает [r,g,b] 0-255. */
function avg(file, crop) {
  const r = spawnSync(FF, ['-hide_banner', '-i', file, '-vf', `${crop},scale=1:1`,
    '-frames:v', '1', '-f', 'rawvideo', '-pix_fmt', 'rgb24', 'pipe:1'], { maxBuffer: 1 << 22 });
  const b = r.stdout;
  return b && b.length >= 3 ? [b[0], b[1], b[2]] : null;
}

/** Однотонность зоны: разброс яркости. У поля разброс почти нулевой, у картинки большой. */
function spread(file, crop) {
  const r = spawnSync(FF, ['-hide_banner', '-i', file, '-vf', `${crop},format=yuv420p,signalstats,metadata=print`,
    '-frames:v', '1', '-f', 'null', '-'], { encoding: 'utf8' });
  const t = String(r.stderr || '');
  const num = (re) => { const m = t.match(re); return m ? parseFloat(m[1]) : null; };
  const mn = num(/YMIN:\s*([\d.]+)/), mx = num(/YMAX:\s*([\d.]+)/), av = num(/YAVG:\s*([\d.]+)/);
  return { min: mn, max: mx, avg: av, range: mn === null || mx === null ? null : mx - mn };
}

const dist = (a, b) => (a && b ? Math.round(Math.hypot(a[0] - b[0], a[1] - b[1], a[2] - b[2])) : 0);
const light = (c) => (c ? (c[0] + c[1] + c[2]) / 3 : 0);
const gray = (c) => (c ? Math.max(c[0], c[1], c[2]) - Math.min(c[0], c[1], c[2]) : 99);

/**
 * Белые поля по краям. Полосой считаем 2 процента ширины или высоты: тоньше бывает антиалиасинг
 * настоящей картинки, толще уже съедает содержимое.
 * @returns {{sides:string[], white:boolean, pad:boolean}} какие края залиты и белые ли они
 */
function bars(file) {
  const strips = {
    слева: [`crop=iw*0.02:ih:0:0`, `crop=iw*0.06:ih:iw*0.05:0`],
    справа: [`crop=iw*0.02:ih:iw*0.98:0`, `crop=iw*0.06:ih:iw*0.89:0`],
    сверху: [`crop=iw:ih*0.02:0:0`, `crop=iw:ih*0.06:0:ih*0.05`],
    снизу: [`crop=iw:ih*0.02:0:ih*0.98`, `crop=iw:ih*0.06:0:ih*0.89`],
  };
  const sides = [];
  let white = false;
  for (const [name, [edge, inner]] of Object.entries(strips)) {
    const s = spread(file, edge);
    const ce = avg(file, edge), ci = avg(file, inner);
    // Поле = полоса почти однотонная (разброс мал) И заметно отличается от того, что рядом внутри.
    if (s.range !== null && s.range <= 12 && dist(ce, ci) >= 18) {
      sides.push(name);
      // Белое поле это яркая и бесцветная полоса. Кремовая заливка под цвет карточки (наш
      // осознанный вариант для инфографики) до 244 не дотягивает, поэтому и порог такой.
      if (light(ce) >= 244 && gray(ce) <= 10) white = true;
    }
  }
  return { sides, white, pad: sides.length > 0 };
}

/**
 * Цвет волос: средний цвет двух боковых зон верхней половины кадра. В портрете это волосы, а не
 * фон и не кожа. Зоны намеренно узкие и высокие, чтобы поймать прядь, а не плечо.
 * Годится, чтобы ОПОЗНАТЬ семью цвета (светлые, тёмные, рыжие) на обложке. Для сравнения ДВУХ
 * кадров этого мало, см. hairShift ниже.
 */
function hairColor(file) {
  const l = avg(file, 'crop=iw*0.16:ih*0.34:iw*0.04:ih*0.06');
  const r = avg(file, 'crop=iw*0.16:ih*0.34:iw*0.80:ih*0.06');
  if (!l || !r) return null;
  return [0, 1, 2].map((i) => Math.round((l[i] + r[i]) / 2));
}

// ЗАМЕР СМЕНЫ ЦВЕТА ВОЛОС: САМОЕ БОЛЬШОЕ ИЗ ДВУХ ЧИСЕЛ, А НЕ КАЖДОЕ (09.08, вторая редакция).
// Первая версия требовала смену на КАЖДОМ из кадров 3 и 4, и забраковала годные посты. Причина в
// замысле третьего кадра: он «клон-кадр», держит ту же крупность, ракурс и ФОН, что обложка.
// Боковые зоны там попадают в ту же стену, и число выходит маленьким даже когда волосы сменились.
// Живой пример: пост ff6ea3bb (нов22), чёрные волосы стали медно-рыжими на ОБОИХ кадрах, видно
// глазами на контактном листе, а замер дал кадр 3 → 12 и кадр 4 → 38, и гейт забраковал пост.
// Оба кадра заказываются одним промптом с одной целью по цвету, поэтому доказательства с одного
// кадра достаточно: если модель послушалась там, она послушалась и здесь. А случай «цвет не тронут
// вообще» ловится всё равно: тогда МАЛЫ оба числа (старый склад: нов12 → 11 и 0, нов01 → 16 и 1).
// Пробовал и отбросил: сетка из 15 клеток по кадру. Она ловит ЛЮБОЕ изменение, а не цвет волос, и
// на старом посте нов12 дала 106 при цвете волос, которого никто не менял.
//
// ЧТО ЭТА МЕРА НА САМОМ ДЕЛЕ МЕРИТ (замер 09.08 вечером, признать честно). Боковые полосы верхней
// половины кадра это далеко не только волосы: при плане «лицо занимает треть ширины» они попадают в
// ФОН рядом с головой. То есть число всегда было смесью «сменились волосы» и «сменился фон», и
// работало правило только потому, что кадр 3 был клон-кадром с тем же фоном, что обложка.
// С 09.08 вечера кадр 3 снимается в ДРУГОМ месте (яркая Москва против домашней обложки), и число
// раздувается фоном: на живом посте 69e59f0d (ru01) вышло 1-3 = 207 при пороге 26. Значит правило
// больше НЕ ловит «волосы не тронули» на кадре 3, оно проходит почти всегда.
// Порог и правило оставлены как есть намеренно, а не подкручены на глазок:
//   • вырожденный случай (кадр 3 это копия обложки, числа 0-11) оно по-прежнему ловит;
//   • честной калибровки без настоящего замера волос не выйдет, а замер волос требует найти голову.
//     Пробовал по-настоящему: детектор лиц (yunet, он в проекте есть) плюс зоны слева, справа и над
//     лицом дают на 8 живых постах разброс 52-190 при ЛЮБОМ исходе, то есть тоже не разделяют:
//     мешает разный свет в разных локациях. Отброшено как не решающее задачу.
// Поэтому приговор по цвету волос теперь выносят ГЛАЗА на контактном листе (qasheets), и это записано
// не как «пока так», а как факт: числом эту разницу мы мерить не умеем.

/**
 * Семья цвета волос на кадре: 'light' | 'dark' | 'red'. Нужна промптам смены цвета: они выбирают
 * целевой оттенок ОТ ИСХОДНОГО, и раньше сборщик передавал им 'auto', то есть перекладывал выбор
 * на модель. Модель в этом месте регулярно выбирала «почти тот же» оттенок, и смены цвета не было.
 */
function hairFamily(file) {
  const c = hairColor(file);
  if (!c) return 'auto';
  const [r, g, b] = c;
  if (light(c) >= 118) return 'light';
  // Рыжий: красный канал заметно выше синего при живой насыщенности. Порог мягкий, потому что
  // тёмно-рыжий по яркости неотличим от каштана, а целевой цвет для них всё равно разный.
  if (r - b >= 34 && r > g) return 'red';
  return 'dark';
}

/** Перцептивный отпечаток и расстояние берём из гейта обложек: один алгоритм на весь проект. */
const { hashImage, hamming } = require('./coverguard.cjs');

// ПОРОГИ. Подобраны на живых кадрах склада 09.08 и вынесены наружу, чтобы их правили здесь, а не
// подкручивали по копии в каждом скрипте.
// Порог 14 бит взят с живого поста 289f5a14 (нов12): там финал был перекадрировкой ОБЛОЖКИ, и
// отпечатки расходились ровно на 12 бит, то есть порог 10 такой брак пропускал.
const T = {
  frameDiff: 14,      // минимальное расхождение отпечатков РАЗНЫХ кадров, бит
  cropDiff: 20,       // ниже этого финал читается как перекадрировка другого кадра, а не догенерация
  hairDelta: 26,      // минимальное расстояние в цвете волос между обложкой и образом
};

/**
 * Полная проверка карусели перед складом.
 * @param {string[]} files четыре локальных файла кадров по порядку
 * @param {object} o
 * @param {string} o.template шаблон поста
 * @param {string} o.hook текст хука на первом кадре
 * @param {string} o.caption подпись поста
 * @param {boolean} [o.frame4gen] финал догенерирован. undefined значит «сборщик не сообщил»
 * @param {boolean} o.phoneUsed сборщик поставил мокап телефона
 * @param {string[]} [o.sourceSizes] размеры исходников кадров как «ШxВ»: нужны, чтобы поймать
 *        вертикальное сжатие (лицо тянется), см. проверку пропорций ниже
 * @returns {{ok:boolean, problems:string[], numbers:object}}
 */
function checkCarousel(files, { template, hook = '', caption = '', frame4gen, phoneUsed = false,
  sourceSizes = null, loc3 = '', loc4 = '', frame4Variants = null } = {}) {
  const rules = TPL.get(template);
  const problems = [];
  const numbers = { шаблон: template, тип: TPL.kindRu(template) };

  if (!Array.isArray(files) || files.length !== 4) {
    return { ok: false, problems: [`кадров ${files ? files.length : 0}, а должно быть ровно 4`], numbers };
  }
  for (const f of files) if (!fs.existsSync(f)) return { ok: false, problems: [`нет файла кадра ${f}`], numbers };

  // 1. РАЗМЕР
  const sizes = files.map(size);
  numbers.размеры = sizes.map((s) => `${s.w}x${s.h}`).join(' ');
  sizes.forEach((s, i) => {
    if (s.w !== W || s.h !== H) problems.push(`кадр ${i + 1} размером ${s.w}x${s.h}, а обязан быть ${W}x${H} (4:5)`);
  });

  // 2. ПОЛЯ. Для кадра-инфографики поля под цвет бумаги разрешены, белые не разрешены нигде.
  const cardFrame = TPL.frame2Kind(template) === 'card' ? 1 : -1;
  files.forEach((f, i) => {
    const b = bars(f);
    if (!b.pad) return;
    if (b.white) problems.push(`кадр ${i + 1}: БЕЛЫЕ поля по краям (${b.sides.join(', ')})`);
    else if (i !== cardFrame) problems.push(`кадр ${i + 1}: поля по краям (${b.sides.join(', ')}), фото обязано быть обрезкой без полей`);
    else numbers.поля_карточки = b.sides.join(', ');
  });

  // 3. КАДРЫ РАЗНЫЕ, А ФИНАЛ НЕ КРОП ПРЕДЫДУЩЕГО
  const hs = files.map((f) => { try { return hashImage(f); } catch { return null; } });
  const pairs = [[0, 1], [0, 2], [0, 3], [1, 2], [1, 3], [2, 3]];
  numbers.расхождения = {};
  for (const [a, b] of pairs) {
    // НЕПОСЧИТАННЫЙ ОТПЕЧАТОК — НЕ «КАДРЫ РАЗНЫЕ» (14.08, поймано аудитом).
    // Здесь стояло 99 при непосчитанном хэше, а оба порога ниже (14 и 20) сравнивают строгим
    // «меньше». То есть 99 проходило ОБЕ проверки: и «кадры одинаковые», и «финал выкроен из
    // обложки». Сбой ffmpeg на одном кадре работал как справка о том, что всё в порядке, и в
    // числах 99 неотличимо от измеренного (живые значения 12 и 124). Теперь такой пост честно
    // уходит в брак: лучше пересобрать, чем выпустить карусель из четырёх одинаковых кадров.
    if (!hs[a] || !hs[b]) {
      problems.push(`отпечаток кадра ${!hs[a] ? a + 1 : b + 1} не посчитался — сравнить кадры нечем, `
        + 'проверка на дубли не состоялась');
    }
    if (!hs[a] || !hs[b]) { numbers.расхождения[`${a + 1}-${b + 1}`] = 'не посчитано'; continue; }
    const d = hamming(hs[a], hs[b]);
    numbers.расхождения[`${a + 1}-${b + 1}`] = d;
    if (d < T.frameDiff) problems.push(`кадры ${a + 1} и ${b + 1} практически одинаковые (расхождение ${d} бит, нужно от ${T.frameDiff})`);
  }
  // МЕТКА «ФИНАЛ ДОГЕНЕРИРОВАН» ЭТО УТОЧНЕНИЕ, А РЕШАЮТ ЧИСЛА (09.08, вторая редакция). Первая
  // версия требовала метку всегда, и на старом складе забраковала 88 постов из 89: ключ frame4_gen
  // пишет только новый сборщик, а у старых постов его нет в принципе. Отсутствие метки это «сборщик
  // не знает», а не «финал выкроен». Поэтому: метка false (сборщик ЗНАЕТ, что положил кроп) это
  // брак, метка отсутствует это строка в отчёте, а приговор выносит расхождение отпечатков ниже.
  if (frame4gen === false) problems.push('финал выкроен из соседнего кадра: сборщик сам сообщил, что генерации не было');
  if (frame4gen === undefined || frame4gen === null) numbers.финал_догенерирован = 'сборщик не сообщил (старый пост)';
  // ФИНАЛ СВЕРЯЕМ СО ВСЕМИ ТРЕМЯ кадрами, а не только с третьим. Живой брак 289f5a14 (нов12) был
  // перекадрировкой ОБЛОЖКИ: с третьим кадром финал расходился на 124 бита, всё выглядело чисто,
  // а с первым — на 12. Проверка «не кроп» имеет смысл только против каждого кадра поста.
  for (const k of ['1-4', '2-4', '3-4']) {
    if (numbers.расхождения[k] < T.cropDiff) {
      problems.push(`кадр 4 похож на перекадрировку кадра ${k[0]} (расхождение ${numbers.расхождения[k]} бит, нужно от ${T.cropDiff})`);
    }
  }

  // 3a. ВЕРТИКАЛЬНОЕ СЖАТИЕ. Число тут ровно одно: пропорции исходника против пропорций кадра.
  // Кадр всегда 4:5, поэтому «сжатием» будет любой исходник, чьи пропорции сильно отличаются, а
  // приведён он БЕЗ обрезки и без полей. Из этого и растянутое лицо (09.08, начальник дважды ловил
  // «растянутое лицо, ужас»). Проверяем только когда сборщик отдал размеры исходников: снаружи
  // по готовому кадру это не восстановить.
  if (Array.isArray(sourceSizes)) {
    sourceSizes.forEach((s, i) => {
      const m = String(s || '').match(/(\d+)\D+(\d+)/);
      if (!m) return;
      const r = Number(m[1]) / Number(m[2]);
      numbers[`пропорции_исходника_${i + 1}`] = r.toFixed(3);
      // Сжатие даёт кадр 4:5 из исходника с другими пропорциями И без полей по краям. Если поля
      // есть, это вписывание (проверено выше), если пропорции близки к 0.8, сжимать было нечего.
      const b = bars(files[i]);
      if (Math.abs(r - 0.8) > 0.06 && !b.pad) {
        problems.push(`кадр ${i + 1}: исходник ${s} (пропорции ${r.toFixed(2)}) приведён к 4:5 без обрезки и без полей, `
          + 'то есть вертикальным сжатием: лицо тянется');
      }
    });
  }

  // 3b. ЛОКАЦИИ КАДРОВ 3 И 4 (09.08, приказ начальника: «4 снимок она на локации, которая отличается
  // от 3»). Проверяем не «постарались», а факт: сборщик обязан записать выбранные локации, и они
  // обязаны быть разными. Пустая локация это тоже брак: раньше при пустом месте промпт подставлял
  // «спокойный фон», и модель рисовала салон с кадром «на отзыв клиента».
  if (rules.kind === 'card' || rules.kind === 'art') {
    numbers.локация_3 = loc3 || '(не задана)';
    numbers.локация_4 = loc4 || '(не задана)';
    if (frame4gen === true) {
      if (!loc3 || !loc4) problems.push('локации кадров 3 и 4 не записаны, а без них нельзя проверить, что места разные');
      else if (loc3 === loc4) problems.push(`кадры 3 и 4 сняты в одной локации («${loc3}»), а места обязаны отличаться`);
    }
  }

  // 4. ТЕЛЕФОН
  numbers.телефон_разрешён = rules.phone === true;
  if (phoneUsed && !rules.phone) problems.push(`мокап телефона в шаблоне «${template}»: телефон разрешён только в тренде с волосами и сердечками`);

  // 4a. ДВА ВАРИАНТА ЧЕТВЁРТОГО КАДРА (09.08). Один пост отдаётся двумя видами: четыре кадра
  // фотопостом в тикток и смонтированный рилс в инстаграм, и слово на плашке у них РАЗНОЕ
  // («шаблоны» против «промптов»), потому что по нему мы и различаем источник трафика. Значит
  // финалов должно быть два, по одному на площадку, и оба обязаны существовать.
  if (frame4Variants) {
    const need = TPL.frame4Platforms();
    const have = Object.keys(frame4Variants).filter((k) => frame4Variants[k]);
    numbers.финалы_по_площадкам = have.join(', ') || '(нет)';
    for (const pl of need) {
      if (!frame4Variants[pl]) problems.push(`нет варианта кадра 4 для площадки «${pl}» (слово «${TPL.frame4Marker(pl)}»)`);
      // ФАЙЛ ОБЯЗАН СУЩЕСТВОВАТЬ, А НЕ ТОЛЬКО ЗНАЧИТЬСЯ В СПИСКЕ (09.08 ночью). Проверка «ключ есть»
      // ловила только совсем пустой список: сборщик пишет в него путь ДО того, как ffmpeg положил
      // файл, и если плашка не легла, ключ остаётся, а варианта нет.
      else if (!fs.existsSync(frame4Variants[pl])) problems.push(`вариант кадра 4 для «${pl}» записан, но файла нет: ${frame4Variants[pl]}`);
    }
    // ВАРИАНТЫ ОБЯЗАНЫ ОТЛИЧАТЬСЯ ДРУГ ОТ ДРУГА (09.08 ночью, начальник второй раз про слово на
    // плашке: «под тикток шаблоны, а под инстаграм промпты только»). Слово на плашке гейт прочитать
    // не может (OCR у нас нет), но одинаковые файлы значат ОДНО слово на обеих площадках, а это
    // убивает всю аналитику источников: по слову мы и различаем, откуда пришёл человек.
    const pair = need.map((pl) => frame4Variants[pl]).filter((f) => f && fs.existsSync(f));
    if (pair.length === need.length) {
      const same = pair.every((f) => fs.statSync(f).size === fs.statSync(pair[0]).size)
        && pair.every((f) => fs.readFileSync(f).equals(fs.readFileSync(pair[0])));
      if (same) problems.push('варианты кадра 4 для тиктока и для рилса это один и тот же файл: слово на плашке не различается');
    }
  } else if (frame4gen === true) {
    problems.push('сборщик не сообщил варианты кадра 4 по площадкам: нужны оба, для тиктока и для рилса');
  }

  // 5. ЦВЕТ ВОЛОС (только карточные шаблоны: там смена цвета это сам смысл поста)
  if (rules.kind === 'card') {
    const h1 = hairColor(files[0]);
    const ds = [2, 3].map((i) => dist(h1, hairColor(files[i])));
    numbers['цвет_волос_1-3'] = ds[0];
    numbers['цвет_волос_1-4'] = ds[1];
    if (Math.max(...ds) < T.hairDelta) {
      problems.push(`цвет волос не сменился: расстояние до обложки ${ds[0]} на кадре 3 и ${ds[1]} на кадре 4, `
        + `хотя бы одно должно быть от ${T.hairDelta}`);
    }
  }

  // 5а. ОДИН ЧЕЛОВЕК НА ВСЁМ ПОСТЕ (09.08 ночью, самая дорогая поломка фабрики).
  //
  // ЧТО БЫЛО. Начальник поймал глазами пост нов28: на обложке одна девушка, на кадрах 3 и 4 другая,
  // и различались ЧЕРТЫ ЛИЦА, а не только цвет волос. Соседний пост нов29 при том же коде лицо
  // держал, то есть поломка плавающая, и на объёме в сто постов глазами её не выловить.
  //
  // ПОЧЕМУ ЭТОГО ПРАВИЛА ЗДЕСЬ НЕ БЫЛО РАНЬШЕ. Мерить было нечем. Расстояние по цвету волос (пункт
  // 5) для этого не годится в принципе: оно берёт боковые полосы кадра, то есть фон, и на живом
  // посте давало 207 при пороге 26. Теперь мера есть: facesim.py, эмбеддинги SFace, косинус.
  // Проверена на известных начальнику примерах — нов28 («другая девушка») даёт 0.084, нов29 («лицо
  // нормально») даёт 0.514, а по 34 постам склада числа легли двумя кучками с пустотой между 0.33
  // и 0.41, куда канонический порог SFace 0.363 и попадает.
  //
  // ПОЧЕМУ МЕРА НЕ ВАЛИТ ПОСТ, КОГДА САМА НЕ СРАБОТАЛА. Нет питона, нет модели, лица в кадре не
  // нашлись — гейт пишет «не проверено» в числа и идёт дальше по остальным правилам. Молча ставить
  // ноль нельзя: ноль читается как «другой человек» и забракует весь склад из-за отсутствия файла.
  {
    const { faceSim } = require('./facesim.cjs');
    // ЛОВУШКИ ЛОЖНОГО БРАКА (13.08, правило начальника). Мерить сходство можно НЕ ВЕЗДЕ:
    //   · stylized: шаблон перерисовывает человека ПО ЗАМЫСЛУ, другое лицо там товар, а не брак;
    //   · сердечки (kind 'hearts'): кадры 3 и 4 это арт (чб, сердца, профиль), низкое сходство
    //     там законно. На этой ловушке чуть не срезали 59 годных постов разом;
    //   · phone: на кадре 3 мокап локскрина, лица в кадре нет вообще, мера вернёт мусор.
    // У таких шаблонов меру не зовём совсем (или зовём без кадра 3): прогон питона это секунды
    // на каждом посте волны, и число, которым запрещено пользоваться, не стоит и их.
    if (rules.stylized || rules.kind === 'hearts') {
      numbers.лицо_проверка = rules.stylized
        ? 'не мерим: шаблон перерисовывает человека по замыслу (stylized)'
        : 'не мерим: у сердечек кадры 3 и 4 это арт, низкое сходство там законно';
    } else {
      const мерим3 = rules.phone !== true;   // у телефонных шаблонов кадр 3 это мокап без лица
      const fsim = мерим3 ? faceSim(files) : faceSim([files[0], files[3]]);
      if (fsim.error) {
        numbers.лицо_проверка = `не проверено: ${fsim.error}`;
      } else {
        const d13 = мерим3 ? fsim.pairs['1-3'] : null;
        const d14 = мерим3 ? fsim.pairs['1-4'] : fsim.pairs['1-2'];
        numbers['лицо_1-3'] = мерим3 ? (d13 === null ? 'лица нет' : d13) : 'не мерим: мокап телефона';
        numbers['лицо_1-4'] = d14 === null ? 'лица нет' : d14;
        numbers.лицо_порог = fsim.same;
        // МАШИННЫЕ ПОЛЯ ДЛЯ СБОРЩИКОВ (13.08). Сборщик пишет их в meta.face_d3/face_d4 на ЛЮБОМ
        // пути сборки. До этого дня числа заполняла только карточная ветка onepost, у арт-пути в
        // базе оставались null, и пост 4da7fe5a со схожестью 0.135 на финале лежал складом как
        // годный: по запросу «face_d3 IS NULL» его считали непроверенным, а не браком.
        numbers.face_d3 = typeof d13 === 'number' ? d13 : null;
        numbers.face_d4 = typeof d14 === 'number' ? d14 : null;
        const низко = (d) => typeof d === 'number' && d < fsim.same;
        // У КАРТОЧНЫХ рубит ЛЮБОЙ провальный кадр: там кадры 3 и 4 это настоящие портреты по
        // референсу, порог проверен на нов28 против нов29, и ветка генерации уже спасала кадр
        // ретраем. У остальных одиночный провал только помечаем: мера на арте шумит.
        for (const [i, d] of [[3, d13], [4, d14]]) {
          if (d === null || d === undefined) continue;
          if (низко(d) && rules.kind === 'card') {
            problems.push(`на кадре ${i} ДРУГОЙ ЧЕЛОВЕК: схожесть лица с обложкой ${d} при пороге `
              + `${fsim.same} (мера facesim.py, эмбеддинги SFace). Это брак, за который начальник ловил `
              + 'фабрику: пост показывает двух разных девушек как одну');
          } else if (низко(d)) {
            numbers[`лицо_${i}_ниже_порога_арт`] = d;
          } else if (d < 0.42) {
            // Серая зона у порога: ругаться числом рано, но и молчать нельзя. Пусть осмотр знает,
            // на какой кадр смотреть в первую очередь.
            numbers[`лицо_${i}_серая_зона`] = d;
          }
        }
        // ЧИСТОФОТНЫЙ АРТ ТОЖЕ РУБИМ, НО ТОЛЬКО КОГДА НИЖЕ ПОРОГА ОБА КАДРА РАЗОМ (13.08).
        // Раньше арт не рубился вовсе, и подмена человека уезжала на склад: у карточных за лицо
        // отвечала ветка генерации, у арта не отвечал никто. Один низкий кадр из двух оставляем
        // осмотру глазами: одиночное число на арте это не приговор (правило начальника 13.08).
        if (rules.kind !== 'card' && низко(d13) && низко(d14)) {
          problems.push(`на кадрах 3 И 4 ДРУГОЙ ЧЕЛОВЕК: схожесть с обложкой ${d13} и ${d14} при `
            + `пороге ${fsim.same}. Оба кадра разом ниже порога у чистофотного шаблона это подмена `
            + 'человека, а не шум меры');
        }
      }
    }
  }

  // 6. ТЕКСТЫ
  const norm = (s) => String(s || '').toLowerCase().replace(/[«»"'.,!?:;()]/g, ' ').replace(/\s+/g, ' ').trim();
  const hookN = norm(hook), capN = norm(caption);
  numbers.хук = hookN.slice(0, 60);
  if (!hookN) problems.push('нет хука на первом кадре');
  if (!capN) problems.push('нет подписи поста');
  if (hookN && capN && capN.includes(hookN)) problems.push('подпись поста повторяет хук с первого кадра дословно');
  if (hookN && capN) {
    const a = new Set(hookN.split(' ').filter((w) => w.length > 3));
    const b = new Set(capN.split(' ').filter((w) => w.length > 3));
    const common = [...a].filter((w) => b.has(w));
    numbers.общих_слов = common.length;
    if (a.size && common.length / a.size > 0.6) {
      problems.push(`подпись почти повторяет хук (общих слов ${common.length} из ${a.size}): ${common.slice(0, 5).join(', ')}`);
    }
  }
  const tags = String(caption).match(/#\S+/g) || [];
  numbers.хештегов = tags.length;
  if (!tags.length) problems.push('в подписи нет хештегов');
  // ГРАНИЦА СЛОВА ДЛЯ КИРИЛЛИЦЫ РУКАМИ. \b в JS считает буквой только латиницу, поэтому \bмама\b
  // на строке «мама увидела» НЕ СРАБАТЫВАЕТ: между пробелом и «м» границы для движка нет. Ровно на
  // это уже наступали в фильтрах комментов. Живой пример: хук поста 289f5a14 начинался словом
  // «мама», и запрет молчал.
  if (/(^|[^а-яёa-z])мам(а|е|у|ы|ой|очка)?([^а-яёa-z]|$)/i.test(String(hook))) {
    problems.push('в хуке мама: аудитория подростки, мама для них не авторитет (забраковано начальником)');
  }
  // ФРАЗЫ ПРО «БЕЗ ПРОМПТА» ЗАПРЕЩЕНЫ (09.08, приказ начальника: «в описании и на кадрах 4 не пишем
  // теперь, что без промпта, потому что призываем искать промпт их»). Причина не косметическая: на
  // четвёртом кадре мы гоним человека искать слово-маркер («промпты» для инстаграма, «шаблоны» для
  // тиктока), и по этому слову в поисковом запросе различаем площадку. Подпись «промпт не нужен»
  // прямо отговаривает искать, и метка канала перестаёт работать вместе со всей аналитикой.
  const noPrompt = String(caption + ' ' + hook).match(
    /(без|никаких?)\s+(промпт\w*|настро\w*)|промпт\w*\s+(не\s+нужен|не\s+нужн\w+|писать\s+не\s+надо|копировать\s+не\s+надо|придумывать\s+не\s+надо)|ничего\s+не\s+надо\s+придумывать/i);
  if (noPrompt) problems.push(`в тексте фраза «${noPrompt[0]}»: она отговаривает искать наше слово-маркер, а мы на него и гоним`);

  // ИИ-ТЕГИ. Ловим именно теги «это сделано нейросетью» (они тянут пост в техно-аудиторию и в пул
  // ИИ-приколов). Имя нашего бренда «нейронка» под запрет НЕ попадает: это промо, а не ИИ-метка.
  const aiTag = tags.find((t) => /^#(ии|ai|aiart|нейроарт|сгенерировано)(тренд|фото|арт|art)?$/i.test(t)
    || /нейросет|midjourney|chatgpt|dalle|stablediffusion|промт|промпт/i.test(t));
  if (aiTag) problems.push(`в подписи ИИ-тег ${aiTag}: таких хештегов быть не должно`);

  return { ok: problems.length === 0, problems, numbers };
}

module.exports = { checkCarousel, size, bars, hairColor, hairFamily, hairColorDistance: dist, T };

