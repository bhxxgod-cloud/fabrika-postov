// Кириллица в подписи или русский запрос это плюс к нашему типажу, а не минус.
const CYR = /[а-яё]/i;

function liveVerdict(m, mt) {
  // Возвращает {why, flags}: why это отказ, flags это пометки для контактного листа.
  const flags = [];
  const size = `${m.w}x${m.h}`;
  if (AI_SIZES.has(size)) return { why: `размер диффузии ${size} (ИИ или сток, не живой кадр)`, flags };
  const ar = m.w / (m.h || 1);
  if (Math.abs(ar - 2 / 3) < 0.012) return { why: 'кадр 2 к 3 (фотоаппарат, это съёмка)', flags };
  const cap = `${mt.alt || ''} ${mt.desc || ''} ${mt.title || ''}`.trim();
  // ПРАВИЛА «ПОДПИСИ НЕТ ВОВСЕ» ЗДЕСЬ НЕТ, И ЭТО ПРОВЕРЕНО. Оно стояло и отсеяло 45 кадров из
  // 2088. На листе брака из 16 первых восемь оказались живыми селфи ровно нашего типа: пустая
  // подпись значит только то, что репинщик поленился подписать, и на репинах это норма. Брак
  // ловит не пустота, а МАШИННОЕ описание ниже: оно появляется вместо подписи человека.
  if (AUTO_CAPTION.test(mt.alt || '') && !CYR.test(cap)) {
    return { why: 'авто-подпись пина (сток или ИИ, живого автора нет)', flags };
  }
  const dom = String(mt.domain || '').toLowerCase();
  const cd = COMMERCE_DOMAINS.find((d) => dom.includes(d));
  if (cd) return { why: `коммерческий источник: ${cd}`, flags };
  // типаж: только пометка, никогда не отказ
  const t = norm(cap);
  const tw = TYPAGE_WORDS.find((w) => t.includes(` ${w} `));
  if (tw && !CYR.test(cap)) flags.push(`типаж спорный: ${tw}`);
  return { why: null, flags };
}

