"""
Анимированная строка поиска Яндекса поверх кадра: текст печатается сам.

ЗАЧЕМ ОТДЕЛЬНЫМ СКРИПТОМ, А НЕ ФИЛЬТРОМ FFMPEG. drawtext в ffmpeg криво ломает
кириллицу по строкам и не умеет курсор, а весь проект по этой причине рисует
текст в браузере. Но тянуть Chrome ради одной полоски дорого: у нас и так течёт
память от вкладок сборки. PIL рисует то же самое за секунды и без процессов.

ЧТО ПОЛУЧАЕТСЯ НА ВЫХОДЕ: mp4 нужной длины, где кадр поста стоит на месте, а
поверх него появляется строка поиска и в ней посимвольно набирается запрос.
Дальше этот mp4 подставляется в сборку рилса вместо картинки четвёртого кадра.

ЗАТЕМНЕНИЕ КРАЁВ обязательно: строка мелкая, кадр под ней пёстрый, и без
притемнения глаз её просто не находит. Затемняем не всю картинку, а низ,
градиентом, чтобы лицо сверху осталось нетронутым.
"""
import math
import os
import subprocess
import sys

from PIL import Image, ImageDraw, ImageFont

ЗАПРОС = os.environ.get('YABAR_TEXT', 'нейронка про шаблоны')
ПОДВОДКА = os.environ.get('YABAR_LEAD', 'делала себе тут, просто наберите в яндексе:')
ПОДПИСЬ = os.environ.get('YABAR_SUB', 'neironka.pro · первые генерации бесплатно')
FPS = int(os.environ.get('YABAR_FPS', '30'))
ДЛИНА = float(os.environ.get('YABAR_SECONDS', '5'))

# Тайминг набора. Пауза перед началом нужна, чтобы зритель успел увидеть кадр
# до того, как на нём что-то поедет: иначе строка воспринимается как помеха.
ПАУЗА_ДО = float(os.environ.get('YABAR_PAUSE', '0.30'))
НА_ЗНАК = float(os.environ.get('YABAR_PER_CHAR', '0.030'))

ШРИФТЫ = [
    '/System/Library/Fonts/Supplemental/Arial Bold.ttf',
    '/Library/Fonts/Arial Bold.ttf',
    '/System/Library/Fonts/HelveticaNeue.ttc',
]
ШРИФТЫ_ОБЫЧНЫЕ = [
    '/System/Library/Fonts/Supplemental/Arial.ttf',
    '/System/Library/Fonts/HelveticaNeue.ttc',
]


def шрифт(размер, жирный=True):
    for п in (ШРИФТЫ if жирный else ШРИФТЫ_ОБЫЧНЫЕ):
        try:
            return ImageFont.truetype(п, размер)
        except Exception:
            pass
    return ImageFont.load_default()


def затемнить_низ(кадр, откуда=0.55, сила=150):
    """Градиент от прозрачного к тёмному сверху вниз."""
    W, H = кадр.size
    слой = Image.new('L', (1, H), 0)
    пиксели = слой.load()
    старт = int(H * откуда)
    for y in range(H):
        if y < старт:
            пиксели[0, y] = 0
        else:
            доля = (y - старт) / max(1, H - старт)
            # Квадрат даёт мягкое начало и плотный низ: линейный градиент
            # виден полосой, а этот читается как естественная тень.
            пиксели[0, y] = int(сила * (доля ** 1.6))
    маска = слой.resize((W, H))
    тень = Image.new('RGB', (W, H), (0, 0, 0))
    return Image.composite(тень, кадр, маска.point(lambda v: v))


def нарисовать(кадр, набрано, курсор_виден, появление, мышь=None, клик=0.0, выдача=0.0):
    """Один кадр: строка поиска поверх фото."""
    W, H = кадр.size
    im = кадр.copy()
    if появление <= 0:
        return im

    # Затемнение включаем вместе со строкой и той же силой, чтобы они
    # появлялись как одно целое, а не двумя отдельными событиями.
    im = затемнить_низ(im, откуда=float(os.environ.get('YABAR_DIM_FROM','0.50')), сила=int(150 * появление))
    d = ImageDraw.Draw(im, 'RGBA')

    # ПОДЛОЖКА ПОД БЛОК, если на кадре под ней есть что перекрыть (например
    # старая вожжённая строка). Раньше это место замазывалось размытым куском
    # фона, и получалась мутная полоса: владелец справедливо назвал это
    # «замыленной строкой». Ровная тёмная подложка честнее: она читается как
    # часть оформления, а не как испорченная картинка.
    подложка = float(os.environ.get('YABAR_PANEL', '0'))
    if подложка > 0:
        верх = int(H * float(os.environ.get('YABAR_PANEL_TOP', '0.60')))
        низкрай = int(H * float(os.environ.get('YABAR_PANEL_BOTTOM', '0.76')))
        d.rectangle([0, верх, W, низкрай], fill=(12, 12, 14, int(255 * подложка * появление)))

    СТИЛЬ = os.environ.get('YABAR_STYLE', 'светлый')
    тёмная = СТИЛЬ == 'тёмный'
    фон_строки = (28, 30, 36) if тёмная else (255, 255, 255)
    цвет_текста = (236, 238, 242) if тёмная else (22, 24, 29)
    цвет_лупы = (138, 143, 152) if тёмная else (154, 160, 166)

    поля = int(W * 0.040)   # владелец 27.08: строку чуть длиннее
    низ = int(H * float(os.environ.get('YABAR_Y', '0.66')))
    высота = int(os.environ.get('YABAR_H', '112'))
    радиус = int(os.environ.get('YABAR_R', '56'))  # пилюля, как в свежем поиске, а не прямоугольник 2015 года
    a = int(255 * появление)

    ш_подводки = шрифт(30, жирный=False)
    b = d.textbbox((0, 0), ПОДВОДКА, font=ш_подводки)
    d.text((поля, низ - 52 - (b[3] - b[1])), ПОДВОДКА, font=ш_подводки, fill=(255, 255, 255, a))

    # Сама строка. Гаснет, когда приходит выдача: она займёт это же место.
    стр_видна = max(0.0, 1.0 - выдача * 1.6)
    кн_видна = max(0.0, 1.0 - выдача * 3.0)   # кнопка гаснет раньше: её текст лез сквозь сниппет
    aс = int(a * стр_видна)
    x2 = W - поля
    # Мягкая тень под строкой: без неё пилюля выглядит наклейкой поверх кадра.
    d.rounded_rectangle([поля + 3, низ + 6, x2 + 3, низ + высота + 6], radius=радиус, fill=(0, 0, 0, int(aс * 0.22)))
    d.rounded_rectangle([поля, низ, x2, низ + высота], radius=радиус, fill=фон_строки + (aс,))

    # Лупа: круг и палочка. Рисуем фигурами, а не эмодзи: эмодзи на разных
    # системах выглядит по-разному, а нам нужен один вид на всех машинах.
    цx, цy = поля + 42, низ + высота // 2
    d.ellipse([цx - 12, цy - 14, цx + 10, цy + 8], outline=цвет_лупы + (aс,), width=4)
    d.line([цx + 8, цy + 6, цx + 18, цy + 16], fill=цвет_лупы + (aс,), width=4)

    # Текст запроса
    ш_текста = шрифт(38)
    тx = поля + 76
    bb = d.textbbox((0, 0), набрано or 'н', font=ш_текста)
    тy = низ + (высота - (bb[3] - bb[1])) // 2 - bb[1]
    if набрано:
        d.text((тx, тy), набрано, font=ш_текста, fill=цвет_текста + (aс,))
        ширина = d.textbbox((0, 0), набрано, font=ш_текста)[2]
    else:
        ширина = 0

    if курсор_виден:
        кx = тx + ширина + 4
        d.rounded_rectangle([кx, низ + 27, кx + 4, низ + высота - 27], radius=2, fill=цвет_текста + (a,))

    # Правый край: кнопка «Найти» или кружок голосового помощника — смотря какой стиль
    if СТИЛЬ == 'алиса':
        цр = высота // 2 - 14
        ццx, ццy = x2 - цр - 22, низ + высота // 2
        d.ellipse([ццx - цр, ццy - цр, ццx + цр, ццy + цр], fill=(124, 77, 255, a))
        # три полоски эквалайзера внутри кружка
        for i, вы in enumerate((14, 22, 14)):
            xx = ццx - 10 + i * 10
            d.rounded_rectangle([xx - 3, ццy - вы // 2, xx + 3, ццy + вы // 2], radius=3,
                                fill=(255, 255, 255, a))
    else:
        ш_кнопки = шрифт(30)
        подпись = 'Найти'
        шп = d.textbbox((0, 0), подпись, font=ш_кнопки)[2]
        кш = шп + 72
        отступ = 9
        d.rounded_rectangle([x2 - кш, низ + отступ, x2 - отступ, низ + высота - отступ],
                            radius=радиус, fill=(252, 63, 29, int(a * кн_видна)))
        d.text((x2 - кш + 30, низ + (высота - 30) // 2 - 4), подпись, font=ш_кнопки,
               fill=(255, 255, 255, int(a * кн_видна)))
    # ═══ ВЫДАЧА ПОСЛЕ КЛИКА ═════════════════════════════════════════════════════════════════
    # Сниппет собран по настоящей выдаче Яндекса: иконка сайта, фиолетовый заголовок
    # посещённой ссылки, зелёный домен, серое описание в две строки.
    if выдача > 0:
        ав = int(255 * min(1.0, выдача))
        сдвиг = int(28 * (1 - min(1.0, выдача)))   # выезжает снизу вверх
        вy = низ + сдвиг
        ввысота = 250
        d.rounded_rectangle([поля - 10, вy - 18, x2 + 10, вy + ввысота], radius=28,
                            fill=(255, 255, 255, int(ав * 0.97)))
        # иконка сайта: тёмный кружок с треугольником, как favicon в выдаче
        иx, иy = поля + 22, вy + 22
        d.ellipse([иx - 18, иy - 18, иx + 18, иy + 18], fill=(24, 26, 32, ав))
        d.polygon([(иx, иy - 9), (иx + 9, иy + 7), (иx - 9, иy + 7)], fill=(255, 255, 255, ав))
        ш_заг = шрифт(34)
        d.text((поля + 56, вy + 2), 'Все нейросети онлайн на русском', font=ш_заг,
               fill=(112, 63, 168, ав))
        d.text((поля + 56, вy + 44), 'в одном окне — Нейронка', font=ш_заг, fill=(112, 63, 168, ав))
        d.text((поля + 56, вy + 92), 'neironka.pro', font=шрифт(27), fill=(30, 130, 60, ав))
        ш_оп = шрифт(26, жирный=False)
        d.text((поля + 12, вy + 134), 'GPT-5.5, Claude Opus, Veo, Nano Banana Pro,',
               font=ш_оп, fill=(52, 56, 64, ав))
        d.text((поля + 12, вy + 168), 'Midjourney и ещё 60+ нейросетей для текста,',
               font=ш_оп, fill=(52, 56, 64, ав))
        d.text((поля + 12, вy + 202), 'картинок, видео и озвучки — без VPN.',
               font=ш_оп, fill=(52, 56, 64, ав))

    # ═══ КУРСОР МЫШИ ════════════════════════════════════════════════════════════════════════
    # Обычная белая стрелка с тёмной обводкой, как системный курсор. В момент клика
    # уменьшается — так глаз читает нажатие без всякой подписи.
    if мышь is not None and выдача < 0.35:
        мx, мy = мышь
        м = 1.0 - 0.18 * клик
        L = 34 * м
        точки = [(мx, мy), (мx, мy + L), (мx + L * 0.28, мy + L * 0.74),
                 (мx + L * 0.46, мy + L * 1.02), (мx + L * 0.60, мy + L * 0.94),
                 (мx + L * 0.42, мy + L * 0.66), (мx + L * 0.72, мy + L * 0.62)]
        aм = int(a * max(0.0, 1.0 - выдача * 2.4))
        d.polygon(точки, fill=(255, 255, 255, aм), outline=(20, 20, 24, aм))
        if клик > 0:
            # круг-волна от нажатия
            р = int(26 * клик)
            d.ellipse([мx - р, мy - р, мx + р, мy + р],
                      outline=(255, 255, 255, int(aм * (1 - клик) * 0.8)), width=3)

    # Подпись домена под строкой: делает кадр похожим на реальную выдачу, а не на макет.
    if os.environ.get('YABAR_DOMAIN', '1') != '0' and выдача <= 0:
        ш_дом = шрифт(26, жирный=False)
        if СТИЛЬ == 'подсказка':
            # Первая строка автодополнения: так кадр читается не как надпись поверх фото,
            # а как настоящий момент, когда поиск уже предложил нужный сайт.
            пв = 74
            пy = низ + высота + 12
            d.rounded_rectangle([поля, пy, x2, пy + пв], radius=26,
                                fill=(28, 30, 36, int(a * 0.94)) if тёмная else (255, 255, 255, int(a * 0.96)))
            # квадратик фавикона
            фx, фy = поля + 26, пy + пв // 2
            d.rounded_rectangle([фx - 16, фy - 16, фx + 16, фy + 16], radius=8, fill=(252, 63, 29, a))
            d.text((фx - 9, фy - 15), 'н', font=шрифт(24), fill=(255, 255, 255, a))
            d.text((поля + 66, пy + 22), ПОДПИСЬ, font=ш_дом,
                   fill=(236, 238, 242, a) if тёмная else (22, 24, 29, a))
        else:
            d.text((поля + 8, низ + высота + 16), ПОДПИСЬ,
                   font=ш_дом, fill=(228, 230, 235, int(a * 0.9)))

    return im


def main():
    исходник, выход = sys.argv[1], sys.argv[2]
    кадр = Image.open(исходник).convert('RGB')
    всего = int(ДЛИНА * FPS)
    папка = os.environ.get('YABAR_TMP', '/tmp/yabar')
    os.makedirs(папка, exist_ok=True)
    for f in os.listdir(папка):
        os.remove(os.path.join(папка, f))

    for i in range(всего):
        t = i / FPS
        # Появление: полсекунды. Быстрее читается как мигание, медленнее тормозит.
        появление = min(1.0, max(0.0, (t - ПАУЗА_ДО + 0.5) / 0.5)) if t >= ПАУЗА_ДО - 0.5 else 0.0
        знаков = 0 if t < ПАУЗА_ДО else min(len(ЗАПРОС), int((t - ПАУЗА_ДО) / НА_ЗНАК))
        # Курсор мигает раз в полсекунды и гаснет, когда набор кончен и прошла секунда.
        конец_набора = ПАУЗА_ДО + len(ЗАПРОС) * НА_ЗНАК
        курсор = (t < конец_набора + 0.3) and (math.floor(t * 2) % 2 == 0 or знаков < len(ЗАПРОС))

        # МЫШЬ ЕДЕТ К КНОПКЕ, КЛИКАЕТ, ПОЯВЛЯЕТСЯ ВЫДАЧА (владелец 29.08).
        ЕДЕТ, НАЖИМ = 0.80, 0.20
        старт_мыши = конец_набора + 0.35
        Ш, В = кадр.size
        поля_ = int(Ш * 0.040)
        низ_ = int(В * float(os.environ.get('YABAR_Y', '0.66')))
        выс_ = int(os.environ.get('YABAR_H', '112'))
        цель = (Ш - поля_ - 96, низ_ + выс_ // 2 - 10)      # середина кнопки «Найти»
        откуда = (int(Ш * 0.30), низ_ + выс_ + 190)          # выезжает снизу слева
        мышь = клик = выдача = None
        if t >= старт_мыши:
            ход = min(1.0, (t - старт_мыши) / ЕДЕТ)
            плавно = ход * ход * (3 - 2 * ход)               # мягкий разгон и торможение
            мышь = (int(откуда[0] + (цель[0] - откуда[0]) * плавно),
                    int(откуда[1] + (цель[1] - откуда[1]) * плавно))
            тк = t - (старт_мыши + ЕДЕТ)
            клик = max(0.0, 1.0 - тк / НАЖИМ) if 0 <= тк <= НАЖИМ else 0.0
            после_клика = t - (старт_мыши + ЕДЕТ + НАЖИМ)
            выдача = min(1.0, max(0.0, после_клика / 0.35))
        нарисовать(кадр, ЗАПРОС[:знаков], курсор, появление,
                   мышь=мышь, клик=(клик or 0.0), выдача=(выдача or 0.0)).save(
            os.path.join(папка, f'{i:05d}.jpg'), quality=92)

    subprocess.run([
        'ffmpeg', '-y', '-loglevel', 'error',
        '-framerate', str(FPS), '-i', os.path.join(папка, '%05d.jpg'),
        '-c:v', 'libx264', '-preset', 'medium', '-crf', '20',
        '-pix_fmt', 'yuv420p', выход,
    ], check=True)

    # ЗВУК КЛАВИАТУРЫ, СИНХРОННЫЙ С НАБОРОМ.
    #
    # Готовый луп «клацанья» сюда не годится: он играет в своём ритме, а буквы
    # появляются в своём, и рассинхрон между звуком и картинкой слышно сразу.
    # Поэтому клик синтезируется на КАЖДЫЙ знак и ставится ровно в тот момент,
    # когда знак появился.
    #
    # Сам клик это очень короткий шум, зажатый полосовым фильтром и резкой
    # огибающей: так звучит касание стекла, а не механическая клавиша. Высоту
    # чуть меняем от знака к знаку, иначе одинаковые щелчки читаются как
    # металлический тик и выдают синтез.
    if os.environ.get('YABAR_CLICKS', '1') != '0':
        звук = os.path.splitext(выход)[0] + '-клики.wav'
        входы, фильтры, метки = [], [], []
        for i in range(len(ЗАПРОС)):
            t = ПАУЗА_ДО + i * НА_ЗНАК
            if t >= ДЛИНА:
                break
            мс = int(t * 1000)
            частота = 2100 + (i * 137) % 900
            входы += ['-f', 'lavfi', '-t', '0.06', '-i', 'anoisesrc=c=white:a=0.55:r=44100']
            фильтры.append(
                f'[{i}:a]bandpass=f={частота}:width_type=h:w=900,'
                f'afade=t=in:st=0:d=0.004,afade=t=out:st=0.012:d=0.045,'
                f'volume=-9dB,adelay={мс}|{мс},'
                f'aformat=sample_fmts=fltp:sample_rates=44100:channel_layouts=stereo[c{i}]'
            )
            метки.append(f'[c{i}]')

        # ЩЕЛЧОК МЫШИ В МОМЕНТ НАЖАТИЯ НА «НАЙТИ» (29.08, приказ владельца).
        #
        # ПОЧЕМУ ОН ЗВУЧИТ ИНАЧЕ, ЧЕМ КЛАВИАТУРА. Клавиша по стеклу — это шипящий верх, а кнопка
        # мыши это короткий сухой щелчок с телом внизу: пластик, а не стекло. Поэтому полоса ниже
        # (900 Гц против двух тысяч), затухание вдвое короче, и щелчков ДВА — нажатие и отпускание
        # через 70 мс, как у настоящей кнопки. Один щелчок ухо читает как «тик» и не верит.
        #
        # ВРЕМЯ БЕРЁМ ИЗ ТОЙ ЖЕ ФОРМУЛЫ, ЧТО И КАРТИНКА (старт_мыши + ЕДЕТ): считать его отдельно
        # значит завести второй источник правды, и первая же правка анимации разведёт звук с
        # нажатием. Момент клика виден глазом — рассинхрон в полкадра слышно.
        _конец_набора = ПАУЗА_ДО + len(ЗАПРОС) * НА_ЗНАК
        _клик_мыши = _конец_набора + 0.35 + 0.80          # старт_мыши + ЕДЕТ
        for j, (сдвиг, громкость, длит) in enumerate([(0.0, -4, 0.05), (0.070, -9, 0.04)]):
            t = _клик_мыши + сдвиг
            if t >= ДЛИНА:
                break
            # Номер входа = сколько их уже добавлено. У каждого ШЕСТЬ аргументов
            # ('-f','lavfi','-t','<длина>','-i','<источник>'), а не четыре: на этой арифметике
            # клик мыши получал номера 30 и 31 вместо 20 и 21, и ffmpeg падал на несуществующем
            # входе — то есть звука не было вовсе, причём молча для вызывающего.
            n = len(входы) // 6
            мс = int(t * 1000)
            входы += ['-f', 'lavfi', '-t', '0.05', '-i', 'anoisesrc=c=white:a=0.7:r=44100']
            фильтры.append(
                f'[{n}:a]bandpass=f=900:width_type=h:w=700,'
                f'afade=t=in:st=0:d=0.002,afade=t=out:st=0.006:d={длит},'
                f'volume={громкость}dB,adelay={мс}|{мс},'
                f'aformat=sample_fmts=fltp:sample_rates=44100:channel_layouts=stereo[m{j}]'
            )
            метки.append(f'[m{j}]')

        if метки:
            фильтры.append(
                ''.join(метки)
                + f'amix=inputs={len(метки)}:duration=longest:normalize=0,'
                + f'apad,atrim=0:{ДЛИНА},asetpts=N/SR/TB[out]'
            )
            subprocess.run(
                ['ffmpeg', '-y', '-loglevel', 'error'] + входы
                + ['-filter_complex', ';'.join(фильтры), '-map', '[out]', звук],
                check=True,
            )
            print(f'клики: {звук}, {len(метки)} штук')

    print(f'готово: {выход}, {всего} кадров, {ДЛИНА} сек')


if __name__ == '__main__':
    main()
