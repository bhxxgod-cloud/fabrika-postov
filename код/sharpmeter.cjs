function прокси() {
  const out = [];
  for (const f of ['/tmp/px/kz_sous_500_magos.txt', '/tmp/px/kz_magos_100.txt']) {
    try {
      for (const l of fs.readFileSync(f, 'utf8').split('\n')) {
        const p = l.trim().split(':');
        if (p.length === 4) out.push(`http://${p[2]}:${p[3]}@${p[0]}:${p[1]}`);
      }
    } catch { /* нет файла с прокси, обойдёмся прямым доступом */ }
  }
  return out;
}

/** Довести ссылку до локального файла. Локальный путь возвращается как есть. */
function добыть(ист) {
  if (!/^https?:\/\//i.test(ист)) {
    if (!fs.existsSync(ист)) throw new Error(`нет файла: ${ист}`);
    return { файл: ист, врем: false };
  }
  const дест = path.join(os.tmpdir(), `sharp_${process.pid}_${Math.random().toString(36).slice(2, 8)}.bin`);
  const пул = прокси();
  const порядок = [null, пул[0], пул[Math.floor(пул.length / 2)]].filter((v, i) => i === 0 || v);
  let беда = 'не пробовали';
  for (const px of порядок) {
    const args = ['-sS', '--fail', '--max-time', '90', '-o', дест, ист];
    if (px) args.push('--proxy', px);
    const r = spawnSync('curl', args, { encoding: 'utf8' });
    // Целостность проверяем по маркеру конца картинки: оборванный jpeg декодер дорисует зелёным,
    // и мы замерим резкость зелёного блока (ровно этот брак уже был на кадре 4, см. rgen.cjs).
    if (r.status === 0 && fs.existsSync(дест)) {
      const b = fs.readFileSync(дест);
      const целый = b.length > 10000 && ((b[0] === 0xFF && b[1] === 0xD8 && b[b.length - 2] === 0xFF && b[b.length - 1] === 0xD9)
        || (b[0] === 0x89 && b.subarray(b.length - 12).includes(Buffer.from('IEND'))));
      if (целый) return { файл: дест, врем: true };
      беда = `картинка оборвана (${b.length} байт)`;
    } else беда = `curl код ${r.status}`;
  }
  try { fs.unlinkSync(дест); } catch { /* нечего убирать */ }
  throw new Error(`не скачалось (${беда}): ${ист}`);
}

