const сид = (s) => { let h = 0; for (const c of s) h = (h * 31 + c.codePointAt(0)) >>> 0; return h; };
// ИНДЕКС ИЗ ХЕША — ТОЛЬКО ЧЕРЕЗ >>> (15.08, поймано владельцем: в группу ушли подписи с двумя
