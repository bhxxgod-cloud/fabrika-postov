// «вот что бывает, когда наконец разбираешься в себе» и «это реально я, сама в шоке», то есть текст
// не про разбор, не про оценку и не про кафе. Читатель видит расхождение мгновенно.
//
// ═══ ПЕРЕСБОРКА 12.08: ПРИКАЗ ПО ПЕРВОЙ СТРОКЕ ══════════════════════════════════════════════
// Начальник посмотрел живой выход («гуляла во дворе-колодце старого дома днём и заодно закинула
// свою фотку, а мне разобрали внешность» плюс опись слайдов и «сохрани себе») и сказал дословно:
// «вот этот текст пизда полная, там хуета». И следом задал схему: «1 хук должен быть байтовым и
