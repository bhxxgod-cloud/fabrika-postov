// Классы мест. Порядок проверки важен: «веранда кафе» это кафе, а не улица, хотя улица там названа.
const МЕСТА = [
  ['lux', /дубай|марин|небоскрёб|лобби|мрамор|яхт|пентхаус/i],
  ['cafe', /кафе|веранд|кофейн|ресторан|рестик|столик|барн(ая)? стойк/i],
  ['shop', /витрин|книжн|магазин|торгов/i],
  ['study', /библиотек|универ|учёб|коворк|офис/i],
  ['park', /парк|набережн|сквер|бульвар|дорожк|двор/i],
  ['city', /сити|башн|стекл|бизнес-центр/i],
  ['street', /улиц|фасад|тротуар|переход|мост|центр(е)? москв|проспект|питер|санкт/i],
  ['home', /дома|комнат|кухн|балкон|коридор|прихож|подоконник|окн|постел|спальн|квартир|ванн|душ/i],
];
// КЛАСС МЕСТА СЧИТАЕМ ТОЛЬКО ПО ПЕРВОЙ ЧАСТИ ЗАКАЗА ЛОКАЦИИ, ДО ЗАПЯТОЙ. Найдено на пробе (посты
// 04, 08 и 09): в хвосте локации перечисляется обстановка, и «за спиной остеклённая рама» на кадре
// НА БАЛКОНЕ давала класс «среди башен» (совпадение по «стекл»), а «за спиной окно» в такси давало
// класс «дома». Место это то, что названо первым, остальное это свет и мебель.
const МЕСТО_СЛОВОМ = {
  lux: 'в дубае', cafe: 'в кафе', shop: 'у витрины', study: 'на учёбе', park: 'на улице',
  city: 'среди башен', street: 'на улице', home: 'дома',
};
function классМеста(text) {
  const t = String(text || '').split(',')[0];
  if (!t.trim()) return null;
  for (const [k, re] of МЕСТА) if (re.test(t)) return k;
  return null;
}
function времяСуток(text) {
  const t = String(text || '');
  if (/утром|утренн/i.test(t)) return 'morning';
  if (/вечером|вечерн|ноч/i.test(t)) return 'evening';
  if (/днём|дневн|солнц/i.test(t)) return 'day';
  return null;
}
// КОРОТКАЯ ФРАЗА МЕСТА. Берём первую часть промпта локации до запятой: там всегда стоит само место и
// время («на летней веранде кафе днём»), а после запятой начинается перечисление мебели и света,
// которое в подписи читается как техзадание. Ничего не досочиняем: это дословный факт заказа.
// Регистр НЕ меняем: в локациях стоят имена собственные (Москва-Сити, Дубай), и «москва-сити»
// строчными выдаёт машинный текст.
function фразаМеста(loc) {
  const t = String(loc || '').split(',')[0].trim();
  if (!t || t.length > 60) return null;
  if (/[\\/]/.test(t)) return null;     // слеш в подписи запрещён, а место это чужой текст
  return t;
}

const ЦВЕТ_ИСХОДНИКА = { light: 'светлых', dark: 'тёмных', red: 'рыжих' };
function сторонаЦвета(aim) {
  const a = String(aim || '');
  if (/блонд/i.test(a)) return 'blond';
  if (/рыж|медн/i.test(a)) return 'red';
  if (/шоколад|каштан|тёмн/i.test(a)) return 'dark';
  return null;
}

/**
 * Факты поста для подписи. Всё, чего нет, остаётся null, и блок про это не собирается.
 * @param {object} o
 * @param {string} o.template шаблон поста
 * @param {string} [o.hook] хук с первого кадра
 * @param {object} [o.meta] meta поста из базы (главный источник фактов)
 * @param {string} [o.seed] ключ поста для хэша (id поста, если он уже есть)
 * @param {string} [o.hairLen] целевая длина волос словами, если вызывающий её знает
 */
function collectFacts(o = {}) {
  const meta = o.meta || {};
  const template = String(o.template || meta.template || '').trim();
  const t = TPL.get(template);
  const тема = ТЕМА_ПО_СЕМЬЕ[t.family] || (t.kind === 'hearts' ? 'hearts' : 'art');
  const hook = String(o.hook || meta.hook_text || '').trim();
  const loc3 = String(meta.loc3 || o.loc3 || '').trim() || null;
  const loc4 = String(meta.loc4 || o.loc4 || '').trim() || null;
  const srcHair = String(meta.src_hair || o.srcHair || '').trim() || null;
  const hairIdx = Number.isFinite(Number(meta.hair_idx)) ? Number(meta.hair_idx) : null;
  let hairAim = null;
  if (PK && srcHair && ЦВЕТ_ИСХОДНИКА[srcHair] && hairIdx !== null) {
    try { hairAim = PK.hairTarget(srcHair, hairIdx); } catch { hairAim = null; }
  }
  // СМЕНА ЦВЕТА СЧИТАЕТСЯ ПОДТВЕРЖДЁННОЙ ТОЛЬКО ПО ЗАМЕРУ. hair_d это расхождение цвета волос между
  // обложкой и образом, его считает гейт; норма смены у нас от 26 (см. onepost). Если замера нет,
  // говорить «я покрасилась» нельзя: модель регулярно оставляет исходный оттенок, и подпись соврёт.
  // ПЕРЕРИСОВАННЫЙ ШАБЛОН ПРО КРАСКУ НЕ ГОВОРИТ (12.08). У stylized-шаблонов (аниме, пиксар,
  // поп-арт, фигурка, плюш) кадры 3 и 4 это РИСУНОК, и цвет волос там принадлежит рисунку, а не ей:
  // фраза «смотрю на себя в платиновый блонд и не понимаю, чего тянула» под аниме-портретом это
  // ровно то враньё про картинку, ради которого весь этот модуль и написан. Замер hair_d их не
  // отличает, поэтому право говорить про краску даёт КОНТРАКТ ШАБЛОНА, как и право говорить про место.
  const hairD = Number.isFinite(Number(meta.hair_d)) ? Number(meta.hair_d) : null;
  const hairChanged = Boolean(hairAim) && hairD !== null && hairD >= 26 && t.stylized !== true;
  // ТИР ОБРАЗА. Метка люкса в проекте уже живёт (meta.lux, см. promptkit.postTier), плюс сама
  // локация может быть дорогой: Дубай, лобби, марина уходят только люксу.
  const luxПоМесту = классМеста(loc3) === 'lux' || классМеста(loc4) === 'lux';
  const tier = (meta.lux === true || String(meta.tier || '') === 'lux' || luxПоМесту) ? 'lux' : 'plain';
  return {
    template, family: t.family, kind: t.kind, тема, hook,
    loc3, loc4,
    place3: фразаМеста(loc3), place4: фразаМеста(loc4),
    scene3: классМеста(loc3), scene4: классМеста(loc4),
    time3: времяСуток(loc3), time4: времяСуток(loc4),
    tier, luxПоМесту,
    srcHair, srcHairRu: srcHair ? (ЦВЕТ_ИСХОДНИКА[srcHair] || null) : null,
    hairAim, hairD, hairChanged, hairSide: сторонаЦвета(hairAim),
    hairLen: String(o.hairLen || meta.hair_len || '').trim() || null,
    // Кадр, на котором ПЕРВЫЙ раз виден результат: у карточных семей второй кадр занят
    // инфографикой, поэтому результат на третьем (тот же расчёт, что в promptkit.resultFrame).
    cardFrame: t.frame2 === 'card',
    // ═══ ЧТО ДЕЙСТВИТЕЛЬНО СТОИТ НА КАДРАХ 3 И 4 ════════════════════════════════════════════
    // ЖИВОЙ БРАК, ПОЙМАННЫЙ ГЛАЗАМИ НА ПРОБЕ (посты 07 и 09, шаблон img-heart-hair). В meta лежат
    // loc3 и loc4, и подпись честно говорила «дальше я среди башен и в ванной вечером», а на кадрах
    // тренда сердечек стоят арт с сердечками, МОКАП ТЕЛЕФОНА и тот же арт с плашкой: девушки ни в
    // одной локации нет вовсе. Локация в meta это то, что заказывалось пулом, а не то, что видно.
    // Поэтому право говорить про место даёт КОНТРАКТ ШАБЛОНА, а не наличие поля:
    //   • карточные семьи: кадр 3 это образ в локации, кадр 4 это чистое фото в другой локации;
    //   • тренд сердечек и весь арт: последний кадр это тот же арт с плашкой (frame4source
    //     'frame2'), а третий это мокап телефона, значит про локации молчим.
    phoneFrame: meta.frame3_phone === true || t.kind === 'hearts',
    место3НаКадре: Boolean(фразаМеста(loc3)) && !(meta.frame3_phone === true || t.kind === 'hearts'),
    место4НаКадре: Boolean(фразаМеста(loc4)) && t.frame4source === 'cleanphoto',
    seed: String(o.seed || meta.post_id || meta.factory_order || `${template}|${hook}|${loc3 || ''}`),
  };
}

// ═══ БЛОК 1. ПЕРВАЯ СТРОКА: ЧТО ВЫШЛО + СРАЗУ КУДА СМОТРЕТЬ ═════════════════════════════════
// ПЕРЕСБОРКА 14.08. Начальник посмотрел живой выход по золотому часу («обычное селфи из галереи, а
// потом золотой час, и я залипла, сам промпт ниже») и сказал дословно: «онтологически сами описания
// очень слабы, они не про настоящий тикток, а про нашу выдумку… нужно посмотреть, что делают и
// пишут конкуренты». И задал структуру: «цепляющий хук + сразу призыв… и вторая часть это само
// описание, там пару предложений где и как сделать… и после 5 хештегов по теме».
//
// РАЗВЕДКА ПО СВОЕЙ ЖЕ БАЗЕ, А НЕ ПО ВКУСУ. Радар копит подписи чужих постов ниши в radar_posts
// (139 живых подписей с лайками). Структура у ВСЕХ лидеров одна и та же, дословно:
//   «Где сделать такое же фото?👇🏻🖤»       90 000 лайков → 1. в … 2. грузим фото 3. вставляем промпт
//   «я без слов 👩🏼‍🦰💔 как сделать 👇🏼»       87 000 → 1. заходим в бот 2. загружаем фото 3. промпт
//   «Хочешь такой же атмосферный портрет? Промт оставила в описании 👇🏻»   84 000
