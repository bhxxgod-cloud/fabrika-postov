// повторить», хвост). Единственной связью с постом был выбор пула по шаблону и проверка «подпись не
// повторяет хук». Про кадры подпись не знала НИЧЕГО: ни локации, ни образа, ни цвета волос, ни того,
// какой результат показан. Отсюда живой брак: под кадром девушки в кафе в жёлтом пиджаке (пост
