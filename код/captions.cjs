// начальник забраковал дословно («вот этот текст пизда полная, там хуета»).
const БОЛЕЗНИ_ПОДПИСИ = [
  // Болезнь 2: опись слайдов вместо речи. Человек не нумерует свои же кадры.
  [/на (втор|трет|четвёрт|последн)\w*\s+(кадре|слайде)|(втор|трет|четвёрт)ой кадр|а последний |листай/i,
    'опись слайдов («на втором кадре…, третий…, а последний…»): это оглавление, а не рассказ'],
  // Болезнь 1: пассив «мне сделали». Тот же диагноз, что у хуков (hooks.cjs, болезнь 2).
  [/мне (выкатили|поставили|собрали|разобрали|расписали|разложили|подобрали|определили|примерили|сделали|оценили)(?![а-яё])/i,
    'пассив «мне сделали»: звучит как отзыв о салонной услуге, писать активно и от себя'],
  // Внутренняя кухня: наши слова о продукте, зритель их не знает (та же болезнь 3 у хуков).
  [/(^|[^а-яё])(вердикт\w*|разбор\w*|пункт\w*|скоринг\w*|цветотип\w*)(?![а-яё])/i,
    'внутренняя кухня или термин без расшифровки («разбор», «вердикт», «пункт», «цветотип»)'],
  // Денежный оффер: единственная строка, по которой пост читается как реклама с первого взгляда.
  // «БЕСПЛАТНЫЙ ПРОМПТ» ВЫВЕДЕН ИЗ-ПОД ЗАПРЕТА (14.08, приказ начальника дословно: «мы промпт
  // чередуем с другими словами аля инструкция / как сделать сказала ниже / ссылка на бесплатный
  // промпт в профиле»). Разница по существу, а не поблажка: запрет ловил ОФФЕР («попытки
  // бесплатные», «за регу дают 50 ₽») — обещание денежной выгоды за регистрацию, по которому пост
  // читается объявлением. «Бесплатный промпт» описывает то, что человек получит в описании, и в
  // живых подписях ниши стоит открытым текстом. Всё остальное — ₽, регистрация, «бесплатно» само по
  // себе — запрещено как было, поэтому лукахед узкий и только на слово «промпт».
  // ОКОНЧАНИЕ ЗАДАНО КЛАССОМ [а-яё], А НЕ \w: в JS \w это [A-Za-z0-9_] и кириллицу не берёт, поэтому
  // «бесплатн\w*» съедало пустую строку, и лукахед смотрел на «ый» вместо пробела перед «промпт».
  // Та же грабля, что уже ловили в firstcomment с границей слова через \b (см. учение «JS \b + кириллица»).
  [/\d+\s*₽|за регу|регистрац[а-яё]*|бесплатн[а-яё]*(?![а-яё])(?!\s+промпт)|попытки бесплатные/i,
    'деньги и регистрация в подписи: это дословные маркеры рекламы, оффер живёт на сайте и в сторис'],
  // Маркеры рекламных подписей, они же клише из разведки («секрет, который скрывают»).
  [/(^|[^а-яё])(секрет\w*|лайфхак\w*|способ\w*|топ)(?![а-яё])/i,
    'рекламное слово («секрет», «лайфхак», «способ», «топ»)'],
  // Похвальба и превосходные степени: «лучший кадр за год», «лучше съёмки».
  [/лучш(ий|ее|ая|е всего|е всех)\s+(кадр|фото|съёмк)|обошёл все мои|никогда так не нравилась/i,
    'похвальба и превосходная степень: читается как реклама самой себя'],
  [/!/, 'восклицательный знак: живой текст в ленте пишется без него'],
];
// ИМПЕРАТИВЫ ПРИЗЫВА: по ним считаем, что призыв в подписи РОВНО ОДИН. Два призыва гасят друг
// друга, поэтому путь к нам сформулирован утверждением, а не «ищи в яндексе».
const ИМПЕРАТИВЫ = /(^|[^а-яё])(сохрани|сохраняй|сохраните|отправь|отправьте|перешли|скинь|ищи|ищите|набери|наберите|загрузи|загрузите|листай|листайте|напиши|напишите|оставь|оставьте|загляни|заглядывай|читай|попробуй|попробуйте|повтори|повторите|делай|сделай)(?![а-яё])/gi;

function assertCaption(text, F, опции = {}) {
  const t = String(text);
  const беда = (s) => { throw new Error(`captions: ${s}`); };
  const кусок = (re) => { const m = re.exec(t); return m ? `«${t.slice(Math.max(0, m.index - 20), m.index + 25).replace(/\n/g, ' ')}»` : ''; };
  if (/\$\{[^}\n]{1,40}\}/.test(t)) беда(`в подписи осталась заглушка ${кусок(/\$\{[^}\n]{1,40}\}/)}`);
  if (/[\\/]/.test(t)) беда(`в подписи есть слеш, это след разметки, а не речь: ${кусок(/[\\/]/)}`);
  if (/https?:|www\.|[a-zа-я0-9-]+\.(ru|pro|com|net|org|рф)(?![а-яёa-z])/i.test(t)) {
    беда('в подписи ссылка, а ссылка живёт только в сторис');
  }
  for (const [re, слово] of ЗАПРЕТ_СЛОВ) if (re.test(t)) беда(`в подписи запрещённое слово «${слово}»`);
  for (const [re, что] of ПРИМАНКИ) if (re.test(t)) беда(`в подписи приманка вовлечения (${что}), её режет площадка`);
  // Теги считаем отдельно: #бьютигайд это тег, а не слово «гайд» в речи, и хвост тегов не должен
  // ронять подпись по болезням тела (в тегах нет ни пассива, ни описи слайдов).
  const тело0 = t.replace(/(^|\n)#[^\n]*$/g, '').trim();
  for (const [re, что] of БОЛЕЗНИ_ПОДПИСИ) if (re.test(тело0)) беда(`${что}: ${кусок(re)}`);
  if (!differsFromHook(t, F.hook)) беда('подпись повторяет хук с первого кадра');
  // ═══ СЛОВО «КАДР» И ЭМОДЗИ ══════════════════════════════════════════════════════════════════
  // «кадр» стояло в живом выходе четыре раза на три строки: оно живёт сразу в нескольких пулах и
  // склеивает текст. Эмодзи один и тот же (🖤) стоял в 11 из 18 заголовков подписи: на сотнях постов
  // разных аккаунтов это опознавательный знак сетки, ровно как повтор хука.
  const кадров = (тело0.match(/(^|[^а-яё])кадр\w*(?![а-яё])/gi) || []).length;
  if (кадров > 2) беда(`слово «кадр» в подписи ${кадров} раза, предел два: оно склеивает текст`);
  const эмодзи = [...тело0].filter((ch) => /\p{Extended_Pictographic}/u.test(ch));
  if (эмодзи.length > 1) беда(`эмодзи в подписи ${эмодзи.length}, предел один (${эмодзи.join('')})`);
  // ═══ ОДИН ПРИЗЫВ НА ПОДПИСЬ ═══════════════════════════════════════════════════════════════
  const призывы = t.match(ИМПЕРАТИВЫ) || [];
  if (призывы.length > 1) {
    беда(`в подписи ${призывы.length} призыва (${призывы.map((x) => x.trim()).join(', ')}), `
      + 'а работает ровно один: два призыва гасят друг друга');
  }
  // ═══ ДЛИНА ══════════════════════════════════════════════════════════════════════════════════
  // ПЕРВАЯ СТРОКА. Кульминация обязана попасть ДО обрезки: в ленте видно около 125 знаков, во
  // вкладке рилсов 55-60, безопасное окно по замерам 70-96. Поэтому первая строка короткая в обоих
  // режимах, и это важнее общей длины: по живым цифрам длина сама ничего не решает.
  const строка1 = t.split('\n')[0];
  const порогСтроки = опции.режим === 'reels' ? 96 : 110;
  if (строка1.length > порогСтроки) {
    беда(`первая строка подписи ${строка1.length} знаков, а до обрезки видно ${порогСтроки}: `
      + `кульминация не доедет до читателя. Строка: «${строка1}»`);
  }
  // ═══ ПРОВАЛЬНАЯ ЗОНА 51-125 ЗНАКОВ ══════════════════════════════════════════════════════════
  // Самое полезное число всей разведки (PostPlanify, 4 408 постов): медианный ER по длине подписи
  // 1-50 знаков 6,23%, 51-125 знаков 2,04%, 126-300 знаков 3,94%. Середина хуже и коротких, и
  // длинных: это «полторы фразы, которые ни хука не дают, ни смысла». Наши прежние подписи лежали
  // ровно там первым абзацем. Правило: либо ультракоротко, либо содержательно, между — никогда.
  const основной = опции.основной || тело0;
  if (основной.length > 50 && основной.length < 126) {
    беда(`подпись ${основной.length} знаков, это провальная зона 51-125 (медианный ER там вдвое `
      + 'ниже): либо короче 50, либо содержательнее 126');
  }
  // ОСНОВНОЙ ТЕКСТ БЕЗ ТЕГОВ: рилс 150-300 (за 300 медианный охват падает втрое, 141 против 380),
  // карусель 200-500. Потолок жёсткий, нижняя граница проверяется мягко: блок мог не собраться,
  // потому что факта не было, и это законное поведение модуля.
  const потолок = опции.режим === 'reels' ? 300 : 500;
  if (основной.length > потолок) {
    беда(`основной текст ${основной.length} знаков при потолке ${потолок} для режима `
      + `«${опции.режим || 'carousel'}»`);
  }
  // ЖИВОЙ ТЕКСТ: строчными и без точки в конце. Заглавная в начале и точка в конце это школьное
  // сочинение, а не подпись девочки в ленте (правило из ЛОГИКА-ХУКА, перенесено на подпись).
  if (/^[А-ЯЁA-Z]/.test(строка1)) беда(`первая строка начинается с заглавной: «${строка1.slice(0, 30)}»`);
  if (/\.$/.test(основной.trim())) беда('точка в конце подписи: живой текст её не ставит');
  // ТЕМА. Оценка внешности не говорит про подбор макияжа, и наоборот.
  // КЛЮЧЕВОЕ СЛОВО ТЕМЫ ОБЯЗАНО БЫТЬ, И ЭТО НЕ КОСМЕТИКА: по нему пост находят внутренним поиском
  // площадки, а с июля 2025 публичные посты профессиональных аккаунтов индексируются ещё и гуглом.
  // НО СЛОВО ТЕПЕРЬ ЧЕЛОВЕЧЕСКОЕ: «разбор» и «цветотип» из списка убраны, потому что они же стоят
  // в списке болезней (внутренняя кухня и термин). Ключ обязан быть там, где он естественен в речи.
  // «БЕЗ МАКИЯЖА» ЭТО НЕ ПРО МАКИЯЖ (12.08, живой отказ на пробе): зацеп «сфоткалась как есть, без
  // макияжа» описывает кадр 1 и никакого подбора косметики не обещает, а проверка ловила слово и
  // браковала годную подпись. Отрицание вырезаем перед проверкой.
  const проМакияж = t.replace(/без макияжа|ни макияжа|без косметики|не крашусь/gi, ' ');
  if ((F.тема === 'report' || F.тема === 'guide' || F.тема === 'nose')
      && /макияж|помад|тушь|стрелк/i.test(проМакияж)) {
    беда('пост это оценка внешности, а подпись про макияж');
  }
  if (F.тема === 'report' && !/оценк|балл|черт|пропорц|лиц/i.test(t)) {
    беда('пост это оценка лица, а подпись про оценку молчит');
  }
  if (F.тема === 'nose' && !/нос(?![а-яё])|носа|носу|профил/i.test(t)) {
    беда('пост про нос, а подпись про нос молчит');
  }
  if (F.тема === 'colortype' && !/оттен|палитр|цвет/i.test(t)) {
    беда('пост про подбор оттенков, а подпись про оттенки молчит');
  }
  if (F.тема === 'haircut' && !/стрижк|длин|чёлк|каре|волос/i.test(t)) {
    беда('пост про примерку стрижки, а подпись про стрижку молчит');
  }
  if (F.тема === 'hearts' && !/сердеч/i.test(t)) беда('пост про сердечки из волос, а подпись о них молчит');
  // ОБРАЗ. Люкс-слова только при люкс-образе, школьный тон только при обычном.
  if (F.tier !== 'lux' && ЛЮКС_СЛОВА.test(t)) беда(`образ обычный, а подпись про люкс: ${кусок(ЛЮКС_СЛОВА)}`);
  if (F.tier === 'lux' && ШКОЛА_СЛОВА.test(t)) беда('образ дорогой, а подпись строит из себя школьницу');
  // МЕСТО, КОТОРОГО НА КАДРЕ НЕТ, НАЗЫВАТЬ НЕЛЬЗЯ. Заказанная локация лежит в meta даже у тренда
  // сердечек, где кадры 3 и 4 это мокап телефона и арт с плашкой. Проверяем прямо: фраза локации не
  // должна попасть в подпись, если по контракту шаблона этой локации на кадрах не видно.
  if (F.place3 && !F.место3НаКадре && t.includes(F.place3)) {
    беда(`подпись называет место кадра 3 («${F.place3}»), а на кадре мокап телефона или арт`);
  }
  if (F.place4 && !F.место4НаКадре && t.includes(F.place4)) {
    беда(`подпись называет место последнего кадра («${F.place4}»), а последний кадр это арт с плашкой`);
  }
  // МЕСТО. Про дом говорим только если дом действительно на кадрах.
  // САМИ ФРАЗЫ ЛОКАЦИЙ ИЗ ПРОВЕРКИ ВЫРЕЗАНЫ (12.08, живой отказ на пробе): в заказе локации стояло
  // «во дворе-колодце старого дома днём», проверка увидела в нём слово «дома» и забраковала годную
  // подпись, где ни про какой дом речи не было. Локация это дословный факт кадра, судить надо ТО,
  // ЧТО НАПИСАЛИ МЫ, а не то, как называется двор.
  const безЛокаций = [F.place3, F.place4].filter(Boolean)
    .reduce((s, p) => s.split(p).join(' '), t);
  const домаНаКадрах = (F.scene3 === 'home' && F.место3НаКадре) || (F.scene4 === 'home' && F.место4НаКадре);
  if (!домаНаКадрах && /(^|[^а-яё])дома(?![а-яё])/i.test(безЛокаций) && (F.scene3 || F.scene4)) {
    беда('на кадрах улица и город, а подпись говорит про дом');
  }
  if (F.scene3 && F.scene3 !== 'home' && F.scene4 && F.scene4 !== 'home'
      && /вечером дома|у себя в комнате/i.test(t)) {
    беда('ни один кадр не снят дома, а подпись про дом вечером');
  }
  return t;
}

// ═══ БЛОК 5. ХЕШТЕГИ: ИХ ЧИСЛО РЕШАЕТ ПЛОЩАДКА, А НЕ ВКУС ═══════════════════════════════════
// ЗАМЕРЫ РАЗВОДЯТ ПЛОЩАДКИ В РАЗНЫЕ СТОРОНЫ, поэтому и настройка разная:
//   • инстаграм: Metricool, 24 364 803 поста и 375 118 аккаунтов — пост хотя бы с одним хештегом
//     получает на 31,7% МЕНЬШЕ просмотров и на 33,9% меньше взаимодействий. Socialinsider на 35 млн
//     постов даёт обратный знак (+12,6% охвата), то есть эффект слабый и спорный. Держим МИНИМУМ:
//     до 3 тегов при физическом лимите площадки в 5 (с 18.12.2025);
//   • тикток: Metricool, 2 314 756 постов — хештеги дают +5% просмотров и +9% взаимодействий,
//     рекомендация самой площадки 1-2 конкретных описательных тега. Держим 2.
// В живом выходе стояло 5 тегов на обеих площадках: для инстаграма это худший из замеренных
// вариантов, для тиктока просто мимо рекомендации.
// ПЯТЬ ТЕГОВ ВЕЗДЕ (13.08, прямой приказ начальника: «стало 2 хештега вместо 5 — исправь»).
// Замеры Metricool выше остаются в комментарии как знание, но приказ свежее замера. Разведка
// конкурентов 13.08 тоже за 3-5: у аккуратных лидеров жанра ровно столько.
const ТЕГОВ_ПО_ПЛОЩАДКЕ = { reels: 5, instagram: 5, tiktok: 5 };
function лимитТегов(o, режим) {
  if (Number.isFinite(Number(o.tagLimit))) return Math.max(0, Number(o.tagLimit));
  const п = String(o.platform || '').toLowerCase();
  if (ТЕГОВ_ПО_ПЛОЩАДКЕ[п] !== undefined) return ТЕГОВ_ПО_ПЛОЩАДКЕ[п];
  return режим === 'reels' ? ТЕГОВ_ПО_ПЛОЩАДКЕ.reels : ТЕГОВ_ПО_ПЛОЩАДКЕ.tiktok;
}
/** Обрезка строки тегов до лимита площадки. Вызывающий волен отдать сколько угодно, режем здесь. */
function подрезатьТеги(tags, лимит) {
  const все = String(tags || '').trim().split(/\s+/).filter((x) => x.startsWith('#'));
  return все.slice(0, лимит).join(' ');
}

/**
 * Подпись поста из фактов.
 * @param {object} o см. collectFacts, плюс:
 * @param {string} o.marker слово-маркер площадки, ТОЛЬКО из templates.frame4Marker
 * @param {string} o.tags строка хештегов (её собирает вызывающий по пулу шаблона)
 * @returns {string}
 */
function buildCaption(o = {}) {
  // НОВАЯ ЛОГИКА ВЛАДЕЛЬЦА (15.08 вечер): подпись это ПРОДОЛЖЕНИЕ хука обложки, хранится парой
  // рядом с хуком в hooks2.cjs, отдельного мешка нет. Если хук известен там, подпись берём оттуда
  // целиком (первая строка + «где и как» + 5 тегов; тикток с заголовком и шагами). Старая сборка
  // ниже остаётся для чужих хуков и как фолбэк. Выключатель HOOKS_V2=0 только под замер.
  if (process.env.HOOKS_V2 !== '0') {
    try {
      const H2 = require('./hooks2.cjs');
      const pair = H2.известен(o.template) ? H2.pairFor(o.template, o.hook) : null;
      if (pair) {
        const pl = String(o.platform || '') === 'reels' || String(o.mode || '') === 'reels' ? 'instagram' : 'tiktok';
        const t = H2.caption(o.template, pair, pl, { id: o.seed || o.id, marker: o.marker });
        if (t) return t;
      }
    } catch (e) { console.log(`  ⚠ hooks2 подпись не собралась (${String(e.message).slice(0, 80)}), беру старую сборку`); }
  }
  const F = collectFacts(o);
  const marker = String(o.marker || '').trim();
  if (!marker) {
    throw new Error('captions: слово-маркер не передан. Его отдаёт только templates.frame4Marker(platform), '
      + 'руками писать нельзя: по нему мы отличаем трафик тиктока от инстаграма');
  }
  // ═══ РЕЖИМ СБОРКИ: КАРУСЕЛЬ ИЛИ РИЛС ════════════════════════════════════════════════════════
  // Замеры площадки: во вкладке рилсов видно 55-60 знаков подписи против 125 в ленте, а оптимум
  // основного текста рилса 150-300 знаков. Наши прежние подписи были в разы длиннее, то есть под
  // рилс они технически бесполезны: до обрезки не доезжала даже мысль. Поэтому режимов ДВА, и в
  // обоих главное это КОРОТКАЯ ПЕРВАЯ СТРОКА (безопасное окно 70-96 знаков), а не короткий текст:
  // по живым цифрам длина сама ничего не решает, решает механика.
  const режим = String(o.mode || (String(o.platform || '') === 'reels' ? 'reels' : 'carousel'));
  if (режим !== 'reels' && режим !== 'carousel') {
    throw new Error(`captions: неизвестный режим подписи «${режим}», знаю carousel и reels`);
  }
  // СТИЛЬ. 'facts' это разговор от себя, 'dispute' это механика спора с нейросеткой (признание
  // сомнения, частичное согласие, спор, вопрос зрителю), которая на живых постах конкурентов даёт
  // комментарии. Спор про разбор от нейросети имеет смысл только у карточных тем: у сердечек и арта
  // нейросеть ничего не «говорит», спорить не с чем, поэтому там всегда факты.
  const стильЗапрошен = String(o.style || 'facts');
  const стиль = (стильЗапрошен === 'dispute' && ['report', 'nose', 'guide', 'colortype', 'haircut'].includes(F.тема))
    ? 'dispute' : 'facts';
  // ПРИЗЫВ ПО УМОЛЧАНИЮ ТЕПЕРЬ ВОПРОС, И ЭТО ГЛАВНАЯ ПРАВКА ФИНАЛА (12.08). Было: карусель на
  // «сохрани», рилс на «отправь». Вопрос даёт +36,7% комментариев в инстаграме и +26,2% в тиктоке и
  // не читается как просьба о действии, а просьба о действии это профиль engagement bait у Meta.
  // save и send остались рычагами под замер: их передаёт вызывающий явно.
  const типПризыва = String(o.cta || 'question');
  if (!ПРИЗЫВЫ.includes(типПризыва)) {
    throw new Error(`captions: неизвестный призыв «${типПризыва}», знаю: ${ПРИЗЫВЫ.join(', ')}. `
      + 'Кодовое слово в комментариях («напиши слово, пришлю шаблон») выключено совсем: это дословный '
      + 'пример, который площадка называет причиной не рекомендовать пост');
  }
  // ТЕГИ ВЫКЛЮЧАЮТСЯ ЯВНО, А НЕ МОЛЧА (11.08). У трёх постов конкурентов с подтверждённым залётом
  // тегов не было вовсе, а теги нашлись только у слабых, но причинность не доказана. Поэтому это
  // ПЕРЕКЛЮЧАТЕЛЬ под замер (opts.noTags или CAPTION_NOTAGS=1), а не удаление тегов из проекта.
  const безТегов = o.noTags === true || /^(1|true|yes)$/i.test(String(process.env.CAPTION_NOTAGS || ''));
  const теги = безТегов ? '' : подрезатьТеги(o.tags, лимитТегов(o, режим));

  // ПУТЬ К НАМ В ПОДПИСИ НЕ НУЖЕН, когда он уезжает в первый комментарий: иначе в одном тексте два
  // адреса, и человек не понимает, куда идти.
  const безПути = типПризыва === 'comment';
  const части = стиль === 'dispute'
    ? спорСНейронкой(F, marker, режим, безПути)
    : фактыБлоками(F, marker, режим, безПути);
  let блоки = части.concat([призыв(F, типПризыва, стиль)]).filter((b) => b && String(b).trim());
  // ═══ УКЛАДКА РИЛСА В 300 ЗНАКОВ ═════════════════════════════════════════════════════════════
  // Режем не по буквам, а БЛОКАМИ, и только середину: первая строка и призыв неприкосновенны, потому
  // что первая строка это всё, что человек видит до обрезки, а призыв это то, ради чего подпись
  // вообще есть. Из середины уходит самый длинный блок, то есть в тексте остаётся самое короткое и
  // самое конкретное.
  const склейка = (b) => b.join('\n\n');
  while (режим === 'reels' && склейка(блоки).length > 300 && блоки.length > 2) {
    let худший = 1;
    for (let i = 1; i < блоки.length - 1; i++) if (блоки[i].length > блоки[худший].length) худший = i;
    блоки = блоки.filter((_, i) => i !== худший);
  }
  const основной = склейка(блоки);
  const text = теги ? `${основной}\n\n${теги}` : основной;
  assertCaption(text, F, { режим, типПризыва, основной });
  return text;
}

/**
 * Блоки подписи в стиле «факты»: первая строка → деталь → шаги → финал (его добавляет вызывающий).
 *
 * ПОРЯДОК ИЗМЕНИЛСЯ 14.08 ВСЛЕД ЗА ЖАНРОМ. Было «первая строка → две детали по кадрам → путь». Стало
 * «первая строка → одна деталь → шаги»: у живых лидеров ниши сразу после первой строки идёт
 * инструкция, потому что за ней человек и открыл описание. Наши детали при этом никуда не делись,
 * но их теперь ОДНА и только у карусели: рилс с потолком в 300 знаков обязан отдать место шагам.
 *
 * ДЕТАЛЬ ОСТАЛАСЬ РАДИ ПРИКАЗА 11.08 («если у нас волосы разные стали, можно написать, что я бы
 * никогда не сказала, что покрашусь после тренда в тт»): смена цвета волос стоит первой в списке
 * деталей, поэтому при покраске в подпись попадает именно она. Нет факта — нет и блока, это главное
 * правило модуля, и тогда подпись выходит ровно жанровой: результат, шаги, вопрос, теги.
 */
function фактыБлоками(F, marker, режим, безПути) {
  const шаги = безПути ? null : какСделать(F, marker, режим);
  const деталь = режим === 'reels' ? '' : тело(F, 1);
  return [перваяСтрока(F, режим), деталь, шаги].filter(Boolean);
}

// ═══ СТИЛЬ «СПОР С НЕЙРОНКОЙ» ═══════════════════════════════════════════════════════════════
// Механика взята с живого поста конкурента, который делает ровно наше и НЕ скрывает нейросеть, а
// спорит с ней: признание сомнения, потом частичное согласие, потом прямое несогласие, потом вопрос
// зрителю. То же самое дало миллионы западным сканерам внешности («фильтр врёт»). Факты внутри
// остаются нашими: тема, места кадров, смена цвета волос.
// ПЕРВАЯ СТРОКА У СПОРА ТА ЖЕ, ЧТО У ФАКТОВ (12.08): приказ про кадр 1, тренд и обещание промпта
// действует на любой стиль, спор живёт в блоке детали. Слов «разбор» и «пункт» здесь больше нет:
// они в списке болезней (внутренняя кухня), и валидатор на них падает.
const СОГЛАСИЕ = {
  report: 'сначала мне было смешно, что цифру за моё лицо ставит машина, а потом она попала точнее, чем я ждала',
  nose: 'сначала я села спорить, а по старым фото вышло ровно то же самое',
  guide: 'сначала мне было смешно, что мне будут объяснять, как мне лучше выглядеть, а местами она попала в меня',
  colortype: 'сначала я не поверила, что мои оттенки другие, а потом сравнила с косметичкой',
  haircut: 'сначала я не поверила, что мне пойдёт такая длина, а потом сидела и прикидывала',
};
const НЕСОГЛАСИЕ = ['но кое-где я с ней спорю до сих пор',
  'но одну строчку я ей не отдам, там она мимо',
  'но с одним я не согласна, и это не изменится'];
const ВОПРОС_ДОВЕРИЯ = ['а ты бы отдала своё фото на такую оценку или страшно',
  'ты бы поверила машине или своим глазам'];
function спорСНейронкой(F, marker, режим, безПути) {
  const согласие = СОГЛАСИЕ[F.тема] || СОГЛАСИЕ.guide;
  const несогласие = берём(НЕСОГЛАСИЕ, F.seed, 'несогласие');
  // Факт про кадры оставляем: он привязывает спор к тому, что видно.
  const факт = режим === 'reels' ? (волосы(F) || null) : (тело(F, 1) || null);
  return [перваяСтрока(F, режим), [согласие, несогласие].join('. '), факт,
    безПути ? null : какСделать(F, marker, режим)].filter(Boolean);
}

// ═══ МОДЕЛЬ КАК НЕОБЯЗАТЕЛЬНОЕ УЛУЧШЕНИЕ ════════════════════════════════════════════════════
// Сборка выше работает БЕЗ модели, и это главное: OpenRouter сейчас отвечает 402. Модель может
// только переписать готовый текст живее, и на любую беду мы возвращаем исходную подпись. Проверки
// прогоняются заново: текст от модели такой же подозреваемый, как текст из пула.
async function polish(text, F, o = {}) {
  const key = process.env.OPENROUTER_API_KEY || '';
  if (!/^(1|true|yes)$/i.test(String(process.env.CAPTION_LLM || '')) || !key) return text;
  try {
    const r = await fetch('https://openrouter.ai/api/v1/chat/completions', {
      method: 'POST',
      headers: { 'content-type': 'application/json', authorization: `Bearer ${key}` },
      body: JSON.stringify({
        model: o.model || 'google/gemini-2.0-flash-001',
        messages: [{ role: 'user', content: 'Перепиши подпись к посту живее, от первого лица, тем же '
          + 'смыслом и теми же фактами. Ничего не добавляй: ни ссылок, ни новых мест, ни цифр. '
          + 'Запрещены слова «просто», «шок», «вау» и символ слеша. Верни только текст.\n\n' + text }],
      }),
    });
    if (!r.ok) return text;
    const j = await r.json();
    const out = String(((j.choices || [])[0] || {}).message?.content || '').trim();
    if (!out) return text;
    return assertCaption(out, F);
  } catch { return text; }
}

// ЗАДЕЛ ПОД НЕПОДТВЕРЖДЁННОЕ (11.08). Говорят, что с 18 июня можно давать РАЗНУЮ подпись каждому
// слайду карусели, и что карусель показывается повторно с другой картинкой. Проверки руками ещё нет,
// поэтому кода под это НЕТ, но сборка уже разложена на блоки: фактыБлоками и спорСНейронкой отдают
// массив блоков, и подпись под конкретный слайд это выбор блока из того же массива, без переписывания
// модуля. Наружу отдаём и блоки, чтобы такой вызов появился одной функцией, а не правкой сборки.
function captionParts(o = {}) {
  const F = collectFacts(o);
  const marker = String(o.marker || '').trim();
  const режим = String(o.mode || (String(o.platform || '') === 'reels' ? 'reels' : 'carousel'));
  const стиль = String(o.style || 'facts') === 'dispute' ? 'dispute' : 'facts';
  return { facts: F, blocks: стиль === 'dispute' ? спорСНейронкой(F, marker, режим, false)
    : фактыБлоками(F, marker, режим, false) };
}

// ═══ ПОВТОР НАЧАЛ: ДВАДЦАТЬ ПОСТОВ НЕ ИМЕЮТ ПРАВА НАЧИНАТЬСЯ ОДИНАКОВО ══════════════════════
// Правило и арифметика взяты у хуков (hooks.cjs, болезнь 5 и функция частыеНачала): считаем по ДВУМ
// первым словам, знаки препинания и эмодзи не в счёт, предел два. Причина та же и она про нас
// вдвойне: с апреля 2026 правило неоригинальности у инстаграма расширено с рилсов на фото и
// карусели, и одинаковое начало подписи на пятнадцати аккаунтах это ровно тот узор, который оно
// ловит. Здесь функция нужна ДВАЖДЫ: самопроверкой пулов при загрузке модуля (чтобы фразу с
// повторяющимся началом нельзя было дописать руками) и снаружи, чтобы прогнать готовую волну.
const НАЧАЛО_ПРЕДЕЛ = 2;
const началоФразы = (text) => String(text || '').toLowerCase().split('\n')[0]
  .replace(/[^а-яёa-z0-9 ]/gi, ' ').trim().split(/\s+/).slice(0, 2).join(' ');
/** Начала, повторённые чаще предела. @returns {Array<[начало, сколько]>} Пустой массив = чисто. */
function частыеНачала(тексты) {
  const c = new Map();
  for (const t of тексты) { const н = началоФразы(t); if (н) c.set(н, (c.get(н) || 0) + 1); }
  return [...c.entries()].filter(([, n]) => n > НАЧАЛО_ПРЕДЕЛ);
}
/** Ошибки пулов первой строки списком. Пустой массив = пулы валидны. */
function checkПулы() {
  const errs = [];
  const скажи = (пул, m) => errs.push(`captions ${пул}: ${m}`);
  // ПРИЗЫВ К ИНСТРУКЦИИ ПРОВЕРЯЕТСЯ НА ПОВТОР НАЧАЛ ЖЁСТЧЕ ОСТАЛЬНЫХ. Он стоит в КАЖДОЙ первой
  // строке проекта, то есть его однообразие видно на всей ферме разом — ровно та болезнь, из-за
  // которой пул и переписан: раньше все шесть обещаний кончались словом «ниже».
  for (const [н, n] of частыеНачала(ПРИЗЫВ_К_ИНСТРУКЦИИ)) {
    скажи('ПРИЗЫВ_К_ИНСТРУКЦИИ', `${n} фраз начинаются с «${н}», предел ${НАЧАЛО_ПРЕДЕЛ}`);
  }
  for (const [тема, пул] of Object.entries(ХУК_РЕЗУЛЬТАТ)) {
    for (const [н, n] of частыеНачала(пул)) скажи(`ХУК_РЕЗУЛЬТАТ.${тема}`, `${n} фраз с «${н}»`);
  }
  // Болезни тела ловим и в самих пулах: фраза с пассивом или описью слайдов не должна дожить до
  // сборки, иначе её увидит только читатель в ленте.
  const всеФразы = [].concat(ПРИЗЫВ_К_ИНСТРУКЦИИ, ШАГИ_КОРОТКО, ...ШАГИ_ПОЛНО,
    ДЕТАЛЬ_ЭКРАН, ДЕТАЛЬ_МЕСТО, ТОН.lux, НЕСОГЛАСИЕ, ВОПРОС_ДОВЕРИЯ,
    ...Object.values(ХУК_РЕЗУЛЬТАТ), ...Object.values(ВОПРОС_ПО_ТЕМЕ), Object.values(СОГЛАСИЕ),
    Object.values(КОМУ_ОТПРАВИТЬ), ...Object.values(ВОЛОСЫ));
  for (const фраза of всеФразы.flat()) {
    for (const [re, что] of БОЛЕЗНИ_ПОДПИСИ) {
      if (re.test(фраза)) скажи('пул', `«${фраза}»: ${что}`);
    }
    if (/^[А-ЯЁ]/.test(фраза)) скажи('пул', `«${фраза}»: начинается с заглавной`);
  }
  return errs;
}

