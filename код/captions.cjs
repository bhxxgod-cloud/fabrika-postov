function детали(F) {
  const out = [];
  const в = волосы(F);
  if (в) out.push(в);
  if (F.phoneFrame) out.push(берём(ДЕТАЛЬ_ЭКРАН, F.seed, 'экран'));
  // МЕСТО В ТЕЛЕ ТОЛЬКО У ЛЮКСА (13.08, приказ по посту аня-5: «ты не переработал текст»).
  // Разведка 13.08 по 30+ живым подписям лидеров: тело держат ЭФФЕКТ словами и снятие страха,
  // а локация ротора («на крытом рынке в ряду я себя снимаю редко») читается случайной и чужой.
  else if (F.место3НаКадре && F.place3 && F.tier === 'lux') {
    out.push(берём(ДЕТАЛЬ_МЕСТО, F.seed, 'место').replace('${place3}', F.place3));
  }
  // Люкс-кадр правда выглядит дорого, и это ФАКТ по картинке, а не наполнитель: у него тон остаётся.
  if (F.tier === 'lux') out.push(берём(ТОН.lux, F.seed, 'тон'));
  return out.filter(Boolean);
}
function тело(F, сколько) {
  return детали(F).slice(0, сколько).join('. ');
}

