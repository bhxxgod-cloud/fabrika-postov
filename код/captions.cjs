/**
 * Первая строка: что вышло + сразу куда смотреть за инструкцией.
 * Длина держится по замерам (ЛОГИКА-ПОДПИСИ, 3.3): карусель до 110 знаков, рилс до 96.
 * ЖЕРТВУЕМ ПО ПОРЯДКУ: сначала длинным призывом, потом длинным хуком. Призыв не выбрасываем НИКОГДА:
 * без него первая строка перестаёт быть первой строкой жанра и становится просто подписью к фото.
 */
function перваяСтрока(F, режим) {
  const тренд = трендСловами(F);
  const пул = (ХУК_РЕЗУЛЬТАТ[F.тема] || ХУК_РЕЗУЛЬТАТ.art).map((s) => s.replace('${тренд}', тренд));
  const хук = берём(пул, F.seed, 'хук-результат');
  const призыв0 = берём(ПРИЗЫВ_К_ИНСТРУКЦИИ, F.seed, 'призыв-к-инструкции');
  const короткийПризыв = ПРИЗЫВ_К_ИНСТРУКЦИИ.slice().sort((a, b) => a.length - b.length)[0];
  const короткийХук = пул.slice().sort((a, b) => a.length - b.length)[0];
  const предел = режим === 'reels' ? 96 : 110;
  const варианты = [
    `${хук}, ${призыв0}`,
    `${хук}, ${короткийПризыв}`,
    `${короткийХук}, ${короткийПризыв}`,
  ];
  for (const v of варианты) if (v.length <= предел) return v;
  return варианты[варианты.length - 1];
}

