// ═══ ХЭШ ПОСТА ══════════════════════════════════════════════════════════════════════════════
// Та же сумма кодов символов, что у promptkit.hairLenByHash: одна арифметика на весь проект.
function хэш(seed, соль = '') {
  const s = `${соль}|${String(seed || '')}`;
  return Array.from(s).reduce((a, ch) => a + ch.codePointAt(0), 0);
}
// РАЗМАЗЫВАЮЩИЙ ХЭШ ДЛЯ ВЫБОРА ИЗ ПУЛА (12.08). Простая сумма кодов годится, чтобы РАЗВЕСТИ соседние
// посты (у соседей суммы отличаются на единицу, значит и варианты соседние), но она плохо
// РАЗМАЗЫВАЕТ волну: у постов одного шаблона строка сида отличается парой символов, суммы ложатся
// кучно, и на прогоне двадцати постов один и тот же зацеп выпадал пять раз. Здесь взят FNV-1a: он
// такой же детерминированный (один пост всегда даёт одну подпись), но лавинный, и на пробе из 24
// постов число разных начал выросло с 15 до 22.
// СУММУ КОДОВ НЕ ТРОГАЕМ: на ней стоит раздача длины волос (promptkit.hairLenByHash), и её замена
// перетасовала бы уже заказанные образы. Лавинный хэш живёт ТОЛЬКО внутри выбора фраз подписи.
function индекс(seed, соль, n) {
  let h = 2166136261;
  for (const ch of `${соль}|${String(seed || '')}`) {
    h ^= ch.codePointAt(0);
    h = Math.imul(h, 16777619) >>> 0;
  }
  return h % n;
}
/** Выбор из пула по хэшу поста. Соль своя у каждого блока, иначе блоки ходят парами. */
function берём(list, seed, соль) {
  const arr = (list || []).filter(Boolean);
  if (!arr.length) return null;
  return arr[индекс(seed, соль, arr.length)];
}

