//
// СЛУЧАЙНОСТИ В МОДУЛЕ НЕТ. Где выбор всё же нужен, он идёт ПО ХЭШУ ПОСТА (id, а без него хук плюс
// локации плюс шаблон) со своей солью на каждый блок. Один и тот же пост всегда даёт одну и ту же
// подпись, а соседние посты расходятся: это то же правило, по которому раздаются обложки, хештеги и
// длина волос (см. promptkit.hairLenByHash).
//
// МОДЕЛЬ НЕ НУЖНА. OpenRouter сейчас отвечает 402 (кончился баланс), и вся сборка обязана работать
// без модели. Модель тут только НЕОБЯЗАТЕЛЬНОЕ улучшение: асинхронная polish(), которую никто из
