//
// СХЕМА ТЕПЕРЬ ТАКАЯ (обоснование каждого блока в ЛОГИКА-ПОДПИСИ.md, часть 3):
//   [1] ПЕРВАЯ СТРОКА  обязательна   зацеп по кадру 1 + название тренда словами аудитории +
//                                    обещание «промпт ниже». Её читают все, остальное читают не все
//   [2] ДЕТАЛЬ         из факта      ОДНА видимая деталь и реакция на неё, без описи слайдов
//   [3] ПУТЬ К НАМ     обязателен    утверждение «нашла по запросу «нейронка про X» в яндексе»
//   [4] ФИНАЛ          обязателен    вопрос по кадру (императив только как рычаг под замер)
//   [5] ТЕГИ           по площадке   инстаграм и рилс 3, тикток 2
// Длины: первая строка карусель до 110, рилс до 96; весь текст без тегов карусель 200-500, рилс
// 150-300; зона 51-125 знаков запрещена (там медианный ER вдвое ниже, чем по краям).
//
// ГЛАВНОЕ ПРАВИЛО МОДУЛЯ: КАЖДЫЙ БЛОК СОБИРАЕТСЯ ИЗ ФАКТА, А ЕСЛИ ФАКТА НЕТ, БЛОК НЕ СОБИРАЕТСЯ.
// Никаких «подставим что-нибудь похожее»: молчание дешевле вранья, потому что бракуют именно за
// враньё (кадр в дорогом кафе и подпись про детское лицо). Поэтому нет локаций в meta, значит нет
