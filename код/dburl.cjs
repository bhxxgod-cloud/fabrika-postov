'use strict';
// СТРОКА ПОДКЛЮЧЕНИЯ К БАЗЕ: ОДНО МЕСТО ВМЕСТО 189 ЧТЕНИЙ /tmp.
//
// ЗАЧЕМ (14.08, по итогам аудита хрупкости). В ночь 13-14.08 macOS подчистила /tmp, и ферма встала
// ЦЕЛИКОМ — не частично. Главная причина: строку подключения читают 189 файлов проекта, и у 122 из
// них нет вообще никакого запасного пути. Постоянная копия лежит в ~/.neironka/secrets/dburl.txt,
// но о ней знает только boot.sh, а прикладной код про этот путь не слышал. То есть переезд ключей
// в надёжное место спасал ферму лишь при условии, что кто-то помнил запустить boot.sh.
//
// ЧТО ДЕЛАЕТ ЭТОТ ФАЙЛ. Даёт строку по цепочке: переменная окружения → домашняя папка → /tmp.
// Ровно та же цепочка уже работает у ключа модели (onepost.cjs, armValidationKey) и там себя
// оправдала. После этого уборка /tmp перестаёт быть аварией: код сам найдёт копию.
//
// ПОБОЧНО И ВАЖНО: если строка нашлась в надёжном месте, а в /tmp её нет — кладём обратно в /tmp.
// Так продолжают работать те файлы, которые ещё читают /tmp напрямую, и переход можно делать
// постепенно, а не одной правкой в 189 местах.
//
// Использование:  const DBURL = require('./dburl.cjs')();
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');

const ВРЕМЕННЫЙ = '/tmp/dburl.txt';
const ПОСТОЯННЫЙ = path.join(os.homedir(), '.neironka', 'secrets', 'dburl.txt');

let память = null;

/**
 * Строка подключения к базе.
 * @param {boolean} [молча] не бросать исключение, а вернуть пустую строку
 */
function строкаБазы(молча) {
  if (память) return память;

  const изОкружения = String(process.env.DB_PUBLIC_URL || process.env.DATABASE_URL || '').trim();
  if (изОкружения) { память = изОкружения; return память; }

  for (const файл of [ПОСТОЯННЫЙ, ВРЕМЕННЫЙ]) {
    try {
      const s = fs.readFileSync(файл, 'utf8').trim();
      if (!s) continue;
      память = s;
      // Вернуть копию в /tmp, если её там нет: файлы, ещё не переведённые на этот модуль,
      // читают именно оттуда, и без копии они продолжат падать.
      if (файл === ПОСТОЯННЫЙ) {
        try {
          if (!fs.existsSync(ВРЕМЕННЫЙ) || !fs.readFileSync(ВРЕМЕННЫЙ, 'utf8').trim()) {
            fs.writeFileSync(ВРЕМЕННЫЙ, s); fs.chmodSync(ВРЕМЕННЫЙ, 0o600);
            console.log('  · строка базы восстановлена в /tmp из надёжной копии');
          }
        } catch { /* не смогли вернуть — не беда, сами-то работаем */ }
      }
      return память;
    } catch { /* нет файла, идём дальше */ }
  }

  if (молча) return '';
  throw new Error('строки подключения к базе нет нигде: ни в DB_PUBLIC_URL, '
    + `ни в ${ПОСТОЯННЫЙ}, ни в ${ВРЕМЕННЫЙ}. Восстанови из Railway, см. HANDOFF-alina.md`);
}

/** Сохранить строку в надёжное место (зовётся при восстановлении ключей). */
function запомнить(строка) {
  const s = String(строка || '').trim();
  if (!s) return false;
  try {
    fs.mkdirSync(path.dirname(ПОСТОЯННЫЙ), { recursive: true });
    fs.writeFileSync(ПОСТОЯННЫЙ, s); fs.chmodSync(ПОСТОЯННЫЙ, 0o600);
    return true;
  } catch { return false; }
}

module.exports = строкаБазы;
module.exports.строкаБазы = строкаБазы;
module.exports.запомнить = запомнить;
module.exports.ПОСТОЯННЫЙ = ПОСТОЯННЫЙ;
module.exports.ВРЕМЕННЫЙ = ВРЕМЕННЫЙ;

if (require.main === module) {
  const s = строкаБазы(true);
  if (!s) { console.log('строки базы НЕТ нигде'); process.exit(1); }
  console.log('строка базы найдена, длина', s.length);
  console.log('надёжная копия:', fs.existsSync(ПОСТОЯННЫЙ) ? 'есть' : 'НЕТ — сделай запомнить()');
  console.log('копия в /tmp:  ', fs.existsSync(ВРЕМЕННЫЙ) ? 'есть' : 'нет');
}
