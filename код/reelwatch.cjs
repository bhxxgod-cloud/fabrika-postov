'use strict';
// ОТПРАВКА РИЛСОВ В ГРУППУ ПО МЕРЕ НАРЕЗКИ (14.08, приказ владельца «скидывай рилсы в группе по
// мере генерации»).
//
// ЗАЧЕМ ОТДЕЛЬНЫМ СТОРОЖЕМ. Раньше рилсы уходили в группу двумя путями, и оба неудобны: либо
// вручную пачкой через tgblast (владелец видит сотню файлов разом и не может смотреть по ходу),
// либо по одному из onepost вместе с постом — но это работает только когда собирается НОВЫЙ пост,
// а резка старого склада идёт сама по себе и в группу не пишет вообще.
//
// ЧТО ДЕЛАЕТ. Смотрит папку с нарезанными рилсами и отправляет те, которых ещё не отправлял.
// Ничего не режет, не удаляет и в базу не пишет: только читает файлы и шлёт.
//
// ЧЕГО НЕ ДЕЛАЕТ И ПОЧЕМУ.
//   · Не шлёт файл, пока он ДОПИСЫВАЕТСЯ. Резка кладёт mp4 постепенно, и пойманный на середине
//     файл уедет в группу битым. Ждём, пока размер перестанет меняться между заходами.
//   · Не шлёт то, что не прошло приёмочный скан. Скан — последняя проверка перед публикацией, и
//     показывать владельцу заведомый брак незачем: он потратит время на просмотр мусора.
//   · Не шлёт дважды. Реестр в ~/.neironka/reels/tg_sent.txt, он же переживает перезапуск.
//
// Запуск: node reelwatch.cjs <папка> [пауза_сек=60]
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { execFileSync } = require('node:child_process');

const ПАПКА = process.argv[2];
const ПАУЗА = (Number(process.argv[3]) || 60) * 1000;
if (!ПАПКА || !fs.existsSync(ПАПКА)) { console.log('usage: node reelwatch.cjs <папка> [пауза_сек]'); process.exit(1); }

const ХРАНИЛИЩЕ = process.env.VAULT || path.join(os.homedir(), 'Desktop', 'СОКРОВИЩНИЦА-РИЛСЫ');
const РЕЕСТР = path.join(os.homedir(), '.neironka', 'reels', 'tg_sent.txt');
fs.mkdirSync(path.dirname(РЕЕСТР), { recursive: true });
const прочитать = () => new Set((fs.existsSync(РЕЕСТР) ? fs.readFileSync(РЕЕСТР, 'utf8') : '')
  .split('\n').map((s) => s.trim()).filter(Boolean));
const отметить = (имя) => fs.appendFileSync(РЕЕСТР, имя + '\n');

const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
const размеры = new Map();

/** Персона и id поста из имени reel_NN_слот_персона_ID.mp4 — подпись собираем из них. */
function разобрать(имя) {
  const m = имя.match(/^reel_\d+_[a-z0-9]+_(.+?)_([0-9a-f]{8})\.mp4$/);
  return m ? { персона: m[1], пост: m[2] } : { персона: имя.replace(/\.mp4$/, ''), пост: '' };
}

async function заход() {
  const отправлено = прочитать();
  const файлы = fs.readdirSync(ПАПКА).filter((f) => f.endsWith('.mp4') && !отправлено.has(f)).sort();
  for (const f of файлы) {
    const п = path.join(ПАПКА, f);
    let ст; try { ст = fs.statSync(п); } catch { continue; }
    // ФАЙЛ ДОПИСЫВАЕТСЯ — ЖДЁМ. Размер, не изменившийся с прошлого захода, означает, что ffmpeg
    // закрыл файл. Иначе в группу уезжает обрезанное видео, и это выглядит как брак сборки.
    const прошлый = размеры.get(f);
    размеры.set(f, ст.size);
    if (прошлый === undefined || прошлый !== ст.size) continue;
    if (ст.size < 200 * 1024) continue;               // заведомо недописанный или пустой

    // ПРИЁМОЧНЫЙ СКАН ПЕРЕД ОТПРАВКОЙ. Показывать владельцу заведомый брак незачем.
    // УПАВШИЙ СКАН — НЕ «ПРОШЁЛ» (аудит 15.08). Было: catch { скан = '' } → /⛔/.test('') = false →
    // рилс шёл в годные и в группу как чистый. Нет python/easyocr/yunet — весь брак тихо
    // признавался годным. Теперь скан, который не отработал, кладёт рилс в отсев «скан-не-прошёл»
    // на просмотр: неизвестно ≠ хорошо.
    let скан = '';
    let сканУпал = false;
    try {
      скан = execFileSync('node', [path.join(__dirname, 'reelscan.cjs'), п],
        { cwd: __dirname, encoding: 'utf8', timeout: 120000 });
      if (!/ИТОГ:/.test(скан)) сканУпал = true;   // скан не дошёл до итога — вывод неполный
    } catch { сканУпал = true; }
    if (сканУпал) скан = '⛔ скан не отработал (окружение или таймаут) — на просмотр';
    // В СОКРОВИЩНИЦУ ПОПАДАЕТ КАЖДЫЙ РИЛС, И ПРОШЕДШИЙ, И НЕТ (14.08, задача владельца: «1 папка
    // будет чтобы хранить все наше сокровище, будет туда каждый рилс идти и в свои прежние
    // папки»). Прошедший скан идёт в «годные», не прошедший — в «отсев» под своей причиной,
    // чтобы приговор был виден и обратим. Кладём ЖЁСТКОЙ ССЫЛКОЙ: это тот же файл под вторым
    // именем, места не занимает. Разбор — в reelvault.cjs, который разложил старые 1661 штуку.
    const плохой = /⛔/.test(скан);
    const причинаСкана = плохой
      ? (скан.match(/⛔.*/) || [''])[0].replace(/\s+/g, ' ').slice(0, 40).replace(/[^\wа-яА-ЯёЁ -]/g, '').trim() || 'не-прошёл-скан'
      : null;
    try {
      // ГОДНЫЕ — ПЛОСКО, БЕЗ ПОДПАПОК ПО ДНЯМ (аудит 15.08 + приказ владельца «все видео в 1
      // папку годные»). Раньше писали в годные/<день>/, а места.годные() и reelbatch читают папку
      // плоско — новый рилс лёг бы туда, где выборка под залив его не увидит. Дата и так в mtime.
      const куда = плохой
        ? path.join(ХРАНИЛИЩЕ, 'отсев', причинаСкана, f)
        : path.join(ХРАНИЛИЩЕ, 'годные', f);
      fs.mkdirSync(path.dirname(куда), { recursive: true });
      if (!fs.existsSync(куда)) {
        try { fs.linkSync(п, куда); } catch { fs.copyFileSync(п, куда); }
      }
    } catch (e) { console.log(`  ⚠ в сокровищницу не лёг: ${String(e.message).slice(0, 60)}`); }

    if (плохой) {
      console.log(`  ⛔ не шлю (не прошёл скан): ${f} — ${причинаСкана}`);
      отметить(f);                                     // второй раз не проверяем
      continue;
    }

    const { персона, пост } = разобрать(f);
    try {
      execFileSync('node', [path.join(__dirname, 'tgsend.cjs'), п,
        ...(пост ? ['--key', `${пост}:reel`] : []),
        '--persona', персона, '--type', 'рилс',
        '--note', 'хук внизу кадра, карточка на весь экран'],
      { cwd: __dirname, encoding: 'utf8', timeout: 240000 });
      отметить(f);
      console.log(`  ✅ ушёл в группу: ${персона} (${f})`);
    } catch (e) {
      console.log(`  ✗ не ушёл ${f}: ${String(e.message).split('\n').slice(-2).join(' ').slice(0, 90)}`);
    }
    await sleep(2500);                                 // не долбим телеграм подряд
  }
}

(async () => {
  console.log(`сторож рилсов пошёл: ${ПАПКА}, заход раз в ${ПАУЗА / 1000} с`);
  for (;;) { await заход().catch((e) => console.log('заход упал:', e.message)); await sleep(ПАУЗА); }
})();
