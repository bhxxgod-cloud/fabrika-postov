// ═══ ЗАМЕР «КАРТИНКА ДРУГАЯ» ═════════════════════════════════════════════════════════════════
// Тот же счёт, что в coverguard.cjs: dHash 16x16 = 256 бит, расхождение считаем по Хэммингу.
// Держим ОДИН питон на весь прогон через отдельные вызовы: картинок единицы, скорость не важна,
// а лишняя зависимость важна.
function хеш(файл) {
  const код = [
    'import sys, numpy as np',
    'from PIL import Image',
    'im = Image.open(sys.argv[1]).convert("L").resize((17,16), Image.LANCZOS)',
    'a = np.asarray(im, dtype=np.int16)',
    'b = (a[:,1:] > a[:,:-1]).flatten()',
    'print("".join("1" if x else "0" for x in b))',
  ].join('\n');
  return execFileSync('python3', ['-c', код, файл], { encoding: 'utf8' }).trim();
}
const расхождение = (a, b) => {
  let n = 0;
  for (let i = 0; i < a.length; i++) if (a[i] !== b[i]) n++;
  return n;
};

// ═══ ЧТО ЗАКАЗЫВАЕМ ══════════════════════════════════════════════════════════════════════════
// Места берём из общего пула локаций промпткита, по одному на кадр и БЕЗ ПОВТОРОВ: два кадра в
// одном месте похожи фоном, а фон это половина расхождения по хешу.
// КАЖДАЯ ДЕВОЧКА НАЧИНАЕТ С РАЗНОГО МЕСТА (15.08, находка ветки аватарок).
//
// ЧТО БЫЛО ВИДНО. На листе аватарок из свежих обложек почти у всех папок один и тот же фон:
// Москва-Сити и неоновые полосы. Перцептивный хеш это не ловит — лица и позы разные, расхождение
// в сотню бит, — а человек читает как «снято в одной студии». Ровно тот признак сетки, ради
// борьбы с которым весь доген и затевался.
//
// ПРИЧИНА. Счёт мест начинался с нуля У КАЖДОЙ девочки: первый кадр всегда pickCityPlaces(0),
// второй всегда следующее тихое место, и так далее. Пул в 43 городских и 46 тихих локаций при
// этом почти не использовался: все ходили по одной и той же тропинке от его начала.
//
// ЛЕЧЕНИЕ. Сдвигаем старт по имени девочки: у каждой свой вход в пул, и первые кадры — а их и
// смотрят чаще всего — расходятся по местам. Сдвиг детерминированный, так что добор той же
// девочки продолжит её же тропинку, а не начнёт заново.
const стартПула = (() => {
  let h = 0;
  for (const с of ПЕРСОНА) h = (h * 31 + с.codePointAt(0)) >>> 0;
  return h % 37;   // 37 — простое, чтобы шаг не совпадал с длиной пулов 43 и 46
})();

function планы(n, сдвиг = 0) {
  const из = [];
  for (let k = 0; k < n * 3 && из.length < n; k++) {
    const i = k + сдвиг + стартПула;  // добор берёт СЛЕДУЮЩИЕ места, а не те же самые
    const p = pk.pickCityPlaces(i);
    const m = i % 2 === 0 ? p.loc3 : (pk.nextQuietPlace(null) || p.loc3);
    const место = typeof m === 'string' ? m : (m && (m.place || m.loc || m.name));
    const свет = typeof m === 'object' && m ? (m.light || '') : '';
    if (место && !из.some((x) => x.место === место)) из.push({ место, свет });
  }
  return из.slice(0, n).map((x, i) => ({
    ...x,
    поза: pk.poseTweak(`${ПЕРСОНА}#${i}`, 3),
    одежда: i % 2 === 0 ? 'верх спокойный и закрытый' : 'куртка и футболка, закрытая',
  }));
}

(async () => {
  // СДВИГ СЧИТАЕМ ПЕРВЫМ ДЕЛОМ: от него зависят и номера файлов, и выбор мест. Раньше он стоял
  // ниже плана, и обращение к нему через typeof падало — const в мёртвой зоне бросает
  // ReferenceError, а не отдаёт undefined, как это делает var. Поймано сухим прогоном.
  const ужеЕсть = fs.existsSync(ПАПКА)
    ? fs.readdirSync(ПАПКА).filter((f) => /^обложка\d+.*\.jpg$/.test(f)).sort() : [];
  const СДВИГ = ужеЕсть.length;

  const план = планы(СКОЛЬКО, СДВИГ);
  console.log(`девушка «${ПЕРСОНА}», исходник ${ФОТО}`);
  console.log(`заказов ${план.length}, модель ${MODEL} ${RES} ${ASPECT}, оценка ~$${(план.length * ((rgen.PRICE_RES[MODEL] || {})[RES] || 0.025)).toFixed(2)}`);
  if (СДВИГ) console.log(`в папке уже ${СДВИГ} обложек — продолжаю нумерацию и сверяюсь с ними`);

  if (DRY) {
    for (const [i, p] of план.entries()) {
      const пр = pk.coverPrompt({ place: p.место, light: p.свет, pose: p.поза, clothes: p.одежда });
      console.log(`\n[${i + 1}] место: ${p.место}`);
      console.log(`    промпт (${пр.length} знаков): ${пр.slice(0, 200)}…`);
    }
    console.log('\nДенег не потрачено (--dry). Боевой прогон: тот же вызов с --go.');
    return;
  }

  fs.mkdirSync(ПАПКА, { recursive: true });
  fs.mkdirSync(БРАК, { recursive: true });
  const хешИсходника = хеш(ФОТО);
  const принятые = [{ файл: ФОТО, h: хешИсходника, имя: 'исходник' }];

  // ДОБОР, А НЕ ПЕРЕЗАПИСЬ (14.08: «генерь по 25 на девочек»). Первый прогон сделал по 15, добор
  // просят до 25. Без учёта уже лежащего второй прогон начал бы снова с обложка01 и ЗАТЁР бы
  // оплаченные кадры первого — ровно так мы уже теряли работу на рилсах: в логах 60 нарезок, в
  // папке 23 файла. Уже лежащие обложки идут в «принятые»: новый кадр обязан отличаться и от них
  // тоже, иначе доборы начнут повторять то, что уже сделано и оплачено.
  for (const f of ужеЕсть) {
    const полный = path.join(ПАПКА, f);
    принятые.push({ файл: полный, h: хеш(полный), имя: f });
  }

  // Заказы идут пачками по CONC: провайдер держит несколько параллельных, а очередь по одному
  // растягивает прогон на минуты без всякой пользы.
  const готово = [];
  for (let i = 0; i < план.length; i += CONC) {
    const пачка = план.slice(i, i + CONC);
    const res = await Promise.all(пачка.map(async (p, j) => {
      const н = СДВИГ + i + j + 1;
      const пр = pk.coverPrompt({ place: p.место, light: p.свет, pose: p.поза, clothes: p.одежда });
      // ГОРОД ПИШЕМ В ИМЯ ФАЙЛА (29.08). Сборщик определяет мир кадров 3-4 по имени заглавной:
      // мирОбложки() ищет в нём «дубай», «бали», «питер», «москва». Старые обложки назывались
      // «обложка-дубай-11.jpg» и связка работала, а covergen клал безымянные «обложкаNN» — и для
      // всех новых девочек Дубай не определялся НИ РАЗУ: заглавная снята на крыше в Дубае, а
      // результат тренда уезжал в московскую квартиру.
      const городМеста = (String(p.место).match(/(дубай|бали|питер|санкт-петербург|москв)/i) || [])[1];
      // Неон помечаем в имени так же, как город: сборщик по имени заглавной решает, какую комнату
      // ставить на кадры 3-4, и без метки неоновая заглавная получила бы обычную квартиру — свет
      // первого кадра не сошёлся бы с остальными.
      const метка = НЕОНОВОЕ_МЕСТО.test(String(p.место)) ? '-неон'
        : городМеста
          ? '-' + городМеста.toLowerCase().replace('санкт-петербург', 'питер').replace('москв', 'москва')
          : '';
      const out = path.join(ПАПКА, `обложка${метка}${String(н).padStart(2, '0')}.jpg`);
      try {
        // genToFile, А НЕ generate: generate возвращает ССЫЛКУ, файл сам не пишет. Скачивание с
        // повторами живёт в genToFile — заказ уже оплачен, и ронять его на сетевой заминке нельзя
        // (см. разбор сгоревших четырёх постов в rgen.cjs:266).
        // ФОН НЕОНОВОЙ ЗАГЛАВНОЙ — ФОТОГРАФИЕЙ, А НЕ ОПИСАНИЕМ (30.08). Владелец отобрал 38
        // снимков неоновых комнат и попросил ставить их на заглавную. Описание словами модель
        // читает как «сделай что-то похожее», и неон выходил каждый раз свой — то выжженный,
        // то отсутствующий. Снимок она копирует точно. Комната прикладывается вторым референсом
        // и выбирается по номеру кадра, чтобы в пачке не повторялась.
        const рефы = [ФОТО];
        if (НЕОН.length && НЕОНОВОЕ_МЕСТО.test(String(p.место))) {
          рефы.push(НЕОН[(н - 1) % НЕОН.length]);
        }
        await rgen.genToFile(out, { model: MODEL, prompt: пр, refFiles: рефы, resolution: RES, aspect: ASPECT });
        return { н, out, место: p.место };
      } catch (e) {
        console.log(`  ✗ кадр ${н} не сгенерился: ${String(e.message).slice(0, 90)}`);
        return null;
      }
    }));
    готово.push(...res.filter(Boolean));
  }

  // ═══ ПРИЁМКА ═══════════════════════════════════════════════════════════════════════════════
  const fk = require(path.join(REPO, 'facesim.cjs'));
  let принято = 0;
  let спорных = 0;
  for (const г of готово) {
    if (!fs.existsSync(г.out)) continue;
    const h = хеш(г.out);
    const отИсходника = расхождение(h, хешИсходника);
    const ближайший = принятые.reduce((м, п) => {
      const d = расхождение(h, п.h);
      return d < м.d ? { d, имя: п.имя } : м;
    }, { d: 999, имя: '' });

    // keepsFace, А НЕ faceSim НАПРЯМУЮ. faceSim отдаёт {pairs:{'1-2':0.53}, faces, same}: число
    // лежит в паре по номерам кадров, а не полем верхнего уровня. Первая версия читала выдуманное
    // поле .v, получала undefined и написала «лицо не измерено» на ТРЁХ кадрах подряд — при том что
    // питон отработал и вернул 0.53. Главная проверка молча не работала, а прогон выглядел удачным.
    // keepsFace как раз про одну пару и сам разбирает этот ответ.
    const зам = fk.keepsFace(ФОТО, г.out);
    // Решение по СВОЕМУ порогу, а не по зам.ok: тот считан с общего SAME_FACE (см. ПОРОГ_ЛИЦА).
    const лицоТоЖе = зам.d == null ? null : зам.d >= ПОРОГ_ЛИЦА;
    const картинкаДругая = ближайший.d > ПОРОГ_БИТ;

    const строка = `кадр ${г.н}: лицо ${зам.d == null ? 'НЕ ИЗМЕРЕНО' : зам.d.toFixed(3)} (порог ${ПОРОГ_ЛИЦА}), `
      + `расхождение с исходником ${отИсходника} бит, с ближайшим принятым ${ближайший.d} бит`;

    // СЕРАЯ ЗОНА — ВЛАДЕЛЬЦУ, А НЕ В БРАК (14.08, его слова: «если девочка немного не похожа —
    // можешь согласовать со мной»). Порог 0.363 это одна черта, а между 0.33 и 0.363 живут кадры,
    // где узнаваемость спорная: число говорит «нет», глаз часто говорит «да, она». Свой же
    // facesim.cjs про это прямо пишет — «приговор глазами». Молча жечь такие кадры значит
    // выбрасывать оплаченную работу по формальности, поэтому они идут отдельной стопкой на просмотр.
    // ЛИЦО БОЛЬШЕ НЕ ОТСЕИВАЕТ, ТОЛЬКО ЗАПИСЫВАЕТСЯ (14.08, владелец дважды: «все обложки
    // подходят», «кидай мне все забракованные, вернём в работу»). Он просмотрел и те, что число
    // забраковало — 0.324 и 0.307 — и принял их. Значит порог тут не помощник, а помеха: он жёг
    // оплаченную работу по формальности, тогда как узнаваемость решает глаз.
    // Число не выбрасываем: оно уходит В ИМЯ ФАЙЛА, и любую обложку можно отсортировать по
    // сходству, не пересчитывая. Отсев остаётся ОДИН — «картинка другая», и он не про вкус, а про
    // механику: ковергард всё равно склеит слишком похожие, и пост просто не соберётся.
    if (лицоТоЖе === false || лицоТоЖе === null) {
      const метка = зам.d == null ? 'без-замера' : `лицо${зам.d.toFixed(3)}`;
      const нов = г.out.replace('.jpg', `_${метка}.jpg`);
      fs.renameSync(г.out, нов);
      принятые.push({ файл: нов, h, имя: `кадр ${г.н}` });
      принято++;
      спорных++;
      console.log(`  ✓ ${строка} → взял (лицо ниже порога, помечено в имени)`);
    } else if (false) {
      // НЕИЗМЕРЕННОЕ ЛИЦО НЕ ПРОХОДИТ. Ровно этот путь и дал ложный успех выше: кадр без замера
      // шёл в «принято» с пометкой в логе, а пометку в потоке строк никто не читает. Пропущенная
      // проверка — это не «наверное нормально», это неизвестность, и решается она глазами.
      fs.renameSync(г.out, path.join(БРАК, path.basename(г.out).replace('.jpg', '_лицо-не-измерено.jpg')));
      console.log(`  ✗ ${строка} → замер не прошёл (${зам.error || 'причина не названа'}), в брак на просмотр`);
    } else if (!картинкаДругая) {
      fs.renameSync(г.out, path.join(БРАК, path.basename(г.out).replace('.jpg', '_слишком-похоже.jpg')));
      console.log(`  ✗ ${строка} → ковергард склеит, в брак`);
    } else {
      принятые.push({ файл: г.out, h, имя: `кадр ${г.н}` });
      принято++;
      console.log(`  ✓ ${строка}`);
    }
  }

  // spentSoFar отдаёт ОБЪЕКТ {orders, usd}, а не число (rgen.cjs:163).
  const счёт = rgen.spentSoFar();
  console.log(`\nпринято ${принято} из ${готово.length}, заказов ${счёт.orders}, потрачено $${счёт.usd}`);
  if (спорных) console.log(`из них ${спорных} с лицом ниже порога — взяты, число в имени файла`);
  console.log(`готовые обложки: ${ПАПКА}`);

  // ═══ ЗАДАНИЯ НА СБОРКУ ═══════════════════════════════════════════════════════════════════════
  // ОДНА ОБЛОЖКА = ОДИН ПОСТ (14.08, вопрос владельца: «мы их юзаем по 1 кадр или нет?»). Да, и
  // иначе нельзя: ковергард сравнивает готовые обложки, а надпись хука меняет картинку на 0-6 бит
  // из 256 — две карточки с одного фото он считает одной. Ровно так и появились те 90 рилсов на
  // восьми фотографиях. Поэтому каждая принятая обложка идёт СВОИМ исходником и своим постом.
  //
  // ПОЧЕМУ ФАЙЛ ЗАДАНИЙ ПИШЕТСЯ ЗДЕСЬ. Без него принятые кадры лежат в папке мёртвым грузом:
  // сборка ходит по jobs-файлам и про новую папку не знает. Соседний случай уже был — предзаказ
  // отработал на 117 кадров, а сборка их не увидела, потому что кадры идут в позиции 3/4, и никто
  // этого не заметил, пока не полезли считать. Здесь связь замыкается сразу.
  // Шаблон каждой обложке даётся СВОЙ, по кругу: один пост это одна обложка И один шаблон.
  const TPL = require(path.join(REPO, 'templates.cjs'));
  const шаблоны = TPL.list().filter((t) => !/anime|размер|фея/i.test(t));
  const задания = принятые.filter((п) => п.имя !== 'исходник').map((п, i) => {
    const t = шаблоны[i % шаблоны.length];
    const ключ = `${ПЕРСОНА}-${String(i + 1).padStart(2, '0')}-${t}`;
    return `${t}|${п.файл}|${ПЕРСОНА}-${String(i + 1).padStart(2, '0')}|${ключ}`;
  });
  if (задания.length) {
    const файл = path.join(ПАПКА, 'задания.txt');
    fs.writeFileSync(файл, задания.join('\n') + '\n');
    console.log(`задания на сборку: ${файл} (${задания.length} постов, по одному на обложку)`);
    console.log(`запуск: bash postfactory.sh ${файл}`);
  }
  if (принято < готово.length) console.log(`брак лежит рядом: ${БРАК} — посмотри глазами, что поехало`);
})().catch((e) => { console.log('упало:', e.message); process.exit(1); });
