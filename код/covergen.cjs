// ЗАЧЕМ. Приказ владельца дословно: «задача сгенерить 1 кадры, где девочка будет максимально
// похожей на свой ориг — просто чтобы фото не уникализировать, а новое сделать».
//
// ЧТО ЭТО ЧИНИТ. Замер того же дня по пачке 14-08: 90 рилсов из 209 сделаны на ВОСЬМИ фотографиях.
// Одно фото уходило на десяток аккаунтов, отличаясь только надписью хука. Правило «одно фото =
// один пост» это закрыло, но упёрлось в запас: исходников тринадцать, а нужны сотни. Догенерация
// обложек снимает потолок: с одной девушки получается сколько угодно РАЗНЫХ снимков её же.
//
// ЧЕМ ОТЛИЧАЕТСЯ ОТ ПРЕДЗАКАЗА (preorder_frames.cjs). Тот делает кадры 3/4 и там СМЕНА ОБРАЗА
// обязательна: другой цвет и длина волос. Здесь наоборот — держим всё, по чему её узнают, а меняем
// только день и обстановку. Промпт живёт в promptkit.coverPrompt, там же разбор почему он короткий.
//
// ПРИЁМКА КАЖДОГО КАДРА, ДВА ЗАМЕРА, И ОБА ОБЯЗАТЕЛЬНЫ:
//   · ЛИЦО ТО ЖЕ — facesim (эмбеддинги SFace, порог из питона). Не сошлось — это другая девушка,
//     кадр в брак. Без этой проверки мы платим за чужих людей и узнаём об этом на заливе;
//   · КАРТИНКА ДРУГАЯ — dHash 16x16, тот же счёт, что у coverguard (порог 48 бит). Сравниваем и с
//     исходником, и со всеми уже принятыми кадрами этой девушки. Мало бит — ковергард всё равно
//     склеит их при сборке, и мы вернёмся ровно туда, откуда начали.
// Кадр, не прошедший любой из двух, НЕ удаляется, а откладывается в «брак» — глазами по нему
// видно, что именно поехало, и промпт правится по факту, а не на ощупь.
//
// ЗАПУСК:
//   node covergen.cjs --dry  <фото> [сколько]   план и промпты, БЕЗ денег
//   node covergen.cjs --go   <фото> [сколько]   боевой прогон (тратит деньги)
// Персона берётся из имени файла. Готовое кладётся в ~/Desktop/ОБЛОЖКИ-ДОГЕН/<персона>/.
