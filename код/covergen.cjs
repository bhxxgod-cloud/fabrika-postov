const ПОРОГ_БИТ = Number(process.env.COVER_MIN_BITS || 48); // тот же порог, что у coverguard
// ПОРОГ ЛИЦА ДЛЯ ОБЛОЖКИ СВОЙ, НИЖЕ ОБЩЕГО (14.08). facesim.SAME_FACE = 0.363 — черта для
