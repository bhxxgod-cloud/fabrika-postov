#!/bin/bash
# ПОДЪЁМ ФЕРМЫ ПОСЛЕ ПЕРЕЗАГРУЗКИ ИЛИ УБОРКИ /tmp.
#
# ЗАЧЕМ ЭТОТ ФАЙЛ СУЩЕСТВУЕТ. В ночь 13-14.08.2026 macOS подчистила /tmp и разом унесла:
# строку подключения к базе (её читают 187 файлов), ключ фабрики генерации, ключ зрения,
# куку заливки на сайт, токены телеграма, файлы заданий, реестр POST-OK и 162 готовых
# нарезанных рилса. Конвейер встал целиком — не частично. Ключи раскладывали обратно руками.
#
# Ревизия 14.08 показала, почему это повторится: постоянная копия ключей лежит в
# ~/.neironka/secrets/, но НИ ОДИН скрипт про этот путь не знает. Все 187 читают /tmp.
# То есть папка secrets выглядит как решённая задача, а на деле это копия на память.
#
# ЭТОТ СКРИПТ — МОСТ МЕЖДУ НИМИ. Он раскладывает ключи из постоянного места туда, где их
# ищут скрипты, и поднимает сторожей. Запускать после каждой перезагрузки; лучше повесить
# на автозапуск (см. хвост файла).
#
# ПОЧЕМУ НЕ ПЕРЕПИСАТЬ 187 ФАЙЛОВ. Можно, и когда-нибудь нужно. Но это 187 мест правки в
# работающем конвейере, а этот файл закрывает ту же дыру за тридцать строк и прямо сегодня.
set -u
REPO="$(cd "$(dirname "$0")" && pwd)"
SECRETS="$HOME/.neironka/secrets"
cd "$REPO" || exit 1

echo "════ КЛЮЧИ ════"
# ТОЛЬКО ЛАТИНСКИЕ ИМЕНА ПЕРЕМЕННЫХ. Кириллическое имя bash молча не принимает: `local из=…` даёт
# «not a valid identifier», функция валится, и файл ведёт себя так, будто ключей нет вообще. Эту
# ловушку ферма ловила уже трижды (worker2.sh, postfactory.sh и первая версия этого файла), причём
# каждый раз она выглядит как поломка чего-то другого. В комментариях кириллица безвредна.
#
# слева имя файла в постоянном хранилище, справа путь, по которому его ищут скрипты
put_key() {
  local from="$SECRETS/$1" to="$2"
  if [ -s "$from" ]; then
    cp "$from" "$to" && chmod 600 "$to" 2>/dev/null
    echo "  ✅ $to"
  elif [ -s "$to" ]; then
    # обратный ход: в /tmp ключ есть, а в хранилище нет — сохраняем на будущее
    mkdir -p "$SECRETS" && cp "$to" "$from" && chmod 600 "$from"
    echo "  ↩ $1 сохранён в хранилище из $to"
  else
    echo "  ❌ НЕТ НИ ТАМ НИ ТАМ: $1 — восстанови из Railway, см. HANDOFF-alina.md"
  fi
}
mkdir -p "$SECRETS"; chmod 700 "$SECRETS"
put_key dburl.txt          /tmp/dburl.txt           # строка базы, её читают 187 файлов
put_key rgkey.txt          /tmp/.rgkey              # ключ фабрики генерации кадров (платный)
put_key orkey.txt          /tmp/orkey.txt           # ключ зрения для card_qa (платный)
put_key admin_cookie.txt   /tmp/admin_cookie.txt    # кука заливки на neironka.pro

echo
echo "════ ТЕЛЕГРАМ ════"
# ТОКЕНЫ РАСКЛАДЫВАЕТ tgrestore.sh, А НЕ МЫ (14.08). Первая версия этого файла копировала телеграм
# сама — и это была ошибка того же рода, что и пять копий вёрстки хука. Хуже: в secrets/ лежала
# копия tg_bot.txt с ДРУГИМ ботом (xmoneyforporsche_bot), а ферма ночью работала на claudex057_bot.
# То есть после перезагрузки boot.sh молча подменил бы бота, и связь с владельцем умерла бы тихо:
# отчёты уходили бы в никуда, а понять это можно было бы только по тишине. Ту копию увели в
# secrets/tg_bot_xmoneyforporsche.НЕ-ИСПОЛЬЗУЕТСЯ.txt, живые токены сохранены в ~/.neironka/.
# Раскладка живёт в одном месте, у tgrestore.sh — он же и сам мост поднимает.
if [ -x "$REPO/tgrestore.sh" ] || [ -f "$REPO/tgrestore.sh" ]; then
  # БЕЗ --no-daemon (14.08, поймано аудитом). Здесь стоял флаг --no-daemon, и он ГЛУШИЛ то самое,
  # ради чего строка написана: tgrestore.sh при этом флаге выходит ДО блока подъёма моста. То есть
  # комментарий выше обещал «он же и сам мост поднимает», а сам boot.sh это и запрещал. Мост —
  # единственный канал, по которому владелец отвечает ферме; после перезагрузки он не вставал.
  bash "$REPO/tgrestore.sh" || echo "  ⚠ телеграм не восстановился, см. вывод выше"
else
  echo "  ❌ нет tgrestore.sh — связь с владельцем не поднимется"
fi

echo
echo "════ ОПЛАЧЕННЫЕ КАДРЫ ════"
# 601 МБ УЖЕ ОПЛАЧЕННЫХ КАДРОВ ЛЕЖАЛИ В /tmp (найдено ревизией 14.08). Уборка унесла бы их так же,
# как унесла ключи, — но здесь цена другая: это живые деньги, кадры генерирует платная фабрика.
# Вместе с ними в /tmp лежит manifest.json — ЗАЩИТА ОТ ДВОЙНОЙ ОПЛАТЫ: по нему предзаказ понимает,
# что кадр для этой персоны и шаблона уже куплен. Потерять манифест значит заказать всё заново и
# заплатить второй раз за то же самое. Поэтому папка целиком дублируется в домашнюю.
#
# ВОССТАНАВЛИВАЕМ ТОЛЬКО ЕСЛИ В /tmp ПУСТО. Обратной перезаписи здесь быть не должно: сборка читает
# из /tmp прямо сейчас, и копия старше живого состояния затёрла бы свежие кадры.
BACKUP="$HOME/.neironka/preorder-backup"
if [ -s "$BACKUP/manifest.json" ]; then
  if [ ! -s /tmp/preorder/manifest.json ]; then
    mkdir -p /tmp/preorder && cp -R "$BACKUP/." /tmp/preorder/
    echo "  ✅ возвращено из копии: $(find /tmp/preorder -type f | wc -l | tr -d ' ') файлов"
  else
    echo "  · кадры на месте, копию не трогаю ($(find /tmp/preorder -type f | wc -l | tr -d ' ') файлов)"
  fi
else
  # РАНЬШЕ ЗДЕСЬ ПЕЧАТАЛАСЬ КОМАНДА, А НЕ ВЫПОЛНЯЛАСЬ (14.08, поймано аудитом). Совет «сделай
  # rsync» бесполезен: копия нужна как раз тогда, когда её некому сделать руками. Оплаченные
  # кадры и манифест-защита от повторной оплаты стоят $11 за прогон — дешевле скопировать.
  echo "  ⚠ копии предзаказа нет, делаю сейчас"
  [ -d /tmp/preorder ] && rsync -a /tmp/preorder/ "$BACKUP/" 2>/dev/null && \
    echo "  ✅ скопировано: $(find "$BACKUP" -type f | wc -l | tr -d " ") файлов"
fi

echo
echo "════ МЁРТВЫЕ ЗАМКИ КОНВЕЙЕРА ════"
# После жёсткого выключения файлы-замки остаются, а процессов-владельцев уже нет.
# Живой держатель проверяется по номеру процесса; мёртвый держит полосу до 45 минут.
freed=0
for f in /tmp/genposts.lock*; do
  [ -e "$f" ] || continue
  pid=$(cat "$f" 2>/dev/null | tr -d '[:space:]')
  if [ -z "$pid" ] || ! ps -p "$pid" >/dev/null 2>&1; then rm -f "$f"; freed=$((freed+1)); fi
done
echo "  снято мёртвых замков: $freed"

echo
echo "════ СИРОТСКИЕ ВКЛАДКИ ════"
# Убитый onepost не закрывает вкладку хрома — сироты копятся и душат машину
# (13.08 поймали 47 ГБ и OOM). Уборка безопасна: у неё четыре предохранителя,
# живого воркера она не тронет (adminbrowser.cjs:260-337).
node -e "require('$REPO/adminbrowser.cjs').прибратьСиротские().catch(()=>{})" 2>/dev/null \
  && echo "  уборка выполнена" || echo "  уборка не отработала (хром не поднят — это норма)"

echo
echo "════ ГОТОВО ════"
echo "  Проверить связь с базой:  node -e \"new (require('pg').Client)({connectionString:require('fs').readFileSync('/tmp/dburl.txt','utf8').trim(),ssl:{rejectUnauthorized:false}}).connect().then(()=>console.log('база отвечает')).catch(e=>console.log('база молчит:',e.message))\""
echo
echo "  Повесить на автозапуск (один раз):"
echo "    ~/Library/LaunchAgents/pro.neironka.boot.plist → ProgramArguments: /bin/bash $REPO/boot.sh"
echo "    launchctl load ~/Library/LaunchAgents/pro.neironka.boot.plist"
echo "  Приложению нужен Full Disk Access, иначе оно не увидит Рабочий стол."
