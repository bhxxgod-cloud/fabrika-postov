//
// ЧЕМ ЭТОТ ПУЛ ОТЛИЧАЕТСЯ ОТ СТАРОГО, И ПОЧЕМУ СТАРЫЙ БЫЛ СЛАБЫЙ. Старые фразы ОПИСЫВАЛИ содержимое
