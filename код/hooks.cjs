/**
 * ДИАГНОЗ ФРАЗЫ. Отдаёт список болезней, которые в ней нашлись (пустой массив = фраза здорова).
 * Работает по ПЛОСКОМУ тексту: перенос строки для болезни это просто пробел.
 * @returns {Array<{болезнь:string, совпало:string, чем:string}>}
 */
function диагноз(text) {
  const плоский = String(text || '').replace(/\n/g, ' ');
  const out = [];
  for (const [имя, re, чем] of БОЛЕЗНИ) {
    const m = плоский.match(re);
    if (m) out.push({ болезнь: имя, совпало: m[0].trim(), чем });
  }
  return out;
}

// БОЛЕЗНЬ 5: ОДИНАКОВОЕ НАЧАЛО. Замер разбора: 18 самых частых хуков стартовали с трёх одинаковых
// слов, и лента видит однотипный контент даже без сверки текстов. Порог два: третья фраза с тем же
// началом это уже узор. Считаем по ДВУМ первым словам, знаки препинания и эмодзи не в счёт.
const НАЧАЛО_ПРЕДЕЛ = 2;
const началоФразы = (text) => String(text || '').toLowerCase().replace(/\n/g, ' ')
  .replace(/[^а-яёa-z0-9 ]/gi, ' ').trim().split(/\s+/).slice(0, 2).join(' ');

/** Начала, повторённые в пуле чаще предела. @returns {Array<[начало, сколько]>} */
function частыеНачала(тексты) {
  const c = new Map();
  for (const t of тексты) { const н = началоФразы(t); if (н) c.set(н, (c.get(н) || 0) + 1); }
  return [...c.entries()].filter(([, n]) => n > НАЧАЛО_ПРЕДЕЛ);
}

