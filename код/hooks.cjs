//
// ПОЧЕМУ. Пост попадает в разбор по условию seedNum(id) % 4 === 0, а строка выбиралась как
// seedNum(id + суффикс) % 4. Эти два остатка СВЯЗАНЫ алгебраически: FNV умножает состояние на
// нечётную константу по модулю 2^32, а такое умножение — биекция на младших битах. Значит если
// младшие два бита у seedNum(id) закреплены условием отбора, то и после дописывания суффикса они
// закреплены. Не «плохо перемешалось», а строго ноль вариантов.
//
// Замер трёх способов на тех же 749 постах:
//   суффикс, младшие биты  → {1: 749}                     полный схлоп
//   префикс, младшие биты  → {1: 227, 3: 522}             половина пула мертва
//   старшие биты           → {0:184, 1:203, 2:191, 3:171} ровно
