/**
 * Строки пула (как они лежат в коде) по шаблону и семье. Без фильтра по фактам.
 *
 * СЕМЬЯ ПО УМОЛЧАНИЮ ТЕПЕРЬ 'mix', А НЕ 'base' (11.08, и это главная причина жалобы начальника
 * «ничего не поменялось»). Семья tt с его же дословными эталонами («моё лицо когда подруга начала
 * завидовать после теста», «мой колорист меня проклял после этого тренда») была написана, проверена
 * и НЕ ВЫДАВАЛАСЬ НИ РАЗУ: параметр family не передаёт ни один вызывающий (ни onepost через
 * slidekit.factoryHook, ни rehook_covers), а по умолчанию отдавалась base. То есть на обложках
 * стояли ровно те спокойные «признания», которые он и назвал слабыми, а байт лежал мёртвым кодом.
 * Проверка check гоняет обе семьи по одним правилам, поэтому мешать их безопасно, и пул на шаблон
 * заодно вырастает вдвое (это же лечит повторы надписей в ленте).
 */
function rowsFor(template, family) {
  const key = keyFor(template);
  const f = String(family || 'mix');
  // У УЗКИХ СЕМЕЙ (lip/brow/nose/haircut/colortype) тт-пула пока НЕТ, и «mix» падал бы на
  // [...undefined] прямо при выборе хука в сборке. Пустой тт-пул это не ошибка: семья новая, её
  // байт-варианты допишутся отдельно, а base-фразы годны на обе площадки.
  return f === 'mix' ? [...(POOLS[key] || []), ...(POOLS_TT[key] || [])] : ((FAMILIES[f] || POOLS)[key] || []);
}

/**
 * Пул хуков (массив строк) по шаблону, УЖЕ отфильтрованный под образ поста.
 * @param {string} template
 * @param {string} [family] 'base' (по умолчанию), 'tt' или 'mix' (обе семьи вместе).
 * @param {object} [look]   факты образа поста, как их понимает lookFacts. БЕЗ них отдаётся только
 *                          безопасное ядро (фразы, которые не называют ни стрижку, ни цвет, ни тон),
 *                          потому что проверить остальные не на чем, а молчание лучше вранья.
 */
function poolFor(template, family, look) {
  const rows = rowsFor(template, family);
  const facts = lookFacts(look);
  const ok = Object.keys(facts).length
    ? rows.filter((r) => !looksClash(r, facts))
    : rows.filter(isSafeCore);
  // Пустого пула быть не может: безопасное ядро есть в каждом типе поста. Но если однажды кто-то
  // разметит конкретикой ВСЁ, лучше отдать ядро, чем уронить сборку поста на пустом массиве.
  const use = ok.length ? ok : rows.filter(isSafeCore);
  return use.map((r) => r[1]);
}

// Хеш сида: тот же FNV-1a, что в slidekit.seedNum. Скопирован СПЕЦИАЛЬНО, а не взят через require:
// slidekit после вставки (см. ниже) начнёт требовать этот файл, и общий хеш дал бы круговой require.
// Math.imul обязателен: обычное умножение на 16777619 вылетает за 2^53, младшие биты теряются в
// округлении double, и соседние сиды дают один остаток.
const seedNum = (s) => { let h = 2166136261; for (const ch of String(s)) h = Math.imul(h ^ ch.charCodeAt(0), 16777619) >>> 0; return h >>> 0; };

/**
 * ХУК НА ПОСТ. Раздача ПО ХЕШУ, как теги и стиль финального кадра: один и тот же пост при
 * пересборке получает тот же текст (иначе на перевыпуске обложка приезжает с новой фразой и
 * начальник видит «пост поехал»), а соседние посты расходятся.
 *
 * @param {string} template  шаблон поста (meta->>'template')
 * @param {object} [opts]
 * @param {string} [opts.seed]   id поста, персона+дата, любой стабильный ключ. Без сида берём случайный.
 * @param {string} [opts.avoid]  не отдавать этот текст. Нужно там, где на один пост берутся ДВА хука
 *                               из одного пула (обложка рисуется у нас, hookText уезжает в заказ
 *                               фабрики): без avoid обе фразы выпадали одинаковыми.
 * @param {string} [opts.own]    свой текст. Отдаём его, если он проходит по длине 20-140.
 * @param {string} [opts.family] 'base' (по умолчанию, признание от первого лица), 'tt' (тиктоковский
 *                               байт с эмодзи и «>>>»), 'mix' (обе семьи в одном мешке).
 * @param {object} [opts.look]   ФАКТЫ ОБРАЗА ПОСТА, чтобы хук не спорил с картинкой. Один объект, и
 *                               его можно передать любым из трёх видов (см. lookFacts):
 *                                 { hairLenIdx, srcHair, hairIdx }  ровно те переменные, что уже
 *                                                                   считает onepost перед кадром 3;
 *                                 { lenName, colorName }            названия из promptkit словами;
 *                                 { dlina, cvet, ton }              токенами.
 *                               Без look выдаётся только безопасное ядро.
 * @returns {string} текст в две строки, разделитель \n
 *
 * ГДЕ ЭТО ПОДКЛЮЧИТЬ (менять руками):
 *   1. slidekit.cjs, функция factoryHook: СДЕЛАНО — тело зовёт require('./hooks.cjs').pick(...),
 *      своя копия пула (константа FACTORY_HOOKS) оттуда удалена. Сигнатура factoryHook при этом
 *      РАСШИРЕНА третьим аргументом-объектом, старые вызовы без него продолжают работать и просто
 *      получают безопасное ядро. Чтобы факты доехали, onepost зовёт хук так:
 *        factoryHook(TEMPLATE, null, { look: { hairLenIdx, srcHair, hairIdx } })
 *      (все три переменные там уже есть, hairLenIdx считается строкой pk.hairLenByHash(tag)).
 *      ВАЖНО ПРО ПОРЯДОК: сейчас coverHook() зовётся РАНЬШЕ, чем считаются srcHair и hairLenIdx,
 *      поэтому вызов хука надо переставить ПОСЛЕ них, иначе в look приедут undefined и пост опять
 *      получит только ядро (не соврёт, но и конкретики не увидит).
 *   2. rehook_covers.cjs, функция poolFor: заменить на
 *        return require('./hooks.cjs').poolFor(tpl);
 *      и удалить локальный HOOKS_BY_TPL. Раздача там уже по хешу id, она сохраняется. Фактов образа
 *      у перевыпуска обложек нет, поэтому там честно останется безопасное ядро.
 */
function pick(template, opts) {
  const o = opts || {};
  const own = String(o.own || '').trim();
  if (own.length >= 20 && own.length <= 140) return own;
  // НОВАЯ ЛОГИКА ВЛАДЕЛЬЦА (15.08 вечер) ЖИВЁТ В hooks2.cjs: пул на шаблон, одна строка живой речи,
  // пара «обложка → описание». Этот файл остаётся историей и фолбэком для шаблонов, которых там нет.
  // Выключатель HOOKS_V2=0 только под сравнение на замере.
  if (process.env.HOOKS_V2 !== '0') {
    try {
      const H2 = require('./hooks2.cjs');
      if (H2.известен(template)) { const h = H2.pick(template, o); if (h) return h; }
    } catch (e) { console.log(`  ⚠ hooks2 не отработал (${String(e.message).slice(0, 80)}), беру старый пул`); }
  }
  const pool = poolFor(template, o.family, o.look);
  const avoid = String(o.avoid || '').trim();
  let free = avoid ? pool.filter((h) => h !== avoid) : pool;
  // ЗАНЯТЫЕ ХУКИ ОБХОДИМ (11.08). Замер по складу: 336 постов, а разных хуков всего 68, самый частый
  // повторён 17 раз, и на живом аккаунте нашлись ДВА поста с одинаковой надписью рядом в сетке.
  // Причина не в узости пула (в нём 158 фраз), а в выборе по хэшу: на пуле в тридцать фраз хэш
  // обязан совпадать, это задача о днях рождения. Поэтому зовущий передаёт список уже занятых
  // фраз (свои по этому аккаунту плюс последние по всей ферме), и мы выбираем из свободных.
  // СРАВНИВАЕМ ПО ПЛОСКОМУ ВИДУ, И БЕЗ ЭТОГО ЗАЩИТА НЕ РАБОТАЛА ВООБЩЕ (ревизия 14.08).
  // Фразы в пуле лежат с переводом строки (он же разделитель двух строк на кадре), а в базу
  // хук пишется УЖЕ ПЛОСКИМ: onepost.cjs:1281 и :1367 делают hook.replace(/\n/g, ' ').
  // Значит занято.has(h) сравнивал «мне дали 8.4,\nа я себе ставила шесть» с
  // «мне дали 8.4, а я себе ставила шесть» и не совпадал НИ РАЗУ — обход занятых был
  // написан, но не срабатывал ни одного раза с 11.08.
  // Цена бездействия по замеру: 612 постов с хуком, из них всего 211 разных фраз;
  // «мне разобрали лицо по полочкам» стоит на 17 постах у 17 РАЗНЫХ девочек. Это готовый
  // поисковый запрос, по которому сетка находится за минуту.
  const плоско = (s) => String(s || '').replace(/\s+/g, ' ').trim();
  const занято = new Set((o.avoidSet || []).map(плоско).filter(Boolean));
  if (занято.size) {
    const свободные = free.filter((h) => !занято.has(плоско(h)));
    // Если свободных не осталось, берём как раньше: повтор лучше, чем пост без хука. Но это уже
    // сигнал, что пул пора расширять, и зовущий об этом узнаёт по полю «повтор» в pickПодробно.
    if (свободные.length) free = свободные;
  }
  const use = free.length ? free : pool;
  return o.seed != null && o.seed !== ''
    ? use[seedNum(o.seed) % use.length]
    : use[Math.floor(Math.random() * use.length)];
}

