//   7. Хук НЕ равен подписи поста. Подпись собирает slidekit.postCaption и сама отбрасывает
//      заголовки, пересекающиеся с хуком больше чем на 40% слов, поэтому фразы отсюда в пулы
//      подписей копировать НЕЛЬЗЯ, иначе сверка перестанет находить отличающийся вариант.
//
// ПУЛ РАЗЛОЖЕН ПО ТИПУ ПОСТА, А НЕ ПО ШАБЛОНУ. Тип определяет, про что вообще можно врать на
// обложке: у оценки внешности есть цифры, у гайда их нет, у тренда нет ни цифр, ни разбора.
// Обложка обязана обещать то, что реально лежит на кадре 2, иначе свайп заканчивается разочарованием.
//
// ═══ ХУК НЕ ИМЕЕТ ПРАВА СПОРИТЬ С КАРТИНКОЙ (11.08, баг с живого поста) ═══════════════════════════
// ЧТО УВИДЕЛ НАЧАЛЬНИК. Хук «все пишут, что мне идёт каре, а мне объяснили, почему нет», а на кадрах
// 3 и 4 девочка ровно С КАРЕ. Дословно: «и она сделала каре, бред, давай логику описаний менять».
//
// КОРЕНЬ. Хук выбирался из пула ДО генерации и о посте не знал НИЧЕГО, а целевой образ (цвет волос и
// длина) решается отдельно: цвет по хэшу персоны (onepost, hairIdx), длина по хэшу поста
// (promptkit.hairLenByHash). Два независимых броска монеты, и рано или поздно они противоречат друг
// другу. Это тот же корень, что у жалобы на подписи: текст не знает фактов поста. Слабый текст видно
// хуже, чем врущий, поэтому чинится это раньше сленга.
//
// КАК ПОЧИНЕНО, ТРИ ЧАСТИ:
//   1. РАЗМЕТКА. У фразы появилось пятое (для base третье) поле, объект упоминаний: какие признаки
//      внешности фраза называет и с каким знаком. «мне идёт каре, а объяснили почему нет» это
//      {kare:'-'}, «была уверена, что мне идёт блонд» это {blond:'-'}, «мой нос моя фишка» это
//      {nos:'+'}. Поле необязательное, и его отсутствие означает «фраза конкретики не называет».
//   2. БЕЗОПАСНОЕ ЯДРО. Фраза БЕЗ упоминаний стрижки, цвета и тона соврать не может по построению,
//      поэтому годится всегда. Таких фраз в пуле большинство (счётчик печатает node hooks.cjs), а
//      конкретика это небольшая группа, которая выдаётся только при совпадении фактов.
//   3. ФИЛЬТР. pick принимает факты поста (opts.look) и выбрасывает фразы, которые с ними спорят:
//      пост делает каре, значит фразы, отрицающие каре, из выборки выпадают; пост уходит в блонд,
//      значит «мне не идёт светлое» выпадает. БЕЗ ФАКТОВ выдаётся ТОЛЬКО безопасное ядро: старые
//      вызовы (rehook_covers, ручные прогоны) от этого не ломаются, они просто перестают получать
//      конкретику. Молчание лучше вранья.
//
// ЧЕРТЫ ЛИЦА (глаза, брови, губы, нос, скулы) размечаются, но НЕ фильтруются: пост их не меняет и
// фактов по ним нет, поэтому спорить с кадром они не могут. Разметка там нужна только чтобы видеть,
// о чём фраза, и не собрать пул, где каждая вторая про нос.
'use strict';

// ═══ ФАКТЫ ОБРАЗА И КОНФЛИКТ С ТЕКСТОМ ══════════════════════════════════════════════════════════

// СЛОВАРЬ ПРИЗНАКОВ. Ключ это признак, значение это КАТЕГОРИЯ. Категория важнее самого признака:
// внутри категории значение поста ровно одно (одна длина, один цвет, один тон), поэтому «фраза хвалит
// блонд, а пост красит в шоколад» ловится сравнением по категории, а не перечислением пар.
const LOOK_FEATURES = {
  // ДЛИНА И ФОРМА. Значения повторяют пул promptkit.HAIR_LENGTHS, только словом, а не строкой промпта.
  kare: 'dlina', plechi: 'dlina', dlinnye: 'dlina', hvost: 'dlina', puchok: 'dlina', chelka: 'dlina',
  // ЦВЕТ и ТОН это РАЗНЫЕ категории: пепельный блонд и платиновый блонд оба blond, но тон у них один,
  // а у медно-рыжего другой, и фразы про «мне идёт холодное» цепляются именно за тон.
  blond: 'cvet', temnoe: 'cvet', ryzhee: 'cvet',
  holodnyj: 'ton', teplyj: 'ton',
  // ЧЕРТЫ ЛИЦА: пост их не задаёт, поэтому категория помечена как нефильтруемая (см. LOOK_FILTERED).
  glaza: 'cherty', brovi: 'cherty', guby: 'cherty', nos: 'cherty', skuly: 'cherty', koja: 'cherty',
};
// Фильтруются только те категории, по которым у поста ЕСТЬ факт.
const LOOK_FILTERED = new Set(['dlina', 'cvet', 'ton']);
const LOOK_SIGNS = new Set(['+', '-', '0']);

// РАСПОЗНАВАНИЕ ФАКТА ПО НАЗВАНИЮ ИЗ promptkit. Названия оттуда приходят человеческими строками
// («короткое каре до линии челюсти», «холодный пепельный блонд»), и разбирать их надо здесь: в
// promptkit это значения промпта, а не словарь признаков, и лезть туда за токенами нельзя.
// ПОРЯДОК ПРАВИЛ ЗНАЧИМ: «платиновый блонд» обязан стать холодным, а «медно-рыжий» тёплым, поэтому
// тон определяется по названию оттенка, а не по цвету.
const LEN_RULES = [[/каре/i, 'kare'], [/хвост/i, 'hvost'], [/пучок/i, 'puchok'],
  [/чёлк|челк/i, 'chelka'], [/до плеч|плеч/i, 'plechi'], [/длинн/i, 'dlinnye']];
const COLOR_RULES = [[/блонд|платинов|пепельн/i, 'blond'], [/рыж|медн/i, 'ryzhee'],
  [/шоколад|каштан|тёмн|темн|брюнет/i, 'temnoe']];
const TONE_RULES = [[/холодн|пепельн|платинов/i, 'holodnyj'], [/медн|рыж|шоколад|каштан|тёплый|золот/i, 'teplyj']];
const matchRule = (rules, s) => { for (const [re, tok] of rules) if (re.test(s)) return tok; return null; };

/**
 * ФАКТЫ ОБРАЗА ПОСТА В ВИДЕ ТОКЕНОВ. Принимает что есть, отдаёт {dlina, cvet, ton} без пустых ключей.
 * Три способа позвать, все три равнозначны:
 *   lookFacts({ dlina: 'kare', cvet: 'blond' })                  уже токенами
 *   lookFacts({ lenName: pk.hairLen(i), colorName: pk.hairTarget(srcHair, hairIdx) })  названиями
 *   lookFacts({ hairLenIdx: 3, srcHair: 'dark', hairIdx: 0 })     индексами, как их считает onepost
 * Последний способ сам зовёт promptkit, потому что пулы длин и цветов живут ТАМ и дублировать их
 * здесь нельзя: разъедутся при первой же правке пула, и фильтр начнёт врать молча.
 * @returns {{dlina?:string,cvet?:string,ton?:string}} пустой объект = фактов нет
 */
function lookFacts(src) {
  const s = src || {};
  const out = {};
  // Токены, если их передали прямо. Неизвестный токен это опечатка, и молчать о ней нельзя: фильтр
  // от опечатки не падает, он просто перестаёт фильтровать, а это ровно тот баг, который мы чиним.
  for (const cat of ['dlina', 'cvet', 'ton']) {
    const v = s[cat];
    if (!v) continue;
    if (LOOK_FEATURES[v] !== cat) throw new Error(`hooks: признак «${v}» не из категории ${cat}`);
    out[cat] = v;
  }
  let lenName = s.lenName || '';
  let colorName = s.colorName || '';
  if ((!lenName || !colorName) && (s.hairLenIdx != null || s.srcHair)) {
    try {
      const pk = require('./promptkit.cjs');
      if (!lenName && s.hairLenIdx != null) lenName = pk.hairLen(s.hairLenIdx);
      // hairTarget без известной семьи исходника отдаёт общую фразу без названия цвета, и это
      // правильно: цвета мы тогда НЕ ЗНАЕМ, а значит фразы про цвет не выдаём вообще.
      if (!colorName && s.srcHair && s.srcHair !== 'auto') colorName = pk.hairTarget(s.srcHair, s.hairIdx || 0);
    } catch { /* promptkit недоступен: остаёмся без фактов, то есть на безопасном ядре */ }
  }
  if (!out.dlina && lenName) out.dlina = matchRule(LEN_RULES, lenName) || undefined;
  if (!out.cvet && colorName) out.cvet = matchRule(COLOR_RULES, colorName) || undefined;
  if (!out.ton && colorName) out.ton = matchRule(TONE_RULES, colorName) || undefined;
  for (const k of Object.keys(out)) if (!out[k]) delete out[k];
  return out;
}

/** Объект упоминаний из строки пула: он лежит последним и это единственный объект в строке. */
function rowLook(row) {
  for (let i = row.length - 1; i >= 0; i--) if (row[i] && typeof row[i] === 'object') return row[i];
  return null;
}

/** Фраза без упоминаний фильтруемых категорий: соврать про образ не может по построению. */
function isSafeCore(row) {
  const m = rowLook(row);
  if (!m) return true;
  return !Object.keys(m).some((f) => LOOK_FILTERED.has(LOOK_FEATURES[f]));
}

/**
 * СПОРИТ ЛИ ФРАЗА С ОБРАЗОМ ПОСТА. true = не выдавать.
 * Три правила, больше их не нужно:
 *   • нет факта по категории, а фраза про неё говорит  → не выдаём (это и есть «молчание лучше вранья»);
 *   • знак '-' и факт совпал с признаком              → фраза отрицает то, что на кадре (баг с каре);
 *   • знак '+' и факт по категории другой             → фраза хвалит то, чего на кадре нет.
 * Знак '0' это нейтральное называние, оно не спорит ни с чем, но факт по категории всё равно нужен:
 * «угадай, что мне сказали про мою чёлку» на кадре с пучком читается так же криво.
 */
function looksClash(row, facts) {
  const m = rowLook(row);
  if (!m) return false;
  for (const [f, sign] of Object.entries(m)) {
    const cat = LOOK_FEATURES[f];
    if (!LOOK_FILTERED.has(cat)) continue;      // черты лица пост не задаёт, спорить не о чем
    const fact = facts[cat];
    if (!fact) return true;
    if (sign === '-' && fact === f) return true;
    if (sign === '+' && fact !== f) return true;
  }
  return false;
}

// ═══ СВОЯ ЛОГИКА ХУКА ПОД КАЖДЫЙ ШАБЛОН (11.08, приказ начальника) ══════════════════════════════
// ДОСЛОВНО: «выкати агента который пересоберет логику 1 картинки по описанию, у нас слабые хуки,
// ничего не поменялось. Под бьюти гайд должна быть 1 логика, под фото с сердечками волосами другая».
//
// ЧТО БЫЛО НЕ ТАК, ПО ФАКТУ, А НЕ ПО ВКУСУ. Пулов было три (report, guide, trend), но ПРАВИЛА у них
// не было ни одного: любую фразу можно было дописать в любой пул, и проверка её пропускала. Поэтому
// пулы расползлись в одну кашу «признание от первого лица», и разница между постом с карточкой-
// разбором и постом с обработанным селфи на обложке не читалась вообще. Начальник это и увидел.
//
// ТЕПЕРЬ У КАЖДОГО ПУЛА ЕСТЬ ПРОВЕРЯЕМОЕ ПРАВИЛО (поля надо/нельзя ниже, проверяет check).
// Правило отвечает на один вопрос: ЧТО ХУК ОБЯЗАН ОБЕЩАТЬ, чтобы обещание нашлось на кадре 2.
//   report  оценка внешности (кадр 2 это карточка с БАЛЛАМИ): вердикт со стороны, цифра разрешена
//           и работает лучше всего, спор с цифрой ещё лучше;
//   guide   бьюти-гайд, цветотип, подбор стрижки, обложка журнала (кадр 2 это карточка-РАЗБОР без
//           баллов): вердикт со стороны обязателен, а баллов на карточке нет, значит и в хуке их
//           быть не может;
//   hearts  тренд «волосы сердечками» (карточки в посте НЕТ, есть арт по одному селфи): обещать
//           разбор нечем, поэтому логика другая — результат кадра и реакция окружающих;
//   art     остальной арт (чб, ретро, дудлы, новые формы): правило то же, что у сердечек.
//
// ПОЧЕМУ ПРАВИЛО ИМЕННО ТАКОЕ, А НЕ «пиши поинтереснее». Оно проверяемое. Слово-маркер вердикта
// («разбор», «тест», «гайд», «цветотип», «мне идёт») означает, что судит КТО-ТО СНАРУЖИ, а значит
// зритель листает за приговором себе. Слово-маркер реакции («бести спросила», «бывший ответил»,
// «глоу ап», «на аве») означает, что листают за причиной чужой реакции. Фраза без обоих маркеров
// это просто бойкая строчка, и на обложке она не работает: именно такие копились в пулах раньше.
//
// МАРКЕРЫ ВЕРДИКТА ЭТО ИСТОЧНИК ПРИГОВОРА, А НЕ ГЛАГОЛ РЕЧИ, И ЭТО ВАЖНО. Первая версия списка
