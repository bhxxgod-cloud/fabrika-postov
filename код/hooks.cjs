//   6a. ШЕСТЬ БОЛЕЗНЕЙ ИЗ РАЗБОРА (файл ЛОГИКА-ХУКА.md, гейт БОЛЕЗНИ + частыеНачала ниже):
//      термин без расшифровки (цветотип, андертон, контуринг), пассив «мне поставили», внутренняя
//      кухня («разбор», «вердикт», «пункт 4»), прямая команда зрителю («свайпни и сравни»),
