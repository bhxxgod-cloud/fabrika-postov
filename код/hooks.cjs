/**
 * Пост этой очереди — про подписчицу?
 * Считается ОТ ID ПОСТА, а не случайно: один и тот же пост всегда даёт один ответ, и пересборка
 * поста не превращает его из личного в чужой (иначе хук и подпись разъехались бы между прогонами).
 */
function проПодписчицу(id) {
  const каждый = Number(process.env.SUB_EVERY || 4);
  if (!каждый || каждый < 2) return false;
  return seedNum(String(id || '')) % каждый === 0;
}
