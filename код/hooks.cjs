//      ОСНОВАНИЯ У БОЛЕЗНЕЙ РАЗНЫЕ, и с 12.08 они не сваливаются в кучу: «команда» держится на
//      досмотре и нативности (петля и живая речь), а не на алгоритме — см. её комментарий в БОЛЕЗНИ.
//   6b. ДЛИНА ЭТО НЕ ТОЛЬКО ВЁРСТКА. Правила 1-3 (две строки, 13-38 знаков) заодно выполняют
//      официальное требование Instagram к рекомендуемости: текст не должен закрывать бо́льшую часть
//      экрана (help.instagram.com/313829416281232). Значит «давайте надпись покрупнее и на три
