/** Комментарии на пробелы той же длины: позиции символов не съезжают, номера строк остаются верными. */
const безКомментариев = (src) => src.replace(/\/\/[^\n]*/g, (m) => ' '.repeat(m.length));

/**
 * Литералы массива-константы прямо из исходника файла.
 * @returns {Array<{текст:string, строка:number}>} или null, если константы в файле нет
 */
function литералыКонстанты(src, имя) {
  const s = безКомментариев(src);
  const i = s.indexOf(`const ${имя} = `);
  if (i < 0) return null;
  // Баланс скобок от первой открывающей, со скипом строк: внутри фраз скобок нет, но «(((» в тексте
  // однажды появятся, и на них парсер обязан не сломаться.
  let j = i; while (j < s.length && s[j] !== '[' && s[j] !== '{') j++;
  let depth = 0, конец = s.length;
  for (let k = j; k < s.length; k++) {
    const ch = s[k];
    if (ch === "'" || ch === '"' || ch === '`') { const q = ch; k++; while (k < s.length && s[k] !== q) { if (s[k] === '\\') k++; k++; } continue; }
    if (ch === '[' || ch === '{') depth++;
    else if (ch === ']' || ch === '}') { depth--; if (!depth) { конец = k; break; } }
  }
  const блок = s.slice(j, конец);
  const out = [];
  for (const m of блок.matchAll(/'((?:[^'\\]|\\.)*)'/g)) {
    const текст = m[1].replace(/\\n/g, '\n').replace(/\\'/g, "'");
    out.push({ текст, строка: s.slice(0, j + m.index).split('\n').length });
  }
  return out;
}

/**
 * Ошибки ВНЕШНИХ пулов (болезни 1-6). Длину, число строк и логику шаблона тут не меряем: заголовки
 * подписи это одна длинная строка по построению, а болезни одинаковы для любой надписи.
 * @returns {string[]} строки вида «файл:строка «фраза»: болезнь»
 */
function checkВнешние() {
  const errs = [];
  for (const [файл, имя, про] of ВНЕШНИЕ_ПУЛЫ) {
    let src = '';
    try { src = require('node:fs').readFileSync(require('node:path').join(__dirname, файл), 'utf8'); }
    catch { errs.push(`${файл}: файл не читается, а в нём живёт пул ${имя} (${про})`); continue; }
    const rows = литералыКонстанты(src, имя);
    if (!rows) { errs.push(`${файл}: не найдена константа ${имя} (${про}) — пул переименовали или унесли, гейт его больше не сторожит`); continue; }
    for (const { текст, строка } of rows) {
      for (const d of диагноз(текст)) {
        errs.push(`${файл}:${строка} «${текст.replace(/\n/g, ' / ')}»: болезнь «${d.болезнь}» — «${d.совпало}»: ${d.чем}`);
      }
    }
    for (const [н, n] of частыеНачала(rows.map((r) => r.текст))) {
      errs.push(`${файл} ${имя}: ${n} фраз начинаются с «${н}», предел ${НАЧАЛО_ПРЕДЕЛ} (болезнь 3 части 3: лента видит однотипный контент)`);
    }
  }
  return errs;
}

