#!/usr/bin/env node
'use strict';
// ЭТАЛОН ЛИЦА ПЕРСОНЫ: С ЧЕМ СВЕРЯТЬ КАДР 1 (13.08, разбор жалобы начальника «стал здоровый нос,
// а на исходном селфи она милая»; пост 10 персоны розовая-полумесяц, шаблон img-brow-map).
//
// ЧТО СЛОМАЛОСЬ. Кадр 1 у нас считается неприкосновенным: onepost берёт файл начальника, режет в
// 4:5, наносит хук — и всё. Гейты построены на том же допущении: framegate меряет схожесть лица
// пар 1-3 и 1-4, то есть КАДР 1 ВЗЯТ ЗА ЭТАЛОН, а cover_qa смотрит резкость и красоту, но не
// личность. Пока обложкой была фотография живого человека, этого хватало.
//
// Допущение перестало быть верным 12.08, когда появился facegen.cjs («один раз найденная девушка
// становится бесконечной»): обложки теперь РИСУЕТ модель по референсу. С этого момента кадр 1 стал
// такой же генерацией, как кадры 3 и 4, — но проверять его не с чем: эталона у нас нигде не лежало.
//
// ЗАМЕР, ИЗ КОТОРОГО ВЫРОС ЭТОТ ФАЙЛ (13.08, склад, facesim.py, порог 0.363).
// Пакет обложек МОДЕЛИ-НОВЫЕ-13-08 для тега «розовая» был заказан НЕ с живого селфи, а с файла
// РОЗОВАЯ/pink1_новый.jpg, то есть с предыдущей генерации facegen. Числа по цепочке:
//   живое селфи (РОЗОВАЯ/розовая_исходник.jpg) ↔ pink1_новый (поколение 1) = 0.200  ← уже чужой человек
//   pink1_новый ↔ розовая_25_новый (поколение 2)                            = 0.751  ← «лицо сохранено»
//   живое селфи ↔ розовая_25_новый (это кадр 1 живого поста img-brow-map)   = 0.318  ← ЧУЖОЙ ЧЕЛОВЕК
// Каждый ШАГ по отдельности проверку проходит (сверяется с ближайшим родителем), а сумма двух шагов
// уводит от живого человека за порог. По всем 15 постам персоны: 14 из 15 кадров 1 ниже 0.363
// (от 0.181 до 0.343). У персон, чей пакет заказан с настоящей фотографии, тем же замером всё
// цело: аня 0.888-0.914, тату-розовая 0.787-0.831, веснушки 0.487-0.697, загорелая 0.635-0.666,
// бмв-очки 0.535-0.563.
//
// ОТСЮДА ПРАВИЛО. У персоны есть ОДИН эталон — та самая живая фотография, с которой всё началось.
// Сверять любую обложку надо С НИМ, а не с ближайшим родителем, иначе дрейф копится молча.
//
// ПОЧЕМУ РЕЕСТР ЗАПОЛНЯЕТСЯ РУКАМИ, А НЕ САМ. Соблазн «взять первую обложку персоны за эталон»
// нужно погасить сразу: у розовой-полумесяца первой обложкой как раз и была подмена, и автоматика
// закрепила бы чужое лицо навсегда, да ещё и с видом законности. Эталон это решение человека,
// поэтому он кладётся командой и хранится вместе с отпечатком sha256: если файл по пути подменят,
// гейт это увидит числом (та же логика, что у source_sha256 в onepost).
//
// ПОРОГ. Тот же канонический 0.363, что у facesim.py: два порога в одном проекте разъедутся.
// Сверх него введена СЕРАЯ ЗОНА до 0.45 — предупреждение, но не брак. Обоснование числом: у
// сломанной персоны один кадр из пятнадцати дал 0.377, то есть брак прижимается к порогу вплотную,
// а самый низкий ЗДОРОВЫЙ живой кадр дал 0.487. Между 0.363 и 0.45 приговор выносят глаза.
//
// Запуск:
//   node faceref.cjs --set <персона> <файл> [--как <тег,тег>] [--почему "текст"]   запомнить эталон
//   node faceref.cjs --list                                      что записано
//   node faceref.cjs --check <персона> <файл>                    сверить кадр с эталоном
//   node faceref.cjs --audit [--persona <имя>] [--limit 50]      пройти по складу и померить кадр 1
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const { faceSim, SAME_FACE } = require('./facesim.cjs');

const РЕЕСТР = path.join(__dirname, 'эталоны.json');
// Серая зона сверху: ниже БРАК — чужой человек, выше СЕРАЯ — точно свой, между ними глаза.
const СЕРАЯ = 0.45;

/** Ключ персоны нормализован так же, как в coverguard.cjs: в базе одна девочка бывает и «Дарья», и «дарья». */
const ключ = (persona) => String(persona || '').trim().toLowerCase();

function реестр() {
  try { return JSON.parse(fs.readFileSync(РЕЕСТР, 'utf8')); } catch { return {}; }
}

function sha(f) {
  try { return crypto.createHash('sha256').update(fs.readFileSync(f)).digest('hex'); } catch { return null; }
}

/**
 * Эталон персоны или null, если его не записывали.
 * @returns {{файл:string, sha256:string, добавлен:string, почему:string, подменён?:boolean}|null}
 */
function эталон(persona) {
  const з = реестр()[ключ(persona)];
  if (!з || !з.файл) return null;
  if (!fs.existsSync(з.файл)) return { ...з, пропал: true };
  // ПОДМЕНУ ФАЙЛА ПО ПУТИ ЛОВИМ ЧИСЛОМ. Папки исходников переиспользуются волнами (см. шапку
  // onepost про source_sha256): путь остаётся, а картинка под ним уже другая.
  const s = sha(з.файл);
  return { ...з, подменён: !!(з.sha256 && s && s !== з.sha256) };
}

/**
 * Записать эталон персоны. Перезапись разрешена: начальник вправе сменить эталонное фото.
 *
 * ПСЕВДОНИМЫ ОБЯЗАТЕЛЬНЫ, А НЕ УКРАШЕНИЕ. Одна и та же девочка зовётся в базе «розовая-полумесяц»,
 * а в пакете кадров тегом «розовая» (файлы розовая_25_новый.jpg). Сборщик спросит эталон по имени
 * персоны, facegen — по тегу. Если запись одна, второй спросивший получит «эталона нет» и гейт
 * промолчит ровно там, где он и нужен. Поэтому все имена кладём как отдельные ключи на один файл.
 */
function запомнить(persona, файл, почему = '', псевдонимы = []) {
  const p = path.resolve(файл);
  if (!fs.existsSync(p)) throw new Error(`нет файла ${p}`);
  const r = реестр();
  const з = {
    файл: p, sha256: sha(p), добавлен: new Date().toISOString().slice(0, 19).replace('T', ' '),
    почему: почему || 'эталон задан руками',
  };
  for (const имя of [persona, ...псевдонимы].filter(Boolean)) {
    r[ключ(имя)] = имя === persona ? з : { ...з, псевдоним_для: ключ(persona) };
  }
  fs.writeFileSync(РЕЕСТР, JSON.stringify(r, null, 1));
  return з;
}

/**
 * Сверить кадр с эталоном персоны.
 *
 * ОТСУТСТВИЕ ЭТАЛОНА ЭТО НЕ БРАК, А «НЕ ПРОВЕРЕНО» (урок validatepost.cjs, где HTTP 402 от vision
 * прочитали как брак и девять годных постов уехали в rejected). Гейт на этом ответе обязан
 * пропускать пост дальше и говорить об этом строкой, а не молча.
 *
 * @returns {{есть:boolean, ok:boolean|null, v:number|null, порог:number, серая:boolean, почему:string, файл?:string}}
 */
function проверить(persona, кадр) {
  const э = эталон(persona);
  if (!э) return { есть: false, ok: null, v: null, порог: SAME_FACE, серая: false, почему: `эталон персоны «${persona}» не записан (node faceref.cjs --set)` };
  if (э.пропал) return { есть: true, ok: null, v: null, порог: SAME_FACE, серая: false, файл: э.файл, почему: `файл эталона пропал: ${э.файл}` };
  if (!fs.existsSync(кадр)) return { есть: true, ok: null, v: null, порог: SAME_FACE, серая: false, файл: э.файл, почему: `нет файла кадра ${кадр}` };
  const r = faceSim([э.файл, кадр]);
  if (r.error) return { есть: true, ok: null, v: null, порог: SAME_FACE, серая: false, файл: э.файл, почему: `мера не сработала: ${r.error}` };
  const v = r.pairs['1-2'];
  // null это «лица не нашли», и это НЕ ноль: ноль читается как «другой человек».
  if (v === null || v === undefined) return { есть: true, ok: null, v: null, порог: r.same, серая: false, файл: э.файл, почему: 'лица не нашлись на эталоне или на кадре' };
  return {
    есть: true, ok: v >= r.same, v, порог: r.same, серая: v >= r.same && v < СЕРАЯ, файл: э.файл,
    подменён: !!э.подменён,
    почему: v >= r.same
      ? (v < СЕРАЯ ? `схожесть с эталоном ${v} — серая зона (порог ${r.same}, уверенно свой от ${СЕРАЯ}), смотреть глазами` : `схожесть с эталоном ${v}`)
      : `на кадре ДРУГОЙ ЧЕЛОВЕК: схожесть с эталоном ${v} при пороге ${r.same}`,
  };
}

// ═══ ЗАПУСК РУКАМИ ═══════════════════════════════════════════════════════════════════════════
async function аудит(персона, лимит) {
  const { Client } = require('pg');
  const url = (process.env.DB_PUBLIC_URL || fs.readFileSync('/tmp/dburl.txt', 'utf8')).trim();
  const c = new Client({ connectionString: url, ssl: { rejectUnauthorized: false } });
  await c.connect();
  const где = персона ? "AND meta->>'persona' = $1" : '';
  const r = await c.query(
    `SELECT id, status, meta->>'persona' persona, meta->>'template' tpl,
            meta->>'source_cover' src, meta->'image_urls'->>0 url
       FROM posts WHERE meta->'image_urls'->>0 IS NOT NULL ${где}
      ORDER BY created_at DESC LIMIT ${Number(лимит) || 50}`, персона ? [персона] : []);
  await c.end();
  const { execFileSync } = require('node:child_process');
  const каталог = '/tmp/faceref';
  fs.mkdirSync(каталог, { recursive: true });
  let брак = 0, серых = 0, нет = 0;
  for (const п of r.rows) {
    // Меряем ЛОКАЛЬНЫЙ исходник обложки, если он на месте: он же ушёл в пост кадром 1, а качать
    // ссылку ради того же лица значит греть сеть на ровном месте. Нет файла — качаем кадр 1.
    let кадр = п.src && fs.existsSync(п.src) ? п.src : null;
    if (!кадр) {
      кадр = path.join(каталог, `${п.id.slice(0, 8)}.jpg`);
      try { if (!fs.existsSync(кадр)) execFileSync('curl', ['-sS', '--fail', '--max-time', '60', '-o', кадр, п.url]); } catch { кадр = null; }
    }
    const в = кадр ? проверить(п.persona, кадр) : { есть: false, почему: 'кадр 1 не достать' };
    if (!в.есть || в.ok === null) нет++;
    else if (!в.ok) брак++;
    else if (в.серая) серых++;
    const знак = !в.есть || в.ok === null ? '·' : в.ok ? (в.серая ? '⚠' : '✓') : '✗';
    console.log(`${знак} ${п.id.slice(0, 8)} ${String(п.status).padEnd(8)} ${String(п.persona).padEnd(20)} ${String(п.tpl).padEnd(22)} ${в.почему}`);
  }
  console.log(`\nитог: постов ${r.rows.length}, чужое лицо на кадре 1: ${брак}, серая зона: ${серых}, не проверено: ${нет}`);
}

async function main() {
  const a = process.argv.slice(2);
  const флаг = (n, d) => { const i = a.indexOf(`--${n}`); return i >= 0 ? a[i + 1] : d; };
  if (a[0] === '--set') {
    const псевдо = String(флаг('как', '')).split(',').map((s) => s.trim()).filter(Boolean);
    const з = запомнить(a[1], a[2], флаг('почему', ''), псевдо);
    console.log(`эталон «${a[1]}»${псевдо.length ? ` (он же ${псевдо.join(', ')})` : ''} = ${з.файл}`
      + `\n  sha256 ${з.sha256.slice(0, 16)}…, записан ${з.добавлен}`);
    return;
  }
  if (a[0] === '--list') {
    const r = реестр();
    const имена = Object.keys(r).sort();
    if (!имена.length) { console.log(`реестр пуст (${РЕЕСТР})`); return; }
    for (const n of имена) {
      const э = эталон(n);
      console.log(`${n.padEnd(22)} ${э.файл}${э.пропал ? '  ✗ ФАЙЛ ПРОПАЛ' : э.подменён ? '  ✗ ФАЙЛ ПОДМЕНЁН (sha не сходится)' : ''}`);
    }
    return;
  }
  if (a[0] === '--check') {
    const в = проверить(a[1], a[2]);
    console.log(`${в.ok === null ? '·' : в.ok ? (в.серая ? '⚠' : '✓') : '✗'} ${в.почему}`);
    process.exit(в.ok === false ? 1 : 0);
  }
  if (a[0] === '--audit') { await аудит(флаг('persona', null), флаг('limit', 50)); return; }
  console.log(fs.readFileSync(__filename, 'utf8').split('\n').filter((l) => l.startsWith('//')).slice(-6).join('\n'));
}

if (require.main === module) main().catch((e) => { console.error('ПАДЕНИЕ:', e.message); process.exit(1); });
module.exports = { эталон, запомнить, проверить, ключ, СЕРАЯ, ПОРОГ: SAME_FACE, РЕЕСТР };
