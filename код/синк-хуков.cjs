// ЗАЧЕМ. Хуки живут в трёх местах и вели их разные ветки чата:
//   hooks2.cjs            хуки НА КАДРЕ поста, пары [хук, продолжение подписи], ведёт генерка;
//   новые-шаблоны-хуки.json  строки владельца под новые тренды, ведёт генерка;
//   хуки-пул.json         хуки под ЗАГОЛОВОК и ПРЕВЬЮ ютуба, веду я.
// По новым шаблонам списки уже разошлись: 8 строк были только у генерки, 22 только у меня, при
// том что владелец диктовал их в один день. Дальше расхождение только росло бы.
//
// ЧТО ДЕЛАЕТ. Вливает в хуки-пул.json недостающие строки из файлов генерки, НЕ трогая уже
// присвоенные номера (на них ссылается реестр hook_usage и имена файлов) и НЕ возвращая то, что
// владелец сегодня вычеркнул глазами: отсев лежит в вычеркнутые-хуки.json, 67 строк.
//
// Запуск:  node синк-хуков.cjs           показать, что изменится
//          node синк-хуков.cjs --влить   применить
const fs = require('fs');
const path = require('path');

const П = (f) => path.join(__dirname, f);
const пул = JSON.parse(fs.readFileSync(П('хуки-пул.json'), 'utf8'));
const новые = JSON.parse(fs.readFileSync(П('новые-шаблоны-хуки.json'), 'utf8'));
const выч = JSON.parse(fs.readFileSync(П('вычеркнутые-хуки.json'), 'utf8'));
const { регистр } = require('./регистр.cjs');

// Русские слаги генерки к нашим английским: имена файлов и шаблоны у нас латиницей.
const КАРТА = {
  'люкс-бренд': 'luxury-brand', 'люкс-сумка': 'lux-bag', 'психологический-возраст': 'psy-age',
  'сколько-выглядишь': 'perceived-age', 'количество-партнёров': 'partner-count',
  'разбор-парня': 'boyfriend-report', '10-стрижек': 'haircut-10', 'гайд-барберу': 'barber-guide',
  'будущий-ребёнок': 'baby-match', 'какая-машина': 'car-match', 'я-в-детстве': 'then-now',
};

// Ёфикация: у генерки «ребёнок», у меня «ребенок». Без схлопывания ё→е половина строк
// выглядела как расхождение, и синк собирался влить дубли уже существующих хуков.
const norm = (s) => String(s).toLowerCase().replace(/ё/g, 'е').replace(/[^а-яa-z0-9]/gi, '');
const ПЛОХИЕ = new Set();
for (const k of Object.keys(выч)) for (const s of выч[k] || []) ПЛОХИЕ.add(norm(s));

// Следующий свободный номер шаблона: старые номера НИКОГДА не переиспользуем.
function следующий(шаблон) {
  const был = [...(пул[шаблон]?.крик || []), ...(пул[шаблон]?.пов || [])]
    .map((h) => Number(String(h.id).replace(/^.*-h/, ''))).filter((n) => !isNaN(n));
  return (был.length ? Math.max(...был) : 0) + 1;
}

const план = [];
for (const [ру, en] of Object.entries(КАРТА)) {
  const их = (новые[ру] && новые[ру].хуки) || [];
  if (!их.length) continue;
  if (!пул[en]) пул[en] = { крик: [], пов: [] };
  const есть = new Set([...(пул[en].крик || []), ...(пул[en].пов || [])].map((h) => norm(h.т)));
  for (const строка of их) {
    const n = norm(строка);
    if (есть.has(n)) continue;
    if (ПЛОХИЕ.has(n)) { план.push({ шаблон: en, строка, что: 'ПРОПУСК: вычеркнута владельцем' }); continue; }
    план.push({ шаблон: en, строка, что: 'добавить', регистр: регистр(строка) });
    есть.add(n);
  }
}

// Обратная сверка: чего нет у генерки, но есть у меня. Это не правка, это список на отдачу.
const отдать = [];
for (const [ру, en] of Object.entries(КАРТА)) {
  const их = new Set(((новые[ру] && новые[ру].хуки) || []).map(norm));
  for (const рег of ['крик', 'пов']) for (const h of пул[en]?.[рег] || []) {
    if (!их.has(norm(h.т))) отдать.push({ шаблон: en, id: h.id, строка: h.т });
  }
}

if (!process.argv.includes('--влить')) {
  if (план.length) { console.log('ВЛИТЬ К СЕБЕ (' + план.filter((x) => x.что === 'добавить').length + '):'); console.table(план); }
  else console.log('вливать нечего: все строки генерки уже есть');
  console.log('\nОТДАТЬ ГЕНЕРКЕ (' + отдать.length + ' строк, которых нет у них):');
  console.table(отдать.slice(0, 40));
  if (отдать.length > 40) console.log('  ... и ещё ' + (отдать.length - 40));
  console.log('\nприменить: node синк-хуков.cjs --влить');
  process.exit(0);
}

let n = 0;
for (const x of план) {
  if (x.что !== 'добавить') continue;
  const рег = x.регистр;
  пул[x.шаблон][рег] = пул[x.шаблон][рег] || [];
  пул[x.шаблон][рег].push({ id: x.шаблон + '-h' + String(следующий(x.шаблон)).padStart(2, '0'), т: x.строка });
  n++;
}
fs.writeFileSync(П('хуки-пул.json'), JSON.stringify(пул, null, 1));
console.log('влито строк: ' + n);
