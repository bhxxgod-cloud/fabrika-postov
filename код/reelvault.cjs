// reelvault.cjs — СОКРОВИЩНИЦА: ВСЕ РИЛСЫ ПРОЕКТА В ОДНОЙ ПАПКЕ (14.08).
//
// ЗАЧЕМ. Задача владельца дословно: «собери все наши рилсы когда либо сделанные в 1 папку и
// придумай логику отсева откровенного мусора и отсортируй ненужные. 1 папка будет чтобы хранить
// все наше сокровище! будет туда каждый рилс идти и в свои прежние папки».
//
// ЧТО НАШЛОСЬ ПРИ ЗАМЕРЕ: 2444 файла .mp4 на 3.7 ГБ, разбросанных по 20 папкам. Больше трети —
// копии одного и того же: «чубамба/2026-08-13» и «БРАК/хук-под-подписью-90/13-08-нарезанные» это
// один набор из 229 файлов, лежащий дважды; «РИЛСЫ ВСЕ/11-08-уникализированные» дублирует такую
// же папку в БРАКе. Поэтому первое, что делает хранилище, — считает содержимое, а не имена.
//
// ЖЁСТКИЕ ССЫЛКИ, А НЕ КОПИИ. Владелец просил, чтобы рилс лежал И в сокровищнице, И в своей
// прежней папке. Копирование удвоило бы 3.7 ГБ на ровном месте. Жёсткая ссылка — это ТОТ ЖЕ файл,
// видимый под двумя именами: места занимает ноль, открывается одинаково отовсюду. Диск один том,
// так что ссылки работают. Если ссылка не встала (разные тома) — честно копируем.
//
// ЛОГИКА ОТСЕВА. Мусор бывает трёх сортов, и они разного происхождения:
//   · ДУБЛЬ — тот же файл под другим путём. Считаем sha1 содержимого;
//   · ЗНАЕМ, ЧТО БРАК — файл лежит в папке брака, разобранной ранее (хук на лице, хук под
//     подписью, карточка с полями, дубли-по-посту). Эти приговоры уже вынесены глазами, и
//     пересматривать их заново незачем: путь и есть приговор;
//   · БИТЫЙ — файл меньше 100 КБ или не читается ffprobe. Такой не откроется и у зрителя.
// Всё остальное считается годным и попадает в «годные». Спорное не выбрасываем: раскладываем по
// причинам, чтобы решение было видно и обратимо.
//
// СОРТИРОВКА ГОДНЫХ ПО ДАТАМ, а не в одну кучу: 1670 файлов одним списком не листаются.
//
// Запуск:
//   node reelvault.cjs --dry   посчитать и показать план, ничего не трогая
//   node reelvault.cjs --go    разложить
'use strict';
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const crypto = require('node:crypto');
const { execFileSync } = require('node:child_process');

const DRY = !process.argv.includes('--go');
const ХРАНИЛИЩЕ = process.env.VAULT || path.join(os.homedir(), 'Desktop', 'СОКРОВИЩНИЦА-РИЛСЫ');
const КОРНИ = [path.join(os.homedir(), 'Desktop')];
const МИН_РАЗМЕР = 100 * 1024;

// Папки, приговор которым уже вынесен — их содержимое едет в «отсев», а не в «годные».
const БРАК_В_ПУТИ = [
  { кусок: 'хук-на-лице', причина: 'хук-на-лице' },
  { кусок: 'хук-под-подписью', причина: 'хук-под-подписью' },
  { кусок: 'карточка-с-полями', причина: 'карточка-с-полями' },
  { кусок: 'ДУБЛИ-по-посту', причина: 'дубль-по-посту' },
  { кусок: 'ОТБРАКОВКА', причина: 'отбраковка-сканом' },
  { кусок: '_карантин', причина: 'карантин' },
];

function всеФайлы(корень) {
  const из = [];
  const обойти = (д, глубина) => {
    if (глубина > 6) return;
    let список;
    try { список = fs.readdirSync(д, { withFileTypes: true }); } catch { return; }
    for (const э of список) {
      const п = path.join(д, э.name);
      if (э.isDirectory()) {
        if (э.name === 'node_modules' || э.name.startsWith('.')) continue;
        if (п.startsWith(ХРАНИЛИЩЕ)) continue;  // себя не индексируем
        обойти(п, глубина + 1);
      } else if (/\.mp4$/i.test(э.name)) {
        из.push(п);
      }
    }
  };
  обойти(корень, 0);
  return из;
}

const sha1 = (ф) => crypto.createHash('sha1').update(fs.readFileSync(ф)).digest('hex');

// Дата рилса: из имени папки (14-08, 2026-08-13) либо из времени файла.
function когда(ф) {
  const m = ф.match(/(\d{4})-(\d{2})-(\d{2})/) || ф.match(/\b(\d{2})-(\d{2})\b/);
  if (m && m.length === 4) return `${m[1]}-${m[2]}-${m[3]}`;
  if (m && m.length === 3) return `2026-${m[2]}-${m[1]}`;
  const d = fs.statSync(ф).mtime;
  return `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, '0')}-${String(d.getDate()).padStart(2, '0')}`;
}

function положить(откуда, куда) {
  fs.mkdirSync(path.dirname(куда), { recursive: true });
  if (fs.existsSync(куда)) return 'уже там';
  try { fs.linkSync(откуда, куда); return 'ссылка'; }
  catch { fs.copyFileSync(откуда, куда); return 'копия'; }
}

const файлы = КОРНИ.flatMap(всеФайлы);
console.log(`найдено файлов .mp4: ${файлы.length}`);

const поХешу = new Map();
const итог = { годных: 0, дублей: 0, битых: 0, брака: 0 };
const причины = {};

for (const ф of файлы) {
  let размер = 0;
  try { размер = fs.statSync(ф).size; } catch { continue; }
  if (размер < МИН_РАЗМЕР) { итог.битых++; причины['битый-мелкий'] = (причины['битый-мелкий'] || 0) + 1; continue; }

  let h;
  try { h = sha1(ф); } catch { итог.битых++; continue; }
  if (поХешу.has(h)) { итог.дублей++; continue; }
  поХешу.set(h, ф);

  const брак = БРАК_В_ПУТИ.find((б) => ф.includes(б.кусок));
  if (брак) {
    итог.брака++;
    причины[брак.причина] = (причины[брак.причина] || 0) + 1;
    if (!DRY) положить(ф, path.join(ХРАНИЛИЩЕ, 'отсев', брак.причина, path.basename(ф)));
    continue;
  }
  // НЕ НАШЕ ИМЯ — НЕ РИЛС (15.08): личные видео владельца лежали в архиве стола и уехали на акки.
  if (!require('./места.cjs').нашРилс(path.basename(ф))) {
    итог.брака++; причины['НЕ-НАШИ-личные-и-тесты'] = (причины['НЕ-НАШИ-личные-и-тесты'] || 0) + 1;
    if (!DRY) положить(ф, path.join(ХРАНИЛИЩЕ, 'отсев', 'НЕ-НАШИ-личные-и-тесты', path.basename(ф)));
    continue;
  }
  итог.годных++;
  // плоско, без подпапок по датам — см. reelwatch, приказ владельца «все видео в 1 папку»
  if (!DRY) положить(ф, path.join(ХРАНИЛИЩЕ, 'годные', path.basename(ф)));
}

console.log(`\nуникальных по содержимому: ${поХешу.size}`);
console.log(`  годных    ${итог.годных}`);
console.log(`  в отсеве  ${итог.брака}`);
console.log(`  дублей    ${итог.дублей} (не копируем)`);
console.log(`  битых     ${итог.битых}`);
console.log('\nпричины отсева:');
for (const [п, н] of Object.entries(причины).sort((a, b) => b[1] - a[1])) console.log(`  ${String(н).padStart(4)}  ${п}`);
console.log(DRY ? '\nэто был счёт, ничего не трогал. Разложить: --go' : `\nразложено в ${ХРАНИЛИЩЕ}`);
