'use strict';
// СКОЛЬКО ПОТРАЧЕНО НА ГЕНЕРАЦИЮ (17.08, приказ владельца «посчитай, сколько потратили вчера»).
//
// ЗАЧЕМ. Вопрос «сколько ушло вчера» стоил получаса раскопок и всё равно дал вилку: денег на диске
// не было нигде, только в логах конкретных прогонов, а логи затираются и живут по разным папкам.
// Считать пришлось по числу созданных файлов, а это врёт в обе стороны: битый кадр провайдера
// файла не оставляет, но деньги за него списаны, а один и тот же кадр может быть перезаписан.
//
// ОТКУДА ЧИСЛА. Теперь rgen.cjs дописывает строку в ~/.neironka/траты.jsonl на КАЖДЫЙ заказ, в
// момент заказа. Это единственное честное место: деньги списываются при постановке задачи.
// Журнал заведён 17.08, поэтому за более ранние дни он пуст, и это не ошибка чтения.
//
// Запуск:
//   node траты.cjs                 за сегодня и вчера
//   node траты.cjs --дней 7        за последние 7 дней, по дням
//   node траты.cjs --день 2026-08-17
//   node траты.cjs --подробно      разбивка по скриптам и моделям
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');

const ЖУРНАЛ = path.join(os.homedir(), '.neironka', 'траты.jsonl');
const АРГ = process.argv.slice(2);
const опция = (имя, поум = null) => {
  const i = АРГ.indexOf('--' + имя);
  return i >= 0 && АРГ[i + 1] && !АРГ[i + 1].startsWith('--') ? АРГ[i + 1] : поум;
};
const ПОДРОБНО = АРГ.includes('--подробно');
const ДНЕЙ = Number(опция('дней', 2));
const ДЕНЬ = опция('день');

if (!fs.existsSync(ЖУРНАЛ)) {
  console.log(`журнала ещё нет: ${ЖУРНАЛ}`);
  console.log('он заводится при первом же заказе картинки после 17.08. До этого дня трат в нём нет.');
  process.exit(0);
}

// БИТАЯ СТРОКА НЕ ОБНУЛЯЕТ ОТЧЁТ. Журнал дописывается конкурентно из нескольких процессов сборки,
// поэтому оборванный хвост при падении это норма, а не повод показать ноль (урок реестра рилсов).
const строки = fs.readFileSync(ЖУРНАЛ, 'utf8').split('\n').filter(Boolean);
const записи = [];
let битых = 0;
for (const s of строки) {
  try { записи.push(JSON.parse(s)); } catch { битых++; }
}

const день = (iso) => new Date(iso).toLocaleDateString('sv');   // 2026-08-17
const деньги = (n) => `$${n.toFixed(2)}`;

const поДням = new Map();
for (const з of записи) {
  const d = день(з.когда);
  if (!поДням.has(d)) поДням.set(d, { сумма: 0, заказов: 0, скрипты: new Map(), модели: new Map() });
  const т = поДням.get(d);
  т.сумма += з.цена || 0;
  т.заказов++;
  т.скрипты.set(з.кто, (т.скрипты.get(з.кто) || 0) + (з.цена || 0));
  const м = `${з.модель} ${з.размер}`;
  т.модели.set(м, (т.модели.get(м) || 0) + (з.цена || 0));
}

const дни = [...поДням.keys()].sort().reverse();
const показать = ДЕНЬ ? дни.filter((d) => d === ДЕНЬ) : дни.slice(0, ДНЕЙ);

if (!показать.length) {
  console.log(ДЕНЬ ? `за ${ДЕНЬ} трат в журнале нет` : 'журнал пуст');
  process.exit(0);
}

let всего = 0;
for (const d of показать) {
  const т = поДням.get(d);
  всего += т.сумма;
  console.log(`\n${d}: ${деньги(т.сумма)}, заказов ${т.заказов}`);
  if (ПОДРОБНО) {
    const строкой = (m) => [...m.entries()].sort((a, b) => b[1] - a[1])
      .map(([k, v]) => `    ${деньги(v).padStart(8)}  ${k}`).join('\n');
    console.log('  по скриптам:\n' + строкой(т.скрипты));
    console.log('  по моделям:\n' + строкой(т.модели));
  }
}
if (показать.length > 1) console.log(`\nза ${показать.length} дн.: ${деньги(всего)}`);
if (битых) console.log(`\n⚠ битых строк в журнале: ${битых} (обрыв при падении, на сумму влияют мало)`);
