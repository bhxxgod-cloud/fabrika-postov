// ПОДНЯТЬ ТЕМП ТОЛЬКО НОВЫМ КАНАЛАМ.
//
// Старые трогать нельзя (приказ владельца 29.08: «старые уже не трогаем»), а
// общая раскладка «разложить-часы.cjs» перекроила бы и их: она пишет часы всем
// каналам разом, и старые упали бы с 5 публикаций до 3.
//
// Часы берём из её же плана на 3 публикации, но применяем только к шести новым.
// Минуты у каждого свои: в снос 26.08 каналы легли за одновременность, и разводить
// надо обе координаты, час и минуту.
const { Client } = require('pg');
const DBURL = require('./dburl.cjs')();

// Минуты подобраны ПОСЛЕ проверки расписанием, а не взяты из общей раскладки.
// Первый заход дал тесные пары вплоть до ОДНОЙ минуты (00:36 «Другая Я» против
// 00:37 «Красота решает»): общая раскладка считала на 3 публикации у всех, а
// старые каналы остались на пяти, и сетка разъехалась. Синхронность это ровно
// то, за что 26.08 снесли пять каналов, поэтому разводим руками и проверяем.
// У старых заняты минуты :03 (brand), :06 (iishnaya), :09 (stylist),
// :12 (pokazhu), :36 (drugaya) — новым даём вторую половину часа.
const ПЛАН = {
  new1: { часы: '6,14,22',  минута: 25 },
  new2: { часы: '3,11,19',  минута: 45 },
  new3: { часы: '4,12,20',  минута: 20 },
  new4: { часы: '7,15,23',  минута: 50 },
  new5: { часы: '0,8,16',   минута: 48 },
  new6: { часы: '2,10,18',  минута: 42 },
};

(async () => {
  const c = new Client({ connectionString: DBURL, ssl: { rejectUnauthorized: false } });
  await c.connect();
  for (const [slug, p] of Object.entries(ПЛАН)) {
    const r = await c.query(
      'UPDATE yt_channels SET per_day=3, post_hours=$2, post_minute=$3, updated_at=now() WHERE slug=$1 RETURNING slug, per_day, post_hours, post_minute',
      [slug, p.часы, p.минута],
    );
    if (r.rows[0]) {
      const x = r.rows[0];
      console.log(`  ${x.slug}: ${x.per_day}/сутки, часы ${x.post_hours}, минута :${String(x.post_minute).padStart(2, '0')}`);
    } else console.log(`  ${slug}: канала нет в базе`);
  }
  await c.end();
})().catch((e) => { console.error('ERR', e.message); process.exit(1); });
