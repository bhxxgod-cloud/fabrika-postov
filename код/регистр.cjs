'use strict';
// РЕГИСТР РЕЧИ ХУКА: «крик» или «пов». Одно место на весь проект (25.08.2026).
//
// Два регистра ввёл владелец, правя пул построчно. Определять их «на глаз» в каждом файле было
// ошибкой: первая версия жила в thumbgen.cjs и записала в «крик» дневниковую строку «Мне было
// все равно на сумки! Пока не увидела эту!» только потому, что там восклицание, а не скобки.
//
// ГРАБЛИ, НА КОТОРЫЕ УЖЕ НАСТУПАЛИ: в JS граница слова \b не работает после кириллицы, русские
// буквы для неё не буквы. Регулярка /\bя\b/ не поймала «я плакала», и ВСЕ строки уходили в
// дефолт «крик». Поэтому границы задаём явно через lookaround по русским и латинским буквам.
const сл = (варианты) => new RegExp('(?<![а-яёa-z])(?:' + варианты + ')(?![а-яёa-z])', 'i');

// Приказ ищем В ЛЮБОМ МЕСТЕ строки, а не только в начале: «Нейросеть построила мою карту
// бровей! Смотри!» кричит ничуть не меньше, чем «Смотри, что нашла», и на обложке должна идти
// капсом. Первая версия смотрела только начало и увела такие строки в дневник.
const ПРИКАЗ = /(?:^|[\s.,!?:;])(выкинь|хватит|перестань|смотри|проверь|убери|не\s+неси|дай|покажи|скинь|меняем|исправляем|примерь|исправь|беги)(?![а-яё])/i;
const ОБРАЩЕНИЕ = сл('ты|тебя|тебе|твой|твоя|твоё|твое|твои|твою|твоего|твоей|вас|вам|вы');
const О_СЕБЕ = сл('я|мне|меня|мой|моя|моё|мое|мои|мою|моего|моей|мы|нас|наш|наша|наше|нашего');
const РАССКАЗ = /^\s*[а-яё]+(?:ла|лась)(?![а-яё])/i;   // «Проверила…», «Загрузила…», «Затестила…»
// Первое лицо настоящего времени тоже дневник: «Мечтаю о люкс сумке после гайда». Но «показываю»
// и «исправляем» обращены к зрителю, это крик, поэтому список закрытый, а не по окончанию -ю.
const О_СЕБЕ_СЕЙЧАС = /^\s*(мечтаю|хочу|иду|плачу|сижу|думаю|боюсь|не\s+могу|записываюсь|перекрашиваюсь)(?![а-яё])/i;
const ЭМОЦИЯ = /\(\(|\)\)|\.\.\.\s*$|\(\s*$/;

function регистр(t) {
  const s = String(t || '');
  if (/^\s*пов(?![а-яё])/i.test(s)) return 'пов';        // метка сильнее всего: в «пов ... ты ...» есть «ты»
  // Обращение к зрителю бьёт рассказ о себе: в «Мастер тебе такого не скажет! А я скажу!» есть
  // и «тебе», и «я», но фраза обращена к женщине по ту сторону экрана, значит это крик.
  if (ОБРАЩЕНИЕ.test(s) || ПРИКАЗ.test(s)) return 'крик';
  if (О_СЕБЕ.test(s) || РАССКАЗ.test(s) || О_СЕБЕ_СЕЙЧАС.test(s)) return 'пов';   // рассказ о себе без обращения — дневник
  if (ЭМОЦИЯ.test(s)) return 'пов';
  return 'крик';
}
module.exports = { регистр };
