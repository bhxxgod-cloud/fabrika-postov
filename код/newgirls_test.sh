#!/bin/bash
# ТЕСТ НОВЫХ ДЕВОЧЕК: по одному посту на каждую, чтобы посмотреть на ЗАСТАВКУ до большого залпа.
#
# ЗАЧЕМ ИМЕННО ТАК. Большой прогон это 30 постов на девочку, то есть 180 сборок и часы работы.
# Если фабрика уплывёт лицом (жалоба 13.08: «стал здоровый нос, а была милая как на оригинале»),
# то узнать об этом после 180 постов дорого, а после шести — дёшево. Поэтому сначала по одному.
#
# ПОЧЕМУ ШАБЛОН img-face-report. Он карточный: кадр 1 это селфи с хуком, кадр 2 карточка с баллами.
# Заставка рилса это ровно кадр 1, значит по нему и видно, сохранилось ли лицо. Плюс карточные
# посты дешевле артовых ($0.06 против $0.06-0.09).
#
# ИМЕНА ПЕРЕМЕННЫХ ТОЛЬКО ЛАТИНИЦЕЙ: кириллическое имя bash за переменную не считает и разбирает
# строку как команду (сегодня на этом легли оба воркера постфабрики).
set -u
cd "$HOME/Desktop/neironka-poster" || exit 1

SRC="${1:-$HOME/Desktop/НЕЙРОНКА/НОВЫЕ-ДЕВОЧКИ}"
OUT="$HOME/Desktop/НЕЙРОНКА/ТЕСТ-ДЕВОЧКИ"
LOG="$HOME/.neironka/reels/newgirls.log"
TPL="${TEST_TPL:-img-face-report}"
mkdir -p "$OUT" "$(dirname "$LOG")"

# Персоны в том порядке, в каком лежат файлы (по имени). Порядок задан владельцем 13.08.
PERSONAS=(сучка-в-машине сучка-в-кровати аня-апгрейд анжела-удивлена красивые-глаза блондинка-сучка)

mapfile -t FILES < <(find "$SRC" -maxdepth 1 -type f \( -iname "*.jpg" -o -iname "*.jpeg" -o -iname "*.png" -o -iname "*.webp" \) | sort)
if [ "${#FILES[@]}" -eq 0 ]; then echo "нет фото в $SRC"; exit 1; fi
echo "фото найдено: ${#FILES[@]}, персон заготовлено: ${#PERSONAS[@]}"

# ПОЛОСА ОДНА. Тест это шесть сборок, гнать их параллельно незачем, а лишний процесс сверх полос
# не собирает, а спит в очереди замка, держа вкладку хрома (закон выведен 13.08, цена 47 ГБ).
export OP_LANES=1

i=0
for f in "${FILES[@]}"; do
  p="${PERSONAS[$i]:-девочка-$((i+1))}"
  echo "=== [$((i+1))/${#FILES[@]}] $p ← $(basename "$f") ==="
  TEMPLATE="$TPL" node onepost.cjs "$f" "$p" >> "$LOG" 2>&1 \
    && echo "  OK $p" || echo "  СБОЙ $p (смотри $LOG)"
  i=$((i+1))
done
echo "ТЕСТ ЗАКОНЧЕН — заставки достанет newgirls_covers.cjs"
