#!/bin/bash
# ВОРКЕР СБОРКИ ПОСТОВ. Берёт задания построчно из файла (tpl|file|persona|метка),
# собирает по одному, пропускает уже готовые по метке POST-OK в логе.
#
# ═══ ЗАКОН: ПРОЦЕССОВ РОВНО СТОЛЬКО ЖЕ, СКОЛЬКО ПОЛОС ═══════════════════════════════════════════
# OP_LANES это НЕ лимит внутри процесса, а число файлов-замков /tmp/genposts.lock.N, ОБЩИХ на всю
# машину (onepost.cjs, строки 191-214). Отсюда закон, который 13.08 обошёлся в 47 ГБ и OOM:
# каждый процесс СВЕРХ числа полос ничего не собирает — он спит в очереди замка по 15 секунд,
# ДЕРЖА при этом вкладку хрома. В тот день blast_all.sh поднял 27 процессов на 3 полосы: собирали
# три, остальные двадцать четыре просто держали браузер. Человек при этом думал, что запустил
# параллель на 27.
#
# Поэтому запускать этот файл надо СТРОГО так: сколько воркеров, столько и OP_LANES.
#   OP_LANES=2 nohup bash postfactory.sh /tmp/jobs_a.txt &
#   OP_LANES=2 nohup bash postfactory.sh /tmp/jobs_b.txt &
# Скрипт сам проверяет это соотношение и отказывается стартовать, если оно нарушено.
#
# ПОЧЕМУ НЕ В /tmp. Прежние воркеры жили в скретчпаде сессии Claude. Сессия закрылась — скрипты
# остались в каталоге, который система вправе подчистить в любой момент, и половина конвейера
# держалась на временных файлах. Копию скрипта класть В РЕПУ (это же правило записано в
# ПЕРЕДАЧА-ПАРТНЁРУ-РИЛСЫ-13-08.md, раздел 1.8).
set -u
cd "$HOME/Desktop/neironka-poster" || exit 1

JOBS="${1:?укажи файл заданий: bash postfactory.sh /tmp/jobs_x.txt}"
[ -f "$JOBS" ] || { echo "нет файла заданий: $JOBS"; exit 1; }
# РЕЕСТР СОБРАННОГО ЖИВЁТ В ДОМАШНЕЙ ПАПКЕ, А НЕ В /tmp (14.08).
# Умолчание вело в /tmp/salvo3_prompt.log, и это ломало защиту от повторной сборки дважды.
#   1. Уборка /tmp уносит реестр, и следующий прогон пересобирает УЖЕ СОБРАННОЕ — а каждый пост
#      это оплаченные кадры фабрики. Ровно так ночью 13-14 ушли ключи, база и 162 готовых рилса.
#   2. Проверено сейчас, на живой ферме: файла /tmp/salvo3_prompt.log нет вообще, при этом восемь
#      воркеров работают. То есть пропуск готовых (строка ниже, grep по метке) не срабатывал ни
#      разу за ночь, и защита существовала только на бумаге.
# Домашняя папка переживает и уборку, и перезагрузку; boot.sh её не трогает, потому что это не
# секрет, а состояние. POST_LOG по-прежнему главнее для разовых прогонов.
LOG="${POST_LOG:-$HOME/.neironka/postok.log}"
mkdir -p "$(dirname "$LOG")"
TRIES="${POST_TRIES:-5}"
PAUSE="${POST_SLEEP:-30}"

# СВЕРКА ВОРКЕРОВ И ПОЛОС. Считаем уже живых воркеров этого же скрипта: если их вместе со мной
# больше, чем полос, лишний обязан не стартовать, а не «попробовать и полежать в очереди».
LANES="${OP_LANES:-1}"
# ШАБЛОН ЗАЯКОРЕН НА «bash ...postfactory.sh», И ЭТО НЕ ПРИДИРКА. Голый pgrep -f postfactory.sh
# ловит не только сам воркер, но и ОБОЛОЧКУ, которая его запускала: у неё в командной строке тоже
# есть это имя. На семи воркерах сторож насчитал тринадцать и завернул все семь разом. Якорь ^bash
# отсекает обёртки: у них строка начинается с sh/zsh и пути, а не с «bash».
ALIVE=$(pgrep -f "^bash .*postfactory\.sh" | grep -cv "^$$\$" || true)
if [ "$((ALIVE + 1))" -gt "$LANES" ]; then
  echo "ОТКАЗ: воркеров станет $((ALIVE + 1)), а полос OP_LANES=$LANES."
  echo "Лишний воркер не соберёт ни одного поста — он будет спать в очереди замка, держа хром."
  echo "Подними OP_LANES до числа воркеров или запусти меньше воркеров."
  exit 2
fi
export OP_LANES="$LANES"
# Готовые кадры из предзаказа, если он есть: тогда сборка не ждёт рендер, а берёт лежащее.
[ -f /tmp/preorder/manifest.json ] && export PREORDER_MANIFEST=/tmp/preorder/manifest.json

echo "воркер пошёл: $(basename "$JOBS"), полос $LANES, заданий $(grep -c '|' "$JOBS")"
# ИМЕНА ПЕРЕМЕННЫХ ТОЛЬКО ЛАТИНИЦЕЙ. Кириллическое имя bash за имя переменной не считает и разбирает
# строку как команду: `ЗАДАНИЯ=/tmp/jobs.txt` даёт «No such file or directory», а `read ... метка`
# молча не заполняет метку. Это записано в шапке прежнего worker2.sh, я это правило пропустил и
# положил оба воркера с первого же запуска. Не возвращать кириллицу в имена, только в текст.
while IFS='|' read -r tpl file persona label; do
  [ -z "${tpl:-}" ] && continue
  if grep -q "POST-OK $label" "$LOG" 2>/dev/null; then echo "SKIP $label"; continue; fi
  for att in $(seq 1 "$TRIES"); do
    echo "=== $label попытка $att ==="
    # ОТМЕТКА ПИШЕТСЯ В ФАЙЛ, А НЕ ТОЛЬКО В ЭКРАН, И ЭТО НЕ ПРИДИРКА (ревизия 14.08).
    # Было: `echo "POST-OK $label"` уходил в stdout, а проверка на строке 56 искала метку
    # в файле $LOG. Если stdout воркера направлен НЕ в тот же файл, ветка «уже собрано»
    # не срабатывает никогда, и перезапуск пересобирает всё заново — то есть ПЛАТИТ дважды
    # за уже оплаченные кадры. Ошибка была спрятана: grep по несуществующему файлу молча
    # отвечает «не нашёл» из-за 2>/dev/null. Теперь пишем явно и туда, где ищем.
    if TEMPLATE="$tpl" node onepost.cjs "$file" "$persona"; then
      echo "POST-OK $label"; echo "POST-OK $label" >> "$LOG"; break
    fi
    # Негодный исходник это не сбой сборки, а приговор фотографии: повторять бессмысленно.
    if tail -3 src_unfit.jsonl 2>/dev/null | grep -q "$(basename "$file")"; then
      echo "POST-SKIP $label: исходник негоден"; break
    fi
    [ "$att" = "$TRIES" ] && echo "POST-FAIL $label"
    sleep "$PAUSE"
  done
done < "$JOBS"
echo "ВОРКЕР ЗАКОНЧИЛ $(basename "$JOBS")"
