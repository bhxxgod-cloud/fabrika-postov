// Лица не нашли — падаем на центр, но честно пишем это в отчёт, а не молчим.
const ЦЕЛЬ_ЛИЦА = 0.30;   // где стоять центру лица по высоте окна: выше полосы стикера с запасом

function уложить(ист, вых, окноH) {
  const sz = TT.probeSize(ист);
  if (!sz) throw new Error('размер кадра не прочитался');
  const fb = TT.faceBox(ист);
  const лицо = fb && fb.face ? fb.face : null;
  const по_ширине = Math.round((W * sz.h) / sz.w);        // высота, если тянуть по ширине 1080
  let план;
  if (по_ширине >= окноH) {
    // Свобода по вертикали. Целимся лицом, потом зажимаем в пределы картинки.
    //
    // ОДНОЙ ЦЕЛИ «центр лица на 30%» МАЛО, и это поймано на первой же сборке: у крупного лица
    // (422 px из 1920) центр на 372 уводит МАКУШКУ на 161, то есть под полоски прогресса и ник.
    // Поэтому целимся не в точку, а в КОРИДОР: макушка ниже верхнего интерфейса, подбородок выше
    // полосы стикера. Точка 30% остаётся предпочтением внутри коридора, а не законом.
    const cy = лицо ? лицо.cy : 0.5;
    // ЦЕЛИМСЯ СТРОЖЕ, ЧЕМ СУДИМ, и это не описка. Коридор укладки почти всегда упирается в свой
    // верхний край (предпочтение «лицо на 30%» лежит выше него), поэтому если целиться ровно в
    // приговорную черту 170, макушка встанет НА неё — и любой десяток пикселей расхождения между
    // рамкой лица на исходнике и на готовом кадре роняет кадр в брак. Проверено: при цели 170 из
    // 24 исходников отсеялось 10 вместо 8, причём вылетели те же кадры, что до этого проходили.
    // Целимся в 280, судим по 170 — между ними 110 пикселей на разброс детектора.
    const КОР_ВЕРХ = ВЕРХ_UI + 30;          // куда ЦЕЛИМСЯ макушкой
    const КОР_НИЗ = СТИКЕР_ВЕРХ - 30;       // выше этой черты обязан быть подбородок
    // ПОДЗУМ, КОГДА ОДНОГО СДВИГА НЕ ХВАТАЕТ. На селфи с высоким кадрированием (004_нежное_селфи)
    // лицо стоит у самой верхней кромки исходника: сдвигать окно уже некуда, dy упирается в ноль,
    // и макушка всё равно оказывается под ником и полосками. Тогда увеличиваем картинку — появляется
    // запас сверху, который и уводит лицо вниз. Цена — обрезка по бокам, поэтому потолок 1.2:
    // это максимум 20% ширины, дальше кадр превращается в тесный портрет, а начальник ругал именно
    // «режет бока». Лицо крупнее коридора не зумим вовсе: ему станет только теснее.
    let z = 1;
    if (лицо && лицо.top > 0.001) {
      const надо = КОР_ВЕРХ / (лицо.top * по_ширине);
      const высотаПри = (лицо.h / sz.h) * по_ширине * Math.min(надо, 1.2);
      if (надо > 1 && высотаПри <= КОР_НИЗ - КОР_ВЕРХ) z = Math.min(надо, 1.2);
    }
    const hh = Math.round(по_ширине * z), ww = Math.round(W * z);
    let центр = ЦЕЛЬ_ЛИЦА * окноH;
    if (лицо) {
      const вЛица = (лицо.h / sz.h) * hh;             // высота лица уже в пикселях кадра
      const мин = КОР_ВЕРХ + вЛица / 2;
      const макс = КОР_НИЗ - вЛица / 2;
      // Лицо крупнее коридора (портрет во весь кадр) — ставим по середине коридора: так поля
      // сверху и снизу выйдут одинаковыми, а не завалятся в одну сторону.
      центр = мин <= макс ? Math.max(мин, Math.min(макс, центр)) : (КОР_ВЕРХ + КОР_НИЗ) / 2;
    }
    let dy = Math.round(cy * hh - центр);
    dy = Math.max(0, Math.min(hh - окноH, dy));
    // При зуме ширина стала больше окна — ведём окно за лицом и по горизонтали, иначе центр-кроп
    // срежет половину головы у тех, кто снят не по центру.
    const cx = лицо ? (лицо.x + лицо.w / 2) / sz.w : 0.5;
    let dx = Math.round(cx * ww - W / 2);
    dx = Math.max(0, Math.min(ww - W, dx));
    execFileSync(FF, ['-y', '-i', ист, '-vf',
      `scale=${ww}:${hh},crop=${W}:${окноH}:${dx}:${dy}`, '-q:v', '2', вых], { stdio: 'ignore' });
    план = { ось: 'вертикаль', зум: +z.toFixed(2), сдвиг: dy,
      срезано_px: (hh - окноH) + (ww - W), лицо: !!лицо };
  } else {
    // Свобода по горизонтали. Тянем по высоте, окно ведём за лицом по ширине.
    const по_высоте = Math.round((окноH * sz.w) / sz.h);
    const cx = лицо ? (лицо.x + лицо.w / 2) / sz.w : 0.5;
    let dx = Math.round(cx * по_высоте - W / 2);
    dx = Math.max(0, Math.min(по_высоте - W, dx));
    execFileSync(FF, ['-y', '-i', ист, '-vf',
      `scale=${по_высоте}:${окноH},crop=${W}:${окноH}:${dx}:0`, '-q:v', '2', вых], { stdio: 'ignore' });
    план = { ось: 'горизонталь', сдвиг: dx, срезано_px: по_высоте - W, лицо: !!лицо };
  }
  return план;
}

// Тон подложки берём с САМОГО кадра (как в plates.cjs и stories.cjs), иначе на светлом фото белые
// буквы исчезают, а чёрная панель под светлым кадром читается как чужая заплатка.
function тон(ист) {
  try {
    const r = require('node:child_process').spawnSync(FF, ['-hide_banner', '-i', ист,
      '-vf', 'crop=iw:ih*0.34:0:ih*0.66,scale=1:1', '-frames:v', '1', '-f', 'rawvideo',
      '-pix_fmt', 'rgb24', 'pipe:1'], { maxBuffer: 1 << 20 });
    const b = r.stdout;
    if (b && b.length >= 3) {
      const lum = 0.299 * b[0] + 0.587 * b[1] + 0.114 * b[2];
      const k = lum > 1 ? Math.min(1, 30 / lum) : 1;
      return [Math.round(b[0] * k), Math.round(b[1] * k), Math.round(b[2] * k)];
    }
  } catch { /* тон не прочитался — падаем на почти-чёрный ниже */ }
  return [10, 10, 12];
}
