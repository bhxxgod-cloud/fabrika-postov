/** Детерминированный поток чисел от ключа: одна фотография — одна и та же карточка. */
function поток(ключ) {
  let i = 0;
  return () => {
    const h = crypto.createHash('sha1').update(`${ключ}:${i++}`).digest();
    return (h[0] + h[1] * 256) / 65536;   // 0..1
  };
}
const из = (сл, пул) => пул[Math.floor(сл() * пул.length) % пул.length];
const балл = (сл, низ, верх) => (низ + сл() * (верх - низ)).toFixed(1);
/** Несколько РАЗНЫХ элементов пула: без повторов внутри одного списка. */
function набор(сл, пул, n) {
  const копия = пул.slice(); const вышло = [];
  while (вышло.length < n && копия.length) вышло.push(копия.splice(Math.floor(сл() * копия.length) % копия.length, 1)[0]);
  return вышло;
}

