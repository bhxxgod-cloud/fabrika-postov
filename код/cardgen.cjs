    // У текста высота растёт ступеньками (лишний перенос это сразу полторы строки), поэтому между
    // «влезло» и «не влезло» всегда остаётся зазор в одну-две строки. Две попытки убрать его иначе
    // провалились и обе были пойманы глазами: justify-content:space-between раскидывал остаток
    // между блоками отдельными провалами, а растяжка верхнего ряда надувала боковую панель и
    // оставляла пустоту уже внутри неё. Прибавка к общему промежутку не видна вообще: на девять
    // разделов это десяток пикселей на шов, и карточка просто дышит ровнее.
