// scrollHeight у блока с padding не учитывает НИЖНЕЕ поле: поиск считал, что влезло, а на деле
// последняя строка вылезала на 1.6rem. У .in своего поля нет, поэтому меряется честно.
//
// СРАВНИВАЕМ РОВНО scrollHeight <= clientHeight, БЕЗ ЗАПАСА (второй пойманный баг того же дня).
// scrollHeight никогда не бывает меньше clientHeight: у невлезающего содержимого он больше, у
// влезающего РАВЕН. Поэтому «запас в два пикселя» (clientHeight-2) не выполнялся НИКОГДА, поиск
// каждый раз скатывался в самый мелкий кегль, и карточка стрижек вышла с шестипиксельным текстом
// посреди пустого листа. Запас берём по-другому: после поиска спускаемся шагом по четверти
// пикселя, пока перелив не исчезнет по факту.
//
// СЧИТАЕМ ПОСЛЕ ЗАГРУЗКИ КАРТИНКИ (третий пойманный баг того же дня, тоже глазами: у карточки
// оценки обрезало две нижние строки). Фотография вставлена как data-адрес, но раскладывается она
// всё равно асинхронно: скрипт в конце страницы считал высоты, когда картинки в потоке ещё не
