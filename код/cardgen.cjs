// ═══ КРОПЫ С ОДНОЙ ФОТОГРАФИИ ════════════════════════════════════════════════════════════════
// ПОРТРЕТ ПОД ОКОШКО КАРТОЧКИ (11.08, поймано начальником на первой же карточке: «фото ушло не
// туда, лица не видно»). Раньше кадр вставлялся целиком и обрезался по центру окна, а обложка у нас
// 4:5 и лицо на ней часто выше центра, поэтому в окошко попадала шея или рука.
// Теперь кадрируем ПО ЛИЦУ: находим рамку лица (ttkit.faceBox, тот же yunet, что и в гейтах),
// берём вокруг неё поле в 2.6 высоты лица и ставим глаза примерно на верхнюю треть, как в паспортном
// портрете. Лица не нашли — оставляем верхнюю часть кадра, там лицо оказывается чаще, чем в центре.
//
// 12.08 добавлен режим 'полный' для обложки журнала: там фотография занимает весь кадр 9:16, поэтому
// поле вокруг лица берётся шире (5 высот лица), а голова ставится в верхнюю четверть, как на
// настоящей обложке, чтобы под подзаголовки внизу осталось место.
function портрет(фото, out, режим = 'окно') {
  const { execFileSync } = require('node:child_process');
  const FF = require('ffmpeg-static');
  const TT = require('./ttkit.cjs');
  const b = TT.faceBox(фото);
  const W0 = (b && b.w) || 1080, H0 = (b && b.h) || 1350;
  const полный = режим === 'полный';
  const отн = полный ? W / H : 0.82;            // ширина к высоте окна
  let cw, ch, cx, cy;
  if (b && b.face) {
    ch = Math.min(H0, Math.round(b.face.h * (полный ? 4.6 : 2.6)));
    cw = Math.min(W0, Math.round(ch * отн));
    cx = Math.round(b.face.x + b.face.w / 2 - cw / 2);
    cy = Math.round(b.face.y + b.face.h / 2 - ch * (полный ? 0.26 : 0.42));
  } else {
    ch = Math.round(H0 * (полный ? 0.96 : 0.62));
    cw = Math.min(W0, Math.round(ch * отн));
    cx = Math.round((W0 - cw) / 2); cy = Math.round(H0 * 0.02);
  }
  // Если запрошенное поле шире исходника, высоту урезаем под пропорцию, а не растягиваем кадр.
  if (cw > W0) { cw = W0; ch = Math.round(cw / отн); }
  ch = Math.min(ch, H0);
  cx = Math.max(0, Math.min(cx, W0 - cw));
  cy = Math.max(0, Math.min(cy, H0 - ch));
  const масштаб = полный ? `scale=${W}:-2` : 'scale=560:-2';
  execFileSync(FF, ['-y', '-i', фото, '-vf', `crop=${cw}:${ch}:${cx}:${cy},${масштаб}`,
    '-q:v', '2', out], { stdio: 'ignore' });
  return out;
}

/**
 * ПЯТЬ КАДРОВ С ОДНОЙ ФОТОГРАФИИ. Главное отличие версии 2: макетам мало портрета, им нужны
 * полоса глаз, один глаз крупно, губы, нос и лицо целиком. Фотоматериал взять неоткуда (генерация
 * запрещена), а вот честно переиспользовать её же кадр в разных кропах можно, и именно этим
 * фабричная карточка и выглядит богатой.
 *
 * Все окна отсчитываются от рамки лица yunet: она примерно от бровей до подбородка, поэтому глаза
 * лежат в верхней трети рамки, губы около 0.6–0.85 высоты, нос между ними. Числа выверены глазами
 * на нескольких кадрах из НОВЫЕ7 (см. отчёт по переделке постера).
 *
 * Лица не нашли — все кропы становятся портретом: пустых картинок в вёрстке не бывает.
 */
function кропы(фото, база, режим = 'окно') {
  const { execFileSync } = require('node:child_process');
  const FF = require('ffmpeg-static');
  const TT = require('./ttkit.cjs');
  const корень = String(база).replace(/\.jpe?g$/i, '');
  const мусор = [];
  const прочитать = (p) => { мусор.push(p); return fs.existsSync(p) ? fs.readFileSync(p).toString('base64') : null; };

  const порт = `${корень}_портрет.jpg`;
  портрет(фото, порт, режим);
  const герой = прочитать(порт);
  const вышло = { герой };

  // ВТОРАЯ ПОПЫТКА НАЙТИ ЛИЦО (14.08). Детектор поднимает питон отдельным процессом, и под
  // нагрузкой запуск иногда просто не удаётся — рамки нет, кропов нет, карточка молча показывает
  // портрет вместо губ или носа. Само фото при этом нормальное, лицо на нём есть. Повтор стоит
  // секунду и снимает почти все такие случаи; если и вторая попытка пустая, значит лица правда нет.
  let b = TT.faceBox(фото);
  if (!b || !b.face) {
    b = TT.faceBox(фото);
    if (b && b.face) console.log('  · cardgen: лицо найдено со второй попытки (детектор не запустился с первой)');
  }
  if (b && b.face) {
    const f = b.face; const W0 = b.w; const H0 = b.h;
    const вырезать = (имя, x, y, w, h, ширина) => {
      x = Math.round(x); y = Math.round(y); w = Math.round(w); h = Math.round(h);
      x = Math.max(0, Math.min(x, W0 - 8)); y = Math.max(0, Math.min(y, H0 - 8));
      w = Math.max(8, Math.min(w, W0 - x)); h = Math.max(8, Math.min(h, H0 - y));
      const p = `${корень}_${имя}.jpg`;
      try {
        execFileSync(FF, ['-y', '-i', фото, '-vf', `crop=${w}:${h}:${x}:${y},scale=${ширина}:-2`,
          '-q:v', '2', p], { stdio: 'ignore' });
        const b64 = прочитать(p);
        if (b64) вышло[имя] = b64;
      } catch { /* кроп не вышел — макет возьмёт портрет */ }
    };
    // ═══ ГУБЫ, НОС И ГЛАЗА РЕЖЕМ ПО ТОЧКАМ ЛИЦА, А НЕ ПО ДОЛЯМ РАМКИ (15.08) ═══════════════════
    //
    // ЗАЧЕМ. Владелец дважды за сутки поймал одно и то же: «брак постера — 2 фото не губы, а
    // глаза», потом «губы всегда съезжают», и второй раз это стало блокером запуска сборки.
    //
    // ПРИЧИНА. Доли ниже (губы на 0.58 высоты рамки, нос на 0.34) — это ДОГАДКА о том, где на
    // лице что находится. Она верна только для прямого кадра со средними пропорциями. Наклонила
    // голову, подняла подбородок, лицо длиннее среднего, детектор дал рамку чуть выше — и окно
    // «губы» уезжает на нос, а «нос» на глаза. Никакая подкрутка долей это не чинит: сдвиг разный
    // на каждом кадре.
    //
    // ЧТО ВМЕСТО. Тот же детектор yunet вместе с рамкой отдаёт ПЯТЬ ТОЧЕК: два глаза, кончик носа,
    // два угла рта. Они уже используются в facemetrics для замера лица. Значит координаты рта у нас
    // есть точные — и гадать не нужно. Размер окна считаем от ШИРИНЫ РТА (для губ) и от межглазного
    // расстояния (для носа и глаз): эти мерки живут вместе с лицом и не зависят от того, как
    // детектор поставил рамку.
    //
    // Точек нет (детектор не поднялся, лицо мелкое) — молча падаем на прежние доли: пустых окон в
    // вёрстке быть не должно, а старое поведение хотя бы иногда попадало.
    let т = null;
    try { const с = require('./facemetrics.cjs').сырыеТочки(фото); т = с && с.точки; } catch { /* без точек */ }
    if (т && т.рот_п && т.рот_л && т.глаз_п && т.глаз_л && т.нос) {
      const [пгx, пгy] = т.глаз_п, [лгx, лгy] = т.глаз_л;
      const [нx, нy] = т.нос, [прx, прy] = т.рот_п, [лрx, лрy] = т.рот_л;
      const межглаз = Math.hypot(лгx - пгx, лгy - пгy);
      const ширРта = Math.max(Math.hypot(лрx - прx, лрy - прy), межглаз * 0.6);
      const ртX = (прx + лрx) / 2, ртY = (прy + лрy) / 2;
      const глX = (пгx + лгx) / 2, глY = (пгy + лгy) / 2;
      // Губы: окно в 1.9 ширины рта — рот целиком плюс поля, без подбородка и без носа.
      вырезать('губы', ртX - ширРта * 0.95, ртY - ширРта * 0.42, ширРта * 1.9, ширРта * 0.9, 420);
      // Нос: от переносицы (середина глаз) до чуть ниже кончика.
      вырезать('нос', нx - межглаз * 0.62, глY + межглаз * 0.12, межглаз * 1.24, (нy - глY) + межглаз * 0.5, 420);
      // Полоса глаз и один глаз — тоже от точек: рамка их ловит грубее.
      вырезать('глаза', пгx - межглаз * 0.62, глY - межглаз * 0.42, межглаз * 2.24, межглаз * 0.84, 640);
      вырезать('глаз', лгx - межглаз * 0.42, лгy - межглаз * 0.34, межглаз * 0.84, межглаз * 0.68, 380);
    } else {
      вырезать('глаза', f.x - 0.14 * f.w, f.y + 0.14 * f.h, 1.28 * f.w, 0.32 * f.h, 640);
      вырезать('глаз', f.x - 0.02 * f.w, f.y + 0.21 * f.h, 0.46 * f.w, 0.26 * f.h, 380);
      вырезать('губы', f.x + 0.16 * f.w, f.y + 0.58 * f.h, 0.60 * f.w, 0.28 * f.h, 420);
      вырезать('нос', f.x + 0.26 * f.w, f.y + 0.34 * f.h, 0.48 * f.w, 0.34 * f.h, 420);
    }
    вырезать('лицо', f.x - 0.22 * f.w, f.y - 0.30 * f.h, 1.44 * f.w, 1.60 * f.h, 560);
  }
  for (const p of мусор) { try { fs.unlinkSync(p); } catch { /* уже нет */ } }
  return вышло;
}

/**
 * ЕДИНАЯ ТОЧКА ВХОДА. Вызывающий просит карточку ПО ШАБЛОНУ и ничего не знает про макеты.
 * @param {string} шаблон имя шаблона из templates.cjs (например 'img-haircut-match')
 * @param {string} фото   путь к фотографии героини (обложка поста)
 * @param {string} ключ   обычно id поста: от него зависят все числа и слова
 * @param {string} out    путь к результату (.jpg)
 * @returns {Promise<string>} путь к файлу
 */
async function собрать(шаблон, фото, ключ, out, приёмник, опции) {
  const м = макет(шаблон);
  const ф = кропы(фото, out, м.кадр);
  // ═══ ФОТО-ПЛИТКИ ВМЕСТО КЛИПАРТА (15.08, вердикты владельца по карточкам) ═══════════════════
  //
  // Его слова по пунктам: стрижки — «силуэты-клипарт заменить на РЕАЛЬНЫЕ примеры, каждая
  // генерится НА САМОЙ девочке»; носик — «клипарт-профили заменить на генерённые фото-варианты её
  // носа»; оценка — «что это за ебло справа сверху» про схему-клипарт, взамен разрешена ОДНА
  // универсальная сгенерённая схема на всех. Общий смысл: всё рисованное кодом умирает, красоту
  // рисует модель, вёрстка остаётся под текст и числа.
  //
  // КАК ПОПАДАЮТ ПЛИТКИ. Вызывающий передаёт опции.плитки = [пути к 4-6 фото] — это сгенерённые
  // кадры самой девочки (стрижки или носы, по шаблону). Их кладём в ф как плитка1..плиткаN, и
  // макет, умеющий фото-плитки, берёт их; без плиток он падает на прежний клипарт — пустых
  // карточек не бывает, а старые вызовы работают как работали.
  //
  // СХЕМА ЛИЦА — отдельный случай: она универсальная (решение владельца «можно одну для всех»),
  // поэтому не приходит в опциях, а лежит файлом в репо и подхватывается сама.
  if (опции && Array.isArray(опции.плитки)) {
    опции.плитки.slice(0, 6).forEach((п, i) => {
      try { if (fs.existsSync(п)) ф[`плитка${i + 1}`] = fs.readFileSync(п).toString('base64'); }
      catch { /* нет плитки — макет возьмёт клипарт */ }
    });
  }
  const СХЕМА_ЛИЦА = path.join(__dirname, 'активы', 'схема-лица.png');
  if (fs.existsSync(СХЕМА_ЛИЦА)) {
    try { ф.схемаЛица = fs.readFileSync(СХЕМА_ЛИЦА).toString('base64'); } catch { /* клипарт */ }
  }
  // ЗАМЕР ЛИЦА ТРЕТЬИМ ДОВОДОМ (14.08, претензия владельца «карточки не совсем реальные, они
  // рандомно нарисованы»). Макет, который умеет считать по замеру, берёт его; остальные лишний
  // довод просто не видят, поэтому их правка не трогает. Лица нет или детектора нет — замер null,
  // и макет откатывается на прежний детерминированный поток: пустых карточек быть не должно.
  let зам = null;
  try { зам = require('./facemetrics.cjs').замерить(фото); } catch { /* без замера, как раньше */ }
  await renderHtml(м.html(нормализовать(ф), ключ || path.basename(фото), зам), out, W, H);
  // ЧИСЛА КАРТОЧКИ НАРУЖУ (14.08, разбор маркетолога по пачке 14-08).
  //
  // ЗАЧЕМ. Хук поста выбирается на 525-й строке onepost, а карточка рисуется на 721-й. То есть хук
  // физически не может знать, что выйдет на карточке, — и в каждом третьем рилсе он ей противоречил:
  // «вышло 8.1» при 8.7 на карточке, «поставили 7.9» при 8.5. Зритель видит оба числа на одном
  // экране, и расхождение читается как враньё, а не как опечатка.
  //
  // Отдаём итоговый балл и форму лица в приёмник, если его передали. Совместимость полная: кто
  // звал без приёмника, продолжает получать путь к файлу и ничего не замечает.
  if (приёмник && typeof приёмник === 'object' && зам) {
    приёмник.итог = зам.гармония;                 // среднее по измеренным чертам — то же, что на карточке
    приёмник.форма = зам.форма;
    приёмник.черты = {
      симметрия: зам.симметрия, пропорции: зам.пропорции, глаза: зам.глаза,
      губы: зам.губы, нос: зам.нос, овал: зам.овал,
    };
  }
  return out;
}

/**
 * СТАРЫЙ ВЫЗОВ, оставлен ради совместимости с onepost.cjs (OWN_CARD=1) и ручных проверок.
 * Порядок доводов другой (фото первым), шаблон необязателен: без него рисуется оценка.
 */
const карточка = (фото, out, ключ, шаблон) => собрать(шаблон || ПО_УМОЛЧАНИЮ, фото, ключ, out);

