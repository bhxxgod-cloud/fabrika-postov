function caption(tplId, seed) {
  // Пул ищет КОНТРАКТ (templates.cjs): точный шаблон, потом его СЕМЬЯ, потом общий пул. Точный
  // ключ не находил старый шаблон тренда (hearts-trend, 65 живых постов): пул сердечек лежит под
  // 'img-heart-hair', и такому посту в телеграм уходил общий текст вместо текста про волосы.
  const pool = require('./templates.cjs').textPool(HOOKS, tplId, '*') || HOOKS['*'];
  return [pool[hash('h' + seed) % pool.length], '', STORY[hash('s' + seed) % STORY.length], '', TAGS[hash('t' + seed) % TAGS.length]].join('\n');
}

const NAMES = {
  'img-heart-hair': 'сердечки из волос', 'hearts-trend': 'сердечки из волос',
  'img-beauty-guide': 'бьюти-гайд', 'img-face-report': 'оценка внешности',
  'img-makeup-colortype': 'макияж по цветотипу', 'img-bw-fingers': 'чб сквозь пальцы',
  'img-magazine-cover': 'обложка журнала', 'img-haircut-match': 'подбор стрижки',
};

async function sendVideo(file, caption) {
  const form = new FormData();
  form.append('chat_id', CHAT);
  form.append('caption', caption);
  form.append('supports_streaming', 'true');
  form.append('video', new Blob([fs.readFileSync(file)], { type: 'video/mp4' }), path.basename(file));
  const r = await fetch(`https://api.telegram.org/bot${TOKEN}/sendVideo`, { method: 'POST', body: form });
  const j = await r.json().catch(() => ({}));
  if (!j.ok) throw new Error(j.description || 'телеграм отказал');
  return j.result.message_id;
}

(async () => {
  if (!DIR || !fs.existsSync(DIR)) { console.log('usage: node tgblast.cjs <папка> [с номера]'); process.exit(1); }
  // ОБЩИЙ РУБИЛЬНИК ОТПРАВКИ (09.08, приказ начальника: «не шли в тг ничего, пока не подготовишь
  // все посты»). Пока файл /tmp/NO_TG существует, пачка не уходит. Это главный обход стопа, который
  // оставался: onepost молчал, а залп рилсов отправлялся как ни в чём не бывало. Снимается удалением
  // файла, то есть одним осознанным действием, а не переменной окружения.
  if (fs.existsSync('/tmp/NO_TG')) {
    console.log('ИТОГ: ничего не отправлено, включён общий стоп отправки (/tmp/NO_TG). '
      + 'Снять: rm /tmp/NO_TG');
    process.exit(0);
  }
  if (!TOKEN || !CHAT) { console.log('нет токена или чата: положи их в /tmp/.tgtok и /tmp/.tgchat'); process.exit(1); }

  // Состав пачки пишет magosreels: «N. файл — персона X, пост YYYYYYYY».
  const manifest = path.join(path.dirname(DIR), 'magos-reels-состав.txt');
  const rows = read(manifest).split('\n').filter(Boolean).map((l) => {
    const m = l.match(/^(\d+)\. (\S+) — персона (\S+), пост (\S+)/);
    return m ? { n: +m[1], file: m[2], persona: m[3], post: m[4] } : null;
  }).filter(Boolean);
  if (!rows.length) { console.log('состав пачки не найден: ' + manifest); process.exit(1); }

  const c = new Client({ connectionString: DBURL, ssl: { rejectUnauthorized: false }, connectionTimeoutMillis: 15000 });
  c.on('error', () => {});
  await c.connect();
  const t = await c.query(`SELECT left(id::text,8) id, meta->>'template' tpl FROM posts WHERE left(id::text,8) = ANY($1)`,
    [rows.map((r) => r.post)]);
  const tpl = new Map(t.rows.map((r) => [r.id, NAMES[r.tpl] || r.tpl || '?']));
  const rawTpl = new Map(t.rows.map((r) => [r.id, r.tpl || '*']));
  await c.end().catch(() => {});

  let ok = 0, bad = 0;
  for (const r of rows) {
    if (r.n < FROM) continue;
    const file = path.join(DIR, r.file);
    if (!fs.existsSync(file)) { console.log(`  ⚠ ${r.n}: файла нет`); bad++; continue; }
    const cap = `#маго · пост ${r.n} · модель ${r.persona} · шаблон ${tpl.get(r.post) || '?'} · площадка ${PLATFORM}\n\n— — —\n${caption(rawTpl.get(r.post) || '*', r.post)}`;
    try {
      await sendVideo(file, cap);
      console.log(`  ✅ ${r.n} ${r.persona} (${tpl.get(r.post)})`);
      ok++;
    } catch (e) {
      console.log(`  ✗ ${r.n}: ${String(e.message).slice(0, 80)}`);
      bad++;
    }
    // Телеграм режет частые загрузки видео: держим спокойный темп.
    await sleep(3500);
  }
  console.log(`\nИТОГ: отправлено ${ok}, ошибок ${bad}`);
  process.exit(0);
})().catch((e) => { console.error('ОШИБКА:', e.message); process.exit(1); });
