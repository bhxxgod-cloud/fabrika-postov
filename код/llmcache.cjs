//
// ЗАЧЕМ (14.08, владелец: «почини чтобы не шёл 1 запрос много раз — мы теряем много денег»).
// Замер по логам за сутки: 533 обращения к платной модели зрения на ОДИННАДЦАТИ разных файлах.
// Один только анжела-удивлена.jpg судили 124 раза. Каждый раз — оплаченный запрос про картинку,
// которая не менялась. То же самое может повториться в любом другом месте, где мы спрашиваем
// модель: проверка постов, проверка аватарок, проверка аккаунтов, ответы на комментарии.
//
// ПОЧЕМУ ОБЩИЙ МОДУЛЬ, А НЕ КЭШ В КАЖДОМ ФАЙЛЕ. В проекте семь мест, которые ходят в OpenRouter.
// Кэш, написанный в каждом по-своему, разъедется — это уже случилось с вёрсткой хука, которая
// жила в семи копиях и стоила нам суток работы. Здесь один модуль и один файл на диске.
//
// ЧТО СЧИТАЕТСЯ «ТЕМ ЖЕ ВОПРОСОМ». Ключ собирается из модели, промпта и СОДЕРЖИМОГО картинок.
// Переименовали файл — ключ тот же. Поправили картинку или промпт — ключ другой, спросим заново.
//
// ЧТО НЕ КЭШИРУЕТСЯ, И ЭТО ВАЖНО:
//   · сбои (нет ключа, таймаут, HTTP 402) — это не ответ, а его отсутствие. Запомнить сбой значит
//     навсегда пометить хороший кадр как непроверенный;
//   · творческие задачи, где повтор ВРЕДЕН: тексты постов, подписи, ответы на комментарии. Там
//     одинаковый ответ на одинаковый вход — это одинаковые комментарии с разных аккаунтов, то есть
//     ровно тот след, по которому ферму и вычисляют. Такие вызовы кэш обязаны обходить (creative).
//
// Использование:
//   const { спросить } = require('./llmcache.cjs');
//   const ответ = await спросить({ ключ: {model, prompt, images:[путь|url]}, запрос: () => fetch(...) });
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const crypto = require('node:crypto');

const ФАЙЛ = process.env.LLM_CACHE_FILE || path.join(os.homedir(), '.neironka', 'llm_cache.json');
const ВЫКЛ = process.env.LLM_NOCACHE === '1';

let память = null;
function читать() {
  if (память) return память;
  try { память = JSON.parse(fs.readFileSync(ФАЙЛ, 'utf8')); } catch { память = {}; }
  return память;
}
function писать() {
  try {
    fs.mkdirSync(path.dirname(ФАЙЛ), { recursive: true });
    fs.writeFileSync(ФАЙЛ, JSON.stringify(память));
  } catch { /* не записалось — просто заплатим ещё раз, ронять сборку из-за кэша нельзя */ }
}

/** Отпечаток картинки: по содержимому файла, а для ссылки — по самой ссылке. */
function отпечатокКартинки(x) {
  const s = String(x || '');
  try {
    if (!/^https?:/i.test(s) && fs.existsSync(s)) {
      return crypto.createHash('sha1').update(fs.readFileSync(s)).digest('hex').slice(0, 16);
    }
  } catch { /* не прочиталось */ }
  return crypto.createHash('sha1').update(s).digest('hex').slice(0, 16);
}

/** Ключ вопроса: модель + промпт + содержимое картинок. */
function ключВопроса({ model, prompt, images }) {
  const части = [String(model || ''), String(prompt || '')]
    .concat((images || []).map(отпечатокКартинки));
  return crypto.createHash('sha1').update(части.join('|')).digest('hex');
}

// ЧТО СЧИТАТЬ НАСТОЯЩИМ ОТВЕТОМ, ЕСЛИ ВЫЗЫВАЮЩИЙ НЕ СКАЗАЛ САМ.
// Первая версия проверяла только «не null», и этого оказалось мало: объект вида
// {вердикт: null, error: 'таймаут'} — это тоже объект, и сбой попадал в кэш навсегда. Проверено
// тестом: повторный вызов вернулся из памяти вместо нового запроса. Теперь ищем следы сбоя в самом
// ответе. Список слов взят из того, чем наши проверки помечают неудачу.
const СЛЕДЫ_СБОЯ = /no_key|нет ключа|таймаут|timeout|не получен|не загрузилась|не отработал|rate.?limit|\b402\b|\b429\b|\b5\d\d\b/i;
function поУмолчаниюГоден(ответ) {
  if (ответ === undefined || ответ === null || ответ === '') return false;
  if (typeof ответ === 'object') {
    if (ответ.error || ответ.сбой) return false;
    // Пустой вердикт при наличии поля «вердикт» — тоже отсутствие ответа.
    if ('вердикт' in ответ && !ответ.вердикт) return false;
  }
  try { if (СЛЕДЫ_СБОЯ.test(JSON.stringify(ответ))) return false; } catch { /* не сериализуется */ }
  return true;
}

/**
 * Спросить модель с кэшем.
 * @param {object} o
 * @param {object} o.ключ      {model, prompt, images} — из чего собрать отпечаток вопроса
 * @param {function} o.запрос  функция без доводов, делает НАСТОЯЩИЙ платный вызов
 * @param {function} [o.годен] проверка «это настоящий ответ, а не сбой»; по умолчанию — не пустой
 * @param {boolean} [o.creative] true = не кэшировать (тексты, комментарии: повтор вреден)
 * @param {string} [o.чей]     имя вызывающего для строки в логе
 */
async function спросить({ ключ, запрос, годен, creative, чей }) {
  if (ВЫКЛ || creative) return запрос();
  const k = ключВопроса(ключ || {});
  const было = читать()[k];
  if (было && было.ответ !== undefined) {
    console.log(`  · ${чей || 'модель'}: ответ из кэша (тот же вопрос уже оплачен ${String(было.когда).slice(0, 16)})`);
    return было.ответ;
  }
  const ответ = await запрос();
  const ок = годен ? годен(ответ) : поУмолчаниюГоден(ответ);
  if (ок) { читать()[k] = { ответ, когда: new Date().toISOString() }; писать(); }
  return ответ;
}

/** Сколько вопросов уже оплачено и лежит в памяти — для отчёта о расходе. */
function сколькоВПамяти() { return Object.keys(читать()).length; }

module.exports = { спросить, ключВопроса, сколькоВПамяти, ФАЙЛ };

if (require.main === module) {
  console.log(`кэш ответов модели: ${ФАЙЛ}`);
  console.log(`вопросов запомнено: ${сколькоВПамяти()}`);
  console.log(ВЫКЛ ? 'СЕЙЧАС ВЫКЛЮЧЕН (LLM_NOCACHE=1)' : 'включён');
}
