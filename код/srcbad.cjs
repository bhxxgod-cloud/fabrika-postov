// КАРАНТИН ИСХОДНИКА: файл, по которому пост собирать НЕЛЬЗЯ, больше не попадает в волну.
//
// ЗАЧЕМ ЭТО ОТДЕЛЬНЫМ МОДУЛЕМ (11.08, разбор канала-референса). Отбраковка исходника была только
// внутри onepost.cjs, прямо в гейте обложки, и умела ровно одно: переложить файл из src_good в
// src_bad. Из этого вышли две дыры, обе стоят денег.
//
// ДЫРА ПЕРВАЯ: ОТКАЗ МОДЕРАЦИИ ПРИХОДИТ УЖЕ НА РЕНДЕРЕ, И ЕГО НИКТО НЕ ЗАПОМИНАЛ.
// RenderGrid умеет отклонить сам ИСХОДНИК по содержимому. Полный текст ответа снят по API с
// /creations/301debbf-1139-47de-a383-52ebfc7120dc (в логах волн он обрезан на «The sour», из-за
// чего его четыре часа считали неудачным скачиванием):
//   {"status":"failed","error":"The source image was rejected. Try a different photo."}
// Приходит он НА РЕНДЕРЕ, то есть заказ уже принят и $0.03 списаны, а в том же посте к этой минуте
// оплачен ещё и рендер фабрики. Отказ ДЕТЕРМИНИРОВАННЫЙ: тот же файл отклонят и на второй, и на
// десятый раз (поэтому в refretry.cjs он СОЗНАТЕЛЬНО исключён из ретрая, см. isRenderRefFetchFail,
// и возвращать его туда нельзя). Файл 033_аутфит_девушка_лето_db95db1ca8dcb429.jpg упал так трижды:
// в /tmp/wave25.log, в /tmp/wave_n1.log и в одиночном прогоне 11.08. Каждый раз это оплаченный
// заказ. Никто файл не пометил, и следующая волна брала его снова.
//
// ДЫРА ВТОРАЯ: ПЕРЕНОС В src_bad НЕ СРАБАТЫВАЛ ПО НАСТОЯЩЕМУ ПУТИ. src_good это СИМЛИНК на
// /Users/qq/Desktop/ИСХОДНИКИ-годные, а проверка «файл наш» была строковая (startsWith по
// path.resolve, а он симлинки не разворачивает). Волна с PHOTOS=src_good попадала под неё, а тот же
// самый файл, названный своим настоящим путём (именно так он назван в разборе 11.08), — уже нет:
// брак молча оставался в папке годных. Здесь оба пути сводятся через realpath, поэтому имя, которым
// файл назвали при запуске, больше ничего не решает.
//
// ПОЧЕМУ ПОМИМО ПЕРЕНОСА ЕСТЬ ЕЩЁ И СПИСОК. Перенос работает только внутри нашей папки годных:
// чужие пути (Downloads, inbox заявок) не наши, и трогать файлы там мы права не имеем — это правило
// старше этой задачи. Но запомнить отказ нужно в ЛЮБОМ случае, иначе волна по чужой папке будет
// платить за один и тот же файл вечно. Поэтому запись в список — главное, а перенос — удобство
// (по папке src_bad видно глазами, что забраковано).
//
// НИЧЕГО НЕ УДАЛЯЕМ. Ни здесь, ни где-либо ещё: брак переезжает, а не исчезает.
//
// СПИСОК ДОПИСЫВАЕМ СТРОКОЙ (jsonl), А НЕ ПЕРЕПИСЫВАЕМ ЦЕЛИКОМ. Волна идёт в три полосы
// одновременно, и две полосы, читающие-меняющие-пишущие один json, затрут запись друг друга ровно в
// тот момент, когда она дороже всего. Дозапись строки в режиме append такой гонки не имеет.
'use strict';

const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');

const ДОМ = __dirname;
const ГОДНЫЕ = path.join(ДОМ, 'src_good');
const БРАК = path.join(ДОМ, 'src_bad');
const СПИСОК = path.join(ДОМ, 'src_rejected.jsonl');
// ДВЕ РАЗНЫЕ КУЧИ, И ЭТО НЕ ПОРЯДОК РАДИ ПОРЯДКА (11.08, замер пригодности исходников).
// src_bad это БРАК ПОСТА: фотография, которую нельзя показывать (мыло, артефакты, слабый кадр,
// отказ модерации). src_unfit это ГОДНАЯ ФОТОГРАФИЯ, НЕПРИГОДНАЯ КАК РЕФЕРЕНС ЛИЦА: снимок сам по
// себе нормальный и красивый, но по нему нельзя перерисовать того же человека — лицо мелкое,
// срезано кропом, закрыто предметом или глаза закрыты. Замер это разделяет ясно: 074 (девушка в
// полный рост, солнце, кадр чистый) и 004 (крупное резкое селфи с прищуром) дали на кадре 3
// схожесть 0.36 и 0.335 при пороге 0.363, то есть модель нарисовала другого человека, а как
// фотографии оба кадра нормальные.
// ЗАЧЕМ РАЗДЕЛЯТЬ. Кучу брака смотрят глазами, чтобы понять, что чинить в фабрике; если свалить
// туда же непригодные референсы, эта куча перестанет что-либо значить. И наоборот: непригодные
// исходники это материал для правил ОТБОРА, их полезно видеть отдельным списком.
// ВОЛНА ПРОПУСКАЕТ ОБА СПИСКА одинаково: платить за файл, который уже назван непригодным, так же
// глупо, как за отклонённый модерацией.
const НЕПРИГОДНЫЕ = path.join(ДОМ, 'src_unfit');
const СПИСОК_НЕПРИГОДНЫХ = path.join(ДОМ, 'src_unfit.jsonl');

/** Настоящий путь без симлинков. Файла может уже не быть — тогда возвращаем как есть. */
function настоящий(p) {
  try { return fs.realpathSync(p); } catch { return path.resolve(p); }
}

/**
 * Тот ли это отказ, из-за которого исходник больше нельзя пускать в дело.
 *
 * Ровно один случай: модерация RenderGrid отклонила САМУ фотографию. Всё остальное (не скачался
 * референс, фильтр безопасности на промпт, таймаут) к исходнику отношения не имеет и лечится
 * повтором — карантинить по ним значит выбрасывать годные фотографии.
 */
function отказПоИсходнику(err) {
  const m = String((err && err.message) || err || '');
  return /source image was rejected/i.test(m);
}

/**
 * Имена файлов, которые волне брать НЕЛЬЗЯ: и отказы (src_rejected), и непригодные референсы
 * (src_unfit). Списка два, потому что кучи разные (см. шапку у НЕПРИГОДНЫЕ), а ответ на вопрос
 * «брать ли этот файл в волну» один, и разводить его по двум вызовам значит однажды забыть второй.
 */
function вКарантине() {
  const out = new Set();
  let текст = '';
  for (const файл of [СПИСОК, СПИСОК_НЕПРИГОДНЫХ]) {
    try { текст += `\n${fs.readFileSync(файл, 'utf8')}`; } catch { /* списка ещё нет, это не ошибка */ }
  }
  for (const строка of текст.split('\n')) {
    const s = строка.trim();
    if (!s) continue;
    try {
      const з = JSON.parse(s);
      if (з && з.файл) out.add(path.basename(String(з.файл)));
    } catch { /* битую строку молча пропускаем: список не должен уметь ронять волну */ }
  }
  return out;
}

/**
 * Увести исходник в карантин: записать в список и, если он в нашей папке годных, переложить в
 * src_bad.
 *
 * @param {string} src путь к исходнику, каким его назвали при запуске (симлинки развернём сами)
 * @param {string} причина человеческим языком, попадёт в список и в лог
 * @param {object} [o]
 * @param {string} [o.sha] отпечаток файла, если он уже посчитан выше по коду
 * @param {string} [o.ошибка] полный текст отказа, чтобы через месяц не гадать
 * @returns {{ куда: string }} хвост для строки лога («→ перенесён…» или почему не перенесён)
 */
function вКарантин(src, причина, o = {}) {
  return увести(src, причина, { ...o, куда: БРАК, список: СПИСОК });
}

/**
 * Увести исходник в НЕПРИГОДНЫЕ (src_unfit): фотография нормальная, но как референс лица не
 * годится. Отдельная куча и отдельный список, обоснование в шапке у НЕПРИГОДНЫЕ.
 *
 * Подпись та же, что у вКарантин, чтобы вызывающему не надо было помнить два разных вызова.
 */
function вНепригодные(src, причина, o = {}) {
  return увести(src, причина, { ...o, куда: НЕПРИГОДНЫЕ, список: СПИСОК_НЕПРИГОДНЫХ });
}

/** Общее тело обоих переносов: список — главное, перенос — удобство. */
function увести(src, причина, { sha = null, ошибка = null, куда, список } = {}) {
  const путь = настоящий(src);
  const имя = path.basename(путь);
  const папка = path.basename(куда);
  // Запись в список первым делом: она и защищает от повторной оплаты, а перенос может не выйти.
  try {
    let отпечаток = sha;
    if (!отпечаток) {
      try { отпечаток = crypto.createHash('sha256').update(fs.readFileSync(путь)).digest('hex'); } catch {}
    }
    fs.appendFileSync(список, `${JSON.stringify({
      файл: имя, путь, sha256: отпечаток || null, причина,
      ошибка: ошибка ? String(ошибка).slice(0, 300) : null,
      когда: new Date().toISOString(),
    })}\n`);
  } catch (e) {
    return ` (⚠ в список ${path.basename(список)} не записался: ${e.message} — файл может уйти в волну снова)`;
  }
  // Перенос только внутри нашей папки годных: чужие папки не наши, их только сообщаем.
  try {
    const дом = настоящий(ГОДНЫЕ);
    if (!путь.startsWith(дом + path.sep)) return ` → записан в ${path.basename(список)}, файл не наш и лежит на месте`;
    fs.mkdirSync(куда, { recursive: true });
    fs.renameSync(путь, path.join(куда, имя));
    return ` → перенесён в ${папка}/${имя} и записан в ${path.basename(список)}`;
  } catch (e) {
    return ` → записан в ${path.basename(список)}, но перенести в ${папка} не удалось (${e.message})`;
  }
}

module.exports = { вКарантин, вНепригодные, вКарантине, отказПоИсходнику, СПИСОК, СПИСОК_НЕПРИГОДНЫХ };
