/** Кадры с известным вердиктом: половина из годных, половина из брака. */
function выборка(сколько) {
  const из = (папка, вердикт) => {
    let имена = [];
    try { имена = fs.readdirSync(path.join(ДОМ, папка)).filter((f) => /\.(jpe?g|png|webp)$/i.test(f)); } catch { return []; }
    // Берём с шагом, а не первые подряд: имена начинаются с номера, и первые подряд это один и тот
    // же день сбора, один и тот же запрос, то есть один и тот же тип кадра.
    имена.sort();
    const шаг = Math.max(1, Math.floor(имена.length / Math.max(1, сколько)));
    const out = [];
    for (let i = 0; i < имена.length && out.length < сколько; i += шаг) out.push({ файл: path.join(ДОМ, папка, имена[i]), истина: вердикт, куча: папка });
    return out;
  };
  const половина = Math.max(1, Math.round(сколько / 2));
  // src_bad это брак ПОСТА (мыло, спрятанное лицо, отказ модерации): именно про него мы и спрашиваем
  // модель. src_unfit не берём: мелкое и срезанное лицо это вердикт ЧИСЛОВОГО эшелона, модель про
  // геометрию кропа не спрашивают вовсе, и мешать эти кучи значит мерить не то.
  return [...из('src_good', 'ok', половина).slice(0, половина), ...из('src_bad', 'reject', половина)];
}

async function прогнать(модель, кадры) {
  // Имя модели cover_qa читает из окружения при ЗАГРУЗКЕ файла, поэтому на каждую модель модуль
  // берётся заново из чистого кэша: иначе все прогоны уйдут в первую модель и замер будет ложью.
  process.env.COVER_QA_MODEL = модель;
  delete require.cache[require.resolve('./cover_qa.cjs')];
  const { красота, непроверено } = require('./cover_qa.cjs');
  const r = { модель, сошлось: 0, всего: 0, пропустил_брак: 0, зарубил_годное: 0, не_ответила: 0, по_кучам: {} };
  for (const к of кадры) {
    let в;
    try { в = await красота(к.файл); } catch (e) { в = { вердикт: 'unknown', ok: false, причины: [String(e.message)] }; }
    if (непроверено(в)) { r.не_ответила++; r.последний_сбой = (в.причины || []).join('; ').slice(0, 140); continue; }
    r.всего++;
    const ответ = в.вердикт === 'reject' ? 'reject' : 'ok';
    const к_куче = (r.по_кучам[к.истина] = r.по_кучам[к.истина] || { сошлось: 0, всего: 0 });
    к_куче.всего++;
    if (ответ === к.истина) { r.сошлось++; к_куче.сошлось++; }
    else if (к.истина === 'reject') r.пропустил_брак++;
    else r.зарубил_годное++;
    await new Promise((ок) => setTimeout(ок, 400));   // 429 у openrouter прилетает быстро
  }
  return r;
}

(async () => {
  const арг = process.argv.slice(2);
  const сколько = Number(арг.find((a) => /^\d+$/.test(a)) || 20);
  const своя = арг.find((a) => a.includes('/'));
  const список = своя ? [{ модель: своя, цена100: null }] : КАНДИДАТЫ;

  const кадры = выборка(сколько);
  if (!кадры.length) { console.log('нет кадров с известным вердиктом: пусты src_good и src_bad'); process.exit(1); }
  console.log(`кадров с известным вердиктом: ${кадры.length} `
    + `(годных ${кадры.filter((к) => к.истина === 'ok').length}, брака ${кадры.filter((к) => к.истина === 'reject').length})`);
  console.log(`дорогая модель для сравнения: ${ДОРОГАЯ.модель}, $${ДОРОГАЯ.цена100.toFixed(3)} за 100 проверок\n`);

  const итоги = [];
  for (const к of список) {
    process.stdout.write(`${к.модель} … `);
    const r = await прогнать(к.модель, кадры);
    r.цена100 = к.цена100;
    итоги.push(r);
    if (!r.всего) {
      console.log(`НЕ ОТВЕТИЛА ни разу (${r.последний_сбой || 'без пояснения'})`);
      // 402 это кончившийся баланс, а не свойство модели: дальше по списку будет то же самое.
      if (/402/.test(String(r.последний_сбой || ''))) {
        console.log('\n⛔ ЗАМЕР НЕВОЗМОЖЕН: у ключа openrouter кончился баланс (HTTP 402). '
          + 'Пополните баланс и запустите этот же файл снова, ничего менять не надо.');
        process.exit(2);
      }
      continue;
    }
    console.log(`совпадение ${(r.сошлось / r.всего * 100).toFixed(0)}% (${r.сошлось}/${r.всего})`);
  }

  console.log(`\n${'модель'.padEnd(42)} ${'совпад'.padStart(7)} ${'годн'.padStart(6)} ${'брак'.padStart(6)} `
    + `${'проп.брак'.padStart(10)} ${'заруб.годн'.padStart(11)} ${'$/100'.padStart(8)} ${'экономия'.padStart(9)}`);
  console.log('-'.repeat(105));
  for (const r of итоги) {
    if (!r.всего) { console.log(`${r.модель.padEnd(42)} не ответила`); continue; }
    const пр = (a) => (a && a.всего ? `${(a.сошлось / a.всего * 100).toFixed(0)}%` : '-');
    console.log(`${r.модель.padEnd(42)} ${`${(r.сошлось / r.всего * 100).toFixed(0)}%`.padStart(7)} `
      + `${пр(r.по_кучам.ok).padStart(6)} ${пр(r.по_кучам.reject).padStart(6)} `
      + `${String(r.пропустил_брак).padStart(10)} ${String(r.зарубил_годное).padStart(11)} `
      + `${(r.цена100 != null ? `$${r.цена100.toFixed(3)}` : '-').padStart(8)} `
      + `${(r.цена100 ? `${(ДОРОГАЯ.цена100 / r.цена100).toFixed(0)} раз` : '-').padStart(9)}`);
  }
  const годные = итоги.filter((r) => r.всего && r.сошлось / r.всего > 0.9).sort((a, b) => (a.цена100 || 9) - (b.цена100 || 9));
  console.log(годные.length
    ? `\nВЫВОД: порог 90% проходят ${годные.length}, самая дешёвая из них ${годные[0].модель} `
      + `($${(годные[0].цена100 || 0).toFixed(3)} за 100, дешевле дорогой в ${(ДОРОГАЯ.цена100 / годные[0].цена100).toFixed(0)} раз). `
      + `На 500 обложек в сутки это ${(ДОРОГАЯ.цена100 * 5).toFixed(2)} против ${(годные[0].цена100 * 5).toFixed(2)} доллара.`
    : '\nВЫВОД: порог 90% не прошла ни одна дешёвая модель, гейт оставляем на дорогой.');
})().catch((e) => { console.log(`ОШИБКА: ${e.message}`); process.exit(1); });
