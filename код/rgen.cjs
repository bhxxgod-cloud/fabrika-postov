/** Ключ: сначала переменные окружения (так живёт web на Railway), потом локальный файл. */
function apiKey() {
  const env = process.env.NANO_BANANA_API_KEY || process.env.NEIRONKA_MEDIA_API || process.env.NEIRONKA_MEDIA_API_KEY;
  if (env && env.trim()) return env.trim();
  try { const f = fs.readFileSync(KEY_FILE, 'utf8').trim(); if (f) return f; } catch { /* нет файла, скажем ниже */ }
  throw new Error(`нет ключа модели: ни NANO_BANANA_API_KEY в окружении, ни файла ${KEY_FILE}`);
}

/**
 * Проверка ссылки на референс. Ругаемся ЗДЕСЬ, а не в API: API на негодный референс молчит и
 * отдаёт 202, то есть берёт деньги и рисует незнакомого человека.
 */
function checkRefUrl(u) {
  if (typeof u !== 'string' || !/^https?:\/\//i.test(u)) {
    throw new Error(`референс должен быть публичной http(s)-ссылкой, а не «${String(u).slice(0, 60)}». `
      + 'Локальный файл и data:base64 модель не получит: поля images в этом API нет, оно молча '
      + 'выбрасывается, и кадр выходит с другим человеком. Сначала залей файл в хранилище.');
  }
  return u;
}

