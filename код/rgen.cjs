//
// ЧТО ПИШЕМ. Одна строка JSON на КАЖДЫЙ заказ, в момент заказа (не после успеха): деньги списывают
// при постановке задачи, а не при выдаче картинки, и именно это раньше терялось. Файл дописывается,
// никогда не перезаписывается, и живёт в ~/.neironka, а не на Рабочем столе: стол чистят.
const ЖУРНАЛ = require('node:path').join(require('node:os').homedir(), '.neironka', 'траты.jsonl');
function журналТраты(з) {
  try {
    require('node:fs').mkdirSync(require('node:path').dirname(ЖУРНАЛ), { recursive: true });
    require('node:fs').appendFileSync(ЖУРНАЛ, JSON.stringify({
      когда: new Date().toISOString(),
      цена: Number((з.price || 0).toFixed(4)),
      модель: з.model,
      размер: з.resolution || '?',
      формат: з.aspect || '?',
      метка: з.tag || '',
      // ID ЗАКАЗА (25.08): у провайдера иногда вылезает его логотип на готовом кадре, и для тикета
      // в саппорт нужен номер конкретной генерации. Раньше он жил только в консоли и терялся
      // вместе с окном терминала — владелец спрашивал «есть айди?», а ответить было нечем.
      заказ: з.id || '',
      кто: require('node:path').basename(process.argv[1] || 'неизвестно'),
    }) + '\n');
  } catch (e) {
    // Журнал НИКОГДА не должен ронять генерацию: деньги уже списаны, картинка важнее записи о ней.
    console.log(`  ⚠ журнал трат не записан: ${String(e.message).slice(0, 60)}`);
  }
}

