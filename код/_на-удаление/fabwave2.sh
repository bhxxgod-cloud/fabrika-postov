#!/bin/bash
# ДОБОР ОСТАВШИХСЯ КАДРОВ НАЧАЛЬНИКА (07.08, приказ: «доделай пока посты все 22 что не сделаны,
# что отправил уже не надо»). Свободные кадры определены сверкой с журналом обложек covers.json,
# список лежит в /tmp/free_cuts.txt: 12 штук из 22, десять уже стоят в постах.
#
# Идём ЗАЛПОМ: фабрика это API с бесконечной очередью, лок конвейера с фабричного пути снят.
# Нумерация персон продолжается с 34, чтобы не пересечься с уже собранными (1..33).
cd "$(dirname "$0")"
n=34
while IFS= read -r f; do
  [ -f "$f" ] || continue
  p="девочка$n"
  node -e "require('./slidekit.cjs').to45('$f','refs/$p.jpg')" || { n=$((n+1)); continue; }
  echo "=== $p ← $(basename "$f")"
  node factorypost.cjs "$p" img-heart-hair &
  n=$((n+1))
  sleep 2
done < /tmp/free_cuts.txt
wait
echo "ДОБОР ЗАВЕРШЁН"
