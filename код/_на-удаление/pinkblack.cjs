// ПЯТЬ ДОМАШНИХ КАДРОВ РОЗОВОЙ В ЧЁРНЫХ ВОЛОСАХ (07.08, заказ начальника: «сгенерь 5 разных
// домашних фото девочке с розовыми волосами, где она будет с чёрными волосами и в позициях дома,
// как будто фоткалась на веб камеру для парня, немного женственности и страсти»).
//
// Рамки жёсткие и НЕ снимаются: девушка ОДЕТА (домашняя футболка, рубашка оверсайз, топ, свитер),
// плечи и грудь закрыты, никакой обнажённости и белья как образа. Чувственность даём светом,
// позой, взглядом и мягкостью кадра. Кожа идеально чистая (правило проекта), лицо крупно, живое
// фото без пластиковой ретуши.
//
// Идём ПО ОДНОЙ генерации: движок блокирует кнопку на время рендера, параллели нет.
// Запуск: node pinkblack.cjs [сколько]
'use strict';
const fs = require('node:fs');
const path = require('node:path');
const { siteGenerate } = require('./sitegen.cjs');
const { to45 } = require('./slidekit.cjs');

const REF = path.join(__dirname, 'refs', 'Розовая.jpg');
const OUT = path.join(__dirname, 'refs', 'pink_black');
const LIMIT = Number(process.argv[2] || 5);
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

// Общая часть промпта: человек тот же, волосы ЧЁРНЫЕ (главное требование), домашняя съёмка.
const BASE = 'Та же девушка, что на референсе: то же лицо, тот же разрез глаз, форма губ и овал лица, узнаваемая. '
  + 'ВОЛОСЫ ЧЁРНЫЕ, глубокого натурального чёрного цвета, длинные, распущенные, с живым блеском. Розового цвета в волосах НЕТ. '
  + 'Домашний вечерний кадр, снято на фронтальную камеру телефона, личный снимок для своего парня: тепло, уютно, немного женственно. '
  + 'СВЕТ: мягкий вечерний, тёплая лампа или гирлянда сбоку, полутени, лёгкое зерно как у телефонного снимка. '
  + 'ОНА ОДЕТА: домашняя одежда, плечи и грудь закрыты. Одежда ОДНОТОННАЯ, без принтов и надписей. '
  + 'Кожа идеально чистая и ухоженная, с живой текстурой, без пластиковой ретуши, без кукольных губ. Лицо крупно и хорошо видно. '
  + 'Взрослая девушка. ЗАПРЕЩЕНО: обнажённость, бельё как образ, откровенные позы, надписи и вотермарки на кадре, коллажи, рамки, '
  + 'лишние пальцы и конечности, студийный и кольцевой свет, глянцевая реклама.';

const SCENES = [
  { id: 'bed_knees', p: 'Сидит на кровати, обняв колени, смотрит в камеру снизу вверх, лёгкая улыбка. Мягкий свет от лампы у кровати, смятое одеяло. Домашняя футболка оверсайз.' },
  { id: 'belly_phone', p: 'Лежит на животе на кровати, подперев подбородок рукой, вторая рука у лица, смотрит в камеру. Волосы падают на плечи и постель. Свитер крупной вязки.' },
  { id: 'window', p: 'Стоит у окна вполоборота, вечерний город за стеклом размыт, смотрит через плечо в камеру. Рубашка оверсайз застёгнута, руки в рукавах.' },
  { id: 'mirror_floor', p: 'Сидит на полу у зеркала, спиной к нему, одна рука в волосах, взгляд опущен, спокойное выражение. Тёплый свет гирлянды, отражение мягкое. Топ с длинным рукавом и домашние штаны.' },
  { id: 'sofa_plaid', p: 'Полулежит на диване под пледом, голова на подушке, смотрит в камеру, чуть прикусив губу, расслабленная поза. Настольная лампа за кадром даёт тёплое пятно света.' },
];

(async () => {
  if (!fs.existsSync(REF)) { console.log(`ИТОГ: ✗ нет референса ${REF}`); process.exit(1); }
  fs.mkdirSync(OUT, { recursive: true });
  const { openAdmin } = require('./adminbrowser.cjs');
  const { page, done } = await openAdmin();
  let ok = 0, bad = 0;
  try {
    for (const [i, s] of SCENES.slice(0, LIMIT).entries()) {
      const t0 = Date.now();
      console.log(`[${i + 1}/${Math.min(LIMIT, SCENES.length)}] сцена «${s.id}» — генерю…`);
      try {
        const raw = (await siteGenerate(page, { prompt: BASE + ' СЦЕНА: ' + s.p, refFile: REF,
          out: `/tmp/pb_${s.id}.png` })).out;
        const fin = to45(raw, path.join(OUT, `poza${i + 1}_${s.id}.jpg`));
        console.log(`  ✓ готово за ${Math.round((Date.now() - t0) / 1000)}с → ${fin}`);
        ok++;
      } catch (e) { console.log(`  ✗ сцена «${s.id}»: ${String(e.message).slice(0, 80)}`); bad++; }
      await sleep(2000);
    }
  } finally { await done(); }
  console.log(`ИТОГ: кадров готово ${ok}, ошибок ${bad}, папка ${OUT}`);
  process.exit(0);   // явный выход: иначе живые сокеты CDP держат процесс (грабля 07.08)
})().catch((e) => { console.error('ОШИБКА:', e.message); process.exit(1); });
