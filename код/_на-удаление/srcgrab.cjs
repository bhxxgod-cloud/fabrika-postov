  const арг = process.argv.slice(2);
  const источник = (арг.find((a) => !a.startsWith('--') && !/^\d+$/.test(a)) || 'yandex').toLowerCase();
  const надо = Number(арг.find((a) => /^\d+$/.test(a)) || 60);
