// dreamstime), плюс очевидные фотобанки.
const СТОК = /(^|\.)(shutterstock|istockphoto|gettyimages|dreamstime|depositphotos|123rf|alamy|freepik|magnific|lirp\.cdn-website|adobe|stock\.adobe|vecteezy|pexels|unsplash|canva|placeit|zoonar)\./i;

function аргументы(url, файл, { прокси = null, ua = UA_БРАУЗЕР, секунд = 30, реферер = null } = {}) {
  const args = ['-sS', '--fail', '--compressed', '--max-time', String(секунд), '-o', файл, '-A', ua];
  if (реферер) args.push('-e', реферер);
  if (прокси) args.push('--proxy', прокси);
  args.push(url);
  return args;
}

function качнуть(url, файл, o = {}) {
  const r = spawnSync('curl', аргументы(url, файл, o), { encoding: 'utf8' });
  if (r.status !== 0 || !fs.existsSync(файл)) throw new Error(`curl код ${r.status}`);
  return файл;
}

// СКАЧИВАНИЕ ПАЧКОЙ, И ЭТО ГЛАВНАЯ ПРИЧИНА ТЕМПА (замер 11.08). Первый прогон качал файлы по одному
// и дал около 20 файлов в минуту: почти всё время процесс просто ждал ответа чужого сервера, а
// картинки лежат на десятках разных хостов, то есть ждать их можно одновременно без всякого вреда
// для них. Ограничитель НЕ УБИРАЕМ: одновременных загрузок ровно ПОТОК, иначе мы упрёмся в свой же
// канал и начнём получать обрывы, которые приёмка честно посчитает битыми файлами.
// Страницы выдачи по-прежнему берутся по одной с паузой: там чужой сервис один, и он умеет капчу.
const ПОТОК = Number(process.env.GRAB_CONC || 10);

async function качнутьПачкой(задания, o = {}) {
  const готово = [];
  let сбоев = 0;
  for (let i = 0; i < задания.length; i += ПОТОК) {
    await Promise.all(задания.slice(i, i + ПОТОК).map((з) => new Promise((ок) => {
      const { execFile } = require('node:child_process');
      execFile('curl', аргументы(з.ссылка, з.путь, o), { timeout: (o.секунд || 30) * 1000 + 5000 }, (e) => {
        if (e || !fs.existsSync(з.путь)) { сбоев++; try { fs.unlinkSync(з.путь); } catch {} }
        else готово.push(з);
        ок();
      });
    })));
  }
  return { готово, сбоев };
}

