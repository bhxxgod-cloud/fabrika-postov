/**
 * Ссылки на картинки со страницы выдачи.
 * Ссылка лежит в html как img_url=<двойной urlencode>. Раскодировать надо ДВА раза: один слой
 * яндекса, второй самой ссылки. С одним слоем в путях остаются %25 и качается 404.
 */
function яндексСтраница(запрос, стр) {
  const url = 'https://yandex.ru/images/search?text=' + encodeURIComponent(запрос)
    // isize=large отсекает превью и мелочь на входе: мельче 500 по стороне приёмка всё равно не
    // возьмёт, и качать это значит платить временем за заведомый отказ.
    + `&p=${стр}&isize=large&nomisspell=1`;
  const файл = path.join(ВРЕМ, `ya_${process.pid}_${стр}.html`);
  качнуть(url, файл, { секунд: 35 });
  const html = fs.readFileSync(файл, 'utf8');
  try { fs.unlinkSync(файл); } catch { /* уже нет */ }
  const out = new Set();
  for (const m of html.matchAll(/img_url=([^&"\\]+)/g)) {
    let u = m[1];
    try { u = decodeURIComponent(decodeURIComponent(u)); } catch { try { u = decodeURIComponent(u); } catch { continue; } }
    if (!/^https?:\/\//i.test(u)) continue;
    if (!/\.(jpe?g|png|webp)(\?|$)/i.test(u)) continue;
    let хост = ''; try { хост = new URL(u).hostname; } catch { continue; }
    if (СТОК.test(`${хост}.`)) continue;
    out.add(u);
  }
  return { ссылки: [...out], капча: /showcaptcha|SmartCaptcha/i.test(html) };
}

// СТАРТОВАЯ СТРАНИЦА (--стр0=N), и это не удобство, а лечение главной потери темпа (замер 11.08).
// Второй прогон по тем же запросам с нулевой страницы дал 65% ДУБЛЕЙ: страницы выдачи стабильны, и
// первый прогон их уже выбрал, то есть мы платили полной скоростью скачивания за файлы, которые
// приёмка обязана выбросить. Проверено глазами на паре 0_new/0_old: совпадение настоящее, не промах
// хэша. Поэтому по уже выбранным запросам заходим сразу с той страницы, где прошлый прогон кончился.
async function яндекс({ запросы, надо, страниц, стр0 = 0 }) {
  const кандидаты = [];
  const виданные = new Set();
  let страницОбошли = 0, капч = 0, скачано = 0, сбоев = 0;
  for (let стр = стр0; стр < стр0 + страниц && кандидаты.length < надо; стр++) {
    for (const q of запросы) {
      if (кандидаты.length >= надо) break;
      let р;
      try { р = яндексСтраница(q, стр); страницОбошли++; }
      catch (e) { сбоев++; console.log(`  ⚠ выдача «${q}» стр ${стр}: ${String(e.message).slice(0, 60)}`); continue; }
      if (р.капча) { капч++; console.log(`  ⛔ капча на «${q}» стр ${стр}: жду 30 секунд`); await спать(30000); continue; }
      const задания = [];
      for (const u of р.ссылки) {
        if (задания.length + кандидаты.length >= надо) break;
        if (виданные.has(u)) continue;
        виданные.add(u);
        const рас = (/\.(jpe?g|png|webp)/i.exec(u) || [])[1] || 'jpg';
        задания.push({
          // pid в имени обязателен: слоты гоняются одновременно, а Date.now у них совпадает.
          путь: path.join(ВРЕМ, `y_${process.pid}_${Date.now().toString(36)}_${кандидаты.length + задания.length}.${рас.toLowerCase().replace('jpeg', 'jpg')}`),
          ссылка: u, запрос: q, источник: 'яндекс-картинки',
        });
      }
      const пачка = await качнутьПачкой(задания, { секунд: 25, реферер: 'https://yandex.ru/images/' });
      кандидаты.push(...пачка.готово);
      скачано += пачка.готово.length; сбоев += пачка.сбоев;
      console.log(`  «${q}» стр ${стр}: ссылок ${р.ссылки.length}, скачано ${пачка.готово.length} (всего ${кандидаты.length}/${надо})`);
      // Пауза между запросами к выдаче. Капчи в замере не было, но выдача это не наша ручка, и
      // долбить её без паузы значит получить капчу и потерять канал целиком.
      await спать(1200 + Math.floor(Math.random() * 1300));
    }
  }
  return { кандидаты, статистика: { страницОбошли, капч, скачано, сбоев } };
}

// ── ИНСТАГРАМ ─────────────────────────────────────────────────────────────────────────────────
function прокси() {
  const out = [];
  try {
    for (const f of fs.readdirSync('/tmp/px')) {
      if (!f.endsWith('.txt')) continue;
      for (const l of fs.readFileSync(path.join('/tmp/px', f), 'utf8').split('\n')) {
        const p = l.trim().split(':');
        if (p.length === 4) out.push(`http://${p[2]}:${p[3]}@${p[0]}:${p[1]}`);
      }
    }
  } catch { /* папки нет */ }
  return out;
}

