#!/bin/bash
# ЗАЛП ПО НОВЫМ КАДРАМ ИЗ ТЕЛЕГРАМА (07.08, приказ: «скачал новые фотки с тг в загрузки, много
# штук 30 каждая, это отдельный пост с волосами, начинай»).
#
# Кадры уже приведены к 4:5 и лежат в refs/tg0708/kadrNN.jpg (32 штуки).
# Фабрика это API с бесконечной очередью, лок конвейера с фабричного пути снят, поэтому идём
# ЗАЛПОМ: время пачки равно самому медленному посту, а не сумме всех.
# Параллельность держим на 8 одновременно: у сборки после рендера идёт заливка кадров в админку,
# и совсем без предела мы упирались в неё, а не в фабрику.
cd "$(dirname "$0")"
n=46            # нумерация персон продолжается: 1..45 уже заняты
MAX=8
for f in refs/tg0708/kadr*.jpg; do
  [ -f "$f" ] || continue
  p="девочка$n"
  cp "$f" "refs/$p.jpg"
  echo "=== $p ← $(basename "$f")"
  node factorypost.cjs "$p" img-heart-hair &
  n=$((n+1))
  # держим не больше MAX одновременно
  while [ "$(jobs -rp | wc -l)" -ge "$MAX" ]; do sleep 5; done
done
wait
echo "ЗАЛП ТГ-КАДРОВ ЗАВЕРШЁН"
