#!/bin/bash
# ПАЧКА ПОСТОВ ФАБРИКОЙ ПО СТАНДАРТУ 07.08 (приказ: «давай делать с другими девочками пачками»).
# Стандарт: 3 кадра заказывает фабрика, 4-й собираем сами из ПЕРВОГО фабричного кадра
# (обычное фото, не телефон) с перекадрировкой и фирменным блоком; хук на кадр 1 наш.
#
# Берём только СВОБОДНЫЕ кадры нарезки начальника от 06.08 16:31-16:33: использованные им
# самим уже отработаны («юзнутые уже не нужны, я их выложил»).
# Фабрика держит параллель, но идём по 2 одновременно: у сборки общий лок конвейера.
cd "$(dirname "$0")"
S="/Users/qq/Pictures/Screenshots"
mk() {   # mk <персона> <файл кадра>
  local p="$1" f="$2"
  [ -f "$f" ] || { echo "НЕТ ФАЙЛА: $f"; return; }
  node -e "require('./slidekit.cjs').to45('$f','refs/$p.jpg')" || return
  echo "=== $p ← $(basename "$f")"
  node factorypost.cjs "$p" img-heart-hair
}
# ВСЕ СРАЗУ (07.08): фабрика это API с бесконечной очередью на сервере, а лок конвейера с
# фабричного пути снят. Значит пачка идёт одним залпом, а не парами: время пачки равно времени
# самого медленного поста, а не сумме всех.
mk "девочка26" "$S/Screenshot 2026-08-06 at 16.31.45.png" &
mk "девочка27" "$S/Screenshot 2026-08-06 at 16.32.30.png" &
mk "девочка28" "$S/Screenshot 2026-08-06 at 16.32.41.png" &
mk "девочка29" "$S/Screenshot 2026-08-06 at 16.32.57.png" &
mk "девочка30" "$S/Screenshot 2026-08-06 at 16.33.03.png" &
mk "девочка31" "$S/Screenshot 2026-08-06 at 16.32.48.png" &
mk "девочка32" "$S/Screenshot 2026-08-06 at 16.32.34.png" &
mk "девочка33" "$S/Screenshot 2026-08-06 at 16.31.53.png" &
wait
echo "ПАЧКА ЗАВЕРШЕНА"
