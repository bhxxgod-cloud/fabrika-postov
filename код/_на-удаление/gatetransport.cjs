'use strict';
// ТЕСТ ГЕЙТА ТРАНСПОРТА. Запуск: `node gatetransport.cjs`
//
// ЗАЧЕМ ОТДЕЛЬНЫЙ ФАЙЛ, ЕСЛИ САМОПРОВЕРКА ЕСТЬ В promptkit.audit(). Аудит проверяет РЕГУЛЯРКУ (ловит
// ли она падежи) и списки локаций. А здесь проверяется то, ради чего гейт вообще ставился: что заказ
// с метро НЕ СОБИРАЕТСЯ, даже когда локацию передали строкой мимо всякого пула. Именно так метро и
// доехало до поста нов49, который начальник забраковал словами «некрасивое метро, модные девочки не
// ездят в метро в рф»: три локации метро стояли в пуле живыми, слово «метро» стояло в самом запрете
// промпта, а сборщики умеют передавать место строкой.
//
// ЧТО ЗДЕСЬ ПРОВЕРЯЕТСЯ:
//   1) промпт с метро (и с падежами: «в метро», «у эскалатора», «метрополитен») роняет сборку;
//   2) 20 промптов, собранных по ротору как на живой пачке постов, чисты от транспорта;
//   3) домашние локации кадра 4 чисты и от транспорта, и от ванной;
//   4) гейт не рубит наши разрешённые слова («лифтинг» это уход за кожей, а не лифт).
const pk = require('./promptkit.cjs');
const TPL = require('./templates.cjs');

let провалов = 0;
const ок = (что) => console.log(`  ✓ ${что}`);
const плохо = (что) => { провалов++; console.log(`  ✗ ${что}`); };

// ═══ 1. ГЕЙТ РУБИТ МЕТРО, ПРИЧЁМ В ЛЮБОМ ПАДЕЖЕ ═════════════════════════════════════════════
// Локацию передаём строкой в place: это тот самый путь мимо пула, который списками не закрывается.
console.log('\n1. Подсовываю гейту транспорт (locations мимо пула, как это делают сборщики):');
const дурные = [
  'в метро на платформе, холодный люминесцентный свет, поручни',
  'на эскалаторе метро, длинный тоннель со светильниками за спиной',
  'у эскалатора, за спиной уходящие вниз ступени',
  'на станции московского метрополитена, мраморные пилоны',
  'в подземке вечером, толпа за спиной',
  'в салоне трамвая вечером, ряды потёртых сидений',
  'в автобусе у окна, огни улицы за стеклом',
  'на заднем сиденье такси ночью, огни города за окном',
  'в лифте, тесная кабина и зеркальная стенка',
  'в вагоне электрички у окна',
  'у турникетов в вестибюле, за спиной поток людей',
  'на пассажирском сиденье, ремень и улица за окном',
];
for (const место of дурные) {
  let упало = false, текст = '';
  try {
    pk.lookPrompt({ template: 'img-beauty-guide', step: 3, srcHair: 'light', hairIdx: 0, place: место });
  } catch (e) { упало = true; текст = e.message; }
  if (упало && /ГЕЙТ ТРАНСПОРТА/.test(текст)) ок(`заказ НЕ ушёл: «${место.slice(0, 42)}…»`);
  else плохо(`ПРОПУЩЕНО В ЗАКАЗ: «${место}» ${упало ? '(упало, но не по гейту: ' + текст.slice(0, 80) + ')' : ''}`);
}
// Тот же путь у спасательного промпта по лицу: у него соблазн взять метро самый сильный, потому что
// по замеру сходства лучший результат вышел именно в тоннеле эскалатора.
for (const место of ['на эскалаторе метро, тесный тоннель', 'в вагоне метро, поручни за спиной']) {
  let упало = false;
  try { pk.keepFacePrompt({ srcHair: 'dark', hairIdx: 1, place: место }); } catch (e) { упало = /ГЕЙТ ТРАНСПОРТА/.test(e.message); }
  if (упало) ок(`спасательный промпт НЕ ушёл: «${место.slice(0, 34)}…»`);
  else плохо(`спасательный промпт пропустил «${место}»`);
}

// ═══ 2. ДВАДЦАТЬ ЖИВЫХ ПРОМПТОВ ЧИСТЫ ═══════════════════════════════════════════════════════
// Собираем ровно так, как собирает onepost: пара локаций по ротору, свет локации, кадры 3 и 4.
console.log('\n2. Двадцать промптов по ротору (как на живой пачке постов):');
const шаблоны = TPL.list();
let чистых = 0;
const таблица = [];
for (let rotor = 0; rotor < 10; rotor++) {
  const t = шаблоны[rotor % шаблоны.length];
  const p = pk.pickCityPlaces(rotor);
  for (const [step, place, light, bgMode] of [[3, p.loc3, p.light3, p.bg3], [4, p.loc4, p.light4, p.bg4]]) {
    const prompt = pk.lookPrompt({ template: t, step, srcHair: 'light', hairIdx: rotor % 2, place, light, bgMode });
    const hits = pk.transportHits(prompt);
    if (hits.length) плохо(`ротор ${rotor} кадр ${step}: транспорт ${hits.join(', ')}`);
    else чистых++;
    таблица.push({ ротор: rotor, кадр: step, знаков: prompt.length, локация: (step === 3 ? p.name3 : p.name4).slice(0, 46) });
  }
}
console.table(таблица);
if (чистых === 20) ок(`все 20 промптов чисты от транспорта (кадры 3 и 4, ${шаблоны.length} шаблонов в ротации)`);

// ═══ 3. ДОМАШНИЙ ПУЛ КАДРА 4: НИ ТРАНСПОРТА, НИ ВАННОЙ ══════════════════════════════════════
console.log('\n3. Пул кадра 4 (домашние локации):');
const ВАННА = /ванн|душев|санузел|туалет|унитаз|раковин/i;
for (const l of pk.LOCATIONS.quiet) {
  const hits = pk.transportHits(`${l.place} ${l.light}`);
  if (hits.length) плохо(`${l.slug}: транспорт ${hits.join(', ')}`);
  else if (ВАННА.test(l.place)) плохо(`${l.slug}: ванная, а она запрещена по посту нов61`);
  else ок(`${l.slug}`);
}
console.log(`  домашних локаций в пуле: ${pk.LOCATIONS.quiet.length}, заставок: ${pk.LOCATIONS.city.length}`);

// ═══ 4. ЛОЖНЫХ СРАБАТЫВАНИЙ НЕТ ═════════════════════════════════════════════════════════════
// Ложное срабатывание дороже пропуска: оно роняет сборку живого поста на ровном месте.
console.log('\n4. Разрешённые слова гейт не трогает:');
for (const s of ['лифтинг кожи и ухоженный вид', 'сто километров пути', 'квартира в новостройке',
  'на кухне утром у окна, чашка на столе', 'в коридоре у вешалки, куртки за спиной']) {
  const hits = pk.transportHits(s);
  if (hits.length) плохо(`ложно срублено «${s}» (${hits.join(', ')})`);
  else ок(`«${s}»`);
}

// ═══ 5. РАСПРЕДЕЛЕНИЕ ЛОКАЦИЙ КАДРА 3 НА 50 ПОСТАХ ══════════════════════════════════════════
// Приказ 11.08 после поста d01c49a5 и отчёта отдела качества (транспорт в 37% постов, Москва-Сити в
// 47%): показать распределение и доказать, что транспорта нет ни одного, а одна локация не занимает
// больше 15 процентов выборки.
console.log('\n5. Пятьдесят постов подряд: какие локации выпадают кадру 3');
{
  const N = 50;
  const счёт = new Map(), группы = new Map();
  let транспорта = 0;
  for (let r = 0; r < N; r++) {
    const p = pk.pickCityPlaces(r);
    счёт.set(p.name3, (счёт.get(p.name3) || 0) + 1);
    const g = /москва-сити/i.test(p.loc3) ? 'москва-сити' : 'остальные места';
    группы.set(g, (группы.get(g) || 0) + 1);
    const prompt = pk.lookPrompt({ template: 'img-beauty-guide', step: 3, srcHair: 'light', hairIdx: 0,
      place: p.loc3, light: p.light3, bgMode: p.bg3, hairLenIdx: r % pk.HAIR_LENGTHS.length });
    if (pk.transportHits(prompt).length) транспорта++;
  }
  const строки = [...счёт.entries()].sort((a, b) => b[1] - a[1])
    .map(([имя, n]) => ({ локация: имя.slice(0, 52), постов: n, доля: `${(n / N * 100).toFixed(0)}%` }));
  console.table(строки);
  console.table([...группы.entries()].map(([g, n]) => ({ группа: g, постов: n, доля: `${(n / N * 100).toFixed(0)}%` })));
  const макс = Math.max(...счёт.values());
  if (транспорта === 0) ок(`транспорта в 50 промптах кадра 3: НИ ОДНОГО`);
  else плохо(`транспорт в ${транспорта} промптах из ${N}`);
  if (макс / N <= 0.15) ок(`самая частая локация ${(макс / N * 100).toFixed(0)}% (порог 15%), всего заставок в пуле ${pk.LOCATIONS.city.length}`);
  else плохо(`самая частая локация ${(макс / N * 100).toFixed(0)}%, а больше 15% нельзя`);
}

// ═══ 6. ДЛИНА ВОЛОС МЕНЯЕТСЯ И РАЗДАЁТСЯ ПО ХЭШУ ════════════════════════════════════════════
console.log('\n6. Смена длины волос (приказ 11.08):');
{
  const p = pk.lookPrompt({ template: 'img-beauty-guide', step: 3, srcHair: 'light', hairIdx: 0,
    place: 'в своей комнате вечером, свет от гирлянды', hairLenIdx: 2 });
  if (/ДЛИНА И ФОРМА ВОЛОС МЕНЯЮТСЯ: ровный срез до плеч/.test(p)) ок('длина названа в промпте');
  else плохо('в промпте нет названной длины');
  const пары = new Set();
  for (let i = 0; i < 14; i++) пары.add(`${i % 2}|${pk.hairLen(i)}`);
  if (пары.size === 14) ок('пара «цвет + длина» не повторяется 14 постов подряд');
  else плохо(`пар всего ${пары.size} из 14, цвет и длина не независимы`);
  const h1 = pk.hairLenByHash('op_1754900000_111'), h2 = pk.hairLenByHash('op_1754900000_111');
  if (h1 === h2) ок(`раздача по хэшу поста устойчива (тот же пост → та же длина, ${pk.hairLen(h1)})`);
  else плохо('раздача по хэшу не устойчива, девочка перестрижётся между кадрами');
}

console.log(провалов ? `\nПРОВАЛОВ: ${провалов}` : '\nВСЁ ЗЕЛЁНОЕ: гейт рубит транспорт и не мешает живым промптам');
process.exit(провалов ? 1 : 0);
