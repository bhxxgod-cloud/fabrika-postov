'use strict';
// ДОКАЗАТЕЛЬСТВО ЗЕРНА КРОПАМИ СТО ПРОЦЕНТОВ.
//
// ЗАЧЕМ ОТДЕЛЬНЫЙ ИНСТРУМЕНТ. 11.08 начальник посмотрел склейки «до и после» целыми кадрами и сказал
// дословно: «зерна вообще нет, 0 просто». Урок тут не про силу зерна, а про способ показа: склейка
// двух кадров по 1080 пикселей уменьшается до ширины сообщения, соседние пиксели усредняются, и
// зерно исчезает ИМЕННО НА КАРТИНКЕ ДОКАЗАТЕЛЬСТВА, даже когда в файле оно есть. Поэтому смотреть
// надо кроп сто процентов, без единого масштабирования, и рядом с ним цифру шума по этому же кропу.
//
// ЧТО СОБИРАЕТ. Лист: по строке на каждую ступень силы, в строке шесть кропов 400 на 400 подряд:
//   щека ДО | щека ПОСЛЕ | фон ДО | фон ПОСЛЕ | света ДО | света ПОСЛЕ
// Участок светов ищется замером (самый светлый квадрат кадра) и нужен для проверки главного
// свойства сенсорного шума: он живёт в тенях, а в светах его почти нет. Рядом в json лежит
// насыщенность по всему кадру до и после: по приказу 11.08 она обязана не падать.
// Щека берётся по детектору лица (там кожа, на ней зерно видно лучше всего и там же оно опаснее
// всего для сходства). Фон берётся из верхней части кадра подальше от лица: на ровной стене шум
// виден даже когда на коже его прячет текстура.
//
// ЗАПУСК
//   node phoneproof.cjs --кадр=/tmp/op_..._4_tiktok.jpg --эталон=/tmp/op_..._1.jpg --куда=<папка>
//   node phoneproof.cjs --кадр=… --пресет=5c --куда=…      лестница по пресету, а не по вайбу
'use strict';
const fs = require('node:fs');
const path = require('node:path');
const { spawnSync } = require('node:child_process');
const FF = require('ffmpeg-static');
const pl = require('./phonelook.cjs');

const СТУПЕНИ = [0.6, 1, 1.5, 2.2];   // множители силы зерна
const КРОП = 400;

function ффмпег(args) {
  const r = spawnSync(FF, ['-y', '-hide_banner', '-loglevel', 'error', ...args], { encoding: 'utf8' });
  if (r.status !== 0) throw new Error(`ffmpeg код ${r.status}: ${String(r.stderr).slice(-300)}`);
}

/** Размер кадра, чтобы кропы не уехали за край. */
function размер(файл) {
  const r = spawnSync(FF, ['-hide_banner', '-i', файл], { encoding: 'utf8' });
  const m = String(r.stderr).match(/,\s(\d{2,5})x(\d{2,5})[\s,]/);
  return m ? { w: +m[1], h: +m[2] } : { w: 1080, h: 1350 };
}

/** Кроп сто процентов: без масштабирования, только вырезка. */
function кроп(файл, выход, x, y, разм) {
  const { w, h } = разм;
  const x0 = Math.max(0, Math.min(w - КРОП, Math.round(x - КРОП / 2)));
  const y0 = Math.max(0, Math.min(h - КРОП, Math.round(y - КРОП / 2)));
  // Кроп кодируем БЕЗ ПОТЕРЬ по возможности (q 1): иначе доказательство само добавит артефактов.
  ффмпег(['-i', файл, '-vf', `crop=${КРОП}:${КРОП}:${x0}:${y0}`, '-frames:v', '1', '-c:v', 'mjpeg', '-q:v', '1', выход]);
  return выход;
}

/** Центр самого светлого участка 400 на 400: сетка по кадру, средняя яркость, максимум. */
function ярчайший(файл, разм) {
  const PY = `
import sys, cv2, numpy as np
g = cv2.cvtColor(cv2.imread(sys.argv[1]), cv2.COLOR_BGR2GRAY)
h, w = g.shape[:2]; b = int(sys.argv[2]); шаг = b // 2
лучш = (-1, w // 2, h // 2)
for y in range(0, max(1, h - b), шаг):
    for x in range(0, max(1, w - b), шаг):
        m = float(g[y:y+b, x:x+b].mean())
        if m > лучш[0]: лучш = (m, x + b // 2, y + b // 2)
print(int(лучш[1]), int(лучш[2]))
`;
  const r = spawnSync('python3', ['-c', PY, файл, String(КРОП)], { encoding: 'utf8' });
  const [x, y] = String(r.stdout || '').trim().split(/\s+/).map(Number);
  return Number.isFinite(x) ? { x, y } : { x: разм.w / 2, y: разм.h / 4 };
}

function главное() {
  const арг = process.argv.slice(2);
  const зн = (и, п) => { const a = арг.find((s) => s.startsWith(`--${и}=`)); return a ? a.split('=').slice(1).join('=') : п; };
  const кадр = зн('кадр');
  const эталон = зн('эталон');
  const пресет = зн('пресет');
  const место = зн('место');   // текст локации: от него зависит режим зерна
  const куда = зн('куда', '/Users/qq/Desktop/ТЕЛЕФОННАЯ-ПЛЁНКА-11.08/ДОКАЗАТЕЛЬСТВО');
  if (!кадр || !fs.existsSync(кадр) || (!эталон && !пресет)) {
    console.log('нужно: --кадр=<файл> и либо --эталон=<кадр1>, либо --пресет=5c|11 [--куда=<папка>]');
    process.exit(1);
  }
  fs.mkdirSync(куда, { recursive: true });
  const имя = path.basename(кадр).replace(/\.[a-z]+$/i, '');
  const разм = размер(кадр);
  const л = pl.лицоКадра(кадр);
  // Щека: полрадиуса вниз и полрадиуса в сторону от центра лица. Нет лица, берём центр кадра.
  const щека = л ? { x: л.cx - л.r * 0.42, y: л.cy + л.r * 0.45 } : { x: разм.w / 2, y: разм.h / 2 };
  // Фон: верхняя четверть, с той стороны, где лица нет.
  const фон = { x: л && л.cx > разм.w / 2 ? разм.w * 0.16 : разм.w * 0.84, y: разм.h * 0.16 };
  // САМЫЙ СВЕТЛЫЙ УЧАСТОК ищем замером, а не на глаз: он нужен, чтобы показать главное свойство
  // сенсорного шума, которое мы теперь повторяем, а именно что шум живёт в ТЕНЯХ и в светах его
  // почти нет. Без этого кропа заявление «шум по теням» остаётся словами.
  const света = ярчайший(кадр, разм);

  const строки = [];
  const отчёт = [];
  // --дефолт: одна строка ровно с рабочей силой, без лестницы. Нужен для доказательства правила
  // «на улице зерна меньше»: две такие строки, светлый кадр и тёмный, кладутся одна под другую.
  const ступени = арг.includes('--дефолт') ? [1] : СТУПЕНИ;
  for (const ст of ступени) {
    const обр = path.join(куда, `${имя}__x${String(ст).replace('.', '_')}.jpg`);
    let прим;
    if (пресет) {
      прим = pl.телефонный(кадр, обр, { пресет, сила: ст, надПлашкой: true, лицо: л });
      прим = { пресет, сила: ст };
    } else {
      const r = арг.includes('--дефолт')
        ? pl.подВайб(кадр, обр, { эталон, надПлашкой: true, лицо: л, место })
        : pl.подВайб(кадр, обр, { эталон, надПлашкой: true, лицо: л, место, множительЗерна: ст, итераций: 0 });
      прим = r.примененo;
    }
    const к = {
      щДо: кроп(кадр, path.join(куда, `${имя}__щека_до.jpg`), щека.x, щека.y, разм),
      щПосле: кроп(обр, path.join(куда, `${имя}__щека_x${ст}.jpg`), щека.x, щека.y, разм),
      фДо: кроп(кадр, path.join(куда, `${имя}__фон_до.jpg`), фон.x, фон.y, разм),
      фПосле: кроп(обр, path.join(куда, `${имя}__фон_x${ст}.jpg`), фон.x, фон.y, разм),
      сДо: кроп(кадр, path.join(куда, `${имя}__света_до.jpg`), света.x, света.y, разм),
      сПосле: кроп(обр, path.join(куда, `${имя}__света_x${ст}.jpg`), света.x, света.y, разм),
    };
    const п = pl.профиль([к.щДо, к.щПосле, к.фДо, к.фПосле, к.сДо, к.сПосле]);
    // Насыщенность выносим в отчёт по всему кадру: приказ 11.08, она обязана не упасть.
    const нс = pl.профиль([кадр, обр]);
    отчёт.push({ ступень: ст, применено: прим,
      щека: { до: п[0].зерно, после: п[1].зерно }, фон: { до: п[2].зерно, после: п[3].зерно },
      света: { до: п[4].зерно, после: п[5].зерно },
      насыщенность: { до: нс[0].насыщенность, после: нс[1].насыщенность },
      яркость_светов: { до: п[4].яркость, после: п[5].яркость } });
    const строка = path.join(куда, `${имя}__строка_x${ст}.jpg`);
    ффмпег(['-i', к.щДо, '-i', к.щПосле, '-i', к.фДо, '-i', к.фПосле, '-i', к.сДо, '-i', к.сПосле,
      '-filter_complex', '[0][1][2][3][4][5]hstack=6', '-frames:v', '1', '-c:v', 'mjpeg', '-q:v', '1', строка]);
    строки.push(строка);
    const о = отчёт[отчёт.length - 1];
    console.log(`ступень x${ст}: зерно щека ${о.щека.до} → ${о.щека.после}, фон ${о.фон.до} → ${о.фон.после}, `
      + `света ${о.света.до} → ${о.света.после}, НАСЫЩЕННОСТЬ ${о.насыщенность.до} → ${о.насыщенность.после}`);
  }
  const лист = path.join(куда, `${имя}__${арг.includes('--дефолт') ? 'ДЕФОЛТ' : 'ЛЕСТНИЦА'}_кропы100.jpg`);
  ффмпег([...строки.flatMap((f) => ['-i', f]),
    '-filter_complex', `${строки.map((_, i) => `[${i}]`).join('')}vstack=${строки.length}`,
    '-frames:v', '1', '-c:v', 'mjpeg', '-q:v', '1', лист]);
  fs.writeFileSync(path.join(куда, `${имя}__зерно.json`), JSON.stringify(отчёт, null, 1));
  console.log(`\nлист: ${лист}`);
  console.log('порядок в строке: щека ДО | щека ПОСЛЕ | фон ДО | фон ПОСЛЕ | света ДО | света ПОСЛЕ, '
    + 'строки сверху вниз это ступени '
    + СТУПЕНИ.join(', '));
}

if (require.main === module) главное();
module.exports = { СТУПЕНИ };
