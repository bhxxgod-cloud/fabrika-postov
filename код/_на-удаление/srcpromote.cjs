'use strict';
// ВТОРОЙ ЭШЕЛОН ДЛЯ НАБРАННЫХ ИСХОДНИКОВ: из src_pending в src_good или в src_bad.
//
// ЗАЧЕМ ЕСТЬ ТРЕТЬЯ КУЧА И ПОЧЕМУ НАБОР ЛЁГ НЕ В src_good (11.08, замер глазами).
// Сбор 11.08 дал 841 файл, прошедший ЧИСЛОВОЙ гейт cover_qa (резкость по трём осям, размер лица 14%
// высоты обложки, срез кропом). Модельный эшелон в тот день не работал: у ключа openrouter кончился
// баланс, ручка отвечала 402. Девять принятых файлов были осмотрены глазами, и шесть из девяти
// оказались непригодны:
//   1724 — глянцевая нейрокартинка с пластиковой кожей и водяным знаком;
//   1018 — лицо закрыто маской для плавания, поверх водяной знак yoursite.ru;
//   0299 — КОЛЛАЖ из двух кадров, лицо закрыто руками и воротом;
//   1525 — лицо закрыто тёмными очками;
//   1543 — коммерческая студийная съёмка ПАРЫ, в кадре мужчина, глаза закрыты;
//   0992 — лицо закрыто кленовым листом.
// Ни один из этих шести числовым гейтом не ловится и не может ловиться: кадры резкие, лицо крупное и
// целиком в кропе. Перекрытие лица, посторонний в кадре, коллаж, водяной знак, нейрослоп и чужой
// типаж живут ТОЛЬКО в модельном эшелоне.
//
// ПОЧЕМУ ЭТО НЕЛЬЗЯ БЫЛО ОСТАВИТЬ В src_good. Волна берёт исходники из src_good и ПЛАТИТ за каждый:
// заказ рендера плюс рендер фабрики. Две трети мусора в куче годных это не «потом отсортируем», это
// оплаченный брак в тот же день, причём на обложках, то есть на первом и часто единственном кадре,
// который увидит зритель. Правило «ворота проверки перед отправкой» тут дороже удобства.
//
// ЗАПУСК (нужен живой баланс openrouter):
//   node srcpromote.cjs            всю кучу src_pending
//   node srcpromote.cjs 50         первые 50, чтобы посмотреть глазами на результат разбора
//   COVER_QA_MODEL=google/gemini-2.5-flash-lite node srcpromote.cjs
//     дешёвая модель вместо дорогой. Сначала прогоните coverqa_cheap.cjs: переключать гейт можно
//     только если совпадение с дорогой выше 90 процентов, порог задан начальником.
const fs = require('node:fs');
const path = require('node:path');
const { проверить } = require('./cover_qa.cjs');

const ДОМ = __dirname;
const ОЖИДАНИЕ = path.join(ДОМ, 'src_pending');
const ГОДНЫЕ = path.join(ДОМ, 'src_good');
const БРАК = path.join(ДОМ, 'src_bad');
const НЕПРИГОДНЫЕ = path.join(ДОМ, 'src_unfit');
const ЖУРНАЛ = path.join(ДОМ, 'src_promote.jsonl');
const ПОТОК = Number(process.env.PROMOTE_CONC || 5);   // у openrouter быстро прилетает 429

(async () => {
  let файлы = [];
  try { файлы = fs.readdirSync(ОЖИДАНИЕ).filter((f) => /\.(jpe?g|png|webp)$/i.test(f)).sort(); }
  catch { console.log(`нет папки ${ОЖИДАНИЕ}: разбирать нечего`); process.exit(0); }
  const лимит = Number(process.argv[2] || 0);
  if (лимит > 0) файлы = файлы.slice(0, лимит);
  if (!файлы.length) { console.log('src_pending пуста: весь набор уже разобран'); process.exit(0); }
  console.log(`на разбор: ${файлы.length} файлов, модель ${process.env.COVER_QA_MODEL || 'по умолчанию из cover_qa'}`);

  const ст = { годных: 0, брака: 0, непроверено: 0 };
  for (let i = 0; i < файлы.length; i += ПОТОК) {
    const часть = файлы.slice(i, i + ПОТОК);
    const ответы = await Promise.all(часть.map(async (имя) => {
      const п = path.join(ОЖИДАНИЕ, имя);
      // Числовой эшелон по этим файлам УЖЕ пройден на приёмке (srcfilter.cjs), но проверить()
      // считает его заново, и это правильно: отдельная ветка «только модель» была бы вторым путём
      // принятия решения об обложке, а их должно быть ровно столько же, сколько и раньше, то есть
      // один. Замер числом даровой, платит только модель.
      try { return { имя, п, r: await проверить(п) }; }
      catch (e) { return { имя, п, r: { вердикт: 'unknown', ok: false, причины: [String(e.message)] } }; }
    }));
    for (const { имя, п, r } of ответы) {
      const почему = (r.причины || []).join('; ');
      // ПРОВЕРКА НЕ СОСТОЯЛАСЬ ЭТО НЕ БРАК (урок validatepost.cjs: 402 прочитали как отказ и увели
      // девять годных постов в rejected). Но и «годным» такой файл назвать нельзя: ровно для этого
      // здесь и завёлся src_pending. Поле непроверено у проверить() отдельное именно затем, чтобы
      // решал вызывающий; наше решение — оставить файл ждать, а не пускать его в оплачиваемую волну.
      // ВНИМАНИЕ на структуру ответа: у проверить() поля годится/непригоден/непроверено, никаких
      // r.вердикт и r.модель у него нет. Первая версия этого файла читала несуществующие поля, и
      // ровно поэтому три файла уехали в src_good без вердикта модели: проверка «модель ответила?»
      // всегда давала «да». Отсюда правило: сверяться с описанием проверить(), а не с догадкой.
      if (r.непроверено) {
        ст.непроверено++;
        if (ст.непроверено === 1) console.log(`  ⏸ ${имя}: модель не ответила (${почему.slice(0, 110)}) — оставляю в ожидании`);
        if (/402|Insufficient credits/i.test(почему)) {
          console.log('\n⛔ РАЗБОР НЕВОЗМОЖЕН: у ключа openrouter кончился баланс (HTTP 402). '
            + `Пополните баланс и запустите этот же файл снова. В ожидании ${файлы.length - ст.годных - ст.брака} файлов, ничего не потеряно.`);
          process.exit(2);
        }
        continue;
      }
      // Три исхода, а не два: непригодный референс это своя куча (обоснование в srcbad.cjs).
      const куда = r.годится ? ГОДНЫЕ : (r.непригоден ? НЕПРИГОДНЫЕ : БРАК);
      fs.mkdirSync(куда, { recursive: true });
      try { fs.renameSync(п, path.join(куда, имя)); } catch (e) { console.log(`  ⚠ ${имя} не переложился: ${e.message}`); continue; }
      try {
        fs.appendFileSync(ЖУРНАЛ, `${JSON.stringify({
          файл: имя, годится: !!r.годится, непригоден: !!r.непригоден, куда: path.basename(куда),
          причины: r.причины || [], модель: process.env.COVER_QA_MODEL || null, когда: new Date().toISOString(),
        })}\n`);
      } catch { /* журнал не должен ронять разбор */ }
      if (r.годится) ст.годных++;
      else { ст.брака++; console.log(`  ⛔ ${имя} → ${path.basename(куда)}: ${почему.slice(0, 100)}`); }
    }
    if ((i + ПОТОК) % 50 < ПОТОК) console.log(`  …разобрано ${Math.min(i + ПОТОК, файлы.length)} из ${файлы.length}`);
  }
  console.log(`\nИТОГ РАЗБОРА: годных ${ст.годных}, брака ${ст.брака}, осталось в ожидании ${ст.непроверено}`);
  const в = (п) => { try { return fs.readdirSync(п).filter((f) => /\.(jpe?g|png|webp)$/i.test(f)).length; } catch { return 0; } };
  console.log(`src_good ${в(ГОДНЫЕ)}, src_bad ${в(БРАК)}, src_pending ${в(ОЖИДАНИЕ)}`);
})().catch((e) => { console.log(`ОШИБКА: ${e.message}`); process.exit(1); });
