// ПРОВЕРКА: те же запреты, что в hooks2.check, плюс формат владельца.
const ЗАПРЕТ = [
  [/—|–/, 'длинное тире'],
  [/https?:|\.ru|\.com|\bt\.me|\//i, 'ссылка или слеш'],
  [/красивее меня|лучше меня|хуже меня/i, 'сравнение подписчицы с собой'],
  [/\bвау\b/i, 'запретное слово вау'],
  [/\d\s*[.,]\s*\d|\d+\s*из\s*\d+/, 'цифра оценки'],
];
function check() {
  const errs = [];
  const все = описания();
  const seen = new Set();
  все.forEach((t, i) => {
    const say = (m) => errs.push(`#${i + 1}: ${m}`);
    for (const [re, чем] of ЗАПРЕТ) if (re.test(t)) say(чем);
    if (!/«нейронка про промпты»/.test(t)) say('нет зова в яндекс «нейронка про промпты»');
    if (!/промпт не нужен/.test(t)) say('нет мысли «промпт не нужен»');
    if (!/бесплатно/.test(t)) say('нет слова «бесплатно»');
    if (!/💔/.test(t)) say('нет 💔');
    if (!/фотк/.test(t)) say('нет «загрузи фотку»');
    const n = (t.match(/#[^\s#]+/g) || []).length; if (n !== 5) say(`тегов ${n}, нужно 5`);
    if (t.length < 280 || t.length > 470) say(`длина ${t.length}, нужно 280-470`);
    if (/[a-z]{3,}/i.test(t.replace(/#[^\s#]+/g, ''))) say('латиница в тексте');
    if (seen.has(ВСТУП[i])) say('дубль вступления'); seen.add(ВСТУП[i]);
    if (/[.!?]{2,}|\?\?/.test(t)) say('сдвоенные знаки');
  });
  return errs;
}

